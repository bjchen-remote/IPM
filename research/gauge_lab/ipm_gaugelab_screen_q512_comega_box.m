    'status','comparison_unavailable', ...
    'initialScreenPassed',false, ...
    'eligible',false, ...
    'promotionBlocked',true, ...
    'promotionEvidenceRequired',{ ...
        {'time_evolved_fields','box_refinement','cfl_refinement'}}, ...
    'checks',struct(), ...
    'failures',{{}});
if ~comparison.available
    assessment.failures = {'targetComparisonAvailable'};
    return
end
endpointBoxes = boxes([boxes.boxHalfWidth] >= 1e5);
exactRates = false(size(endpointBoxes));
exactResiduals = false(size(endpointBoxes));
for index = 1:numel(endpointBoxes)
    run = endpointBoxes(index).gaugeRuns.none;
    exactRates(index) = run.rates.c_omega == 0 && ...
        run.rates.canonicalCOmega == 0;
    exactResiduals(index) = run.rates.omegaGaugeResidual == 0;
end
difference = comparison.relativeDifferences;
checks = struct();
checks.exactZeroRate = all(exactRates);
checks.exactZeroResidual = all(exactResiduals);
checks.cLConverged = difference.c_l <= ...
    limits.maximumSuccessiveCLRelativeDifference;
checks.kappaConverged = difference.kappa <= ...
    limits.maximumSuccessiveKappaRelativeDifference;
checks.zeroRateNotTreatedAsConvergenceEvidence = true;
checks.noTimeEvolvedPromotion = true;
assessment.checks = checks;
assessment.failures = failed_checks(checks);
assessment.initialScreenPassed = isempty(assessment.failures);
assessment.eligible = false;
assessment.promotionBlocked = true;
if assessment.initialScreenPassed
    assessment.status = [ ...
        'exploratory_zero_rate_control_passed_requires_' ...
        'time_field_box_cfl_evidence'];
else
    assessment.status = 'exploratory_zero_rate_control_rejected';
end
end

function assessment = assess_gradient_candidate(comparison,limits)
assessment = struct( ...
    'status','comparison_unavailable', ...
    'eligible',false, ...
    'normalizationConverged',false, ...
    'extensivityDetected',false, ...
    'rejectedForExtensiveNormalization',false, ...
    'passedAsNegativeControl',false, ...
    'checks',struct(), ...
    'failures',{{}});
if ~comparison.available
    assessment.failures = {'targetComparisonAvailable'};
    return
end
difference = comparison.relativeDifferences;
growth = comparison.growthRatios;
checks = struct();
checks.rateConverged = difference.c_omega <= ...
    limits.maximumSuccessiveCOmegaRelativeDifference;
checks.energyConverged = difference.gradientEnergy <= ...
    limits.maximumGradientEnergyRelativeDifference;
checks.forcingConverged = difference.gradientForcing <= ...
    limits.maximumGradientForcingRelativeDifference;
checks.absoluteForcingConverged = ...
    difference.gradientAbsoluteForcing <= ...
    limits.maximumGradientAbsoluteForcingRelativeDifference;
checks.energyExtensive = growth.gradientEnergy >= ...
    limits.minimumExtensiveGrowthRatio;
checks.normalEnergyExtensive = growth.gradientEnergyY >= ...
    limits.minimumExtensiveGrowthRatio;
checks.forcingExtensive = growth.gradientForcingMagnitude >= ...
    limits.minimumExtensiveGrowthRatio;
checks.normalForcingExtensive = growth.gradientForcingYMagnitude >= ...
    limits.minimumExtensiveGrowthRatio;
checks.absoluteForcingExtensive = growth.gradientAbsoluteForcing >= ...
    limits.minimumExtensiveGrowthRatio;
assessment.checks = checks;
assessment.normalizationConverged = checks.energyConverged && ...
    checks.forcingConverged;
assessment.extensivityDetected = checks.energyExtensive && ...
    checks.normalEnergyExtensive && checks.forcingExtensive && ...
    checks.normalForcingExtensive;
assessment.eligible = checks.rateConverged && ...
    assessment.normalizationConverged;
assessment.rejectedForExtensiveNormalization = ...
    ~assessment.normalizationConverged && assessment.extensivityDetected;
assessment.passedAsNegativeControl = ...
    assessment.rejectedForExtensiveNormalization;
if assessment.rejectedForExtensiveNormalization
    assessment.status = 'rejected_extensive_global_normalization';
    assessment.failures = cell(0,1);
elseif assessment.eligible
    assessment.status = 'eligible';
    assessment.failures = {'negativeControlDidNotExposeExtensivity'};
else
    assessment.status = 'rejected_inconclusive';
    assessment.failures = {'extensivityNotResolved'};
end
end

function assessment = assess_quadratic_candidate( ...
        comparison,boxes,limits)
assessment = struct( ...
    'status','comparison_unavailable', ...
    'eligible',false, ...
    'checks',struct(), ...
    'failures',{{}});
if ~comparison.available
    assessment.failures = {'targetComparisonAvailable'};
    return
end
endpointMask = [boxes.boxHalfWidth] >= 1e5;
endpointBoxes = boxes(endpointMask);
residuals = NaN(size(endpointBoxes));
curvatureConditions = NaN(size(endpointBoxes));
weightConditions = NaN(size(endpointBoxes));
interiorFractions = NaN(size(endpointBoxes));
nodeMargins = NaN(size(endpointBoxes));
selectionMargins = NaN(size(endpointBoxes));
runtimeAgreement = NaN(size(endpointBoxes));
for index = 1:numel(endpointBoxes)
    run = endpointBoxes(index).gaugeRuns.wall_omega_quadratic_peak;
    diagnostic = run.wallQuadraticPeak;
    residuals(index) = abs( ...
        diagnostic.candidateNormalizedRateResidual);
    curvatureConditions(index) = diagnostic.curvatureCondition;
    weightConditions(index) = diagnostic.weightCondition;
    interiorFractions(index) = diagnostic.vertexInteriorFraction;
    nodeMargins(index) = diagnostic.activeNodeMargin;
    selectionMargins(index) = diagnostic.activeSelectionMargin;
    runtimeAgreement(index) = ...
        diagnostic.runtimeAgreementMaximumRelativeError;
end
difference = comparison.relativeDifferences;
checks = struct();
checks.cLConverged = difference.c_l <= ...
    limits.maximumSuccessiveCLRelativeDifference;
checks.cOmegaConverged = difference.c_omega <= ...
    limits.maximumSuccessiveCOmegaRelativeDifference;
checks.kappaConverged = difference.kappa <= ...
    limits.maximumSuccessiveKappaRelativeDifference;
checks.peakValueConverged = difference.quadraticPeakValue <= ...
    limits.maximumQuadraticPeakRelativeDifference;
checks.forcingConverged = difference.quadraticForcing <= ...
    limits.maximumQuadraticForcingRelativeDifference;
checks.exactRateResidual = max(residuals) <= ...
    limits.maximumQuadraticNormalizedRateResidual;
checks.curvatureResolved = min(curvatureConditions) >= ...
    limits.minimumQuadraticCurvatureCondition;
checks.weightsResolved = min(weightConditions) >= ...
    limits.minimumQuadraticWeightCondition;
checks.vertexInterior = min(interiorFractions) >= ...
    limits.minimumQuadraticVertexInteriorFraction;
checks.activeNode = min(nodeMargins) >= ...
    limits.minimumQuadraticActiveNodeMargin;
checks.activeSelection = min(selectionMargins) >= ...
    limits.minimumQuadraticActiveSelectionMargin;
checks.runtimeAgreement = max(runtimeAgreement) <= ...
    limits.maximumQuadraticRuntimeAgreementError;
assessment.checks = checks;
assessment.failures = failed_checks(checks);
assessment.eligible = isempty(assessment.failures);
if assessment.eligible
    assessment.status = ...
        'admissible_for_time_evolution_screen_not_promoted';
else
    assessment.status = 'rejected_initial_box_screen';
end
end

function comparison = target_comparison( ...
        comparisons,gauge,referenceHalfWidth,candidateHalfWidth)
mask = strcmp({comparisons.gauge},gauge) & ...
    [comparisons.referenceHalfWidth] == referenceHalfWidth & ...
    [comparisons.candidateHalfWidth] == candidateHalfWidth;
index = find(mask,1,'first');
if isempty(index)
    comparison = empty_comparison();
    comparison.gauge = gauge;
    comparison.referenceHalfWidth = referenceHalfWidth;
    comparison.candidateHalfWidth = candidateHalfWidth;
else
    comparison = comparisons(index);
end
end

function failures = screen_failures(screen,settings,gauges)
failures = cell(0,1);
for boxIndex = 1:numel(screen.boxes)
    box = screen.boxes(boxIndex);
    if ~box.preflightPassed
        failures{end+1,1} = sprintf( ...
            'box_%g_preflight',box.boxHalfWidth); %#ok<AGROW>
    end
    if settings.execute
        for gaugeIndex = 1:numel(gauges)
            gauge = gauges{gaugeIndex};
            if ~strcmp(box.gaugeRuns.(gauge).status,'completed')
                failures{end+1,1} = sprintf( ...
                    'box_%g_%s_rhs',box.boxHalfWidth,gauge); %#ok<AGROW>
            end
        end
    end
end
if settings.execute && ~screen.screeningGate.passed
    failures{end+1,1} = 'screening_gate';
end
end

