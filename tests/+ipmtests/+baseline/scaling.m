function residual = rescaled_flux_residual(rhs,rho,flow,ops)
transportU1 = flow.u1+flow.canonicalCL*ops.X+flow.canonicalCR;
transportU2 = flow.u2+flow.canonicalCL*ops.Y;
expected = ipm.field.transport(rho,transportU1,transportU2,ops,'open') + ...
    (2*flow.canonicalCL+flow.canonicalCOmega)*rho;
residual = weighted_l2(rhs/flow.timeSpeed-expected,ops) / ...
    max(weighted_l2(expected,ops),eps);
end

function value = weighted_l2(field,ops)
value = sqrt(sum(field.^2.*ops.weights,'all'));
end
