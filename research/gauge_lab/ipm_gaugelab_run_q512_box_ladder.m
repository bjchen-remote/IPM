function value = relative_difference(reference,candidate)
if ~isfinite(reference) || ~isfinite(candidate)
    value = NaN;
    return
end
scale = max(abs([reference,candidate]));
if scale == 0
    value = 0;
else
    value = (candidate-reference)/scale;
end
end

