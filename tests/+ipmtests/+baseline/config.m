    ~isempty(regexp(remeshProposalSource,'0\.8\^retry','once')) && ...
    ~isempty(regexp(remeshTransferSource, ...
    'ipm\.mesh\.build\s*\(','once')) && ...
    numel(regexp(remeshSource,'\n','match')) < 150, ...
    'ipm:RemeshResolvedBuilderBoundary', ...
    'Adaptive remeshing lost its compact propose-transfer-validate path.');

initializationOverrides = struct('nx',65,'ny',33,'xlim',[-4,4], ...
