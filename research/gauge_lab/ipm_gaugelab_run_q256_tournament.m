function fileName = latest_immutable_checkpoint(candidateDirectory)
fileName = '';
files = dir(fullfile(candidateDirectory,'checkpoint*.mat'));
files = files(~[files.isdir]);
if isempty(files)
    return;
end
newestDate = max([files.datenum]);
indices = find([files.datenum] == newestDate);
if numel(indices) > 1
    names = {files(indices).name};
    [~,nameOrder] = sort(names);
    selected = indices(nameOrder(end));
else
    selected = indices;
end
if isfield(files,'folder') && ~isempty(files(selected).folder)
    fileName = fullfile(files(selected).folder,files(selected).name);
else
    fileName = fullfile(candidateDirectory,files(selected).name);
end
end

