function products = run_fourth_order_lattice_validation(caseName)
%RUN_FOURTH_ORDER_LATTICE_VALIDATION Long q256 validation of one LAT map.
%   The run requests physical time 2.10 so that a successful candidate must
%   cross the archived A=16 Gaussian trusted endpoint rather than merely
%   survive an early oscillation screen.

if nargin < 1 || isempty(caseName)
    caseName = 'analytic_lorentzian_A24_w020_c114_quadrant_256';
end
caseName = validatestring(caseName,{ ...
    'analytic_gaussian_A14_w042_c114_quadrant_256', ...
    'analytic_lorentzian_A24_w020_c114_quadrant_256', ...
    'analytic_lorentzian_A28_w020_c114_quadrant_256', ...
    'analytic_lorentzian_A32_w020_c114_quadrant_256', ...
    'coordinated_log_F80_R16_c114_quadrant_256', ...
    'coordinated_log_F80_R20_c114_quadrant_256', ...
    'coordinated_log_F80_R24_c114_quadrant_256', ...
    'coordinated_log_F80_R28_c114_quadrant_256', ...
    'coordinated_log_F90_R20_c114_quadrant_256', ...
    'coordinated_log_F92_R20_c114_quadrant_256'}, ...
    mfilename,'caseName');

experimentDirectory = fileparts(mfilename('fullpath'));
researchDirectory = fileparts(experimentDirectory);
projectDirectory = fileparts(researchDirectory);
analysisDirectory = fullfile(researchDirectory,'analysis');
addpath(projectDirectory,experimentDirectory,analysisDirectory);
verificationDirectory = fullfile(projectDirectory,'result','verification');
if ~isfolder(verificationDirectory)
    mkdir(verificationDirectory);
end

safeCaseName = lower(regexprep(caseName,'[^A-Za-z0-9]+','_'));
stem = ['fourth_order_lat_validation_',safeCaseName,'_q256_t210'];
requestedResultFile = ipm.output.uniquePath( ...
    fullfile(verificationDirectory,[stem,'.mat']),'lat_validation');
opts = fourth_order_blowup_case(caseName,struct( ...
    'physicalFinalTime',2.10,'resultFile',requestedResultFile));

startedAt = datetime('now','TimeZone','local');
fprintf(['LAT q256 validation started %s\n' ...
    '  case: %s\n  requested physical final time: %.8g\n' ...
    '  result: %s\n'],char(startedAt),caseName, ...
    opts.physicalFinalTime,requestedResultFile);
wallClock = tic;
result = ipm.solve(opts);
elapsedSeconds = toc(wallClock);
assessment = ipm_assess_fourth_order_blowup(result);

resultFile = char(result.metadata.resultFile);
[resultDirectory,resultStem] = fileparts(resultFile);
assessmentFile = fullfile(resultDirectory,[resultStem,'_assessment.mat']);
growthFigureFile = fullfile(resultDirectory,[resultStem,'_growth.png']);
productsFile = fullfile(resultDirectory,[resultStem,'_products.mat']);
save(assessmentFile,'assessment');
[figureHandle,plotData] = ipm_plot_maximum_growth( ...
    assessment,growthFigureFile);
close(figureHandle);

products = struct( ...
    'caseName',caseName, ...
    'startedAt',startedAt, ...
    'completedAt',datetime('now','TimeZone','local'), ...
    'elapsedSeconds',elapsedSeconds, ...
    'resultFile',resultFile, ...
    'assessmentFile',assessmentFile, ...
    'growthFigureFile',growthFigureFile, ...
    'productsFile',productsFile, ...
    'stopReason',result.state.stopReason, ...
    'stopTime',result.state.physicalTime, ...
    'trustedThroughTime',plotData.trustedThroughTime, ...
    'trustedThroughCanonicalTau', ...
        assessment.trustedThroughCanonicalTau, ...
    'steps',result.state.steps);
save(productsFile,'products');
fprintf(['LAT q256 validation completed in %.3f s\n' ...
    '  stop reason: %s\n  raw/trusted physical time: %.12g / %.12g\n' ...
    '  assessment: %s\n  growth figure: %s\n'], ...
    elapsedSeconds,result.state.stopReason,result.state.physicalTime, ...
    plotData.trustedThroughTime,assessmentFile,growthFigureFile);
end
