function products = run_fourth_order_dense_growth()
%RUN_FOURTH_ORDER_DENSE_GROWTH Run and assess the matched 384-cell case.
%   PRODUCTS = RUN_FOURTH_ORDER_DENSE_GROWTH() advances the maintained
%   fourth-order active datum on 384-by-384 first-quadrant cells, requests
%   physical time 2.05, saves the solver result and trusted-prefix
%   assessment, and exports physical-time and canonical-tau growth figures.

experimentDirectory = fileparts(mfilename('fullpath'));
researchDirectory = fileparts(experimentDirectory);
projectDirectory = fileparts(researchDirectory);
analysisDirectory = fullfile(researchDirectory,'analysis');
addpath(projectDirectory,experimentDirectory,analysisDirectory);

stem = 'fourth_order_active_analytic_A16_w055_q384_t205_dt002';
verificationDirectory = fullfile(projectDirectory,'result','verification');
if ~isfolder(verificationDirectory)
    mkdir(verificationDirectory);
end
requestedResultFile = fullfile(verificationDirectory,[stem,'.mat']);
logFile = ipm.output.uniquePath( ...
    fullfile(verificationDirectory,[stem,'.log']),'dense_driver');

opts = fourth_order_blowup_case( ...
    'analytic_moderate_narrow_quadrant_384');
opts.resultFile = requestedResultFile;

diary(logFile);
diaryCleanup = onCleanup(@()diary('off'));
startedAt = datetime('now','TimeZone','local');
fprintf(['Dense fourth-order run started %s\n' ...
    '  stored nodes: %d x %d\n' ...
    '  first-quadrant cells: %d x %d\n' ...
    '  requested physical final time: %.8g\n' ...
    '  result: %s\n'],char(startedAt),opts.nx,opts.ny, ...
    (opts.nx-1)/2,opts.ny-1,opts.physicalFinalTime,requestedResultFile);

wallClock = tic;
result = ipm.solve(opts);
elapsedSeconds = toc(wallClock);
resultFile = char(result.metadata.resultFile);
[resultDirectory,resultStem] = fileparts(resultFile);
assessmentFile = ipm.output.uniquePath( ...
    fullfile(resultDirectory,[resultStem,'_assessment.mat']), ...
    result.metadata.caseId);
growthFigureFile = ipm.output.uniquePath( ...
    fullfile(resultDirectory,[resultStem,'_growth.png']), ...
    result.metadata.caseId);
assessment = ipm_assess_fourth_order_blowup(result);
save(assessmentFile,'assessment');
[figureHandle,plotData] = ipm_plot_maximum_growth( ...
    assessment,growthFigureFile);
close(figureHandle);

coarseResultFile = fullfile(verificationDirectory, ...
    'fourth_order_active_analytic_A16_w055_t195_dt002.mat');
tauGrowthFigureFile = '';
tauGrowthAnalysisFile = '';
if isfile(coarseResultFile)
    tauGrowthFigureFile = ipm.output.uniquePath(fullfile( ...
        verificationDirectory, ...
        'fourth_order_active_A16_w055_q256_vs_q384_tau_growth.png'), ...
        result.metadata.caseId);
    [tauFigureHandle,tauAnalysis] = ipm_plot_tau_growth( ...
        coarseResultFile,result,tauGrowthFigureFile);
    close(tauFigureHandle);
    tauGrowthFigureFile = tauAnalysis.outputFile;
    tauGrowthAnalysisFile = tauAnalysis.analysisFile;
end

products = struct( ...
    'caseName',opts.caseMetadata.caseName, ...
    'resultFile',resultFile, ...
    'assessmentFile',assessmentFile, ...
    'growthFigureFile',growthFigureFile, ...
    'tauGrowthFigureFile',tauGrowthFigureFile, ...
    'tauGrowthAnalysisFile',tauGrowthAnalysisFile, ...
    'logFile',logFile, ...
    'elapsedSeconds',elapsedSeconds, ...
    'stopReason',result.state.stopReason, ...
    'physicalTime',result.state.physicalTime, ...
    'trustedThroughTime',plotData.trustedThroughTime);
fprintf(['Dense fourth-order run completed in %.3f s\n' ...
    '  stop reason: %s\n' ...
    '  raw/trusted physical time: %.12g / %.12g\n' ...
    '  assessment: %s\n' ...
    '  physical-time growth figure: %s\n' ...
    '  canonical-tau growth figure: %s\n'], ...
    elapsedSeconds,result.state.stopReason, ...
    result.state.physicalTime,plotData.trustedThroughTime, ...
    assessmentFile,growthFigureFile,tauGrowthFigureFile);
end
