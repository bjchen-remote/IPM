limits = struct('rhoRelativeL2',5e-4, ...
    'omegaRelativeL2',5e-3,'rhoAbsoluteInf',5e-4, ...
    'omegaAbsoluteInf',5e-3, ...
    'physicalRhoXRelativeDifference',5e-3, ...
    'wallPeakRelativeDifference',5e-3, ...
    'wallWidthRelativeDifference',2e-2, ...
    'maximumAbsoluteLabPeakShift',5e-4, ...
    'maximumAbsolutePhysicalTimeDifference',1e-10);
end

function cadence = frozen_checkpoint_cadence()
cadence = 0.20;
end

function seconds = frozen_wall_clock_budget()
seconds = 7200;
end

function tuple = frozen_numerical_tuple()
tuple = struct('spatialDiscretization','high_order', ...
    'transportScheme','weno5_fd','timeIntegrator','ssprk54', ...
    'remeshTransferScheme','high_order');
end

function [audit,passed] = audit_shared_mesh(opts,limits)
quadratureX = ipm.mesh.quadrature(opts.customX);
quadratureY = ipm.mesh.quadrature(opts.customY);
qualityX = ipm.mesh.quality(opts.customX,7,quadratureX);
qualityY = ipm.mesh.quality(opts.customY,7,quadratureY);
audit = struct('storedNodes',[opts.nx,opts.ny], ...
    'firstQuadrantCells',[(opts.nx-1)/2,opts.ny-1], ...
    'x',qualityX,'y',qualityY,'anchorNodeDistance', ...
    min(abs(opts.customX-1)));
passed = opts.nx == 513 && opts.ny == 257 && ...
    all([qualityX.maximumAdjacentCellRatio, ...
        qualityY.maximumAdjacentCellRatio] <= ...
        limits.maximumAdjacentCellRatio) && ...
    all([qualityX.maximumLogSpacingCurvature, ...
        qualityY.maximumLogSpacingCurvature] <= ...
        limits.maximumLogSpacingCurvature) && ...
    all([qualityX.minimumStencilRcond,qualityY.minimumStencilRcond] >= ...
        limits.minimumStencilRcond) && ...
    all([qualityX.minimumQuadratureWeightRatio, ...
        qualityY.minimumQuadratureWeightRatio] >= ...
        limits.minimumQuadratureWeightRatio) && ...
    all([qualityX.minimumQuadratureWeightToControlWidthRatio, ...
        qualityY.minimumQuadratureWeightToControlWidthRatio] >= ...
        limits.minimumLocalQuadratureWeightRatio) && ...
    all([qualityX.maximumQuadratureWeightToControlWidthRatio, ...
        qualityY.maximumQuadratureWeightToControlWidthRatio] <= ...
        limits.maximumLocalQuadratureWeightRatio);
end

function assert_common_contract(opts)
config = ipm.config.resolve(opts);
scaling = config.scaling;
assert(config.schemaVersion == 4, ...
    'ipm:GaugeLabConfigSchema', ...
    'The production group stage requires configuration schema 4.');
assert(config.grid.nx == 513 && config.grid.ny == 257, ...
    'ipm:GaugeLabResolution','The group stage must be q256.');
assert(strcmp(config.transport.spatialDiscretization,'high_order') && ...
    strcmp(config.transport.transportScheme,'weno5_fd') && ...
    strcmp(config.time.timeIntegrator,'ssprk54') && ...
    strcmp(config.remesh.remeshTransferScheme,'high_order'), ...
    'ipm:GaugeLabNumericalTuple','The fourth-order tuple changed.');
assert(strcmp(scaling.lengthGauge,'transport_anchor') && ...
    scaling.transportAnchorX == 1 && scaling.lengthScaleGain == 1 && ...
    scaling.omegaGaugeWindowRadius == 0.75 && ...
    scaling.pointStrainConditionFloor == 0.25, ...
    'ipm:GaugeLabLengthGauge', ...
    ['The fixed X=1 anchor, localized radius, or condition floor ' ...
    'changed.']);
assert(strcmp(scaling.scalingContract,'exact_gauge_no_feedback_v1'), ...
    'ipm:GaugeLabScalingContract', ...
    'The schema-4 exact-no-feedback scaling contract is required.');
assert(scaling.widthGaugeGain == 0 && scaling.omegaGaugeGain == 0 && ...
    scaling.travelingWaveGain == 0, ...
    'ipm:GaugeLabFeedbackGain', ...
    'All optional scaling feedback gains must be exactly zero.');
assert(~config.remesh.initialAnalyticRemesh && ...
    ~config.remesh.adaptiveRemesh, ...
