    strcmp(firstAudit.evidenceClass,secondAudit.evidenceClass) && ...
    sameMetadataFieldSchema && ...
    firstAudit.currentStrengthenedFieldContractPassed && ...
    secondAudit.currentStrengthenedFieldContractPassed;
