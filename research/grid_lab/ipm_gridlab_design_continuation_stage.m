function policy = x_candidate_reference_policy(options)
tiers = {'external_original_reference_analytic'};
if options.enabled
    tiers{end+1} = ...
        'external_original_reference_anchored_gaussian_if_infeasible';
    if options.rootCorridorXFallbackEnabled
        tiers{end+1} = ...
            'external_original_reference_corridor_if_infeasible';
    end
    if options.currentAxisXFallbackEnabled
        tiers{end+1} = ...
            'trusted_terminal_axis_single_hop_if_infeasible';
    end
end
policy = strjoin(tiers,'_then_');
end

