        strcmp(contract.length.evaluation, ...
            'fixed_coordinate_linear_interpolation') && ...
        contract.length.anchorX == 1 && ...
        isstruct(contract.length.registeredParameters) && ...
        isfield(contract.length.registeredParameters, ...
            'transportAnchorX') && ...
        contract.length.registeredParameters.transportAnchorX == 1 && ...
        isstruct(contract.amplitude) && isscalar(contract.amplitude) && ...
        all(isfield(contract.amplitude,amplitudeFields)) && ...
        strcmp(contract.amplitude.name,expectedGauge) && ...
        amplitude_contract_matches(contract.amplitude,expectedGauge);
