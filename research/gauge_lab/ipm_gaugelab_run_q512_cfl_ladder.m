comparison.method = 'bidirectional_absolute_worst';
comparison.referenceCfl = referenceRecord.cfl;
comparison.candidateCfl = candidateRecord.cfl;
comparison.commonWindow = window;
comparison.referencePhysicalTime = reference.state.physicalTime;
comparison.candidatePhysicalTime = candidate.state.physicalTime;
comparison.physicalTimeDifference = endpointDifference;
comparison.physicalTimeTolerance = endpointTolerance;
comparison.forward = forward;
comparison.reverse = reverse;
comparison.symmetricWorst = worst;
comparison.endpoint = endpoint;
comparison.rateDiagnostics = rateDiagnostic;
comparison.growthDiagnostics = growth;
comparison.checks = checks;
comparison.failures = failures;
comparison.hardPassed = isempty(failures);
end

