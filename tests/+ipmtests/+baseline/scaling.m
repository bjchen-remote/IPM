function report = scaling()
%IPMTESTS.BASELINE.SCALING Verify dynamic clocks, gauges, and rescaled assembly.

fprintf('Running IPM scaling verification...\n');
physicalOpts = ipm.config.resolve(struct( ...
    'nx',65,'ny',33,'xlim',[-4,4],'ymax',4, ...
    'rescalingMode','physical','saveResults',false, ...
    'makePlots',false,'verbose',false,'transportBoundaryMode','closed'));
physicalOps = ipm.mesh.build(physicalOpts);
constantRho = 2.5*ones(physicalOps.ny,physicalOps.nx);
[constantRhs,constantFlow] = ipm.evolve.rhs(constantRho,physicalOps);
scalingRate = 0.7;
constantScalingRhs = ipm.field.transport(constantRho, ...
    scalingRate*physicalOps.X,scalingRate*physicalOps.Y, ...
    physicalOps,'open') + 2*scalingRate*constantRho;

peakResolution = ipm.diagnostics.peakResolution([0,0.6,1,0.6,0,0.8,0], ...
    [0,1,2,4,7,11,16],0.5);
profileValues = [-1;0.6;1;0.6;0;0.8;0];
profileAxis = [0,1,2,4,7,11,16];
profileMeasurement = ipm.diagnostics.measureFeatures( ...
    profileValues,profileAxis,0.5,[]);
profileMask = logical([0,0,0,0,1,1,1]);
maskedProfileMeasurement = ipm.diagnostics.measureFeatures( ...
    profileValues,profileAxis,0.5,profileMask);
subgridPeakLocation = ipm.diagnostics.peakLocation(2-([0,1,3]-1.4).^2,[0,1,3],2);
[unlimitedRateMagnitude,normalizedRates] = ...
    ipm.evolve.rateMagnitude([10,8,0],1);

dynamicOpts = ipm.config.resolve(struct('nx',65,'ny',33,'xlim',[-4,4], ...
    'ymax',4,'initialCondition','degenerate','degeneratePower',4, ...
    'symmetryMode','half_plane', ...
    'rescalingMode','dynamic','saveResults',false, ...
    'makePlots',false,'verbose',false));
dynamicOps = ipm.mesh.build(dynamicOpts);
dynamicRho = ipm.field.initialDensity(dynamicOps,dynamicOpts.physics);
dynamicOps = ipm.evolve.initializeScaling(dynamicRho,dynamicOps);
[dynamicRhs,dynamicFlow] = ipm.evolve.rhs(dynamicRho,dynamicOps);
peakPhaseOpts = dynamicOpts;
peakPhaseOpts.scaling.lengthGauge = 'omega_peak_location';
peakPhaseOps = ipm.mesh.build(peakPhaseOpts);
peakPhaseRho = ipm.field.initialDensity( ...
    peakPhaseOps,peakPhaseOpts.physics);
peakPhaseOps = ipm.evolve.initializeScaling(peakPhaseRho,peakPhaseOps);
[~,peakPhaseFlow] = ipm.evolve.rhs(peakPhaseRho,peakPhaseOps);
peakPhaseContract = ipm.evolve.gaugeContract( ...
    peakPhaseOpts,peakPhaseOps);
dynamicScale0 = struct('logC_l',0,'logC_omega',0, ...
    'physicalTime',0,'X_shift',0,'canonicalTime',0);
dynamicState0 = struct('rho',peakPhaseRho,'flow',peakPhaseFlow, ...
    'scale',dynamicScale0,'ops',peakPhaseOps,'config',peakPhaseOpts, ...
    'mass0',sum(peakPhaseRho.*peakPhaseOps.weights,'all'),'rhoRange0', ...
    [min(peakPhaseRho,[],'all'),max(peakPhaseRho,[],'all')], ...
    'normalizedTime',0,'step',0);
[dynamicRecord,~] = ipm.output.record( ...
    ipm.output.initializeLog(),dynamicState0);
peakPhaseHistoryFields = {'peakLocationRhoXX', ...
    'peakLocationRhoXXScale','peakLocationPhaseDefect', ...
    'peakLocationResponseCondition','peakLocationFullPhaseResidual', ...
    'peakLocationNormalizedFullPhaseResidual'};
peakPhaseHistoryComplete = all(isfield( ...
    dynamicRecord.history.gauge,peakPhaseHistoryFields));
dynamicDiagnostics = ipm.diagnostics.measure(dynamicRho,dynamicFlow,dynamicOps, ...
    sum(dynamicRho.*dynamicOps.weights,'all'));

symmetricOpts = dynamicOpts;
symmetricOpts.physics.symmetryMode = 'double_odd_omega';
symmetricOpts.scaling.lengthGauge = 'omega_peak_location';
anchorOpts = symmetricOpts;
anchorOpts.scaling.lengthGauge = 'transport_anchor';
anchorOpts.scaling.transportAnchorX = 1;
anchorOpts.scaling.lengthScaleGain = 1;
anchorOpts.physics.initialCondition = 'degenerate_primitive';
anchorOpts.physics.degeneratePower = 8;
anchorOpts.scaling.cOmegaGauge = 'wall_omega_peak';
anchorOps = ipm.mesh.build(anchorOpts);
anchorRho = ipm.field.initialDensity(anchorOps,anchorOpts.physics);
anchorOps = ipm.evolve.initializeScaling(anchorRho,anchorOps);
[~,anchorFlow] = ipm.evolve.rhs(anchorRho,anchorOps);
anchorCanonicalVelocity = interp1(anchorOps.x,anchorFlow.u1(1,:), ...
    anchorOpts.scaling.transportAnchorX,'linear') + ...
    anchorFlow.canonicalCL*anchorOpts.scaling.transportAnchorX + ...
    anchorFlow.canonicalCR;
anchorCanonicalWallVelocity = anchorFlow.u1(1,:) + ...
    anchorFlow.canonicalCL*anchorOps.x + anchorFlow.canonicalCR;
anchorCanonicalSlope = interp1(anchorOps.x, ...
    anchorCanonicalWallVelocity*anchorOps.Dx', ...
    anchorOpts.scaling.transportAnchorX,'linear');
anchorBoundedVelocity = interp1(anchorOps.x, ...
    anchorFlow.transportU1(1,:),anchorOpts.scaling.transportAnchorX,'linear');
anchorScale = struct('logC_l',0,'logC_omega',0,'physicalTime',0, ...
    'X_shift',0,'canonicalTime',0);
[~,anchorFlowAfter,anchorScaleAfter] = ipm.evolve.stepSsprk3( ...
    anchorRho,1e-4,anchorOps,anchorScale);
anchorVelocityAfter = interp1(anchorOps.x, ...
    anchorFlowAfter.transportU1(1,:), ...
    anchorOpts.scaling.transportAnchorX,'linear');
anchorSlopeGauge = anchor_wall_gauge_check(anchorOpts);
quadraticPeakGauge = quadratic_peak_gauge_check(anchorOpts);
anchorWindowGauge = anchor_wall_window_check( ...
    anchorOpts,'anchor_wall_window_l2',2);
anchorWindowL4Gauge = anchor_wall_window_check( ...
    anchorOpts,'anchor_wall_window_l4',4);
anchorTemplateGauge = anchor_wall_template_check(anchorOpts);
anchorBulkGauge = anchor_bulk_gradient_check(anchorOpts);
anchorConditionGuarded = anchor_wall_condition_guarded( ...
    anchorOpts,'anchor_wall_slope');
anchorWindowGuarded = anchor_wall_window_l2_guarded(anchorOpts);

widthLengthOpts = dynamicOpts;
widthLengthOpts.scaling.lengthGauge = 'wall_density_width';
widthLengthOps = ipm.mesh.build(widthLengthOpts);
widthLengthRho = ipm.field.initialDensity(widthLengthOps,widthLengthOpts.physics);
widthLengthOps = ipm.evolve.initializeScaling(widthLengthRho,widthLengthOps);
[~,widthLengthFlow] = ipm.evolve.rhs(widthLengthRho,widthLengthOps);
widthLengthContract = ipm.evolve.gaugeContract( ...
    widthLengthOpts,widthLengthOps);

omegaWidthOpts = dynamicOpts;
omegaWidthOpts.scaling.lengthGauge = 'wall_omega_width';
omegaWidthOps = ipm.mesh.build(omegaWidthOpts);
omegaWidthRho = ipm.field.initialDensity(omegaWidthOps,omegaWidthOpts.physics);
omegaWidthOps = ipm.evolve.initializeScaling(omegaWidthRho,omegaWidthOps);
[~,omegaWidthFlow] = ipm.evolve.rhs(omegaWidthRho,omegaWidthOps);
omegaWidthContract = ipm.evolve.gaugeContract( ...
    omegaWidthOpts,omegaWidthOps);

[~,dynamicWallPeakIndex] = max(dynamicFlow.source(1,:));
dynamicPeakLocation = ipm.diagnostics.peakLocation(max(dynamicFlow.source(1,:),0), ...
    dynamicOps.x,dynamicWallPeakIndex);
dynamicPinOffset = dynamicPeakLocation-dynamicOps.rescaling.pinX;

clockScale = struct('logC_l',0,'logC_omega',0,'physicalTime',0, ...
    'X_shift',0,'canonicalTime',0);
[~,clockFlow,clockScaleNew] = ipm.evolve.stepSsprk3( ...
    dynamicRho,1e-3,dynamicOps,clockScale);

dynamicRhoX = dynamicRho*dynamicOps.Dx';
dynamicRhoY = dynamicOps.Dy*dynamicRho;
dynamicRhsX = dynamicRhs*dynamicOps.Dx';
dynamicRhsY = dynamicOps.Dy*dynamicRhs;
physicalDynamicOps = dynamicOps;
physicalDynamicOps.rescaling.enabled = false;
[expectedPhysicalRhs,~] = ipm.evolve.rhs(dynamicRho,physicalDynamicOps);
dynamicFluxResidual = rescaled_flux_residual(dynamicRhs,dynamicRho, ...
    dynamicFlow,dynamicOps);
shiftedFlow = dynamicFlow;
shiftedFlow.u1 = shiftedFlow.u1+7;
shiftedTracking = ipm.diagnostics.trackFeatures( ...
    dynamicRho,expectedPhysicalRhs,shiftedFlow,dynamicOps);
[shiftedCL,shiftedCOmega,shiftedCR] = ipm.evolve.isotropicGauge( ...
    dynamicRho,expectedPhysicalRhs,shiftedFlow,dynamicOps,shiftedTracking);

diagnosticOnlyTracking = ipm.diagnostics.trackFeatures( ...
    dynamicRho,expectedPhysicalRhs,dynamicFlow,dynamicOps);
[diagnosticCL,diagnosticCOmega,diagnosticCR] = ...
    ipm.evolve.isotropicGauge(dynamicRho,expectedPhysicalRhs, ...
    dynamicFlow,dynamicOps,diagnosticOnlyTracking);
perturbedTracking = diagnosticOnlyTracking;
perturbedTracking.resolutionFactor = 1e9;
perturbedTracking.safetyFactor = 1e9;
perturbedTracking.peakExpansionRatio = 1e9;
[perturbedCL,perturbedCOmega,perturbedCR] = ...
    ipm.evolve.isotropicGauge(dynamicRho,expectedPhysicalRhs, ...
    dynamicFlow,dynamicOps,perturbedTracking);
diagnosticRateIndependenceError = max(abs( ...
    [perturbedCL,perturbedCOmega,perturbedCR] - ...
    [diagnosticCL,diagnosticCOmega,diagnosticCR]));

amplitudeFactor = 3;
translatedRho = interp2(dynamicOps.X,dynamicOps.Y,dynamicRho, ...
    dynamicOps.X-0.1,dynamicOps.Y,'linear',0);
[translatedRhs,translatedFlow] = ipm.evolve.rhs(translatedRho,dynamicOps);
[scaledTranslatedRhs,scaledTranslatedFlow] = ipm.evolve.rhs( ...
    amplitudeFactor*translatedRho,dynamicOps);
amplitudeGaugeRateError = max(abs([ ...
    scaledTranslatedFlow.canonicalCL, ...
    scaledTranslatedFlow.canonicalCOmega, ...
    scaledTranslatedFlow.canonicalCR]-amplitudeFactor*[ ...
    translatedFlow.canonicalCL,translatedFlow.canonicalCOmega, ...
    translatedFlow.canonicalCR]));
amplitudeGaugeRhsError = weighted_l2( ...
    scaledTranslatedRhs/scaledTranslatedFlow.timeSpeed- ...
    amplitudeFactor^2*translatedRhs/translatedFlow.timeSpeed, ...
    dynamicOps) / max(weighted_l2(amplitudeFactor^2* ...
    translatedRhs/translatedFlow.timeSpeed,dynamicOps),eps);

recoveredPhysicalOmegaRate = expectedPhysicalRhs*dynamicOps.Dx';
dynamicPeakIndex = dynamicOps.rescaling.pinIndex;
initialPhysicalOmegaPeakRate = recoveredPhysicalOmegaRate(1,dynamicPeakIndex);
initialRescaledOmegaPeakRate = dynamicRhsX(1,dynamicPeakIndex);
initialReconstructedOmegaPeakRate = initialRescaledOmegaPeakRate + ...
    (dynamicFlow.c_l-dynamicFlow.c_omega)* ...
    dynamicFlow.source(1,dynamicPeakIndex);
dynamicGradientEnergyRate = 2*sum((dynamicRhoX.*dynamicRhsX + ...
    dynamicRhoY.*dynamicRhsY).*dynamicOps.weights,'all');
dynamicGradientEnergy = sum((dynamicRhoX.^2+dynamicRhoY.^2) .* ...
    dynamicOps.weights,'all');
dynamicGradientEnergyRateRelative = dynamicGradientEnergyRate / ...
    max(dynamicGradientEnergy,eps);

energyOpts = dynamicOpts;
energyOpts.scaling.cOmegaGauge = 'gradient_energy';
energyOps = ipm.mesh.build(energyOpts);
energyRho = ipm.field.initialDensity(energyOps,energyOpts.physics);
energyOps = ipm.evolve.initializeScaling(energyRho,energyOps);
[energyRhs,energyFlow] = ipm.evolve.rhs(energyRho,energyOps);
energyRhoX = energyRho*energyOps.Dx';
energyRhoY = energyOps.Dy*energyRho;
energyRhsX = energyRhs*energyOps.Dx';
energyRhsY = energyOps.Dy*energyRhs;
energyBaseRhs = energyRhs-energyFlow.c_omega*energyRho;
energyBaseRhsX = energyBaseRhs*energyOps.Dx';
energyBaseRhsY = energyOps.Dy*energyBaseRhs;
energyWeights = energyOps.integrationWeights;
expectedEnergyComponents = [ ...
    sum(energyRhoX.^2.*energyWeights,'all'), ...
    sum(energyRhoY.^2.*energyWeights,'all')];
expectedForcingComponents = [ ...
    sum(energyRhoX.*energyBaseRhsX.*energyWeights,'all'), ...
    sum(energyRhoY.*energyBaseRhsY.*energyWeights,'all')];
expectedGaugeForcing = sum((energyRhoX.*energyBaseRhsX + ...
    energyRhoY.*energyBaseRhsY).*energyWeights,'all');
expectedAbsoluteForcing = sum(abs(energyRhoX.*energyBaseRhsX + ...
    energyRhoY.*energyBaseRhsY).*energyWeights,'all');
energyGaugeRate = 2*sum((energyRhoX.*energyRhsX + ...
    energyRhoY.*energyRhsY).*energyOps.weights,'all');
energyGaugeRateRelative = energyGaugeRate/max(energyFlow.omegaGaugeEnergy,eps);
energyFluxResidual = rescaled_flux_residual(energyRhs,energyRho, ...
    energyFlow,energyOps);
energyScale = struct('logC_l',0,'logC_omega',0,'physicalTime',0, ...
    'X_shift',0,'canonicalTime',0);
energyState = struct('rho',energyRho,'flow',energyFlow, ...
    'scale',energyScale,'ops',energyOps,'config',energyOpts, ...
    'mass0',sum(energyRho.*energyWeights,'all'),'rhoRange0', ...
    [min(energyRho,[],'all'),max(energyRho,[],'all')], ...
    'normalizedTime',0,'step',0);
[energyRecord,~] = ipm.output.record( ...
    ipm.output.initializeLog(),energyState);
energyGaugeHistory = energyRecord.history.gauge;
nonfiniteEnergyOps = energyOps;
nonfiniteEnergyOps.integrationWeights(1,1) = Inf;
nonfiniteEnergyGaugeRejected = false;
try
    ipm.evolve.rhs(energyRho,nonfiniteEnergyOps);
catch exception
    nonfiniteEnergyGaugeRejected = strcmp( ...
        exception.identifier,'ipm:DegenerateNormalization') && ...
        contains(exception.message,'not finite');
end

noneOpts = dynamicOpts;
noneOpts.scaling.cOmegaGauge = 'none';
noneOps = ipm.mesh.build(noneOpts);
noneRho = ipm.field.initialDensity(noneOps,noneOpts.physics);
noneOps = ipm.evolve.initializeScaling(noneRho,noneOps);
[noneRhs,noneFlow] = ipm.evolve.rhs(noneRho,noneOps);
noneFluxResidual = rescaled_flux_residual(noneRhs,noneRho,noneFlow,noneOps);
noneCounterfactualCOmega = -noneFlow.omegaGaugeQuadraticForcing / ...
    noneFlow.omegaGaugeQuadraticPeakValue;

legacyOpts = dynamicOpts;
legacyOpts.scaling.cOmegaGauge = 'strain_point';
legacyOps = ipm.mesh.build(legacyOpts);
legacyRho = ipm.field.initialDensity(legacyOps,legacyOpts.physics);
legacyOps = ipm.evolve.initializeScaling(legacyRho,legacyOps);
[legacyRhs,legacyFlow] = ipm.evolve.rhs(legacyRho,legacyOps);
[legacyU1Rate,~] = ipm.field.velocity(legacyRhs,legacyOps);
legacyStrainRate = legacyU1Rate*legacyOps.Dx';
legacyStrainRate = legacyStrainRate(1,legacyOps.rescaling.originIndex);

report.constantStateRhsInf = max(abs(constantRhs),[],'all');
report.constantStateVelocityInf = max( ...
    hypot(constantFlow.u1,constantFlow.u2),[],'all');
report.constantScalingRhsInf = max(abs(constantScalingRhs),[],'all');
report.connectedPeakGridPoints = peakResolution.gridPoints;
report.connectedPeakAreaPoints = peakResolution.areaPoints;
report.connectedPeakWidth = peakResolution.widths;
report.profileMeasurementPeakIndex = profileMeasurement.peakIndex;
report.maskedProfileMeasurementPeakIndex = ...
    maskedProfileMeasurement.peakIndex;
report.subgridPeakLocation = subgridPeakLocation;
report.unlimitedRateMagnitude = unlimitedRateMagnitude;
report.normalizedRates = normalizedRates;
report.dynamicCL = dynamicFlow.c_l;
report.dynamicCLNominal = dynamicFlow.c_lNominal;
report.dynamicCanonicalCLNominal = dynamicFlow.canonicalCLNominal;
report.dynamicLengthScaleGain = dynamicFlow.lengthScaleGain;
report.dynamicWidthCorrection = dynamicFlow.widthCorrection;
report.dynamicWidthRateScale = dynamicFlow.widthRateScale;
report.dynamicWidthControlMode = dynamicFlow.widthControlMode;
report.dynamicPeakGridPoints = dynamicFlow.peakGridPoints;
report.dynamicTargetPeakGridPoints = dynamicFlow.targetPeakGridPoints;
report.dynamicTargetSupportGridPoints = dynamicFlow.targetSupportGridPoints;
report.dynamicTargetCoreGridPoints = dynamicFlow.targetCoreGridPoints;
report.dynamicPeakExpansionRatio = dynamicFlow.peakExpansionRatio;
report.dynamicSafetyFactor = dynamicFlow.safetyFactor;
report.dynamicTrackedWallPeak = dynamicFlow.trackedWallPeak;
report.dynamicTrackedWallPeakWidth = dynamicFlow.trackedWallPeakWidth;
report.transportAnchorCanonicalVelocity = anchorCanonicalVelocity;
report.transportAnchorCanonicalSlope = anchorCanonicalSlope;
report.transportAnchorVelocity = anchorBoundedVelocity;
report.transportAnchorVelocityAfterStep = anchorVelocityAfter;
report.anchorWallSlopeGauge = anchorSlopeGauge;
report.quadraticWallOmegaPeakGauge = quadraticPeakGauge;
report.anchorWallWindowL2Gauge = anchorWindowGauge;
report.anchorWallWindowL4Gauge = anchorWindowL4Gauge;
report.anchorWallTemplateGauge = anchorTemplateGauge;
report.anchorBulkGradientGauge = anchorBulkGauge;
report.anchorWallConditionGuarded = anchorConditionGuarded;
report.anchorWallWindowL2Guarded = anchorWindowGuarded;
report.wallDensityWidthGaugeCL = widthLengthFlow.c_l;
report.wallDensityWidthGaugeResidual = widthLengthFlow.lengthGaugeResidual;
report.wallDensityCrossingConditions = [ ...
    widthLengthFlow.wallDensityLowerCondition, ...
    widthLengthFlow.wallDensityUpperCondition];
report.wallOmegaWidthGaugeCL = omegaWidthFlow.c_l;
report.wallOmegaWidthGaugeResidual = omegaWidthFlow.lengthGaugeResidual;
report.wallOmegaWidthGaugeWidth = omegaWidthFlow.lengthGaugeStrain;
report.dynamicCOmega = dynamicFlow.c_omega;
report.dynamicCR = dynamicFlow.c_r;
report.dynamicCanonicalCL = dynamicFlow.canonicalCL;
report.dynamicCanonicalCOmega = dynamicFlow.canonicalCOmega;
report.dynamicCanonicalCR = dynamicFlow.canonicalCR;
report.dynamicTimeSpeed = dynamicFlow.timeSpeed;
report.dynamicCanonicalRateMagnitude = dynamicFlow.canonicalRateMagnitude;
report.dynamicPinVelocity = dynamicFlow.pinTransportVelocity;
report.dynamicPinGaugeResidual = dynamicFlow.pinGaugeResidual;
report.dynamicPeakTransportVelocity = dynamicFlow.peakTransportVelocity;
report.dynamicTravelingWaveResidual = dynamicFlow.travelingWaveResidual;
report.dynamicTrackedPeakOffset = dynamicFlow.trackedPeakOffset;
report.dynamicLengthGaugeStrain = dynamicFlow.lengthGaugeStrain;
report.dynamicLengthGaugeResidual = dynamicFlow.lengthGaugeResidual;
report.shiftedFrameRates = [shiftedCL,shiftedCOmega,shiftedCR];
report.diagnosticRateIndependenceError = diagnosticRateIndependenceError;
report.amplitudeGaugeRateError = amplitudeGaugeRateError;
report.amplitudeGaugeRhsError = amplitudeGaugeRhsError;
report.dynamicInitialPinOffset = dynamicPinOffset;
report.clockTimeSpeed = clockFlow.timeSpeed;
report.clockCanonicalIncrement = clockScaleNew.canonicalTime;
report.clockPhysicalIncrement = clockScaleNew.physicalTime;
report.dynamicInitialWallPeakWidth = dynamicDiagnostics.wallPeakWidth;
report.dynamicStrainError = dynamicFlow.strainError;
report.dynamicStrainRateResidual = dynamicFlow.strainRateResidual;
report.dynamicStrainCondition = dynamicFlow.strainCondition;
report.dynamicOmegaGaugeEnergy = dynamicFlow.omegaGaugeEnergy;
report.dynamicOmegaGaugeResidual = dynamicFlow.omegaGaugeResidual;
report.dynamicOmegaPeakRateResidual = dynamicFlow.omegaPeakRateResidual;
report.dynamicOmegaGaugePeakX = dynamicFlow.omegaGaugePeakX;
report.dynamicOmegaGaugePeakCondition = dynamicFlow.omegaGaugePeakCondition;
report.dynamicGradientEnergyRateRelative = dynamicGradientEnergyRateRelative;
report.dynamicFluxResidual = dynamicFluxResidual;
report.energyGaugeCOmega = energyFlow.c_omega;
report.energyGaugeResidual = energyFlow.omegaGaugeResidual;
report.energyGaugeGradientRateRelative = energyGaugeRateRelative;
report.energyGaugeEnergyComponents = [energyFlow.omegaGaugeEnergyX, ...
    energyFlow.omegaGaugeEnergyY];
report.energyGaugeForcingComponents = [energyFlow.omegaGaugeForcingX, ...
    energyFlow.omegaGaugeForcingY];
report.energyGaugeForcing = energyFlow.omegaGaugeForcing;
report.energyGaugeAbsoluteForcing = ...
    energyFlow.omegaGaugeAbsoluteForcing;
report.energyGaugeForcingCancellationRatio = ...
    energyFlow.omegaGaugeForcingCancellationRatio;
report.nonfiniteEnergyGaugeRejected = nonfiniteEnergyGaugeRejected;
report.energyFluxResidual = energyFluxResidual;
report.noneGaugeCOmega = noneFlow.c_omega;
report.noneFluxResidual = noneFluxResidual;
report.initialPhysicalOmegaPeakRate = initialPhysicalOmegaPeakRate;
report.initialRescaledOmegaPeakRate = initialRescaledOmegaPeakRate;
report.initialReconstructedOmegaPeakRate = initialReconstructedOmegaPeakRate;
report.dynamicGradientEnergyFractions = [ ...
    dynamicDiagnostics.gradientInnerFraction, ...
    dynamicDiagnostics.gradientNearFraction, ...
    dynamicDiagnostics.gradientOuterFraction];
report.dynamicGradientEffectiveLength = ...
    dynamicDiagnostics.gradientEffectiveLength;
report.legacyPointStrainCOmega = legacyFlow.c_omega;
report.legacyPointStrainCondition = legacyFlow.strainCondition;
report.legacyPointStrainRateResidual = legacyStrainRate;

assert(report.constantStateRhsInf < 1e-12 && ...
    report.constantStateVelocityInf < 1e-12, ...
    'ipm:ConstantState','A constant density must remain at rest.');
assert(report.constantScalingRhsInf < 1e-11, ...
    'ipm:ScalingConstantState', ...
    'Open conservative dilation plus 2*c_l*R did not preserve a constant state.');
assert(abs(peakResolution.gridPoints-7/3) < 1e-13 && ...
    abs(peakResolution.areaPoints-107/60) < 1e-13 && ...
    abs(peakResolution.widths-11/3) < 1e-13, ...
    'ipm:ConnectedPeakResolution', ...
    'Adaptive resolution incorrectly counted a separated secondary peak.');
assert(isequal(profileMeasurement.feature, ...
        [0,0.6,1,0.6,0,0.8,0]) && ...
    isequaln(rmfield(profileMeasurement,'feature'),peakResolution) && ...
    isequal(maskedProfileMeasurement.feature,[0,0,0,0,0,0.8,0]) && ...
    maskedProfileMeasurement.peak == 0.8 && ...
    maskedProfileMeasurement.peakIndex == 6, ...
    'ipm:FeatureMeasurement', ...
    'Feature measurement did not preserve profile clamping or masking.');
assert(abs(subgridPeakLocation-1.4) < 1e-13, ...
    'ipm:SubgridPeakLocation', ...
    'Quadratic subgrid peak localization is inaccurate.');
assert(abs(unlimitedRateMagnitude-10) < 1e-13 && ...
    isequal(normalizedRates,[10;8;0]), ...
    'ipm:RateMagnitude', ...
    'The scaling-rate diagnostic changed the supplied rate vector.');
assert(clockFlow.timeSpeed == 1 && ...
    abs(clockScaleNew.canonicalTime-1e-3) < 10*eps && ...
    clockScaleNew.physicalTime > 0, ...
    'ipm:CanonicalClock', ...
    'The canonical clock is not the unmodified integration clock.');
assert(max(abs([anchorCanonicalVelocity,anchorBoundedVelocity, ...
        anchorVelocityAfter,anchorFlow.canonicalTransportAnchorVelocity, ...
        anchorFlow.transportAnchorVelocity,anchorFlowAfter.canonicalCR, ...
        anchorFlowAfter.c_r,anchorScaleAfter.X_shift])) < 1e-11 && ...
    anchorCanonicalSlope < 0 && ...
    anchorFlow.transportAnchorX == anchorOpts.scaling.transportAnchorX && ...
    anchorFlowAfter.transportAnchorX == ...
        anchorOpts.scaling.transportAnchorX, ...
    'ipm:TransportAnchorGauge', ...
    'The fixed x=1 combined-velocity anchor was not preserved.');
assert(anchorSlopeGauge.formulaError < 1e-12 && ...
    anchorSlopeGauge.rateResidual < 1e-12 && ...
    anchorSlopeGauge.recordedResidualError < 1e-12 && ...
    anchorSlopeGauge.amplitudeRateError < 1e-11 && ...
    anchorSlopeGauge.amplitudeRhsError < 1e-11 && ...
    anchorSlopeGauge.amplitudeNormalizedResidualMagnitude < 1e-12 && ...
    anchorSlopeGauge.amplitudeNormalizedResidualSpread < 1e-12 && ...
    anchorSlopeGauge.shortStepRelativeSlopeDrift < 1e-9 && ...
    anchorSlopeGauge.condition > ...
        anchorOpts.scaling.pointStrainConditionFloor && ...
    anchorSlopeGauge.historyFieldsPresent && ...
    anchorSlopeGauge.referencePreserved && ...
    anchorSlopeGauge.shortStepFinite && anchorConditionGuarded, ...
    'ipm:AnchorWallSlopeGauge', ...
    'The exact anchor-wall slope c_omega gauge regression failed.');
assert(quadraticPeakGauge.formulaError < 1e-12 && ...
    quadraticPeakGauge.rateResidual < 1e-12 && ...
    quadraticPeakGauge.residualReconstructionError < 1e-12 && ...
    quadraticPeakGauge.recordedResidualError < 1e-12 && ...
    quadraticPeakGauge.amplitudeRateError < 1e-11 && ...
    quadraticPeakGauge.amplitudeRhsError < 1e-11 && ...
    quadraticPeakGauge.shortStepRelativePeakDrift < 1e-9 && ...
    quadraticPeakGauge.curvature < 0 && ...
    quadraticPeakGauge.curvatureCondition > 0 && ...
    quadraticPeakGauge.weightCondition > 0 && ...
    quadraticPeakGauge.vertexInteriorFraction > 0 && ...
    quadraticPeakGauge.activeNodeMargin >= 0 && ...
    quadraticPeakGauge.weightSumError < 1e-13 && ...
    quadraticPeakGauge.envelopeDerivativeError < 1e-9 && ...
    quadraticPeakGauge.historyFieldsPresent && ...
    quadraticPeakGauge.finalQualityFieldsPresent && ...
    quadraticPeakGauge.contractRecorded && ...
    quadraticPeakGauge.degenerateCasesRejected && ...
    quadraticPeakGauge.shortStepFinite, ...
    'ipm:QuadraticWallOmegaPeakGauge', ...
    'The exact quadratic wall-omega peak c_omega gauge regression failed.');
assert(anchorWindowGauge.formulaError < 1e-12 && ...
