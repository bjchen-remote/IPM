function screen = ipm_gaugelab_run_q512_gauge_cfl_screen(options)
%IPM_GAUGELAB_RUN_Q512_GAUGE_CFL_SCREEN Short q512 gauge-by-CFL screen.
%   SCREEN = IPM_GAUGELAB_RUN_Q512_GAUGE_CFL_SCREEN() registers four
%   independent fresh-root calculations on the anchor-aligned H=1e6 q512
%   factory and performs no PDE solve.  The registered pairs are
%
%       c_omega gauge: wall_omega_quadratic_peak, none
%       CFL:           0.25, 0.50
%
%   Set OPTIONS.execute=true explicitly to run the bounded short screen.
%   Every run starts from the analytic datum through the one-argument
%   ipm.solve entry point.  Checkpoint input is not accepted.  The mesh is
%   fixed and the numerical tuple is high_order/WENO5-FD/SSPRK(5,4).
%
%   Both gauges record the same quadratic-peak telemetry in the maintained
%   solver history.  For `none` it is explicitly counterfactual and never
%   feeds the prescribed c_omega=0 rate.  Solver snapshots, result files,
%   and checkpoints are disabled; the schema-4 screen summary
%   contains the complete scalar history, algebraic audits, bidirectional
%   terminal comparisons, and cost record.
%
%   Hard gates cover only short-window numerical consistency and exact
%   algebraic constraints.  Ranking hints are diagnostic.  In particular,
%   `none` is a prescribed zero selected rate and is ineligible for an
%   empirical c_omega convergence claim.  No result from this screen is
%   asymptotic, truncation, grid-convergence, or blowup evidence.

if nargin < 1 || isempty(options)
    options = struct();
end
settings = resolve_options(options);
require_dependencies();

[outputDirectory,screenId] = create_output_directory(settings.outputRoot);
summaryFile = fullfile(outputDirectory,'gauge_cfl_screen_summary.mat');
manifestFile = fullfile(outputDirectory,'gauge_cfl_screen_manifest.jsonl');
specifications = run_specifications();
[flatOptions,configurations] = registered_configurations( ...
    settings,specifications,screenId,outputDirectory);
[meshAudit,meshPassed] = audit_mesh(flatOptions{1},settings.boxHalfWidth);
[contractAudits,sharedAudit,contractsPassed] = ...
    audit_registered_contracts(flatOptions,configurations, ...
    specifications,settings);
syntheticAudit = synthetic_derived_telemetry_audit();

runs = repmat(empty_run_record(),numel(specifications),1);
for index = 1:numel(specifications)
    runs(index).index = index;
    runs(index).name = specifications(index).name;
    runs(index).gauge = specifications(index).gauge;
    runs(index).cfl = specifications(index).cfl;
    runs(index).selectedRatePrescribed = ...
        strcmp(specifications(index).gauge,'none');
    runs(index).empiricalRateConvergenceEligible = ...
        ~runs(index).selectedRatePrescribed;
    runs(index).freshStart = true;
    runs(index).restartInput = 'none';
    runs(index).checkpointInputAccepted = false;
    runs(index).config = configurations{index};
    runs(index).contractAudit = contractAudits(index);
    runs(index).gaugeRule = ipm.evolve.gaugeContract( ...
        configurations{index},struct('x',flatOptions{index}.customX));
    runs(index).status = 'registered';
end

startedUtc = utc_stamp();
screen = struct( ...
    'schemaVersion',4, ...
    'kind','q512_fresh_gauge_cfl_short_time_screen', ...
    'screenId',screenId, ...
    'status','registered', ...
    'startedUtc',startedUtc, ...
    'completedUtc','', ...
    'executionMode',execution_mode(settings), ...
    'freshRootsOnly',true, ...
    'checkpointInputsAccepted',false, ...
    'pdeSolveCount',0, ...
    'boxFamily','anchor_aligned_q512_large_box_factory', ...
    'boxHalfWidth',settings.boxHalfWidth, ...
    'domain',struct('x',[-settings.boxHalfWidth,settings.boxHalfWidth], ...
        'y',[0,settings.boxHalfWidth]), ...
    'gauges',{{'wall_omega_quadratic_peak','none'}}, ...
    'cflCandidates',[0.25,0.50], ...
    'nonExecutedReference',gradient_energy_reference(), ...
    'requested',requested_summary(settings), ...
    'numericalTuple',numerical_tuple(), ...
    'gaugeContract',gauge_contract(), ...
    'counterfactualDefinition',counterfactual_definition(), ...
    'interpretation',[ ...
        'short_time_numerical_and_algebraic_screen_only_not_' ...
        'asymptotic_truncation_grid_or_blowup_evidence'], ...
    'lateTimeEvidence',false, ...
    'truncationEvidence',false, ...
    'gridConvergenceEvidence',false, ...
    'blowupEvidence',false, ...
    'meshAudit',meshAudit, ...
    'meshPassed',meshPassed, ...
    'contractAudits',contractAudits, ...
    'sharedContractAudit',sharedAudit, ...
    'syntheticDerivedTelemetryAudit',syntheticAudit, ...
    'preflightPassed',meshPassed && contractsPassed && ...
        sharedAudit.passed && syntheticAudit.passed, ...
    'hardLimits',hard_limits(), ...
    'runs',runs, ...
    'cflComparisons',repmat(empty_comparison(),0,1), ...
    'gaugeComparisons',repmat(empty_comparison(),0,1), ...
    'rankingHints',empty_ranking_hints(), ...
    'completedRuns',0, ...
    'successfulRuns',0, ...
    'hardPassed',false, ...
    'orchestrationWallSeconds',NaN, ...
    'outputDirectory',outputDirectory, ...
    'summaryFile',summaryFile, ...
    'manifestFile',manifestFile, ...
    'failures',{{}});
save_summary(summaryFile,screen);
append_manifest(manifestFile,struct( ...
    'event','gauge_cfl_screen_registered', ...
    'timestampUtc',startedUtc, ...
    'screenId',screenId, ...
    'schemaVersion',4, ...
    'executionMode',screen.executionMode, ...
    'freshRootsOnly',true, ...
    'checkpointInputsAccepted',false, ...
    'boxHalfWidth',settings.boxHalfWidth, ...
    'gauges',{screen.gauges}, ...
    'cflCandidates',screen.cflCandidates, ...
    'nonExecutedReference',screen.nonExecutedReference, ...
    'requested',screen.requested, ...
    'preflightPassed',screen.preflightPassed, ...
    'summaryFile',summaryFile));

if ~screen.preflightPassed
    screen.status = 'preflight_rejected';
    screen.failures = preflight_failures(screen);
    screen.completedUtc = utc_stamp();
    save_summary(summaryFile,screen);
    append_manifest(manifestFile,struct( ...
        'event','gauge_cfl_screen_preflight_rejected', ...
        'timestampUtc',screen.completedUtc, ...
        'screenId',screenId, ...
        'failures',{screen.failures}));
    error('ipm:GaugeLabQ512GaugeCflPreflight', ...
        'The q512 gauge-by-CFL screen failed preflight; inspect %s.', ...
        summaryFile);
end

if ~settings.execute
    for index = 1:numel(screen.runs)
        screen.runs(index).status = 'preflight_only';
    end
    screen.status = 'preflight_complete';
    screen.completedUtc = utc_stamp();
    screen.failures = {};
    save_summary(summaryFile,screen);
    append_manifest(manifestFile,struct( ...
        'event','gauge_cfl_screen_preflight_complete', ...
        'timestampUtc',screen.completedUtc, ...
        'screenId',screenId, ...
        'pdeSolveCount',0, ...
        'resultFilesWritten',0, ...
        'checkpointFilesWritten',0));
    if settings.verbose
        fprintf(['Q512 GAUGE x CFL PREFLIGHT: 4 fresh roots, H=%.0e, ' ...
            'summary=%s\n'],settings.boxHalfWidth,summaryFile);
    end
    return
end

orchestrationClock = tic;
terminalResults = cell(numel(specifications),1);
for index = 1:numel(specifications)
    specification = specifications(index);
    run = screen.runs(index);
    run.status = 'running';
    run.startedUtc = utc_stamp();
    screen.runs(index) = run;
    save_summary(summaryFile,screen);
    append_manifest(manifestFile,struct( ...
        'event','fresh_root_started', ...
        'timestampUtc',run.startedUtc, ...
        'screenId',screenId, ...
        'run',run.name, ...
        'gauge',run.gauge, ...
        'cfl',run.cfl, ...
        'freshStart',true, ...
        'restartInput','none'));

    solveClock = tic;
    try
        % One argument is deliberate: no checkpoint can enter a screen root.
        screen.pdeSolveCount = screen.pdeSolveCount+1;
        result = ipm.solve(flatOptions{index});
        run.cost.solveWallSeconds = toc(solveClock);
        result = ipm.output.validate(result);
        [telemetry,counterfactualWallSeconds] = ...
            summarize_telemetry(result,specification);
        run.cost.counterfactualWallSeconds = counterfactualWallSeconds;
        run.cost.totalWallSeconds = run.cost.solveWallSeconds+ ...
            counterfactualWallSeconds;
        run.cost.steps = result.state.steps;
        run.cost.solveWallSecondsPerStep = safe_per_step( ...
            run.cost.solveWallSeconds,result.state.steps);
        run.cost.totalWallSecondsPerStep = safe_per_step( ...
            run.cost.totalWallSeconds,result.state.steps);
        run.telemetry = telemetry;
        run.stopReason = result.state.stopReason;
        run.resultMetadata = result.metadata;
        run.resultFile = '';
        run.solverResultRetained = false;
        [run.postAudit,run.hardPassed] = audit_executed_run( ...
            result,run,settings,screen.hardLimits);
        if run.hardPassed
            run.status = 'completed';
        else
            run.status = 'postrun_rejected';
        end
        terminalResults{index} = strip_snapshots(result);
    catch exception
        run.cost.solveWallSeconds = finite_elapsed( ...
            run.cost.solveWallSeconds,solveClock);
        run.status = 'failed';
        run.errorIdentifier = exception.identifier;
        run.errorMessage = exception.message;
        run.hardPassed = false;
    end
    run.completedUtc = utc_stamp();
    screen.runs(index) = run;
    screen.completedRuns = index;
    save_summary(summaryFile,screen);
    append_manifest(manifestFile,run_manifest_record( ...
        screenId,run));
end

screen.successfulRuns = nnz([screen.runs.hardPassed]);
if all(~cellfun(@isempty,terminalResults))
    [screen.cflComparisons,screen.gaugeComparisons] = ...
        build_comparisons(terminalResults,screen.runs, ...
        specifications,settings.comparisonWindowCap,screen.hardLimits);
end
screen.rankingHints = build_ranking_hints( ...
    screen.runs,screen.cflComparisons,screen.gaugeComparisons);
screen.orchestrationWallSeconds = toc(orchestrationClock);
comparisonPass = all([screen.cflComparisons.hardPassed]) && ...
    all([screen.gaugeComparisons.hardPassed]) && ...
    numel(screen.cflComparisons) == 2 && ...
    numel(screen.gaugeComparisons) == 2;
screen.hardPassed = screen.successfulRuns == numel(screen.runs) && ...
    comparisonPass;
screen.failures = execution_failures(screen);
if screen.hardPassed
    screen.status = 'short_screen_passed';
elseif screen.successfulRuns < numel(screen.runs)
    screen.status = 'run_gate_failed';
else
    screen.status = 'comparison_gate_failed';
end
screen.completedUtc = utc_stamp();
save_summary(summaryFile,screen);
append_manifest(manifestFile,struct( ...
    'event','gauge_cfl_screen_finished', ...
    'timestampUtc',screen.completedUtc, ...
    'screenId',screenId, ...
    'status',screen.status, ...
    'pdeSolveCount',screen.pdeSolveCount, ...
    'successfulRuns',screen.successfulRuns, ...
    'hardPassed',screen.hardPassed, ...
    'cflComparisonsPassed',all([screen.cflComparisons.hardPassed]), ...
    'gaugeComparisonsPassed',all([screen.gaugeComparisons.hardPassed]), ...
    'orchestrationWallSeconds',screen.orchestrationWallSeconds, ...
    'failures',{screen.failures}));

if settings.verbose
    fprintf(['Q512 GAUGE x CFL SCREEN: status=%s, runs=%d/%d, ' ...
        'wall=%.3f s, summary=%s\n'],screen.status, ...
        screen.successfulRuns,numel(screen.runs), ...
        screen.orchestrationWallSeconds,summaryFile);
end
end

function settings = resolve_options(options)
if ~isstruct(options) || ~isscalar(options)
    error('ipm:GaugeLabQ512GaugeCflOptions', ...
        'options must be a scalar structure.');
end
allowed = {'execute','preflightOnly','outputRoot','verbose', ...
    'physicalFinalTime','canonicalFinalTime','maxDt','maxSteps', ...
    'outputEvery','comparisonWindowCap'};
unknown = setdiff(fieldnames(options),allowed,'stable');
if ~isempty(unknown)
    error('ipm:GaugeLabQ512GaugeCflOptions', ...
        'Unknown option(s): %s.',strjoin(unknown,', '));
end
executeSpecified = isfield(options,'execute');
settings.execute = logical_option(options,'execute',false);
settings.preflightOnly = logical_option(options,'preflightOnly',false);
if settings.preflightOnly
    if executeSpecified && settings.execute
        error('ipm:GaugeLabQ512GaugeCflOptions', ...
            'execute=true and preflightOnly=true are contradictory.');
    end
    settings.execute = false;
elseif ~settings.execute
    settings.preflightOnly = true;
end
settings.outputRoot = path_option( ...
    options,'outputRoot',default_output_root());
settings.verbose = logical_option(options,'verbose',true);
settings.physicalFinalTime = numeric_option( ...
    options,'physicalFinalTime',0.03);
settings.canonicalFinalTime = numeric_option( ...
    options,'canonicalFinalTime',0.05);
settings.maxDt = numeric_option(options,'maxDt',0.004);
settings.maxSteps = numeric_option(options,'maxSteps',128);
settings.outputEvery = numeric_option(options,'outputEvery',1e-10);
settings.comparisonWindowCap = numeric_option( ...
    options,'comparisonWindowCap',[-2,2,2]);
settings.boxHalfWidth = 1e6;
settings.minimumRecordCount = 16;

validateattributes(settings.physicalFinalTime,{'numeric'}, ...
    {'scalar','real','finite','positive','<=',0.05},mfilename, ...
    'physicalFinalTime');
validateattributes(settings.canonicalFinalTime,{'numeric'}, ...
    {'scalar','real','finite','positive','<=',0.05},mfilename, ...
    'canonicalFinalTime');
validateattributes(settings.maxDt,{'numeric'}, ...
    {'scalar','real','finite','positive','<=',0.004},mfilename,'maxDt');
validateattributes(settings.maxSteps,{'numeric'}, ...
    {'scalar','real','finite','integer','positive','<=',128}, ...
    mfilename,'maxSteps');
validateattributes(settings.outputEvery,{'numeric'}, ...
    {'scalar','real','finite','positive','<=',1e-10},mfilename, ...
    'outputEvery');
validateattributes(settings.comparisonWindowCap,{'numeric'}, ...
    {'vector','numel',3,'real','finite'},mfilename, ...
    'comparisonWindowCap');
settings.comparisonWindowCap = settings.comparisonWindowCap(:)';
if settings.comparisonWindowCap(2) <= ...
        settings.comparisonWindowCap(1) || ...
        settings.comparisonWindowCap(3) <= 0
    error('ipm:GaugeLabQ512GaugeCflWindow', ...
        'comparisonWindowCap must be [xMin,xMax,yMax].');
end
end

function specifications = run_specifications()
gauges = {'wall_omega_quadratic_peak','none'};
cflValues = [0.25,0.50];
specifications = repmat(struct('name','','gauge','','cfl',NaN),4,1);
cursor = 0;
for gaugeIndex = 1:numel(gauges)
    for cflIndex = 1:numel(cflValues)
        cursor = cursor+1;
        gauge = gauges{gaugeIndex};
        shortGauge = gauge;
        if strcmp(gauge,'wall_omega_quadratic_peak')
            shortGauge = 'quadratic_peak';
        end
        specifications(cursor) = struct( ...
            'name',sprintf('%s_cfl_%03d',shortGauge, ...
                round(100*cflValues(cflIndex))), ...
            'gauge',gauge, ...
            'cfl',cflValues(cflIndex));
    end
end
end

function [flatOptions,configurations] = registered_configurations( ...
        settings,specifications,screenId,outputDirectory)
flatOptions = cell(numel(specifications),1);
configurations = cell(numel(specifications),1);
baseMetadata = run_metadata(screenId,specifications(1));
overrides = struct( ...
    'xlim',[-settings.boxHalfWidth,settings.boxHalfWidth], ...
    'ymax',settings.boxHalfWidth, ...
    'physicalFinalTime',settings.physicalFinalTime, ...
    'finalTime',settings.canonicalFinalTime, ...
    'maxDt',settings.maxDt, ...
    'maxSteps',settings.maxSteps, ...
    'outputEvery',settings.outputEvery, ...
    'cfl',specifications(1).cfl, ...
    'rescalingMode','dynamic', ...
    'dynamicScaleGeometry','isotropic', ...
    'scalingContract','exact_gauge_no_feedback_v1', ...
    'lengthGauge','transport_anchor', ...
    'transportAnchorX',1, ...
    'cOmegaGauge',specifications(1).gauge, ...
    'lengthScaleGain',1, ...
    'widthGaugeGain',0, ...
    'omegaGaugeGain',0, ...
    'travelingWaveGain',0, ...
    'spatialDiscretization','high_order', ...
    'transportScheme','weno5_fd', ...
    'timeIntegrator','ssprk54', ...
    'remeshTransferScheme','high_order', ...
    'initialAnalyticRemesh',false, ...
    'adaptiveRemesh',false, ...
    'remeshMaximumCellRatio',1.08, ...
    'resultFile',fullfile(outputDirectory, ...
        'solver_result_must_not_exist_quadratic_peak_cfl_025.mat'), ...
    'saveResults',false, ...
    'storeSnapshots',false, ...
    'makePlots',false, ...
    'livePlot',false, ...
    'writeVideo',false, ...
    'verbose',false, ...
    'caseMetadata',baseMetadata);
flatOptions{1} = fourth_order_blowup_case( ...
    'coordinated_log_anchor_F80_R20_large_box_quadrant_512', ...
    overrides);
for index = 1:numel(specifications)
    if index > 1
        flatOptions{index} = flatOptions{1};
    end
    specification = specifications(index);
    flatOptions{index}.cOmegaGauge = specification.gauge;
    flatOptions{index}.cfl = specification.cfl;
    flatOptions{index}.resultFile = fullfile(outputDirectory, ...
        ['solver_result_must_not_exist_',specification.name,'.mat']);
    metadata = run_metadata(screenId,specification);
    flatOptions{index}.caseMetadata. ...
        q512GaugeCflShortScreen = metadata.q512GaugeCflShortScreen;
    configurations{index} = ipm.config.resolve(flatOptions{index});
end
end

