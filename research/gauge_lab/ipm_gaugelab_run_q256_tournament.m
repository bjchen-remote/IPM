function [ranking,winner] = rank_runs(runs)
eligible = find([runs.eligible]);
if isempty(eligible)
    ranking = {};
    winner = '';
    return;
end
score = NaN(numel(eligible),6);
for row = 1:numel(eligible)
    run = runs(eligible(row));
    score(row,:) = [max(abs([ ...
        run.audit.canonicalCL.relativeTrendAcrossWindow, ...
        run.audit.canonicalCOmega.relativeTrendAcrossWindow])),max( ...
        run.audit.canonicalCL.detrendedRelativeRms, ...
        run.audit.canonicalCOmega.detrendedRelativeRms), ...
        abs(run.audit.canonicalKappa.relativeTrendAcrossWindow), ...
        run.pairwisePhysicalCovariance.worst.physicalRhoXRelativeDifference, ...
        run.pairwisePhysicalCovariance.worst.omegaRelativeL2, ...
        run.elapsedSeconds];
end
if any(~isfinite(score),'all')
    error('ipm:GaugeLabNonfiniteRanking', ...
        'An eligible candidate has a nonfinite tournament score.');
end
[~,order] = sortrows(score,1:size(score,2));
ranking = {runs(eligible(order)).cOmegaGauge};
winner = ranking{1};
end

