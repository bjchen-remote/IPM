function gaugeName = checkpoint_signature_c_omega_gauge(signature)
gaugeName = '';
if complete_checkpoint_signature(signature) && ...
        isstruct(signature.config) && isscalar(signature.config) && ...
        isfield(signature.config,'scaling') && ...
        isstruct(signature.config.scaling) && ...
        isscalar(signature.config.scaling) && ...
        isfield(signature.config.scaling,'cOmegaGauge') && ...
        is_text(signature.config.scaling.cOmegaGauge)
    gaugeName = char(signature.config.scaling.cOmegaGauge);
end
end

function passed = checkpoint_signature_gauge_matches(signature,gaugeName)
passed = allowed_c_omega_gauge(gaugeName) && ...
    strcmp(checkpoint_signature_c_omega_gauge(signature),char(gaugeName));
end

function passed = signature_state_matches_event(signature,event)
passed = complete_checkpoint_signature(signature) && ...
    is_finite_numeric_scalar(signature.step) && ...
    signature.step == event.parentStep && ...
    isstruct(signature.scale) && isscalar(signature.scale) && ...
    all(isfield(signature.scale,{'canonicalTime','physicalTime'})) && ...
    scalar_close(signature.scale.canonicalTime, ...
        event.parentCanonicalTime) && ...
    scalar_close(signature.scale.physicalTime,event.parentPhysicalTime) && ...
    is_finite_numeric_scalar(signature.normalizedTime) && ...
    scalar_close(signature.normalizedTime,event.parentCanonicalTime) && ...
    isnumeric(signature.x) && isnumeric(signature.y) && ...
    numel(signature.x) == 1025 && numel(signature.y) == 513 && ...
    isfield(event,'cOmegaGauge') && ...
    checkpoint_signature_gauge_matches( ...
        signature,event.cOmegaGauge);
end

function passed = signature_commits_chain_prefix(signature,prefix,rootRunId)
passed = complete_checkpoint_signature(signature) && ...
    isstruct(signature.config) && isscalar(signature.config) && ...
    isfield(signature.config,'output') && ...
    isstruct(signature.config.output) && ...
    isfield(signature.config.output,'caseMetadata') && ...
    isstruct(signature.runMetadata) && ...
    isfield(signature.runMetadata,'caseMetadata');
if ~passed
    return
end
metadata = signature.config.output.caseMetadata;
passed = isstruct(metadata) && isscalar(metadata) && ...
    isfield(metadata,'q512GaugeRoot') && ...
    isstruct(metadata.q512GaugeRoot) && ...
    isscalar(metadata.q512GaugeRoot) && ...
    isfield(metadata.q512GaugeRoot,'runId') && ...
    isfield(metadata.q512GaugeRoot,'cOmegaGauge') && ...
    strcmp(char(metadata.q512GaugeRoot.runId),rootRunId) && ...
    checkpoint_signature_gauge_matches( ...
        signature,metadata.q512GaugeRoot.cOmegaGauge) && ...
    isequaln(signature.runMetadata.caseMetadata,metadata);
if ~passed
    return
end
if isempty(prefix)
    passed = ~isfield(metadata,'q512ContinuationChain') && ...
        ~isfield(metadata,'q512ContinuationCurrent') && ...
        (~isfield(signature.runMetadata,'resumeCount') || ...
        isequal(signature.runMetadata.resumeCount,0));
else
    canonicalPrefix = canonical_compare_value(prefix);
    passed = isfield(metadata,'q512ContinuationChain') && ...
        isfield(metadata,'q512ContinuationCurrent') && ...
        isequaln(metadata.q512ContinuationChain,canonicalPrefix) && ...
        isequaln(metadata.q512ContinuationCurrent, ...
            canonicalPrefix{end}) && ...
        isfield(signature.runMetadata,'resumeCount') && ...
        isequal(signature.runMetadata.resumeCount,numel(prefix));
end
end

function output = canonical_compare_value(input)
if isa(input,'function_handle')
    output = struct('kind','function_handle','text',func2str(input));
elseif isstruct(input)
    if ~isscalar(input)
        output = arrayfun(@canonical_compare_value,input, ...
            'UniformOutput',false);
        return
    end
    output = struct();
    names = sort(fieldnames(input));
    for index = 1:numel(names)
        output.(names{index}) = canonical_compare_value(input.(names{index}));
    end
elseif iscell(input)
    output = cell(size(input));
    for index = 1:numel(input)
        output{index} = canonical_compare_value(input{index});
    end
else
    output = input;
end
end

