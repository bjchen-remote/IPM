function checks = comparison_checks( ...
        reference,candidate,endpoint,physical,rateDiagnostic, ...
        physicalTimeDifference,limits)
checks = struct();
checks.rootPostAudits = reference.integrity.postAuditPassed && ...
    candidate.integrity.postAuditPassed;
checks.trustedTerminals = reference.integrity.trustedTerminal && ...
    candidate.integrity.trustedTerminal;
checks.exactContracts = reference.integrity.exactContract && ...
    candidate.integrity.exactContract;
checks.recordedTimestepSamples = ...
    reference.timestep.acceptedStepSampleCount > 0 && ...
    candidate.timestep.acceptedStepSampleCount > 0;
checks.completeTimestepCoverage = ...
    reference.timestep.outputCadenceAtOrBelowMinimumDt && ...
    candidate.timestep.outputCadenceAtOrBelowMinimumDt && ...
    reference.timestep.completeAcceptedStepCoverage && ...
    candidate.timestep.completeAcceptedStepCoverage;
checks.maximumDtRespected = reference.timestep.maximumDtRespected && ...
    candidate.timestep.maximumDtRespected;
checks.maximumCflRespected = reference.timestep.maximumCflRespected && ...
    candidate.timestep.maximumCflRespected;
checks.physicalEndpoint = abs(physicalTimeDifference) <= ...
    limits.maximumPhysicalEndpointDifference;
checks.canonicalEndpoint = ...
    abs(endpoint.canonicalTimeRelativeDifference) <= ...
    limits.maximumCanonicalEndpointRelativeDifference;
checks.terminalCL = abs(endpoint.cLRelativeDifference) <= ...
    limits.maximumTerminalCLRelativeDifference;
checks.terminalCOmega = abs(endpoint.cOmegaRelativeDifference) <= ...
    limits.maximumTerminalCOmegaRelativeDifference;
checks.terminalKappa = abs(endpoint.kappaRelativeDifference) <= ...
    limits.maximumTerminalKappaRelativeDifference;
checks.terminalCOmegaOverCL = ...
    abs(endpoint.cOmegaOverCLRelativeDifference) <= ...
    limits.maximumTerminalRateRatioRelativeDifference;
checks.terminalKappaOverCL = ...
    abs(endpoint.cLMinusCOmegaOverCLRelativeDifference) <= ...
    limits.maximumTerminalRateRatioRelativeDifference;
checks.physicalRhoX = ...
    abs(endpoint.physicalRhoXRelativeDifference) <= ...
    limits.maximumPhysicalRhoXRelativeDifference;
checks.rhoRelativeL2 = physical.rhoRelativeL2 <= ...
    limits.maximumRhoRelativeL2;
checks.omegaRelativeL2 = physical.omegaRelativeL2 <= ...
    limits.maximumOmegaRelativeL2;
checks.rhoAbsoluteInf = physical.rhoAbsoluteInf <= ...
    limits.maximumRhoAbsoluteInf;
checks.omegaAbsoluteInf = physical.omegaAbsoluteInf <= ...
    limits.maximumOmegaAbsoluteInf;
checks.labPeakShift = physical.labPeakShift <= ...
    limits.maximumLabPeakShift;
checks.wallPeak = physical.wallPeakRelativeDifference <= ...
    limits.maximumWallPeakRelativeDifference;
checks.wallWidth = physical.wallWidthRelativeDifference <= ...
    limits.maximumWallWidthRelativeDifference;
checks.rateDiagnosticsWhenAvailable = ...
    ~rateDiagnostic.appliedToHardGate || rateDiagnostic.hardPassed;
end

function window = common_window(reference,candidate,cap)
window = [max([cap(1),min(reference.grid.comovingPhysicalX), ...
    min(candidate.grid.comovingPhysicalX)]), ...
    min([cap(2),max(reference.grid.comovingPhysicalX), ...
    max(candidate.grid.comovingPhysicalX)]), ...
    min([cap(3),max(reference.grid.physicalY), ...
    max(candidate.grid.physicalY)])];
if window(2) <= window(1) || window(3) <= 0
    error('ipm:GaugeLabQ512CflLadderWindow', ...
        'The two CFL results have no common physical comparison window.');
end
end

