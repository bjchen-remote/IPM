function name = rung_name(halfWidth)
% Seventeen significant digits give a one-to-one text representation for
% distinct finite IEEE-754 doubles; rounded scientific notation did not.
raw = sprintf('large_%.17g',halfWidth);
name = strrep(raw,'+','');
name = strrep(name,'-','m');
name = strrep(name,'.','p');
end

