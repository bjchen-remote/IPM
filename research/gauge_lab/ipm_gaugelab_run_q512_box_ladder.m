function gate = assess_campaign_box_gate(ladder)
gate = empty_box_gate();
gate.targetHalfWidth = ladder.campaignBoxHalfWidth;
large = find(strcmp({ladder.rungs.boxMode},'large_box'));
target = large([ladder.rungs(large).boxHalfWidth] == ...
    ladder.campaignBoxHalfWidth);
if numel(target) ~= 1
    gate.status = 'campaign_box_rung_unavailable';
    gate.failures = {'campaignBoxRungAvailable'};
    return
end
target = target(1);
smaller = large([ladder.rungs(large).boxHalfWidth] < ...
    ladder.campaignBoxHalfWidth);
if isempty(smaller)
    gate.status = 'predecessor_rung_unavailable';
    gate.failures = {'campaignBoxPredecessorAvailable'};
    return
end
[~,position] = max([ladder.rungs(smaller).boxHalfWidth]);
reference = smaller(position);
gate.referenceRung = ladder.rungs(reference).name;
gate.candidateRung = ladder.rungs(target).name;
gate.referenceHalfWidth = ladder.rungs(reference).boxHalfWidth;
gate.candidateHalfWidth = ladder.rungs(target).boxHalfWidth;
matches = arrayfun(@(record) ...
    strcmp(record.referenceRung,gate.referenceRung) && ...
    strcmp(record.candidateRung,gate.candidateRung), ...
    ladder.successiveLargeComparisons);
if nnz(matches) ~= 1
    gate.status = 'campaign_box_comparison_unavailable';
    gate.failures = {'campaignBoxComparisonAvailable'};
    return
end
comparison = ladder.successiveLargeComparisons(matches).comparison;
gate.comparison = comparison;
if ~comparison.available
    gate.status = 'campaign_box_comparison_unavailable';
    gate.failures = {'campaignBoxComparisonAvailable'};
    return
end
worst = comparison.symmetricWorst;
limits = ladder.hardLimits;
terminalFar = ladder.rungs(target).metrics.farBoundary.terminal;
checks = struct();
checks.campaignBoxComparisonAvailable = comparison.available;
checks.allRootsPostAudited = all([ladder.rungs.postAuditPassed]);
largeRungs = strcmp({ladder.rungs.boxMode},'large_box');
checks.allLargeBoxTransportAnchorsAreExactNodes = ...
    all([ladder.rungs(largeRungs).anchorIsGridNode]);
checks.physicalEndpoint = comparison.available && ...
    abs(comparison.physicalTimeDifference) <= ...
    limits.maximumPhysicalEndpointDifference;
checks.rhoRelativeL2 = comparison.available && ...
    worst.rhoRelativeL2 <= limits.maximumRhoRelativeL2;
checks.omegaRelativeL2 = comparison.available && ...
    worst.omegaRelativeL2 <= limits.maximumOmegaRelativeL2;
checks.rhoAbsoluteInf = comparison.available && ...
    worst.rhoAbsoluteInf <= limits.maximumRhoAbsoluteInf;
checks.omegaAbsoluteInf = comparison.available && ...
    worst.omegaAbsoluteInf <= limits.maximumOmegaAbsoluteInf;
checks.labPeakShift = comparison.available && ...
    worst.labPeakShift <= limits.maximumLabPeakShift;
checks.wallPeak = comparison.available && ...
    worst.wallPeakRelativeDifference <= ...
    limits.maximumWallPeakRelativeDifference;
checks.wallWidth = comparison.available && ...
    worst.wallWidthRelativeDifference <= ...
    limits.maximumWallWidthRelativeDifference;
checks.physicalRhoX = comparison.available && ...
    worst.physicalRhoXRelativeDifference <= ...
    limits.maximumPhysicalRhoXRelativeDifference;
checks.canonicalCL = comparison.available && ...
    worst.canonicalCLRelativeDifference <= ...
    limits.maximumCanonicalCLRelativeDifference;
checks.canonicalCOmega = comparison.available && ...
    worst.canonicalCOmegaRelativeDifference <= ...
    limits.maximumCanonicalCOmegaRelativeDifference;
checks.gradientEnergy = comparison.available && ...
    worst.gradientEnergyRelativeDifference <= ...
    limits.maximumGradientEnergyRelativeDifference;
checks.gradientForcing = comparison.available && ...
    worst.gradientForcingRelativeDifference <= ...
    limits.maximumGradientForcingRelativeDifference;
checks.gradientAbsoluteForcing = comparison.available && ...
    worst.gradientAbsoluteForcingRelativeDifference <= ...
    limits.maximumGradientAbsoluteForcingRelativeDifference;
checks.forcingCancellationRatio = comparison.available && ...
    worst.forcingCancellationRatioAbsoluteDifference <= ...
    limits.maximumForcingCancellationRatioAbsoluteDifference;
checks.campaignFarSource = isfinite(terminalFar.sourceRatio) && ...
    terminalFar.sourceRatio <= limits.maximumFarBoundarySourceRatio;
checks.campaignFarVelocity = isfinite(terminalFar.velocityRatio) && ...
    terminalFar.velocityRatio <= limits.maximumFarBoundaryVelocityRatio;
gate.checks = checks;
gate.failures = failed_checks(checks);
gate.passed = isempty(gate.failures);
if gate.passed
    gate.status = 'passed';
else
    gate.status = 'gate_failed';
end
end

