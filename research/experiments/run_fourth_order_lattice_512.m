function products = run_fourth_order_lattice_512(coarseSource,caseName)
%RUN_FOURTH_ORDER_LATTICE_512 Run and analyze the matched final q512 case.
%   COARSESOURCE is the optimized q256 result or assessment.  The solver
%   result and its local assessment are saved before any cross-grid plots
%   are attempted, so a postprocessing failure cannot discard the long run.
%   RUN_FOURTH_ORDER_LATTICE_512(COARSESOURCE,CASENAME) selects the explicit
%   q512 factory case.  A preflight requires the corresponding long q256
%   case, identical numerical tuple and mapping provenance, and strict
%   nesting of both realized axes before the expensive solve begins.

experimentDirectory = fileparts(mfilename('fullpath'));
researchDirectory = fileparts(experimentDirectory);
projectDirectory = fileparts(researchDirectory);
analysisDirectory = fullfile(researchDirectory,'analysis');
addpath(projectDirectory,experimentDirectory,analysisDirectory);
verificationDirectory = fullfile(projectDirectory,'result','verification');
if ~isfolder(verificationDirectory)
    mkdir(verificationDirectory);
end
if nargin < 1 || isempty(coarseSource)
    coarseSource = fullfile(verificationDirectory, ...
        ['fourth_order_lat_validation_analytic_lorentzian_a28_w020_' ...
        'c114_quadrant_256_q256_t210.mat']);
end
if nargin < 2 || isempty(caseName)
    caseName = 'analytic_lorentzian_A28_w020_c114_quadrant_512';
end
caseName = validatestring(caseName,{ ...
    'analytic_lorentzian_A28_w020_c114_quadrant_512', ...
    'coordinated_log_F90_R20_c114_quadrant_512', ...
    'coordinated_log_F92_R20_c114_quadrant_512'}, ...
    mfilename,'caseName');
if ~(ischar(coarseSource) || ...
        (isstring(coarseSource) && isscalar(coarseSource)) || ...
        (isstruct(coarseSource) && isscalar(coarseSource)))
    error('ipm:FourthOrderLattice512CoarseSource', ...
        'coarseSource must identify one scalar q256 result or assessment.');
end
if (ischar(coarseSource) || isstring(coarseSource)) && ...
        ~isfile(char(coarseSource))
    error('ipm:FourthOrderLattice512CoarseMissing', ...
        'The optimized q256 source does not exist: %s',char(coarseSource));
end

safeCaseName = lower(regexprep(caseName,'[^A-Za-z0-9]+','_'));
stem = ['fourth_order_active_',safeCaseName,'_t210_dt002'];
requestedResultFile = ipm.output.uniquePath( ...
    fullfile(verificationDirectory,[stem,'.mat']),'lat_q512');
opts = fourth_order_blowup_case(caseName, ...
    struct('resultFile',requestedResultFile));
assert_matching_mapping(coarseSource,opts);

startedAt = datetime('now','TimeZone','local');
fprintf(['Final LAT q512 run started %s\n' ...
    '  stored nodes: %d x %d\n' ...
    '  first-quadrant cells: %d x %d\n' ...
    '  requested physical final time: %.8g\n' ...
    '  maximum steps: %d\n  result: %s\n'], ...
    char(startedAt),opts.nx,opts.ny,(opts.nx-1)/2,opts.ny-1, ...
    opts.physicalFinalTime,opts.maxSteps,requestedResultFile);
wallClock = tic;
result = ipm.solve(opts);
elapsedSeconds = toc(wallClock);

resultFile = char(result.metadata.resultFile);
[resultDirectory,resultStem] = fileparts(resultFile);
assessmentFile = fullfile(resultDirectory,[resultStem,'_assessment.mat']);
growthFigureFile = fullfile(resultDirectory,[resultStem,'_growth.png']);
productsFile = fullfile(resultDirectory,[resultStem,'_products.mat']);
assessment = ipm_assess_fourth_order_blowup(result);
save(assessmentFile,'assessment');

refinementAssessment = struct();
refinementAssessmentSucceeded = false;
refinementAssessmentError = struct('identifier','','message','');
try
    refinementAssessmentFile = ipm.output.uniquePath(fullfile( ...
        resultDirectory,[resultStem,'_refinement_assessment.mat']), ...
        result.metadata.caseId);
    refinementAssessment = ipm_assess_lattice_refinement( ...
        coarseSource,result);
    save(refinementAssessmentFile,'refinementAssessment');
    refinementAssessmentSucceeded = true;
catch exception
    refinementAssessmentFile = '';
    refinementAssessmentError = struct( ...
        'identifier',exception.identifier, ...
        'message',exception.message);
    warning('ipm:FourthOrderLattice512RefinementAssessment', ...
        ['The q512 solver result and local assessment were saved, but ' ...
        'the cross-grid refinement assessment failed (%s): %s'], ...
        exception.identifier,exception.message);
end
[figureHandle,physicalPlot] = ipm_plot_maximum_growth( ...
    assessment,growthFigureFile);
close(figureHandle);

comparisonStem = ['fourth_order_active_',safeCaseName,'_q256_vs_q512'];
resolutionFigureFile = ipm.output.uniquePath(fullfile( ...
    verificationDirectory,[comparisonStem,'_growth.png']), ...
    result.metadata.caseId);
[figureHandle,resolutionComparison] = ...
    ipm_compare_maximum_growth_resolution( ...
    coarseSource,result,resolutionFigureFile);
close(figureHandle);
tauFigureFile = ipm.output.uniquePath(fullfile( ...
    verificationDirectory,[comparisonStem,'_tau_growth.png']), ...
    result.metadata.caseId);
[figureHandle,tauAnalysis] = ipm_plot_tau_growth( ...
    coarseSource,result,tauFigureFile);
close(figureHandle);

canonicalFigureFile = '';
canonicalModels = struct();
if exist('ipm_plot_canonical_maximum_models','file') == 2
    canonicalFigureFile = ipm.output.uniquePath(fullfile( ...
        verificationDirectory,[comparisonStem,'_canonical_models.png']), ...
        result.metadata.caseId);
    [figureHandle,canonicalModels] = ...
        ipm_plot_canonical_maximum_models( ...
        coarseSource,result,canonicalFigureFile);
    close(figureHandle);
end

old256 = fullfile(verificationDirectory, ...
    'fourth_order_active_analytic_A16_w055_t195_dt002.mat');
old384 = fullfile(verificationDirectory, ...
    'fourth_order_active_analytic_A16_w055_q384_t205_dt002.mat');
crossGrid = struct();
if isfile(old256)
    fileName = ipm.output.uniquePath(fullfile(verificationDirectory, ...
        'fourth_order_active_old_q256_vs_optimized_q256_growth.png'), ...
        result.metadata.caseId);
    [figureHandle,crossGrid.old256ToOptimized256] = ...
        ipm_compare_maximum_growth_resolution( ...
        old256,coarseSource,fileName);
    close(figureHandle);
end
if isfile(old384)
    fileName = ipm.output.uniquePath(fullfile(verificationDirectory, ...
        'fourth_order_active_old_q384_vs_final_q512_growth.png'), ...
        result.metadata.caseId);
    [figureHandle,crossGrid.old384ToFinal512] = ...
        ipm_compare_maximum_growth_resolution(old384,result,fileName);
    close(figureHandle);
end

products = struct( ...
    'caseName',opts.caseMetadata.caseName, ...
    'startedAt',startedAt, ...
    'completedAt',datetime('now','TimeZone','local'), ...
    'elapsedSeconds',elapsedSeconds, ...
    'coarseSource',coarseSource, ...
    'resultFile',resultFile, ...
    'assessmentFile',assessmentFile, ...
    'refinementAssessmentFile',refinementAssessmentFile, ...
    'refinementAssessmentSucceeded', ...
        refinementAssessmentSucceeded, ...
    'refinementAssessmentError',refinementAssessmentError, ...
    'growthFigureFile',growthFigureFile, ...
    'resolutionFigureFile',resolutionFigureFile, ...
    'tauFigureFile',tauAnalysis.outputFile, ...
    'tauAnalysisFile',tauAnalysis.analysisFile, ...
    'canonicalFigureFile',canonicalFigureFile, ...
    'productsFile',productsFile, ...
    'stopReason',result.state.stopReason, ...
    'stopTime',result.state.physicalTime, ...
    'trustedThroughTime',assessment.trustedThroughTime, ...
    'trustedThroughCanonicalTau', ...
        assessment.trustedThroughCanonicalTau, ...
    'steps',result.state.steps, ...
    'refinementAssessment',refinementAssessment, ...
    'physicalPlot',physicalPlot, ...
    'resolutionComparison',resolutionComparison, ...
    'tauAnalysis',tauAnalysis, ...
    'canonicalModels',canonicalModels, ...
    'crossGrid',crossGrid);
save(productsFile,'products','-v7.3');
fprintf(['Final LAT q512 run completed in %.3f s\n' ...
    '  stop reason: %s\n  raw/trusted physical time: %.12g / %.12g\n' ...
    '  assessment: %s\n  tau comparison: %s\n'], ...
    elapsedSeconds,result.state.stopReason,result.state.physicalTime, ...
    assessment.trustedThroughTime,assessmentFile,tauAnalysis.outputFile);
end

function assert_matching_mapping(coarseSource,fineOptions)
coarseResult = ipm.output.validate(source_result(coarseSource));
if ~isfield(coarseResult,'grid') || ...
        ~all(isfield(coarseResult.grid,{'x','y'}))
    error('ipm:FourthOrderLattice512CoarseGrid', ...
        'The q256 source does not contain its realized grid axes.');
end
if numel(coarseResult.grid.x) ~= 513 || numel(coarseResult.grid.y) ~= 257
    error('ipm:FourthOrderLattice512CoarseResolution', ...
        'The final q512 run requires a 513-by-257-node q256 source.');
end
[trusted,~] = ipm.output.trustedMask(coarseResult);
trustedPrefix = ipm.output.continuousTrustedPrefix(trusted);
lastTrusted = find(trustedPrefix,1,'last');
if strcmp(fineOptions.caseMetadata.smoothGrid.profile, ...
        'coordinated_log_spacing')
    minimumTrustedTime = 1.72352016681;
    horizonPassed = ~isempty(lastTrusted) && ...
        coarseResult.history.common.physicalTime(lastTrusted) > ...
        minimumTrustedTime;
else
    minimumTrustedTime = 0.5;
    horizonPassed = ~isempty(lastTrusted) && ...
        coarseResult.history.common.physicalTime(lastTrusted) >= ...
        minimumTrustedTime;
end
if ~horizonPassed
    error('ipm:FourthOrderLattice512CoarseHorizon', ...
        ['The q256 source does not meet the required trusted horizon ' ...
        't=%.12g for this final q512 run.'],minimumTrustedTime);
end
expectedCoarseCase = strrep(fineOptions.caseMetadata.caseName, ...
    'quadrant_512','quadrant_256');
if ~isfield(coarseResult.metadata,'caseMetadata') || ...
        ~isfield(coarseResult.metadata.caseMetadata,'caseName') || ...
        ~strcmp(coarseResult.metadata.caseMetadata.caseName, ...
        expectedCoarseCase)
    error('ipm:FourthOrderLattice512CoarseCase', ...
        'The q256 source is not the matching named coarse case %s.', ...
        expectedCoarseCase);
end
assert_numerical_tuple(coarseResult.config,fineOptions);
coarseGrid = source_smooth_grid(coarseResult);
fineGrid = fineOptions.caseMetadata.smoothGrid;
fields = {'profile','mappingKind','monitorCoordinate','mappingVersion', ...
    'strength','width','peakCenter','profileParameters'};
if ~all(isfield(coarseGrid,fields)) || ~all(isfield(fineGrid,fields))
    error('ipm:FourthOrderLattice512MappingProvenance', ...
        'Both q256 and q512 sources must carry complete LAT provenance.');
end
coarseSignature = struct();
fineSignature = struct();
for index = 1:numel(fields)
    name = fields{index};
    coarseSignature.(name) = coarseGrid.(name);
    fineSignature.(name) = fineGrid.(name);
end
if ~isequaln(coarseSignature,fineSignature)
    error('ipm:FourthOrderLattice512MappingMismatch', ...
        ['The q256 source and requested q512 case use different LAT ' ...
        'mappings; refusing an unmatched refinement run.']);
end
assert_nested_axis(coarseResult.grid.x,fineOptions.customX,'x');
assert_nested_axis(coarseResult.grid.y,fineOptions.customY,'y');
end

function assert_numerical_tuple(coarseConfig,fineOptions)
% Compare the frozen configurations that the solver actually uses.  The
% case factory intentionally leaves schema defaults out of its flat option
% structure, whereas the saved coarse result is already resolved/grouped.
fineConfig = ipm.config.resolve(fineOptions);
checks = { ...
    'transport','spatialDiscretization'; ...
    'transport','transportScheme'; ...
    'time','timeIntegrator'; ...
    'time','cfl'; ...
    'time','maxDt'; ...
    'remesh','remeshTransferScheme'; ...
    'remesh','initialAnalyticRemesh'; ...
    'remesh','adaptiveRemesh'; ...
    'physics','initialCondition'; ...
    'physics','degeneratePower'; ...
    'physics','symmetryMode'; ...
    'elliptic','farBoundaryMode'; ...
    'elliptic','greenSourceTolerance'; ...
    'elliptic','greenMaxSources'; ...
    'transport','transportBoundaryMode'; ...
    'scaling','rescalingMode'; ...
    'scaling','dynamicScaleGeometry'; ...
    'scaling','cOmegaGauge'; ...
    'scaling','lengthGauge'};
for index = 1:size(checks,1)
    domain = checks{index,1};
    name = checks{index,2};
    if ~isfield(coarseConfig,domain) || ...
            ~isfield(coarseConfig.(domain),name) || ...
            ~isfield(fineConfig,domain) || ...
            ~isfield(fineConfig.(domain),name) || ...
            ~isequaln(coarseConfig.(domain).(name), ...
            fineConfig.(domain).(name))
        error('ipm:FourthOrderLattice512NumericalTuple', ...
            'The q256/q512 option %s is not identical.',name);
    end
end
end

function result = source_result(source)
if ischar(source) || (isstring(source) && isscalar(source))
    payload = load(char(source));
    if isfield(payload,'result')
        result = payload.result;
    elseif isfield(payload,'assessment') && ...
            isfield(payload.assessment,'sourceMetadata')
        result = load_source_result(payload.assessment.sourceMetadata);
    else
        error('ipm:FourthOrderLattice512CoarseContract', ...
            'The q256 source file must contain result or assessment.');
    end
elseif isfield(source,'metadata') && isfield(source,'grid')
    result = source;
elseif isfield(source,'sourceMetadata')
    result = load_source_result(source.sourceMetadata);
else
    error('ipm:FourthOrderLattice512CoarseContract', ...
        'The q256 source structure lacks result metadata.');
end
end

function result = load_source_result(metadata)
if ~isfield(metadata,'resultFile') || ~isfile(char(metadata.resultFile))
    error('ipm:FourthOrderLattice512CoarseResultMissing', ...
        ['An assessment input must point to its existing q256 result ' ...
        'through sourceMetadata.resultFile.']);
end
payload = load(char(metadata.resultFile),'result');
if ~isfield(payload,'result')
    error('ipm:FourthOrderLattice512CoarseContract', ...
        'The assessment source result file does not contain result.');
end
result = payload.result;
end

function grid = source_smooth_grid(result)
metadata = result.metadata;
if ~isfield(metadata,'caseMetadata') || ...
        ~isfield(metadata.caseMetadata,'smoothGrid')
    error('ipm:FourthOrderLattice512MappingProvenance', ...
        'The q256 source does not contain smooth-grid provenance.');
end
grid = metadata.caseMetadata.smoothGrid;
end

function assert_nested_axis(coarseAxis,fineAxis,axisName)
coarseAxis = coarseAxis(:);
fineAxis = fineAxis(:);
refinementFactor = (numel(fineAxis)-1)/(numel(coarseAxis)-1);
roundedFactor = round(refinementFactor);
if roundedFactor <= 1 || abs(refinementFactor-roundedFactor) > ...
        256*eps(max(1,refinementFactor)) || ...
        numel(fineAxis) ~= roundedFactor*(numel(coarseAxis)-1)+1
    error('ipm:FourthOrderLattice512GridRatio', ...
        'The q256/q512 %s axes do not have an integer refinement ratio.', ...
        axisName);
end
sampledFine = fineAxis(1:roundedFactor:end);
domainScale = max(1,abs(coarseAxis(end)-coarseAxis(1)));
if max(abs(sampledFine-coarseAxis)) > 1e-12*domainScale
    error('ipm:FourthOrderLattice512GridNotNested', ...
        ['The requested q512 %s axis does not strictly contain every ' ...
        'q256 node; refusing an unmatched-shape run.'],axisName);
end
end
