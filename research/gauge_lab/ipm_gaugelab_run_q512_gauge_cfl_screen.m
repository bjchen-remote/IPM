function audit = requested_endpoint_audit(result,settings)
state = result.state;
config = result.config;
roundoffPhysical = 100*eps(max(1,abs(settings.physicalFinalTime)));
roundoffCanonical = 100*eps(max(1,abs(settings.canonicalFinalTime)));
physicalClockSpeed = result.scale.Comega/result.scale.Cx;
physicalStopTolerance = max(roundoffPhysical, ...
    config.time.minDt*physicalClockSpeed*(1+100*eps));
canonicalStopTolerance = max(roundoffCanonical,config.time.minDt);
physicalRemainder = settings.physicalFinalTime-state.physicalTime;
canonicalRemainder = settings.canonicalFinalTime-state.canonicalTime;
physicalReached = strcmp(state.stopReason,'physical_final_time') && ...
    physicalRemainder >= -roundoffPhysical && ...
    physicalRemainder <= physicalStopTolerance && ...
    canonicalRemainder >= -roundoffCanonical;
canonicalReached = strcmp(state.stopReason,'final_time') && ...
    canonicalRemainder >= -roundoffCanonical && ...
    canonicalRemainder <= canonicalStopTolerance && ...
    physicalRemainder >= -roundoffPhysical;
audit = struct( ...
    'passed',physicalReached || canonicalReached, ...
    'acceptedPhysicalEndpoint',physicalReached, ...
    'acceptedCanonicalEndpoint',canonicalReached, ...
    'physicalRemainder',physicalRemainder, ...
    'canonicalRemainder',canonicalRemainder, ...
    'physicalStopTolerance',physicalStopTolerance, ...
    'canonicalStopTolerance',canonicalStopTolerance, ...
    'terminalPhysicalClockSpeed',physicalClockSpeed, ...
    'minimumCanonicalStep',config.time.minDt);
end

function [cflComparisons,gaugeComparisons] = build_comparisons( ...
        results,runs,specifications,windowCap,limits)
cflComparisons = repmat(empty_comparison(),2,1);
gauges = {'wall_omega_quadratic_peak','none'};
for index = 1:numel(gauges)
    gauge = gauges{index};
    left = find_specification(specifications,gauge,0.25);
    right = find_specification(specifications,gauge,0.50);
    cflComparisons(index) = physical_comparison( ...
        results{left},results{right},runs(left),runs(right), ...
        windowCap,limits,'same_gauge_cfl',true);
end
gaugeComparisons = repmat(empty_comparison(),2,1);
cflValues = [0.25,0.50];
for index = 1:numel(cflValues)
    cfl = cflValues(index);
    left = find_specification( ...
        specifications,'wall_omega_quadratic_peak',cfl);
    right = find_specification(specifications,'none',cfl);
    gaugeComparisons(index) = physical_comparison( ...
        results{left},results{right},runs(left),runs(right), ...
        windowCap,limits,'same_cfl_gauge_covariance',false);
end
end

function comparison = physical_comparison( ...
        reference,candidate,referenceRun,candidateRun,cap,limits, ...
        comparisonKind,includeRateChecks)
comparison = empty_comparison();
comparison.kind = comparisonKind;
comparison.referenceRun = referenceRun.name;
comparison.candidateRun = candidateRun.name;
comparison.referenceGauge = referenceRun.gauge;
comparison.candidateGauge = candidateRun.gauge;
comparison.referenceCfl = referenceRun.cfl;
comparison.candidateCfl = candidateRun.cfl;
try
    endpointDifference = candidate.state.physicalTime- ...
        reference.state.physicalTime;
    window = common_window(reference,candidate,cap);
    forward = ipm.output.compare(reference,candidate,window);
    reverse = ipm.output.compare(candidate,reference,window);
    names = physical_metric_names();
    worst = struct();
    for index = 1:numel(names)
        name = names{index};
        worst.(name) = max(abs([forward.(name),reverse.(name)]));
    end
    endpoint = struct( ...
        'physicalTimeDifference',endpointDifference, ...
        'physicalRhoXRelativeDifference',symmetric_relative_difference( ...
            referenceRun.telemetry.endpoint.physicalRhoXInf, ...
            candidateRun.telemetry.endpoint.physicalRhoXInf), ...
        'physicalQuadraticPeakRelativeDifference', ...
            symmetric_relative_difference( ...
            referenceRun.telemetry.endpoint.physicalQuadraticPeak, ...
            candidateRun.telemetry.endpoint.physicalQuadraticPeak), ...
        'cLRelativeDifference',symmetric_relative_difference( ...
            referenceRun.telemetry.endpoint.c_l, ...
            candidateRun.telemetry.endpoint.c_l), ...
        'counterfactualCOmegaScaledDifference',scaled_difference( ...
            referenceRun.telemetry.endpoint. ...
                counterfactualQuadraticCOmega, ...
            candidateRun.telemetry.endpoint. ...
                counterfactualQuadraticCOmega,0.1), ...
        'rescaledQuadraticPeakRelativeDifference', ...
            symmetric_relative_difference( ...
            referenceRun.telemetry.endpoint.rescaledQuadraticPeak, ...
            candidateRun.telemetry.endpoint.rescaledQuadraticPeak));
    checks = physical_comparison_checks( ...
        endpointDifference,worst,endpoint,limits);
    if includeRateChecks
        checks.cLConsistency = endpoint.cLRelativeDifference <= ...
            limits.maximumCflCLRelativeDifference;
        checks.counterfactualCOmegaConsistency = ...
            endpoint.counterfactualCOmegaScaledDifference <= ...
            limits.maximumCflCounterfactualCOmegaScaledDifference;
        checks.rescaledQuadraticPeakConsistency = ...
            endpoint.rescaledQuadraticPeakRelativeDifference <= ...
            limits.maximumCflRescaledQuadraticPeakRelativeDifference;
    end
    failures = failed_checks(checks);
    comparison.available = true;
    comparison.status = ternary(isempty(failures),'passed','gate_failed');
    comparison.commonWindow = window;
    comparison.forward = forward;
    comparison.reverse = reverse;
    comparison.symmetricWorst = worst;
    comparison.endpoint = endpoint;
    comparison.checks = checks;
    comparison.failures = failures;
    comparison.hardPassed = isempty(failures);
catch exception
    comparison.status = 'comparison_failed';
    comparison.errorIdentifier = exception.identifier;
    comparison.errorMessage = exception.message;
end
end

