signature = struct('nodeCount',numel(axis), ...
    'endpoints',axis([1,end])', ...
    'minimumSpacing',min(diff(axis)), ...
    'maximumSpacing',max(diff(axis)), ...
    'spacingNorm',norm(diff(axis)), ...
    'weightedSum',sum((1:numel(axis))'.*axis));
end

