function products = ipm_gaugelab_run_q256_tournament(userOptions)
%IPM_GAUGELAB_RUN_Q256_TOURNAMENT Run a schema-4 q256 gauge group stage.
%   All candidates start from the same physical initial datum and fixed grid.
%   Only cOmegaGauge changes.  The scaling contract is exact and has no
%   state-dependent feedback.  Results are immutable and saved incrementally.

if nargin < 1
    userOptions = struct();
end
options = resolve_options(userOptions);
laboratoryDirectory = fileparts(mfilename('fullpath'));
researchDirectory = fileparts(laboratoryDirectory);
projectDirectory = fileparts(researchDirectory);
experimentDirectory = fullfile(researchDirectory,'experiments');
analysisDirectory = fullfile(researchDirectory,'analysis');
addpath(projectDirectory,experimentDirectory,analysisDirectory, ...
    laboratoryDirectory);

baseOptions = fourth_order_blowup_case(options.baseCaseName,struct( ...
    'lengthGauge','transport_anchor','transportAnchorX',1, ...
    'lengthScaleGain',1,'widthGaugeGain',0,'omegaGaugeGain',0, ...
    'travelingWaveGain',0,'omegaGaugeWindowRadius',0.75, ...
    'pointStrainConditionFloor',0.25, ...
    'maxDt',options.maxDt,'cfl',options.cfl, ...
    'saveResults',false,'makePlots',false,'livePlot',false, ...
    'writeVideo',false,'storeSnapshots',false,'verbose',false));
[meshAudit,meshPassed] = audit_shared_mesh(baseOptions,options.meshLimits);
if ~meshPassed
    error('ipm:GaugeLabMeshGate', ...
        'The shared q256 axis fails the frozen tournament mesh gates.');
end
assert_common_contract(baseOptions);

stamp = char(datetime('now','TimeZone','UTC', ...
    'Format','yyyyMMdd''T''HHmmssSSS''Z'''));
outputParent = fullfile(projectDirectory,'result','verification', ...
    'q256_comega_gauge_tournaments_exact_v4');
if ~isfolder(outputParent)
    mkdir(outputParent);
end
outputDirectory = fullfile(outputParent,['tournament_',stamp]);
if isfolder(outputDirectory)
    error('ipm:GaugeLabOutputCollision', ...
        'Tournament directory already exists: %s',outputDirectory);
end
mkdir(outputDirectory);
summaryFile = fullfile(outputDirectory,'tournament_summary.mat');
manifestFile = fullfile(outputDirectory,'tournament_manifest.jsonl');

specifications = ipm_gaugelab_candidate_specifications( ...
    options.includeNegativeControl);
if ~isempty(options.candidates)
    keep = ismember({specifications.cOmegaGauge},options.candidates);
    specifications = specifications(keep);
end
if isempty(specifications)
    error('ipm:GaugeLabCandidatesEmpty', ...
        'At least one gauge candidate must be selected.');
end

emptyComparison = struct('available',false,'rhoRelativeL2',NaN, ...
    'omegaRelativeL2',NaN,'rhoAbsoluteInf',NaN, ...
    'omegaAbsoluteInf',NaN,'labPeakShift',NaN, ...
    'physicalTimeDifference',NaN, ...
    'physicalRhoXRelativeDifference',NaN, ...
    'wallPeakRelativeDifference',NaN, ...
    'wallWidthRelativeDifference',NaN);
emptyPairwise = struct('available',false, ...
    'method','bidirectional_absolute_worst', ...
    'successfulCompetitorCount',0,'requiredCompetitorCount',2, ...
    'peerCount',0,'requiredPeerCount',1,'peers',{{}}, ...
    'worst',emptyComparison,'passed',false);
emptyPairRecord = struct('peerGauge','','available',false, ...
    'forward',emptyComparison,'reverse',emptyComparison, ...
    'symmetricWorst',emptyComparison,'passed',false, ...
    'errorIdentifier','','errorMessage','');
template = struct('cOmegaGauge','','role','', ...
    'candidateSpecification',struct(),'startedAt',NaT, ...
    'completedAt',NaT,'elapsedSeconds',NaN,'resultFile','', ...
    'assessmentFile','','auditFile','','latestCheckpointFile','', ...
    'stopReason','','errorIdentifier','','errorMessage','', ...
    'failureClass','', ...
    'audit',struct(),'physicalComparison',emptyComparison, ...
    'baselineDisplayComparison',emptyComparison, ...
    'pairwiseComparisons',repmat(emptyPairRecord,0,1), ...
    'pairwisePhysicalCovariance',emptyPairwise, ...
    'physicalCovariancePassed',false,'productionEligible',false, ...
    'artifactDisposition','incomplete','eligible',false);
products = struct('schemaVersion',4, ...
    'kind','q256_comega_gauge_tournament_exact_no_feedback', ...
    'status','running','startedAt',datetime('now','TimeZone','local'), ...
    'completedAt',NaT,'baseCaseName',options.baseCaseName, ...
    'requestedPhysicalFinalTime',options.physicalFinalTime, ...
    'requestedMaximumTimeStep',options.maxDt, ...
    'requestedCfl',options.cfl, ...
    'outputDirectory',outputDirectory,'summaryFile',summaryFile, ...
    'manifestFile',manifestFile,'meshLimits',options.meshLimits, ...
    'meshAudit',meshAudit,'physicalCovarianceLimits', ...
    options.physicalCovarianceLimits,'checkpointCanonicalCadence', ...
    options.checkpointCanonicalCadence,'checkpointEnabled',true, ...
    'checkpointAtExit',true, ...
    'checkpointImmutable',true,'wallClockBudgetSeconds', ...
    options.wallClockBudgetSeconds, ...
    'requiredConfigSchemaVersion',4, ...
    'configurationContract','exact_gauge_no_feedback_v1', ...
    'numericalTuple',frozen_numerical_tuple(),'fixedMesh',true, ...
    'candidateSpecifications',specifications, ...
    'physicalCovarianceMethod','symmetric_pairwise_bidirectional_worst', ...
    'minimumSuccessfulCompetitors',2, ...
    'displayBaselineGauge','gradient_energy', ...
    'legacyPhysicalComparisonUsage','display_only_not_scored', ...
    'baselineDisplay',struct(),'pairwiseEvidence',struct(),'runs', ...
    repmat(template,numel(specifications),1),'ranking',{{}}, ...
    'provisionalWinner','','postprocessingStatus','pending', ...
    'plotFile','','plotError',struct(),'failureSummary',struct(), ...
    'elapsedSeconds',NaN,'wallClockBoundary',false, ...
    'wallClockOverrunSeconds',NaN);
save(summaryFile,'products');
append_manifest(manifestFile,struct('event','tournament_started', ...
    'timestampUtc',stamp,'outputDirectory',outputDirectory, ...
    'schemaVersion',products.schemaVersion, ...
    'requiredConfigSchemaVersion',products.requiredConfigSchemaVersion, ...
    'configurationContract',products.configurationContract, ...
    'numericalTuple',products.numericalTuple,'fixedMesh',true, ...
    'candidateSpecifications',specifications, ...
    'physicalFinalTime',options.physicalFinalTime, ...
    'maxDt',options.maxDt,'cfl',options.cfl, ...
    'meshLimits',options.meshLimits, ...
    'physicalCovarianceLimits',options.physicalCovarianceLimits, ...
    'checkpointCanonicalCadence',options.checkpointCanonicalCadence, ...
    'checkpointEnabled',true,'checkpointAtExit',true, ...
    'checkpointImmutable',true, ...
    'wallClockBudgetSeconds',options.wallClockBudgetSeconds, ...
    'physicalCovarianceMethod',products.physicalCovarianceMethod, ...
    'minimumSuccessfulCompetitors', ...
    products.minimumSuccessfulCompetitors));

contractReference = [];
tournamentClock = tic;
wallClockBoundary = false;
for index = 1:numel(specifications)
    specification = specifications(index);
    if index > 1
        completedDurations = [products.runs.elapsedSeconds];
        completedDurations = completedDurations(isfinite(completedDurations));
        forecast = max(600,1.35*median(completedDurations));
        if toc(tournamentClock)+forecast > options.wallClockBudgetSeconds
            wallClockBoundary = true;
            append_manifest(manifestFile,struct( ...
                'event','tournament_stopped','timestampUtc',utc_stamp(), ...
                'reason','wall_clock_boundary','elapsedSeconds', ...
                toc(tournamentClock),'nextCandidate', ...
                specification.cOmegaGauge,'forecastSeconds',forecast));
            break;
        end
    end
    run = template;
    run.cOmegaGauge = specification.cOmegaGauge;
    run.role = specification.role;
    run.candidateSpecification = specification;
    run.startedAt = datetime('now','TimeZone','local');
    candidateDirectory = fullfile(outputDirectory, ...
        specification.cOmegaGauge);
    mkdir(candidateDirectory);
    requestedResultFile = fullfile(candidateDirectory,'result.mat');
    requestedCheckpointFile = fullfile(candidateDirectory,'checkpoint.mat');
    fprintf('\nGAUGE GROUP %d/%d: %s\n',index,numel(specifications), ...
        specification.cOmegaGauge);
    append_manifest(manifestFile,struct('event','candidate_started', ...
        'timestampUtc',utc_stamp(),'candidate', ...
        specification.cOmegaGauge,'role',specification.role));
    wallClock = tic;
    try
        metadata = struct('gaugeTournament',struct( ...
            'schemaVersion',4,'stage','q256_exact_no_feedback_group', ...
            'candidate',specification.cOmegaGauge, ...
            'baseCaseName',options.baseCaseName, ...
            'onlyAmplitudeGaugeVaried',true, ...
            'candidateSpecification',specification, ...
            'configurationContract', ...
            'exact_gauge_no_feedback_v1', ...
            'physicalCovarianceMethod', ...
            'symmetric_pairwise_bidirectional_worst'));
        opts = fourth_order_blowup_case(options.baseCaseName,struct( ...
            'cOmegaGauge',specification.cOmegaGauge, ...
            'lengthGauge','transport_anchor','transportAnchorX',1, ...
            'lengthScaleGain',1,'widthGaugeGain',0, ...
            'omegaGaugeGain',0,'travelingWaveGain',0, ...
            'omegaGaugeWindowRadius',0.75, ...
            'pointStrainConditionFloor',0.25, ...
            'physicalFinalTime',options.physicalFinalTime, ...
            'maxDt',options.maxDt,'cfl',options.cfl, ...
            'resultFile',requestedResultFile, ...
            'checkpoint',struct('enabled',true, ...
                'file',requestedCheckpointFile,'every', ...
                options.checkpointCanonicalCadence,'atExit',true), ...
            'caseMetadata',metadata,'saveResults',true, ...
            'storeSnapshots',false,'makePlots',false,'livePlot',false, ...
            'writeVideo',false,'verbose',options.verbose));
        if isempty(contractReference)
            contractReference = opts;
        end
        assert_candidate_contract(contractReference,opts);
        result = ipm.solve(opts);
        run.elapsedSeconds = toc(wallClock);
        run.completedAt = datetime('now','TimeZone','local');
        run.resultFile = char(result.metadata.resultFile);
        if isfield(result.metadata,'latestCheckpointFile')
            run.latestCheckpointFile = ...
                char(result.metadata.latestCheckpointFile);
        end
        if isempty(run.latestCheckpointFile) || ...
                ~isfile(run.latestCheckpointFile)
            run.latestCheckpointFile = ...
                latest_immutable_checkpoint(candidateDirectory);
        end
        run.stopReason = result.state.stopReason;
        run.failureClass = classify_stop_reason(run.stopReason);
        assessment = ipm_assess_fourth_order_blowup(result);
        assessmentFile = fullfile(candidateDirectory,'assessment.mat');
        save(assessmentFile,'assessment');
        run.assessmentFile = assessmentFile;
        audit = ipm_gaugelab_assess(result,options.physicalFinalTime);
        auditFile = fullfile(candidateDirectory,'gauge_audit.mat');
        save(auditFile,'audit');
        run.auditFile = auditFile;
        run.audit = audit;
        if strcmp(run.failureClass,'target_reached') && ~audit.hardPassed
            run.failureClass = classify_audit_failure(audit);
        end

        fprintf(['GAUGE RESULT %s: stop=%s class=%s, ' ...
            't/tau %.9g/%.9g, steps %d, ' ...
            'osc cl/cw %.3e/%.3e, drift cl/cw %.3e/%.3e, ' ...
            'pairwise covariance pending\n'], ...
            run.cOmegaGauge,run.stopReason,run.failureClass, ...
            audit.physicalTime,audit.canonicalTau, ...
            audit.steps,audit.canonicalCL.detrendedRelativeRms, ...
            audit.canonicalCOmega.detrendedRelativeRms, ...
            audit.canonicalCL.relativeTrendAcrossWindow, ...
            audit.canonicalCOmega.relativeTrendAcrossWindow);
        candidateEvent = 'candidate_completed';
        if ~strcmp(run.failureClass,'target_reached')
            candidateEvent = 'candidate_stopped';
        end
        append_manifest(manifestFile,struct('event',candidateEvent, ...
            'timestampUtc',utc_stamp(),'candidate',run.cOmegaGauge, ...
            'resultFile',run.resultFile,'checkpointFile', ...
            run.latestCheckpointFile,'hardPassed',audit.hardPassed, ...
            'stopReason',run.stopReason,'failureClass',run.failureClass, ...
            'pairwiseCovariancePending',true));
    catch exception
        run.elapsedSeconds = toc(wallClock);
        run.completedAt = datetime('now','TimeZone','local');
        run.errorIdentifier = exception.identifier;
        run.errorMessage = exception.message;
        run.failureClass = classify_exception(exception);
        run.latestCheckpointFile = ...
            latest_immutable_checkpoint(candidateDirectory);
        fprintf(2,'GAUGE ERROR %s: %s (%s)\n', ...
            run.cOmegaGauge,exception.message,exception.identifier);
        append_manifest(manifestFile,struct('event','candidate_failed', ...
            'timestampUtc',utc_stamp(),'candidate',run.cOmegaGauge, ...
            'identifier',exception.identifier,'message',exception.message, ...
            'failureClass',run.failureClass,'checkpointFile', ...
            run.latestCheckpointFile));
    end
    products.runs(index) = run;
    save(summaryFile,'products','-v7.3');
end

[products.runs,products.baselineDisplay] = ...
    populate_baseline_display_comparisons(products.runs, ...
    products.displayBaselineGauge,emptyComparison);
[products.runs,products.pairwiseEvidence] = ...
    evaluate_pairwise_covariance(products.runs, ...
    options.physicalCovarianceLimits,emptyComparison, ...
    emptyPairwise,emptyPairRecord);
for index = 1:numel(products.runs)
    run = products.runs(index);
    if isempty(run.cOmegaGauge)
        continue;
    end
    append_manifest(manifestFile,struct( ...
        'event','candidate_pairwise_assessed','timestampUtc',utc_stamp(), ...
        'candidate',run.cOmegaGauge, ...
        'successfulCompetitorCount', ...
        run.pairwisePhysicalCovariance.successfulCompetitorCount, ...
        'peerCount',run.pairwisePhysicalCovariance.peerCount, ...
        'physicalCovariancePassed',run.physicalCovariancePassed, ...
        'failureClass',run.failureClass,'eligible',run.eligible));
end

attempted = ~cellfun(@isempty,{products.runs.cOmegaGauge});
failureClasses = {products.runs(attempted).failureClass};
competitive = attempted & ...
    ~strcmp({products.runs.role},'negative_control');
pairwiseInfrastructureFailed = ...
    ~isempty(products.pairwiseEvidence.errors);
products.elapsedSeconds = toc(tournamentClock);
products.wallClockOverrunSeconds = max(0, ...
    products.elapsedSeconds-options.wallClockBudgetSeconds);
if products.wallClockOverrunSeconds > 0
    wallClockBoundary = true;
    append_manifest(manifestFile,struct( ...
        'event','wall_clock_budget_overrun','timestampUtc',utc_stamp(), ...
        'elapsedSeconds',products.elapsedSeconds, ...
        'budgetSeconds',options.wallClockBudgetSeconds, ...
        'overrunSeconds',products.wallClockOverrunSeconds));
end
products.wallClockBoundary = wallClockBoundary;
products.failureSummary = summarize_failures(products.runs,attempted, ...
    wallClockBoundary,pairwiseInfrastructureFailed);
if any(strcmp(failureClasses,'unexpected_error')) || ...
        pairwiseInfrastructureFailed
    [products.ranking,~] = rank_runs(products.runs);
    products.provisionalWinner = '';
    products.status = 'failed_infrastructure';
elseif wallClockBoundary
    [products.ranking,~] = rank_runs(products.runs);
    products.provisionalWinner = '';
    products.status = 'wall_clock_boundary';
elseif products.pairwiseEvidence.successfulCompetitorCount < ...
        products.minimumSuccessfulCompetitors
    products.ranking = {};
    products.provisionalWinner = '';
    products.status = insufficient_competitor_status( ...
        products.failureSummary);
else
    [products.ranking,products.provisionalWinner] = rank_runs(products.runs);
    if products.failureSummary.failureCategoryCount > 1
        products.status = 'completed_with_mixed_failures';
    elseif products.failureSummary.designedSafetyStopCount > 0
        products.status = 'completed_with_designed_safety_stops';
    elseif products.failureSummary.numericalGateFailureCount > 0
        products.status = 'completed_with_numerical_gate_failures';
    elseif products.failureSummary.gaugeFailureCount > 0
        products.status = 'completed_with_gauge_failures';
    elseif any(competitive & ~[products.runs.eligible])
        products.status = 'completed_with_gate_failures';
    else
        products.status = 'completed';
    end
end
products.completedAt = datetime('now','TimeZone','local');
if ~strcmp(products.status,'failed_infrastructure')
    try
        plotFile = fullfile(outputDirectory,'q256_gauge_tournament_rates.png');
        [figureHandle,products.plotFile] = ...
            ipm_gaugelab_plot_tournament(products,plotFile);
        close(figureHandle);
        products.postprocessingStatus = 'completed';
    catch exception
        products.plotFile = '';
        products.plotError = struct('identifier',exception.identifier, ...
            'message',exception.message);
        products.postprocessingStatus = 'failed';
        products.provisionalWinner = '';
    end
else
    products.postprocessingStatus = 'not_run';
end
products.elapsedSeconds = toc(tournamentClock);
products.wallClockOverrunSeconds = max(0, ...
    products.elapsedSeconds-options.wallClockBudgetSeconds);
products.wallClockBoundary = products.wallClockBoundary || ...
    products.wallClockOverrunSeconds > 0;
products.failureSummary.wallClockBoundary = products.wallClockBoundary;
if products.wallClockBoundary && ...
        ~strcmp(products.status,'failed_infrastructure')
    products.status = 'wall_clock_boundary';
    products.provisionalWinner = '';
end
save(summaryFile,'products','-v7.3');
append_manifest(manifestFile,struct('event','tournament_finished', ...
    'timestampUtc',utc_stamp(),'status',products.status, ...
    'postprocessingStatus',products.postprocessingStatus, ...
    'pairwiseEvidenceAvailable',products.pairwiseEvidence.available, ...
    'failureSummary',products.failureSummary, ...
    'elapsedSeconds',products.elapsedSeconds, ...
    'wallClockBoundary',products.wallClockBoundary, ...
    'wallClockOverrunSeconds',products.wallClockOverrunSeconds, ...
    'ranking',{products.ranking}, ...
    'provisionalWinner',products.provisionalWinner));
fprintf('\nGAUGE TOURNAMENT COMPLETE: %s\n',summaryFile);
fprintf('Tournament status: %s\n',products.status);
fprintf(['Run outcomes: target=%d, designed safety=%d, numerical gate=%d, ' ...
    'gauge failure=%d, unexpected crash=%d, not attempted=%d\n'], ...
    products.failureSummary.targetReachedCount, ...
    products.failureSummary.designedSafetyStopCount, ...
    products.failureSummary.numericalGateFailureCount, ...
    products.failureSummary.gaugeFailureCount, ...
    products.failureSummary.unexpectedCrashCount, ...
    products.failureSummary.notAttemptedCount);
fprintf('Provisional q256 group winner: %s\n',products.provisionalWinner);
end

function options = resolve_options(user)
if ~isstruct(user) || ~isscalar(user)
    error('ipm:GaugeLabOptions','Options must be a scalar structure.');
end
options = struct( ...
    'baseCaseName','coordinated_log_F80_R20_c114_quadrant_256', ...
    'physicalFinalTime',0.55,'includeNegativeControl',false, ...
    'maxDt',2e-3,'cfl',0.25,'candidates',{{ ...
        'gradient_energy','anchor_wall_window_l2', ...
        'anchor_wall_template_projection','anchor_bulk_gradient_l2', ...
        'anchor_wall_window_l4'}},'verbose',true);
names = fieldnames(user);
unknown = setdiff(names,fieldnames(options));
if ~isempty(unknown)
    error('ipm:GaugeLabOptionName','Unknown option(s): %s', ...
        strjoin(unknown,', '));
end
for index = 1:numel(names)
    options.(names{index}) = user.(names{index});
end
options.meshLimits = frozen_mesh_limits();
options.physicalCovarianceLimits = frozen_physical_covariance_limits();
options.checkpointCanonicalCadence = frozen_checkpoint_cadence();
options.wallClockBudgetSeconds = frozen_wall_clock_budget();
validateattributes(options.physicalFinalTime,{'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(options.maxDt,{'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(options.cfl,{'numeric'}, ...
    {'scalar','real','finite','>',0,'<=',0.5});
options.includeNegativeControl = normalize_flag( ...
    options.includeNegativeControl,'includeNegativeControl');
options.verbose = normalize_flag(options.verbose,'verbose');
if isstring(options.baseCaseName)
    if ~isscalar(options.baseCaseName) || ismissing(options.baseCaseName)
        error('ipm:GaugeLabBaseCase','baseCaseName must be scalar text.');
    end
    options.baseCaseName = char(options.baseCaseName);
elseif ~ischar(options.baseCaseName) || ~isrow(options.baseCaseName)
    error('ipm:GaugeLabBaseCase','baseCaseName must be scalar text.');
end
if ~iscellstr(options.candidates)
    error('ipm:GaugeLabCandidates','candidates must be a cell array of text.');
end
options.candidates = cellfun(@char,options.candidates,'UniformOutput',false);
options.candidates = cellfun(@(value)lower(strtrim(value)), ...
    options.candidates,'UniformOutput',false);
if options.includeNegativeControl && ...
        ~any(strcmp(options.candidates,'none'))
    options.candidates{end+1} = 'none';
end
allowed = {ipm_gaugelab_candidate_specifications(true).cOmegaGauge};
unrecognized = setdiff(options.candidates,allowed);
if ~isempty(unrecognized)
    error('ipm:GaugeLabCandidateName','Unknown candidate(s): %s', ...
        strjoin(unrecognized,', '));
end
if any(strcmp(options.candidates,'none')) && ...
        ~logical(options.includeNegativeControl)
    error('ipm:GaugeLabNegativeControlDisabled', ...
        'Set includeNegativeControl=true to request candidate none.');
end
end

