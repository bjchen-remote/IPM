function complete = has_finite_equal_length_fields(value,names,count)
complete = isstruct(value) && isscalar(value);
for index = 1:numel(names)
    name = names{index};
    complete = complete && isfield(value,name) && ...
        isnumeric(value.(name)) && isreal(value.(name)) && ...
        numel(value.(name)) == count && all(isfinite(value.(name)));
end
end

function [runs,pairs,successful,comparisonEligible,allPassed,subsetPassed] = ...
        compare_all_pairs(runs,results,protocol)
successful = [runs.integrityPassed] & ~cellfun(@isempty,results');
competitors = find(successful);
sufficient = numel(competitors) >= protocol.minimumSuccessfulCandidates;
pairs = repmat(empty_pair(),0,1);
peerRecords = cell(numel(runs),1);
for index = 1:numel(peerRecords)
    peerRecords{index} = repmat(empty_pair(),0,1);
end
for firstPosition = 1:numel(competitors)-1
    first = competitors(firstPosition);
    for secondPosition = firstPosition+1:numel(competitors)
        second = competitors(secondPosition);
        pair = empty_pair();
        pair.candidateA = runs(first).lengthGauge;
        pair.candidateB = runs(second).lengthGauge;
        try
            pair.forward = directional_comparison( ...
                results{first},results{second}, ...
                protocol.comparisonWindow);
            pair.reverse = directional_comparison( ...
                results{second},results{first}, ...
                protocol.comparisonWindow);
            pair.symmetricWorst = symmetric_worst( ...
                pair.forward,pair.reverse);
            pair.available = true;
            pair.passed = covariance_passed( ...
                pair.symmetricWorst, ...
                protocol.physicalCovarianceLimits);
        catch exception
            pair.errorIdentifier = exception.identifier;
            pair.errorMessage = exception.message;
        end
        pairs(end+1,1) = pair; %#ok<AGROW>
        peerRecords{first}(end+1,1) = pair;
        peerRecords{second}(end+1,1) = reverse_pair(pair);
    end
end
allPassed = sufficient && ~isempty(pairs) && ...
    all([pairs.available]) && all([pairs.passed]);
reference = find(strcmp({runs.lengthGauge}, ...
    protocol.physicalCovarianceReference),1,'first');
if isempty(reference) || ~successful(reference)
    error('ipm:GaugeLabCLCovarianceReference', ...
        'The preregistered physical-covariance reference is unavailable.');
end
comparisonEligible = false(size(successful));
for index = 1:numel(runs)
    runs(index).pairwiseComparisons = peerRecords{index};
    if isempty(peerRecords{index})
        runs(index).physicalCovariancePassed = false;
        runs(index).worstPhysicalCovarianceMetric = NaN;
        runs(index).worstAllPeerPhysicalCovarianceMetric = NaN;
    else
        available = [peerRecords{index}.available];
        if index == reference
            runs(index).physicalCovariancePassed = successful(index);
        else
            againstReference = strcmp( ...
                {peerRecords{index}.candidateB}, ...
                runs(reference).lengthGauge);
            runs(index).physicalCovariancePassed = ...
                successful(index) && nnz(againstReference) == 1 && ...
                peerRecords{index}(againstReference).available && ...
                peerRecords{index}(againstReference).passed;
        end
        if all(available)
            values = arrayfun(@(pair)covariance_scalar( ...
                pair.symmetricWorst,protocol.physicalCovarianceLimits), ...
                peerRecords{index});
            runs(index).worstAllPeerPhysicalCovarianceMetric = max(values);
        end
    end
    comparisonEligible(index) = runs(index).integrityPassed && ...
        runs(index).physicalCovariancePassed;
end
eligibleNames = {runs(comparisonEligible).lengthGauge};
for index = 1:numel(runs)
    runs(index).worstPhysicalCovarianceMetric = NaN;
    if comparisonEligible(index)
        withinSubset = ismember( ...
            {peerRecords{index}.candidateB},eligibleNames);
        subsetPeers = peerRecords{index}(withinSubset);
        if ~isempty(subsetPeers) && all([subsetPeers.available])
            values = arrayfun(@(pair)covariance_scalar( ...
                pair.symmetricWorst,protocol.physicalCovarianceLimits), ...
                subsetPeers);
            runs(index).worstPhysicalCovarianceMetric = max(values);
        end
    end
    runs(index).rankingEligible = comparisonEligible(index) && ...
        runs(index).rateConvergenceValid;
end
eligiblePairs = arrayfun(@(pair) ...
    any(strcmp(pair.candidateA,{runs(comparisonEligible).lengthGauge})) && ...
    any(strcmp(pair.candidateB,{runs(comparisonEligible).lengthGauge})), ...
    pairs);
subsetPassed = nnz(comparisonEligible) >= ...
    protocol.minimumSuccessfulCandidates && any(eligiblePairs) && ...
    all([pairs(eligiblePairs).available]) && ...
    all([pairs(eligiblePairs).passed]);
end

function comparison = directional_comparison(reference,candidate,window)
comparison = ipm.output.compare(reference,candidate,window);
comparison.available = true;
comparison.physicalTimeDifference = ...
    candidate.state.physicalTime-reference.state.physicalTime;
comparison.physicalRhoXRelativeDifference = relative_difference( ...
    reference.history.common.physicalRhoXInf(end), ...
    candidate.history.common.physicalRhoXInf(end));
referenceWidth = common_wall_half_maximum_width(reference);
candidateWidth = common_wall_half_maximum_width(candidate);
% output.compare uses the run's tracked reporting level.  That level is
% deliberately 0.9 for wall_omega_width and 0.5 for the other c_l gauges,
% so replace it here with one gauge-independent terminal physical width.
comparison.wallWidthRelativeDifference = relative_difference( ...
    referenceWidth,candidateWidth);
comparison.wallWidthDefinition = ...
    'terminal_physical_omega_connected_half_maximum';
end

function width = common_wall_half_maximum_width(result)
x = result.grid.physicalX(:)';
wall = result.physical.omega(1,:);
[peak,peakIndex] = max(wall);
if ~isfinite(peak) || peak <= 0
    error('ipm:GaugeLabCLWallWidth', ...
        'The terminal physical wall omega has no positive finite peak.');
end
threshold = 0.5*peak;
left = peakIndex;
while left > 1 && wall(left-1) >= threshold
    left = left-1;
end
right = peakIndex;
while right < numel(wall) && wall(right+1) >= threshold
    right = right+1;
end
if left == 1 || right == numel(wall)
    error('ipm:GaugeLabCLWallWidth', ...
        'The terminal physical wall-omega half-maximum component is not interior.');
end
leftCrossing = linear_crossing( ...
    x(left-1:left),wall(left-1:left),threshold);
rightCrossing = linear_crossing( ...
    x(right:right+1),wall(right:right+1),threshold);
width = rightCrossing-leftCrossing;
if ~isfinite(width) || width <= 0
    error('ipm:GaugeLabCLWallWidth', ...
        'The common terminal wall-omega half-maximum width is invalid.');
end
end

function crossing = linear_crossing(x,values,threshold)
difference = values(2)-values(1);
if difference == 0
    error('ipm:GaugeLabCLWallWidth', ...
        'A terminal wall-omega half-maximum crossing has zero slope.');
end
fraction = (threshold-values(1))/difference;
crossing = x(1)+fraction*(x(2)-x(1));
end

function worst = symmetric_worst(forward,reverse)
worst = struct('available',forward.available && reverse.available);
names = covariance_metric_names();
for index = 1:numel(names)
    name = names{index};
    worst.(name) = max(abs([forward.(name),reverse.(name)]));
end
end

function passed = covariance_passed(comparison,limits)
passed = comparison.available && ...
    comparison.rhoRelativeL2 <= limits.rhoRelativeL2 && ...
    comparison.omegaRelativeL2 <= limits.omegaRelativeL2 && ...
    comparison.rhoAbsoluteInf <= limits.rhoAbsoluteInf && ...
    comparison.omegaAbsoluteInf <= limits.omegaAbsoluteInf && ...
    comparison.labPeakShift <= limits.maximumAbsoluteLabPeakShift && ...
    comparison.physicalTimeDifference <= ...
        limits.maximumAbsolutePhysicalTimeDifference && ...
    comparison.physicalRhoXRelativeDifference <= ...
        limits.physicalRhoXRelativeDifference && ...
    comparison.wallPeakRelativeDifference <= ...
        limits.wallPeakRelativeDifference && ...
    comparison.wallWidthRelativeDifference <= ...
        limits.wallWidthRelativeDifference;
end

function value = covariance_scalar(comparison,limits)
values = [ ...
    abs(comparison.rhoRelativeL2)/limits.rhoRelativeL2, ...
    abs(comparison.omegaRelativeL2)/limits.omegaRelativeL2, ...
    abs(comparison.rhoAbsoluteInf)/limits.rhoAbsoluteInf, ...
    abs(comparison.omegaAbsoluteInf)/limits.omegaAbsoluteInf, ...
    abs(comparison.labPeakShift)/limits.maximumAbsoluteLabPeakShift, ...
    abs(comparison.physicalTimeDifference)/ ...
        limits.maximumAbsolutePhysicalTimeDifference, ...
    abs(comparison.physicalRhoXRelativeDifference)/ ...
        limits.physicalRhoXRelativeDifference, ...
    abs(comparison.wallPeakRelativeDifference)/ ...
        limits.wallPeakRelativeDifference, ...
    abs(comparison.wallWidthRelativeDifference)/ ...
        limits.wallWidthRelativeDifference];
value = max(values);
end

function names = covariance_metric_names()
names = {'rhoRelativeL2','omegaRelativeL2','rhoAbsoluteInf', ...
    'omegaAbsoluteInf','labPeakShift','physicalTimeDifference', ...
    'physicalRhoXRelativeDifference','wallPeakRelativeDifference', ...
    'wallWidthRelativeDifference'};
end

function reversed = reverse_pair(pair)
reversed = pair;
reversed.candidateA = pair.candidateB;
reversed.candidateB = pair.candidateA;
reversed.forward = pair.reverse;
reversed.reverse = pair.forward;
end

function [ranking,evidence,winner] = rank_runs(runs,isFormal)
ranking = {};
evidence = repmat(empty_ranking_record(),0,1);
winner = '';
rankingEligible = reshape([runs.rankingEligible],[],1);
finiteEvidence = arrayfun(@finite_ranking_evidence,runs(:));
eligible = find(rankingEligible & finiteEvidence);
if ~isFormal || numel(eligible) < 2
    return;
end
score = NaN(numel(eligible),5);
records = repmat(empty_ranking_record(),numel(eligible),1);
for position = 1:numel(eligible)
    index = eligible(position);
    diagnostic = runs(index).rateConvergence;
    cL = diagnostic.seriesSummary.cL;
    cOmega = diagnostic.seriesSummary.cOmega;
    worstTrend = max([cL.maximumAbsoluteRelativeTrend, ...
        cOmega.maximumAbsoluteRelativeTrend]);
    worstMeanSpread = max([cL.relativeWindowMeanSpread, ...
        cOmega.relativeWindowMeanSpread]);
    worstRms = max([cL.maximumRelativeDetrendedRms, ...
        cOmega.maximumRelativeDetrendedRms]);
    score(position,:) = [worstTrend,worstMeanSpread,worstRms, ...
        runs(index).worstPhysicalCovarianceMetric, ...
        runs(index).elapsedSeconds];
    records(position) = struct( ...
        'lengthGauge',runs(index).lengthGauge, ...
        'worstRateRelativeTrend',worstTrend, ...
        'worstNestedWindowMeanSpread',worstMeanSpread, ...
        'worstDetrendedRelativeRms',worstRms, ...
        'worstPhysicalCovarianceMetric', ...
            runs(index).worstPhysicalCovarianceMetric, ...
        'elapsedSeconds',runs(index).elapsedSeconds, ...
        'provisionalStable', ...
            runs(index).rateConvergenceProvisionalStable);
end
[~,order] = sortrows(score,[1,2,3,4,5]);
evidence = records(order);
ranking = {evidence.lengthGauge};
winner = ranking{1};
end

function finite = finite_ranking_evidence(run)
finite = false;
diagnostic = run.rateConvergence;
if ~isstruct(diagnostic) || ...
        ~isfield(diagnostic,'seriesSummary') || ...
        ~all(isfield(diagnostic.seriesSummary,{'cL','cOmega'}))
    return;
end
cL = diagnostic.seriesSummary.cL;
cOmega = diagnostic.seriesSummary.cOmega;
required = {'maximumAbsoluteRelativeTrend', ...
    'relativeWindowMeanSpread','maximumRelativeDetrendedRms'};
if ~all(isfield(cL,required)) || ~all(isfield(cOmega,required))
    return;
end
values = [cL.maximumAbsoluteRelativeTrend, ...
    cOmega.maximumAbsoluteRelativeTrend, ...
    cL.relativeWindowMeanSpread,cOmega.relativeWindowMeanSpread, ...
    cL.maximumRelativeDetrendedRms,cOmega.maximumRelativeDetrendedRms, ...
    run.worstPhysicalCovarianceMetric,run.elapsedSeconds];
finite = all(isfinite(values));
end

