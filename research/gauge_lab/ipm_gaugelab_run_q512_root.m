selectedRatePrescribed = NaN;
selectedField = structure && ...
    isfield(diagnostic,'selectedRatePrescribed');
if selectedField
    selectedRatePrescribed = diagnostic.selectedRatePrescribed;
end
selectedNotPrescribed = selectedField && ...
    islogical(selectedRatePrescribed) && ...
    isscalar(selectedRatePrescribed) && ~selectedRatePrescribed;
provenanceAvailable = structure && ...
    isfield(diagnostic,'selectedRateProvenanceAvailable') && ...
    islogical(diagnostic.selectedRateProvenanceAvailable) && ...
    isscalar(diagnostic.selectedRateProvenanceAvailable) && ...
    diagnostic.selectedRateProvenanceAvailable;
empiricalEligible = structure && ...
    isfield(diagnostic,'empiricalRateConvergenceEligible') && ...
    islogical(diagnostic.empiricalRateConvergenceEligible) && ...
    isscalar(diagnostic.empiricalRateConvergenceEligible) && ...
    diagnostic.empiricalRateConvergenceEligible;
checks = struct( ...
    'scalarStructure',structure, ...
    'criteriaVersion3',criteriaV3, ...
    'selectedRateNotPrescribed',selectedNotPrescribed, ...
    'selectedRateProvenanceAvailable',provenanceAvailable, ...
    'empiricalRateConvergenceEligible',empiricalEligible);
failures = failed_checks(checks);
audit = struct( ...
    'passed',isempty(failures), ...
    'checks',checks, ...
    'failures',{failures}, ...
    'criteriaVersion',select_struct_field( ...
        diagnostic,'criteriaVersion',NaN), ...
    'selectedRatePrescribed',selectedRatePrescribed, ...
    'selectedRateProvenanceAvailable',provenanceAvailable, ...
    'empiricalRateConvergenceEligible',empiricalEligible);
end

function audit = audit_growth_telemetry(result)
common = result.history.common;
requiredHistory = {'canonicalTau','physicalTime','physicalRhoXInf', ...
    'physicalGradInf'};
recordCount = numel(common.t);
historyComplete = all(isfield(common,requiredHistory));
historyFinite = historyComplete && recordCount > 0;
if historyComplete
    for index = 1:numel(requiredHistory)
        values = common.(requiredHistory{index});
        historyFinite = historyFinite && isnumeric(values) && ...
            isreal(values) && isvector(values) && ...
            numel(values) == recordCount && all(isfinite(values(:)));
    end
end
physicalFitAvailable = isfield(result.fit,'maximumGrowthRate') && ...
    growth_fit_schema(result.fit.maximumGrowthRate);
canonicalFitAvailable = isfield(result.fit,'canonicalMaximumGrowth') && ...
    growth_fit_schema(result.fit.canonicalMaximumGrowth);

checks = struct( ...
    'historyComplete',historyComplete, ...
    'historyFinite',historyFinite, ...
    'positivePhysicalMaximum',false, ...
    'nondecreasingClocks',false, ...
    'physicalFitSchema',physicalFitAvailable, ...
    'canonicalFitSchema',canonicalFitAvailable, ...
    'fitInputAvailable',false, ...
    'quadraticTelemetrySchema',true, ...
    'quadraticTelemetryAvailable',true, ...
    'quadraticTelemetryGauge',true, ...
    'quadraticTelemetryAlgebra',true);
initialMaximum = NaN;
terminalMaximum = NaN;
totalLogGrowth = NaN;
if historyFinite
    physicalMaximum = common.physicalRhoXInf(:);
    checks.positivePhysicalMaximum = all(physicalMaximum > 0) && ...
        all(common.physicalGradInf(:) > 0);
    checks.nondecreasingClocks = ...
        all(diff(common.canonicalTau(:)) >= 0) && ...
        all(diff(common.physicalTime(:)) >= 0);
    initialMaximum = physicalMaximum(1);
    terminalMaximum = physicalMaximum(end);
    if initialMaximum > 0 && terminalMaximum > 0
        totalLogGrowth = log(terminalMaximum/initialMaximum);
    end
end
if physicalFitAvailable && canonicalFitAvailable
    physicalFit = result.fit.maximumGrowthRate;
    canonicalFit = result.fit.canonicalMaximumGrowth;
    checks.fitInputAvailable = ...
        isequal(physicalFit.inputAvailable,true) && ...
        isequal(canonicalFit.inputAvailable,true) && ...
        strcmp(physicalFit.observable,'physicalRhoXInf') && ...
        strcmp(canonicalFit.observable,'physicalRhoXInf');
end

quadraticAudit = struct('required',false,'passed',true);
if strcmp(result.config.scaling.cOmegaGauge, ...
        'wall_omega_quadratic_peak')
    [quadraticAudit,quadraticChecks] = ...
        audit_quadratic_growth_telemetry(result);
    checks.quadraticTelemetrySchema = quadraticChecks.schema;
    checks.quadraticTelemetryAvailable = quadraticChecks.available;
    checks.quadraticTelemetryGauge = quadraticChecks.gauge;
    checks.quadraticTelemetryAlgebra = quadraticChecks.algebra;
end
failures = failed_checks(checks);
audit = struct( ...
    'passed',isempty(failures), ...
    'checks',checks, ...
    'failures',{failures}, ...
    'observable','physicalRhoXInf', ...
    'recordCount',recordCount, ...
    'initialPhysicalRhoXInf',initialMaximum, ...
    'terminalPhysicalRhoXInf',terminalMaximum, ...
    'totalLogGrowth',totalLogGrowth, ...
    'quadraticPeakTelemetryAudit',quadraticAudit);
end

function valid = growth_fit_schema(fit)
required = {'valid','points','minimumCredibleEFolds','totalLogGrowth', ...
    'credibleClassification','observable','inputAvailable', ...
    'trustedRecords'};
valid = isstruct(fit) && isscalar(fit) && all(isfield(fit,required)) && ...
    islogical(fit.valid) && isscalar(fit.valid) && ...
    isnumeric(fit.points) && isscalar(fit.points) && ...
    isfinite(fit.points) && fit.points >= 0 && ...
    isequal(fit.minimumCredibleEFolds,3) && ...
    islogical(fit.credibleClassification) && ...
    isscalar(fit.credibleClassification) && ...
    islogical(fit.inputAvailable) && isscalar(fit.inputAvailable) && ...
    isnumeric(fit.trustedRecords) && isscalar(fit.trustedRecords) && ...
    isfinite(fit.trustedRecords) && fit.trustedRecords >= 0;
end

function [audit,checks] = audit_quadratic_growth_telemetry(result)
required = {'schemaVersion','observable','interpretation', ...
    'empiricalClassificationPerformed','selectedGauge', ...
    'inputAvailable','trustedRecords','validRecords', ...
    'storedReconstructionConsistent','physicalTime','canonicalTau', ...
    'physicalQuadraticPeak','inversePhysicalQuadraticPeak', ...
    'quadraticInverseSlopeAlgebraic','quadraticLocalTerminalTime', ...
    'rescaledRhoXInfToQuadraticPeak'};
available = isfield(result.fit,'quadraticPeakTelemetry');
schema = false;
gaugePassed = false;
algebra = false;
maximumDefect = Inf;
trustedRecords = 0;
if available
    telemetry = result.fit.quadraticPeakTelemetry;
    schema = isstruct(telemetry) && isscalar(telemetry) && ...
        all(isfield(telemetry,required)) && ...
        isequal(telemetry.schemaVersion,1);
    if schema
        gaugePassed = ...
            strcmp(telemetry.selectedGauge, ...
                'wall_omega_quadratic_peak') && ...
            strcmp(telemetry.observable, ...
                'selected_wall_omega_quadratic_peak') && ...
            isequal(telemetry.empiricalClassificationPerformed,false) && ...
            isequal(telemetry.inputAvailable,true) && ...
            isequal(telemetry.storedReconstructionConsistent,true);
        rawTrusted = ipm.output.trustedMask(result);
        trusted = ipm.output.continuousTrustedPrefix(rawTrusted);
        trustedRecords = nnz(trusted);
        series = {'physicalTime','canonicalTau', ...
            'physicalQuadraticPeak','inversePhysicalQuadraticPeak', ...
            'quadraticInverseSlopeAlgebraic', ...
            'quadraticLocalTerminalTime', ...
            'rescaledRhoXInfToQuadraticPeak'};
        alignedFinite = telemetry.trustedRecords == trustedRecords && ...
            telemetry.validRecords == trustedRecords && trustedRecords > 0;
        for index = 1:numel(series)
            values = telemetry.(series{index});
            alignedFinite = alignedFinite && isnumeric(values) && ...
                isreal(values) && isvector(values) && ...
                numel(values) == trustedRecords && ...
                all(isfinite(values(:)));
        end
        if alignedFinite
            common = result.history.common;
            peak = result.history.gauge. ...
                omegaGaugeQuadraticPeakValue(trusted);
            peak = peak(:);
            lengthScale = common.C_l(trusted);
            lengthScale = lengthScale(:);
            amplitudeScale = common.C_omega(trusted);
            amplitudeScale = amplitudeScale(:);
            cL = common.canonicalCL(trusted);
            cL = cL(:);
            cOmega = common.canonicalCOmega(trusted);
            cOmega = cOmega(:);
            physicalTime = common.physicalTime(trusted);
            physicalTime = physicalTime(:);
            rescaledMaximum = common.rhoXInf(trusted);
            rescaledMaximum = rescaledMaximum(:);
            physicalPeak = lengthScale./amplitudeScale.*peak;
            inversePeak = 1./physicalPeak;
            kappa = cL-cOmega;
            inverseSlope = -kappa./peak;
            terminalTime = physicalTime + ...
                peak./(kappa.*physicalPeak);
            maximumRatio = rescaledMaximum./peak;
            defects = [ ...
                relative_identity_defect( ...
                    telemetry.physicalTime(:),physicalTime); ...
                relative_identity_defect( ...
                    telemetry.canonicalTau(:), ...
                    reshape(common.canonicalTau(trusted),[],1)); ...
                relative_identity_defect( ...
                    telemetry.physicalQuadraticPeak(:),physicalPeak); ...
                relative_identity_defect( ...
                    telemetry.inversePhysicalQuadraticPeak(:),inversePeak); ...
                relative_identity_defect( ...
                    telemetry.quadraticInverseSlopeAlgebraic(:), ...
                    inverseSlope); ...
                relative_identity_defect( ...
                    telemetry.quadraticLocalTerminalTime(:),terminalTime); ...
                relative_identity_defect( ...
                    telemetry.rescaledRhoXInfToQuadraticPeak(:), ...
                    maximumRatio)];
            maximumDefect = max(defects);
            algebra = all(physicalPeak > 0) && all(inversePeak > 0) && ...
                all(kappa > 0) && maximumDefect <= 1e-10;
        end
    end
end
checks = struct('schema',schema,'available',available && schema && ...
    gaugePassed,'gauge',gaugePassed,'algebra',algebra);
audit = struct( ...
    'required',true, ...
    'passed',all(structfun(@(value)isequal(value,true),checks)), ...
    'checks',checks, ...
    'requiredFields',{required}, ...
    'trustedRecords',trustedRecords, ...
    'maximumAlgebraicDefect',maximumDefect);
end

function defect = relative_identity_defect(actual,expected)
actual = actual(:);
expected = expected(:);
scale = max([abs(actual),abs(expected), ...
    realmin*ones(size(actual))],[],2);
defect = abs(actual-expected)./scale;
end

