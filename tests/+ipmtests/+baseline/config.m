enumNames = normalizedNames;
for nameIndex = 1:numel(defaultNames)
    name = defaultNames{nameIndex};
    invalid = defaultResolved;
    if any(strcmp(name,enumNames))
        invalid.(name) = '__invalid__';
    elseif any(strcmp(name,booleanNames))
        invalid.(name) = 2;
    elseif any(strcmp(name,{'resultFile','videoFile'}))
        invalid.(name) = 42;
    elseif strcmp(name,'xlim')
        invalid.(name) = [NaN,NaN];
    elseif strcmp(name,'caseMetadata')
        invalid.(name) = [];
    else
        invalid.(name) = NaN;
    end
    if strcmp(name,'gridStretch')
        invalid.gridStretchAutomatic = false;
    end
    descriptor = schema.options.(name);
    if isempty(descriptor.errorId)
        assert_any_error(@()resolve_values(invalid),name);
    else
        assert_error(@()resolve_values(invalid),descriptor.errorId);
    end
end

