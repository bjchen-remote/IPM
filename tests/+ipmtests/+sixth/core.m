function config = sixth_order_config(numberOfNodes,mode,boundaryMode)
switch mode
    case 'uniform'
        gridMode = 'uniform';
        stretch = [0,0];
    case 'mild_sinh'
        gridMode = 'stretched';
        stretch = [0.45,0.35];
    case 'stress_sinh'
        gridMode = 'stretched';
        stretch = [1.00,0.75];
    otherwise
        error('ipm:SixthOrderTestGridMode', ...
            'Unknown sixth-order test grid mode ''%s''.',mode);
end
overrides = struct('nx',numberOfNodes,'ny',numberOfNodes, ...
    'xlim',[-1,1],'ymax',1,'gridMode',gridMode, ...
    'gridStretchAutomatic',false,'gridStretch',stretch, ...
    'transportBoundaryMode',boundaryMode, ...
    'symmetryMode','half_plane','adaptiveRemesh',false, ...
    'initialAnalyticRemesh',false,'saveResults',false, ...
    'makePlots',false,'livePlot',false,'writeVideo',false, ...
    'verbose',false);
config = ipm.config.resolve(ipm.config.sixthOrder(overrides));
assert(strcmp(config.transport.spatialDiscretization,'sixth_order') && ...
    strcmp(config.transport.transportScheme,'weno7_fd') && ...
    strcmp(config.time.timeIntegrator,'rk6') && ...
    strcmp(config.remesh.remeshTransferScheme,'sixth_order'), ...
    'ipm:SixthOrderTestTuple', ...
    'The core verifier did not resolve the complete sixth-order tuple.');
end

function values = full_node_norms(errorValues,weights)
weightSum = sum(weights,'all');
values = [sqrt(sum(weights.*abs(errorValues).^2,'all')/weightSum); ...
    max(abs(errorValues),[],'all')];
end

function values = line_norms(errorValues,weights)
weights = weights(:)';
errorValues = errorValues(:)';
values = [sqrt(sum(weights.*abs(errorValues).^2)/sum(weights)); ...
    max(abs(errorValues))];
end

function orders = refinement_orders(errors,h)
orders = log(errors(:,1:end-1)./errors(:,2:end)) ./ ...
    log(h(1:end-1)./h(2:end));
end

function axis = sinh_axis(numberOfNodes,stretch)
reference = linspace(-1,1,numberOfNodes)';
axis = sinh(stretch*reference)/sinh(stretch);
end

function axis = smooth_custom_axis(numberOfNodes)
reference = linspace(-1,1,numberOfNodes)';
axis = reference+0.08*sin(pi*reference);
axis([1,end]) = [-1,1];
end
