function values = resolve_values(overrides)
schema = ipm.config.schema();
values = flatten_config(ipm.config.resolve(overrides),schema);
end

function values = flatten_config(config,schema)
values = struct();
for domainIndex = 1:numel(schema.domainNames)
    domain = config.(schema.domainNames{domainIndex});
    names = fieldnames(domain);
    for nameIndex = 1:numel(names)
        values.(names{nameIndex}) = domain.(names{nameIndex});
    end
end
end

function assert_struct_equal(actual,expected,identifier,message)
assert(isequaln(orderfields(actual),orderfields(expected)),identifier,message);
end

function message = assert_error(action,expectedIdentifier)
try
    action();
catch exception
    assert(strcmp(exception.identifier,expectedIdentifier), ...
        'ipm:UnexpectedConfigError', ...
        'Expected "%s" but received "%s".', ...
        expectedIdentifier,exception.identifier);
    message = exception.message;
    return;
end
error('ipm:MissingConfigError', ...
    'Expected configuration error "%s" was not raised.',expectedIdentifier);
end

function assert_any_error(action,optionName)
try
    action();
catch
    return;
end
error('ipm:MissingOptionValidation', ...
    'Invalid value for option "%s" was accepted.',optionName);
end
