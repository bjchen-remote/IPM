function [x,y,info] = fourth_order_smooth_peak_grid( ...
        opts,strength,width,profile,profileParameters,qualityPolicy)
%FOURTH_ORDER_SMOOTH_PEAK_GRID Smooth symmetric two-peak mapped grid.
%   The base sinh map preserves the active case's remote truncation.  A
%   pair of Gaussian monitors in solver/grid x adds nodes near the two wall
%   derivative peaks without the sharp lattice transition that can excite
%   mapped WENO-FD oscillations.
%
%   PROFILE defaults to 'analytic_double_gaussian'.  The
%   'legacy_abs_gaussian' profile is retained only to reproduce archived
%   campaign results; its use of abs(x) is not differentiable at x=0.
%   'analytic_double_lorentzian' uses smooth algebraic shoulders to avoid
%   an abrupt transition out of the fine peak lattice.  The analytic
%   Gaussian-mixture profile adds a broad shoulder to a narrow peak monitor;
%   PROFILEPARAMETERS may set shoulderStrength and shoulderWidth.  All
%   analytic profiles also accept peakCenter so a fixed lattice can cover
%   the measured peak trajectory instead of only its initial position.
%   'coordinated_log_spacing' bypasses monitor equidistribution.  It puts a
%   uniform fine platform over a prescribed peak path and uses rounded
%   geometric cell widths on both sides.  The two asymptotic log-spacing
%   slopes are solved independently and the cell split is chosen to make
%   those slopes as equal as the integer cell budget permits.

if nargin < 2 || isempty(strength)
    strength = 2;
end
if nargin < 3 || isempty(width)
    width = 0.85;
end
if nargin < 4 || isempty(profile)
    profile = 'analytic_double_gaussian';
end
if nargin < 5 || isempty(profileParameters)
    profileParameters = struct();
end
if nargin < 6 || isempty(qualityPolicy)
    qualityPolicy = default_quality_policy();
else
    qualityPolicy = resolve_quality_policy(qualityPolicy);
end
validateattributes(strength,{'numeric'}, ...
    {'scalar','real','finite','positive'},mfilename,'strength');
validateattributes(width,{'numeric'}, ...
    {'scalar','real','finite','positive'},mfilename,'width');
profile = validatestring(profile, ...
    {'analytic_double_gaussian','analytic_double_lorentzian', ...
    'analytic_gaussian_mixture','coordinated_log_spacing', ...
    'legacy_abs_gaussian'}, ...
    mfilename,'profile');
if ~isstruct(profileParameters) || ~isscalar(profileParameters)
    error('ipm:SmoothPeakGridProfileParameters', ...
        'profileParameters must be a scalar structure.');
end
profileParameters = resolve_profile_parameters(profile,profileParameters);

config = ipm.config.resolve(opts);
grid = config.grid;
physics = config.physics;
if ~strcmp(physics.initialCondition,'degenerate_primitive')
    error('ipm:SmoothPeakGridDatum', ...
        'The smooth peak grid is defined for degenerate_primitive data.');
end
if mod(grid.nx,2) ~= 1 || abs(sum(grid.xlim)) > ...
        100*eps(max(abs(grid.xlim)))
    error('ipm:SmoothPeakGridSymmetry', ...
        'The smooth peak grid requires odd nx and symmetric xlim.');
end

stretch = grid.gridStretch(:)';
if isscalar(stretch)
    stretch = [stretch,stretch];
end
halfWidth = diff(grid.xlim)/2;
midpoint = mean(grid.xlim);
datumPeakCenter = (physics.degeneratePower-1)^(1/physics.degeneratePower);
peakCenter = datumPeakCenter;
if isfield(profileParameters,'peakCenter')
    peakCenter = profileParameters.peakCenter;
end
coordinatedDesign = struct();
if strcmp(profile,'coordinated_log_spacing')
    fineCount = 0;
    [x,coordinatedDesign] = coordinated_log_axis( ...
        halfWidth,grid.nx,profileParameters);
    mappingKind = 'direct_rounded_log_spacing';
    monitorCoordinate = 'none_direct_cell_widths';
else
    fineCount = max(131073,256*(grid.nx-1)+1);
    reference = linspace(-1,1,fineCount);
    baseX = midpoint+halfWidth*sinh_map(reference,stretch(1));
    switch profile
        case 'analytic_double_gaussian'
            monitor = 1+strength*( ...
                exp(-((baseX-peakCenter)/width).^2)+ ...
                exp(-((baseX+peakCenter)/width).^2));
        case 'analytic_double_lorentzian'
            monitor = 1+strength*( ...
                1./(1+((baseX-peakCenter)/width).^2)+ ...
                1./(1+((baseX+peakCenter)/width).^2));
        case 'analytic_gaussian_mixture'
            shoulderStrength = profileParameters.shoulderStrength;
            shoulderWidth = profileParameters.shoulderWidth;
            monitor = 1+strength*( ...
                exp(-((baseX-peakCenter)/width).^2)+ ...
                exp(-((baseX+peakCenter)/width).^2)) + ...
                shoulderStrength*( ...
                exp(-((baseX-peakCenter)/shoulderWidth).^2)+ ...
                exp(-((baseX+peakCenter)/shoulderWidth).^2));
        case 'legacy_abs_gaussian'
            monitor = 1+strength*exp( ...
                -((abs(baseX)-peakCenter)/width).^2);
    end
    massCoordinate = cumtrapz(reference,monitor);
    massCoordinate = (massCoordinate-massCoordinate(1))/ ...
        (massCoordinate(end)-massCoordinate(1));
    mappedReference = interp1(massCoordinate,reference, ...
        linspace(0,1,grid.nx),'pchip');
    x = midpoint+halfWidth*sinh_map(mappedReference,stretch(1));
    x = 0.5*(x-fliplr(x));
    x((grid.nx+1)/2) = 0;
    mappingKind = 'monitor_equidistribution';
    monitorCoordinate = 'solver_grid_x';
end

yReference = linspace(0,1,grid.ny)';
y = grid.ymax*sinh_map(yReference,stretch(2));

qx = ipm.mesh.quadrature(x);
qy = ipm.mesh.quadrature(y);
if any(qx <= 0) || any(qy <= 0)
    error('ipm:SmoothPeakGridQuadrature', ...
        'The smooth peak grid must retain positive high-order quadrature.');
end
qualityX = ipm.mesh.quality(x,7,qx);
qualityY = ipm.mesh.quality(y,7,qy);
ratioLimit = config.remesh.remeshMaximumCellRatio;
if qualityX.maximumAdjacentCellRatio > ratioLimit || ...
        qualityY.maximumAdjacentCellRatio > ratioLimit
    error('ipm:SmoothPeakGridCellRatio', ...
        ['The smooth peak grid adjacent-cell ratios %.6g/%.6g exceed ' ...
        'the configured limit %.6g.'], ...
        qualityX.maximumAdjacentCellRatio, ...
        qualityY.maximumAdjacentCellRatio,ratioLimit);
end
minimumStencilRcond = qualityPolicy.minimumStencilRcond;
if qualityX.minimumStencilRcond < minimumStencilRcond || ...
        qualityY.minimumStencilRcond < minimumStencilRcond
    error('ipm:SmoothPeakGridStencilCondition', ...
        ['The smooth peak grid stencil rcond %.3e/%.3e falls below ' ...
        'the admission floor %.3e.'],qualityX.minimumStencilRcond, ...
        qualityY.minimumStencilRcond,minimumStencilRcond);
end
minimumQuadratureWeightRatio = ...
    qualityPolicy.minimumQuadratureWeightRatio;
if qualityX.minimumQuadratureWeightRatio < ...
        minimumQuadratureWeightRatio || ...
        qualityY.minimumQuadratureWeightRatio < ...
        minimumQuadratureWeightRatio
    error('ipm:SmoothPeakGridQuadratureMargin', ...
        ['The smooth peak grid normalized quadrature margins %.3e/%.3e ' ...
        'fall below the admission floor %.3e.'], ...
        qualityX.minimumQuadratureWeightRatio, ...
        qualityY.minimumQuadratureWeightRatio, ...
        minimumQuadratureWeightRatio);
end
if qualityX.minimumQuadratureWeightToControlWidthRatio < ...
        qualityPolicy.minimumLocalQuadratureWeightRatio || ...
        qualityY.minimumQuadratureWeightToControlWidthRatio < ...
        qualityPolicy.minimumLocalQuadratureWeightRatio || ...
        qualityX.maximumQuadratureWeightToControlWidthRatio > ...
        qualityPolicy.maximumLocalQuadratureWeightRatio || ...
        qualityY.maximumQuadratureWeightToControlWidthRatio > ...
        qualityPolicy.maximumLocalQuadratureWeightRatio
    error('ipm:SmoothPeakGridLocalQuadratureMargin', ...
        ['The smooth peak grid local quadrature/control-width ratios ' ...
        '[%.3e,%.3e]/[%.3e,%.3e] leave the admitted interval ' ...
        '[%.3e,%.3e].'], ...
        qualityX.minimumQuadratureWeightToControlWidthRatio, ...
        qualityX.maximumQuadratureWeightToControlWidthRatio, ...
        qualityY.minimumQuadratureWeightToControlWidthRatio, ...
        qualityY.maximumQuadratureWeightToControlWidthRatio, ...
        qualityPolicy.minimumLocalQuadratureWeightRatio, ...
        qualityPolicy.maximumLocalQuadratureWeightRatio);
end
dx = diff(x);
dy = diff(y);
spacingBalanceX = log_spacing_balance(dx);
reportedStrength = strength;
reportedWidth = width;
if strcmp(profile,'coordinated_log_spacing')
    reportedStrength = NaN;
    reportedWidth = NaN;
end
info = struct( ...
    'strength',reportedStrength,'width',reportedWidth,'profile',profile, ...
    'profileParameters',profileParameters, ...
    'qualityPolicy',qualityPolicy, ...
    'mappingKind',mappingKind, ...
    'monitorCoordinate',monitorCoordinate, ...
    'mappingVersion',mapping_version(profile), ...
    'fineCount',fineCount, ...
    'peakCenter',peakCenter,'datumPeakCenter',datumPeakCenter, ...
    'maximumAdjacentCellRatioX',maximum_ratio(dx), ...
    'maximumAdjacentCellRatioY',maximum_ratio(dy), ...
    'maximumLogSpacingCurvatureX',max(abs(diff(log(dx),2))), ...
    'maximumLogSpacingCurvatureY',max(abs(diff(log(dy),2))), ...
    'minimumQuadratureWeightX',min(qx), ...
    'minimumQuadratureWeightY',min(qy), ...
    'minimumStencilRcondX',qualityX.minimumStencilRcond, ...
    'minimumStencilRcondY',qualityY.minimumStencilRcond, ...
    'minimumQuadratureWeightRatioX', ...
    qualityX.minimumQuadratureWeightRatio, ...
    'minimumQuadratureWeightRatioY', ...
    qualityY.minimumQuadratureWeightRatio, ...
    'minimumLocalQuadratureWeightRatioX', ...
    qualityX.minimumQuadratureWeightToControlWidthRatio, ...
    'maximumLocalQuadratureWeightRatioX', ...
    qualityX.maximumQuadratureWeightToControlWidthRatio, ...
    'minimumLocalQuadratureWeightRatioY', ...
    qualityY.minimumQuadratureWeightToControlWidthRatio, ...
    'maximumLocalQuadratureWeightRatioY', ...
    qualityY.maximumQuadratureWeightToControlWidthRatio, ...
    'maximumFirstDerivativeAmplificationX', ...
    qualityX.maximumFirstDerivativeAmplification, ...
    'maximumFirstDerivativeAmplificationY', ...
    qualityY.maximumFirstDerivativeAmplification, ...
    'maximumSecondDerivativeAmplificationX', ...
    qualityX.maximumSecondDerivativeAmplification, ...
    'maximumSecondDerivativeAmplificationY', ...
    qualityY.maximumSecondDerivativeAmplification, ...
    'logSpacingBalanceX',spacingBalanceX, ...
    'coordinatedDesign',coordinatedDesign);
end

function policy = default_quality_policy()
policy = struct('minimumStencilRcond',1e-9, ...
    'minimumQuadratureWeightRatio',1e-4, ...
    'minimumLocalQuadratureWeightRatio',0.35, ...
    'maximumLocalQuadratureWeightRatio',1.65, ...
    'quadratureWarningRatio',1e-4);
end

function policy = resolve_quality_policy(policy)
if ~isstruct(policy) || ~isscalar(policy)
    error('ipm:SmoothPeakGridQualityPolicy', ...
        'qualityPolicy must be a scalar structure.');
end
defaults = default_quality_policy();
names = fieldnames(policy);
unexpected = setdiff(names,fieldnames(defaults),'stable');
if ~isempty(unexpected)
    error('ipm:SmoothPeakGridQualityPolicy', ...
        'Unknown quality-policy field(s): %s.',strjoin(unexpected,', '));
end
for index = 1:numel(names)
    defaults.(names{index}) = policy.(names{index});
end
policy = defaults;
validateattributes(policy.minimumStencilRcond,{'numeric'}, ...
    {'scalar','real','finite','>',0,'<',1},mfilename, ...
    'qualityPolicy.minimumStencilRcond');
validateattributes(policy.minimumQuadratureWeightRatio,{'numeric'}, ...
    {'scalar','real','finite','>',0,'<',1},mfilename, ...
    'qualityPolicy.minimumQuadratureWeightRatio');
validateattributes(policy.minimumLocalQuadratureWeightRatio,{'numeric'}, ...
    {'scalar','real','finite','>',0,'<',1},mfilename, ...
    'qualityPolicy.minimumLocalQuadratureWeightRatio');
validateattributes(policy.maximumLocalQuadratureWeightRatio,{'numeric'}, ...
    {'scalar','real','finite','>',1},mfilename, ...
    'qualityPolicy.maximumLocalQuadratureWeightRatio');
validateattributes(policy.quadratureWarningRatio,{'numeric'}, ...
    {'scalar','real','finite','>',0,'<',1},mfilename, ...
    'qualityPolicy.quadratureWarningRatio');
if policy.minimumQuadratureWeightRatio > ...
        policy.quadratureWarningRatio
    error('ipm:SmoothPeakGridQualityPolicy', ...
        ['The hard quadrature-weight-ratio floor cannot exceed its ' ...
        'warning threshold.']);
end
end

function version = mapping_version(profile)
switch profile
    case 'analytic_double_gaussian'
        version = 2;
    case 'analytic_double_lorentzian'
        version = 3;
    case 'analytic_gaussian_mixture'
        version = 4;
    case 'coordinated_log_spacing'
        version = 5;
    case 'legacy_abs_gaussian'
        version = 1;
end
end

function parameters = resolve_profile_parameters(profile,parameters)
names = fieldnames(parameters);
if strcmp(profile,'coordinated_log_spacing')
    allowed = {'fineInterval','fineCellFraction','roundingFraction', ...
        'peakCenter'};
    unexpected = setdiff(names,allowed,'stable');
    if ~isempty(unexpected)
        error('ipm:SmoothPeakGridProfileParameters', ...
            'Unknown coordinated-grid parameter(s): %s.', ...
            strjoin(unexpected,', '));
    end
    if ~isfield(parameters,'fineInterval')
        if ~isfield(parameters,'peakCenter')
            parameters.peakCenter = 1.14;
        end
        parameters.fineInterval = parameters.peakCenter+[-0.19,0.16];
    end
    if ~isfield(parameters,'fineCellFraction')
        parameters.fineCellFraction = 80/256;
    end
    if ~isfield(parameters,'roundingFraction')
        parameters.roundingFraction = 28/256;
    end
    validateattributes(parameters.fineInterval,{'numeric'}, ...
        {'vector','numel',2,'real','finite','positive','increasing'}, ...
        mfilename,'profileParameters.fineInterval');
    validateattributes(parameters.fineCellFraction,{'numeric'}, ...
        {'scalar','real','finite','>',0,'<',1},mfilename, ...
        'profileParameters.fineCellFraction');
    validateattributes(parameters.roundingFraction,{'numeric'}, ...
        {'scalar','real','finite','>',0,'<',0.5},mfilename, ...
        'profileParameters.roundingFraction');
elseif strcmp(profile,'analytic_gaussian_mixture')
    allowed = {'shoulderStrength','shoulderWidth','peakCenter'};
    unexpected = setdiff(names,allowed,'stable');
    if ~isempty(unexpected)
        error('ipm:SmoothPeakGridProfileParameters', ...
            'Unknown Gaussian-mixture parameter(s): %s.', ...
            strjoin(unexpected,', '));
    end
    if ~isfield(parameters,'shoulderStrength')
        parameters.shoulderStrength = 2;
    end
    if ~isfield(parameters,'shoulderWidth')
        parameters.shoulderWidth = 0.9;
    end
    validateattributes(parameters.shoulderStrength,{'numeric'}, ...
        {'scalar','real','finite','positive'},mfilename, ...
        'profileParameters.shoulderStrength');
    validateattributes(parameters.shoulderWidth,{'numeric'}, ...
        {'scalar','real','finite','positive'},mfilename, ...
        'profileParameters.shoulderWidth');
elseif strcmp(profile,'analytic_double_lorentzian') || ...
        strcmp(profile,'analytic_double_gaussian')
    allowed = {'peakCenter'};
    unexpected = setdiff(names,allowed,'stable');
    if ~isempty(unexpected)
        error('ipm:SmoothPeakGridProfileParameters', ...
            'Unknown %s parameter(s): %s.',profile, ...
            strjoin(unexpected,', '));
    end
else
    if ~isempty(names)
        error('ipm:SmoothPeakGridProfileParameters', ...
            'Profile %s does not accept profileParameters.',profile);
    end
    parameters = struct();
end
if isfield(parameters,'peakCenter')
    validateattributes(parameters.peakCenter,{'numeric'}, ...
        {'scalar','real','finite','positive'},mfilename, ...
        'profileParameters.peakCenter');
end
end

function mapped = sinh_map(reference,stretch)
if stretch == 0
    mapped = reference;
else
    mapped = sinh(stretch*reference)/sinh(stretch);
end
end

function value = maximum_ratio(widths)
value = max(max(widths(2:end)./widths(1:end-1), ...
    widths(1:end-1)./widths(2:end)));
end

function [axis,design] = coordinated_log_axis(halfWidth,nodeCount,parameters)
% Build one symmetric axis directly from balanced positive-half widths.
numberOfCells = (nodeCount-1)/2;
referenceCells = 256;
refinementFactor = numberOfCells/referenceCells;
if refinementFactor > 1
    refinementLevels = log2(refinementFactor);
    if abs(refinementLevels-round(refinementLevels)) > ...
            100*eps(max(1,refinementLevels))
        error('ipm:CoordinatedGridRefinementFactor', ...
            ['A coordinated grid finer than q256 must use a power-of-two ' ...
            'positive-half refinement factor.']);
    end
    [referenceAxis,design] = coordinated_log_axis( ...
        halfWidth,2*referenceCells+1,parameters);
    positiveAxis = referenceAxis(referenceCells+1:end);
    positiveWidths = diff(positiveAxis);
    fineFirst = design.leftCells+1;
    fineLast = design.leftCells+design.fineCells;
    for level = 1:round(refinementLevels)
        flatFirst = max(1,fineFirst-1);
        flatLast = min(numel(positiveWidths),fineLast+1);
        positiveWidths = nested_geometric_split( ...
            positiveWidths,flatFirst:flatLast);
        fineFirst = 2*(fineFirst-1)+1;
        fineLast = 2*fineLast;
    end
    positiveAxis = [0,cumsum(positiveWidths)];
    positiveAxis(end) = halfWidth;
    axis = [-fliplr(positiveAxis(2:end)),positiveAxis];
    design.leftCells = design.leftCells*refinementFactor;
    design.fineCells = design.fineCells*refinementFactor;
    design.rightCells = design.rightCells*refinementFactor;
    design.roundingCells = design.roundingCells*refinementFactor;
    design.positiveHalfCells = numberOfCells;
    design.fineSpacing = mean(positiveWidths(fineFirst:fineLast));
    design.originSpacing = positiveWidths(1);
    design.remoteSpacing = positiveWidths(end);
    design.leftAsymptoticLogSlope = ...
        design.leftAsymptoticLogSlope/refinementFactor;
    design.rightAsymptoticLogSlope = ...
        design.rightAsymptoticLogSlope/refinementFactor;
    design.asymptoticSlopeBalance = ...
        min(design.leftAsymptoticLogSlope, ...
        design.rightAsymptoticLogSlope)/ ...
        max(design.leftAsymptoticLogSlope, ...
        design.rightAsymptoticLogSlope);
    transitionWidths = [ ...
        positiveWidths(1:design.leftCells), ...
        positiveWidths(design.leftCells+design.fineCells+1:end)];
    transitionJumps = abs(diff(log(transitionWidths)));
    transitionJumps(design.leftCells) = [];
    design.transitionLogSpacing = ...
        spacing_jump_statistics(transitionJumps);
    design.nestedReferencePositiveCells = referenceCells;
    design.nestedRefinementFactor = refinementFactor;
    design.strictlyNested = true;
    return
elseif refinementFactor ~= 1
    error('ipm:CoordinatedGridReferenceResolution', ...
        'The coordinated grid is defined for q256 and power-of-two refinements.');
end
fineInterval = parameters.fineInterval(:)';
if fineInterval(2) >= halfWidth
    error('ipm:CoordinatedGridFineInterval', ...
        'The coordinated fine interval must lie strictly inside xlim.');
end
if isfield(parameters,'peakCenter') && ...
        (parameters.peakCenter <= fineInterval(1) || ...
        parameters.peakCenter >= fineInterval(2))
    error('ipm:CoordinatedGridPeakCenter', ...
        'peakCenter must lie strictly inside the coordinated fine interval.');
end
numberOfFineCells = round(numberOfCells*parameters.fineCellFraction);
roundingCells = round(numberOfCells*parameters.roundingFraction);
if numberOfFineCells < 8 || roundingCells < 2 || ...
        numberOfFineCells+2*(roundingCells+2) > numberOfCells
    error('ipm:CoordinatedGridCellBudget', ...
        ['The fine/rounding fractions leave too few cells for the two ' ...
        'rounded geometric branches.']);
end

fineSpacing = diff(fineInterval)/numberOfFineCells;
leftLength = fineInterval(1);
rightLength = halfWidth-fineInterval(2);
firstLeftCount = roundingCells+2;
lastLeftCount = numberOfCells-numberOfFineCells-roundingCells-2;
bestObjective = inf;
bestSlopeMismatch = inf;
best = struct();
for leftCount = firstLeftCount:lastLeftCount
    rightCount = numberOfCells-numberOfFineCells-leftCount;
    if leftCount*fineSpacing > leftLength || ...
            rightCount*fineSpacing > rightLength
        continue
    end
    leftSlope = solve_rounded_growth( ...
        leftLength,fineSpacing,leftCount,roundingCells,true);
    rightSlope = solve_rounded_growth( ...
        rightLength,fineSpacing,rightCount,roundingCells,false);
    objective = max(leftSlope,rightSlope);
    mismatch = abs(leftSlope-rightSlope);
    tolerance = 100*eps(max(1,objective));
    if isempty(fieldnames(best)) || objective < bestObjective-tolerance || ...
            (abs(objective-bestObjective) <= tolerance && ...
            mismatch < bestSlopeMismatch)
        bestObjective = objective;
        bestSlopeMismatch = mismatch;
        best = struct('leftCount',leftCount,'rightCount',rightCount, ...
            'leftSlope',leftSlope,'rightSlope',rightSlope);
    end
end
if isempty(fieldnames(best))
    error('ipm:CoordinatedGridInfeasible', ...
        'No feasible coordinated log-spacing cell split was found.');
end

leftShape = rounded_bridge_shape(best.leftCount,roundingCells);
rightShape = rounded_geometric_shape(best.rightCount,roundingCells);
leftWidths = fineSpacing*exp(best.leftSlope*fliplr(leftShape));
fineWidths = fineSpacing*ones(1,numberOfFineCells);
rightWidths = fineSpacing*exp(best.rightSlope*rightShape);
% Correct only roundoff in the first/last cells so the protected interval
% and remote endpoint remain exact without perturbing interior ratios.
leftWidths(1) = leftWidths(1)+(leftLength-sum(leftWidths));
rightWidths(end) = rightWidths(end)+(rightLength-sum(rightWidths));
positiveWidths = [leftWidths,fineWidths,rightWidths];
positiveAxis = [0,cumsum(positiveWidths)];
positiveAxis(best.leftCount+1) = fineInterval(1);
positiveAxis(best.leftCount+numberOfFineCells+1) = fineInterval(2);
positiveAxis(end) = halfWidth;
axis = [-fliplr(positiveAxis(2:end)),positiveAxis];

transitionJumps = abs(diff(log([leftWidths,rightWidths])));
% Remove the artificial adjacency between the two branches in the joined
% diagnostic vector; the physical fine platform lies between them.
transitionJumps(best.leftCount) = [];
transitionBalance = spacing_jump_statistics(transitionJumps);
design = struct( ...
    'fineInterval',fineInterval, ...
    'fineCellFraction',parameters.fineCellFraction, ...
    'roundingFraction',parameters.roundingFraction, ...
    'positiveHalfCells',numberOfCells, ...
    'leftCells',best.leftCount, ...
    'fineCells',numberOfFineCells, ...
    'rightCells',best.rightCount, ...
    'roundingCells',roundingCells, ...
    'fineSpacing',fineSpacing, ...
    'originSpacing',positiveWidths(1), ...
    'remoteSpacing',positiveWidths(end), ...
    'leftAsymptoticLogSlope',best.leftSlope, ...
    'rightAsymptoticLogSlope',best.rightSlope, ...
    'asymptoticSlopeBalance', ...
    min(best.leftSlope,best.rightSlope)/ ...
    max(best.leftSlope,best.rightSlope), ...
    'transitionLogSpacing',transitionBalance, ...
    'nestedReferencePositiveCells',referenceCells, ...
    'nestedRefinementFactor',1, ...
    'strictlyNested',true);
end

function refined = nested_geometric_split(widths,fineCells)
% Split every cell exactly while approximating a half-step log-width law.
% Constant coarse geometric progressions become exact progressions with the
% square-root ratio; the protected fine platform remains exactly uniform.
widths = widths(:)';
logWidths = log(widths);
cellCount = numel(widths);
signedSlope = zeros(size(widths));
signedSlope(1) = 0.5*(logWidths(2)-logWidths(1));
signedSlope(2:end-1) = 0.5*( ...
    logWidths(3:end)-logWidths(1:end-2));
signedSlope(end) = logWidths(end)-logWidths(end-1);
signedSlope(fineCells) = 0;
withinCellRatio = exp(0.5*signedSlope);
first = widths./(1+withinCellRatio);
second = widths-first;
refined = zeros(1,2*cellCount);
refined(1:2:end) = first;
refined(2:2:end) = second;
end

function slope = solve_rounded_growth( ...
        targetLength,fineSpacing,cellCount,roundingCells,roundBothEnds)
if roundBothEnds
    shape = rounded_bridge_shape(cellCount,roundingCells);
else
    shape = rounded_geometric_shape(cellCount,roundingCells);
end
minimumLength = fineSpacing*cellCount;
lengthTolerance = 100*eps(max(1,targetLength));
if targetLength < minimumLength-lengthTolerance
    error('ipm:CoordinatedGridBranchInfeasible', ...
        'A coordinated-grid branch has too many fine cells for its length.');
elseif targetLength <= minimumLength+lengthTolerance
    slope = 0;
    return
end
lower = 0;
upper = 1/max(1,cellCount);
while rounded_growth_length(upper,fineSpacing,shape) < targetLength
    upper = 2*upper;
    if upper*max(shape) > log(realmax)-4
        error('ipm:CoordinatedGridGrowthOverflow', ...
            'Unable to bracket a finite coordinated-grid growth slope.');
    end
end
for iteration = 1:80
    midpoint = 0.5*(lower+upper);
    if rounded_growth_length(midpoint,fineSpacing,shape) < targetLength
        lower = midpoint;
    else
        upper = midpoint;
    end
end
slope = 0.5*(lower+upper);
end

function lengthValue = rounded_growth_length(slope,fineSpacing,shape)
lengthValue = fineSpacing*sum(exp(slope*shape));
end

function shape = rounded_geometric_shape(cellCount,roundingCells)
index = 0:cellCount-1;
shape = index-roundingCells/2;
rounded = index <= roundingCells;
shape(rounded) = index(rounded).^2/(2*roundingCells);
end

function shape = rounded_bridge_shape(cellCount,roundingCells)
% Integrate a log-slope ramp that vanishes at both adjacent plateaux.  The
% coarse plateau is the mirrored pair of cells at x=0; rounding this end is
% essential because an unrounded geometric branch has a curvature cusp at
% the symmetry plane.
interfaces = 1:cellCount-1;
increments = min([ones(size(interfaces)); ...
    (interfaces-0.5)/roundingCells; ...
    (cellCount-interfaces-0.5)/roundingCells],[],1);
shape = [0,cumsum(increments)];
end

function balance = log_spacing_balance(widths)
jumps = abs(diff(log(widths(:))));
balance = spacing_jump_statistics(jumps);
end

function statistics = spacing_jump_statistics(jumps)
jumps = jumps(:);
if isempty(jumps)
    statistics = struct('maximum',0,'mean',0,'rms',0,'variance',0, ...
        'coefficientOfVariation',0,'equalizationEfficiency',1, ...
        'halfVariationInterfaceFraction',1, ...
        'ninetyPercentVariationInterfaceFraction',1);
    return
end
totalVariation = sum(jumps);
meanJump = mean(jumps);
if totalVariation == 0
    coefficientOfVariation = 0;
    efficiency = 1;
    halfFraction = 1;
    ninetyFraction = 1;
else
    coefficientOfVariation = std(jumps,1)/meanJump;
    efficiency = totalVariation^2/(numel(jumps)*sum(jumps.^2));
    descending = sort(jumps,'descend');
    cumulative = cumsum(descending);
    halfFraction = find(cumulative >= 0.5*totalVariation,1)/numel(jumps);
    ninetyFraction = find(cumulative >= 0.9*totalVariation,1)/numel(jumps);
end
statistics = struct('maximum',max(jumps),'mean',meanJump, ...
    'rms',sqrt(mean(jumps.^2)), ...
    'variance',mean((jumps-meanJump).^2), ...
    'coefficientOfVariation',coefficientOfVariation, ...
    'equalizationEfficiency',efficiency, ...
    'halfVariationInterfaceFraction',halfFraction, ...
    'ninetyPercentVariationInterfaceFraction',ninetyFraction);
end
