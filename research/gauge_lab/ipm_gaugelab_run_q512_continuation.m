function path = locate_checkpoint(result,requestedFile)
path = '';
if isfield(result.metadata,'latestCheckpointFile')
    candidate = char(result.metadata.latestCheckpointFile);
    if ~isempty(candidate) && isfile(candidate)
        path = candidate;
        return
    end
end
[directory,stem,~] = fileparts(requestedFile);
if isempty(directory)
    directory = '.';
end
candidates = dir(fullfile(directory,[stem,'_*_step*.mat']));
if isempty(candidates)
    return
end
[~,order] = sort([candidates.datenum],'descend');
for index = 1:numel(order)
    candidate = candidates(order(index));
    candidatePath = fullfile(candidate.folder,candidate.name);
    try
        checkpoint = ipm.output.readCheckpoint(candidatePath);
        if checkpoint.payload.state.step == result.state.steps && ...
                isequaln(checkpoint.payload.state.rho,result.state.rho)
            path = candidatePath;
            return
        end
    catch
        % Keep looking for the terminal immutable checkpoint.
    end
end
end

