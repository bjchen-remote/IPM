function guarded = anchor_wall_window_l2_guarded(options)
options.scaling.cOmegaGauge = 'anchor_wall_window_l2';
narrowOptions = options;
narrowOptions.scaling.omegaGaugeWindowRadius = 0.01;
supportRejected = window_l2_initialization_rejected( ...
    narrowOptions,'ipm:OmegaGaugeWindowSupport');

ops = ipm.mesh.build(options);
rho = ipm.field.initialDensity(ops,options.physics);
ops = ipm.evolve.initializeScaling(rho,ops);
try
    ipm.evolve.wallWindowL2(zeros(1,ops.nx),ops,ops.rescaling);
catch exception
    degeneracyRejected = ...
        strcmp(exception.identifier,'ipm:DegenerateNormalization');
    guarded = supportRejected && degeneracyRejected;
    return;
end
guarded = false;
end

