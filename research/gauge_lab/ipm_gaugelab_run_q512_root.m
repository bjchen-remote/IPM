function audit = audit_quadratic_stencil_history( ...
        gridX,stencilCenter,vertexX,recordedFraction)
gridX = gridX(:);
recordCount = numel(stencilCenter);
centerOnGrid = false(recordCount,1);
centerInterior = false(recordCount,1);
vertexInterior = false(recordCount,1);
fractionIdentity = false(recordCount,1);
centerDistance = Inf(recordCount,1);
fractionDefect = Inf(recordCount,1);
centerIndex = NaN(recordCount,1);
for index = 1:recordCount
    [centerDistance(index),nearest] = ...
        min(abs(gridX-stencilCenter(index)));
    centerIndex(index) = nearest;
    tolerance = 128*eps(max([1;abs(stencilCenter(index));abs(gridX)]));
    centerOnGrid(index) = centerDistance(index) <= tolerance;
    centerInterior(index) = nearest > 1 && nearest < numel(gridX);
    if centerOnGrid(index) && centerInterior(index)
        left = gridX(nearest-1);
        right = gridX(nearest+1);
        vertexInterior(index) = vertexX(index) > left+tolerance && ...
            vertexX(index) < right-tolerance;
        expectedFraction = min(vertexX(index)-left, ...
            right-vertexX(index))/(right-left);
        fractionDefect(index) = abs(recordedFraction(index)- ...
            expectedFraction)/max([abs(recordedFraction(index)), ...
            abs(expectedFraction),realmin]);
        fractionIdentity(index) = fractionDefect(index) <= 1e-10 && ...
            recordedFraction(index) > 0 && ...
            recordedFraction(index) <= 0.5+1e-10;
    end
end
audit = struct( ...
    'centerOnGrid',all(centerOnGrid), ...
    'centerInterior',all(centerInterior), ...
    'vertexInterior',all(vertexInterior), ...
    'fractionIdentity',all(fractionIdentity), ...
    'maximumCenterDistance',max(centerDistance), ...
    'maximumFractionDefect',max(fractionDefect), ...
    'centerIndices',centerIndex);
end

