normalized = abs(residual)./scale;
end

function rules = registered_gauge_rules(cOmegaGauge)
rules = struct( ...
    'scalingContract','exact_gauge_no_feedback_v1', ...
    'clock','tau_is_integrated_directly; timeSpeed=1', ...
    'lengthGauge','transport_anchor', ...
    'lengthObservable','V_1(1,0)=0', ...
    'lengthFormula','c_l=-U_1(1,0)', ...
    'amplitudeGauge',cOmegaGauge, ...
    'amplitudeObservable','', ...
    'amplitudeFormula','', ...
    'selectedRatePrescribed',false, ...
    'rateLimiter','absent', ...
    'feedbackGains',[1,0,0,0]);
switch cOmegaGauge
    case 'gradient_energy'
        rules.amplitudeObservable = ...
            'sum(w*(R_X^2+R_Y^2)) is constant';
        rules.amplitudeFormula = [ ...
            'c_omega=-sum(w*(R_X*B_X+R_Y*B_Y))/' ...
            'sum(w*(R_X^2+R_Y^2))'];
    case 'wall_omega_quadratic_peak'
        rules.amplitudeObservable = ...
            'tracked nonuniform quadratic wall R_X peak is constant';
        rules.amplitudeFormula = ...
            'c_omega=-Q[B_X](X_vertex)/Q[R_X](X_vertex)';
    otherwise
        error('ipm:GaugeLabQ512COmegaGauge', ...
            'Unsupported registered cOmegaGauge: %s.',cOmegaGauge);
end
end

