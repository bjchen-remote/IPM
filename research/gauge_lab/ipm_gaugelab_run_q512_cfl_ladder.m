for index = 1:numel(ladder.roots)
    record = ladder.roots(index);
    if ~strcmp(record.status,expected)
        failures{end+1,1} = sprintf('%s:root:%s', ...
            record.name,record.status); %#ok<AGROW>
    end
end
for index = 1:numel(ladder.sharedContractAudit.failures)
    failures{end+1,1} = sprintf('shared_contract:%s', ...
        ladder.sharedContractAudit.failures{index}); %#ok<AGROW>
end
if settings.execute
    if ~ladder.comparison.available
        failures{end+1,1} = sprintf('comparison:%s', ...
            ladder.comparison.status);
    else
        for index = 1:numel(ladder.comparison.failures)
            failures{end+1,1} = sprintf('comparison_gate:%s', ...
                ladder.comparison.failures{index}); %#ok<AGROW>
        end
    end
end
end

