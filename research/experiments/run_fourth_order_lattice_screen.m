function products = run_fourth_order_lattice_screen(campaign)
%RUN_FOURTH_ORDER_LATTICE_SCREEN Dynamic q256 screen for smooth LAT maps.
%   RUN_FOURTH_ORDER_LATTICE_SCREEN('monitor') runs one Gaussian control and
%   two Lorentzian-monitor maps.  The default 'coordinated' campaign runs
%   six rounded-log grids that explicitly equalize adjacent-density
%   changes outside a protected x=0.95--1.30 fine platform.  Every case is
%   integrated through physical time 0.55.

if nargin < 1 || isempty(campaign)
    campaign = 'coordinated';
end
campaign = validatestring(campaign,{'coordinated','monitor'}, ...
    mfilename,'campaign');

experimentDirectory = fileparts(mfilename('fullpath'));
researchDirectory = fileparts(experimentDirectory);
projectDirectory = fileparts(researchDirectory);
analysisDirectory = fullfile(researchDirectory,'analysis');
addpath(projectDirectory,experimentDirectory,analysisDirectory);

if strcmp(campaign,'coordinated')
    names = { ...
        'coordinated_log_F80_R16_c114_quadrant_256', ...
        'coordinated_log_F80_R20_c114_quadrant_256', ...
        'coordinated_log_F80_R24_c114_quadrant_256', ...
        'coordinated_log_F80_R28_c114_quadrant_256', ...
        'coordinated_log_F90_R20_c114_quadrant_256', ...
        'coordinated_log_F92_R20_c114_quadrant_256'};
    stems = { ...
        'fourth_order_lat_screen_coordinated_F80_R16_q256_t055', ...
        'fourth_order_lat_screen_coordinated_F80_R20_q256_t055', ...
        'fourth_order_lat_screen_coordinated_F80_R24_q256_t055', ...
        'fourth_order_lat_screen_coordinated_F80_R28_q256_t055', ...
        'fourth_order_lat_screen_coordinated_F90_R20_q256_t055', ...
        'fourth_order_lat_screen_coordinated_F92_R20_q256_t055'};
    summaryStem = ...
        'fourth_order_lat_screen_coordinated_q256_summary.mat';
else
    names = { ...
        'analytic_gaussian_A14_w042_c114_quadrant_256', ...
        'analytic_lorentzian_A24_w020_c114_quadrant_256', ...
        'analytic_lorentzian_A28_w020_c114_quadrant_256'};
    stems = { ...
        'fourth_order_lat_screen_gaussian_A14_w042_c114_q256_t055', ...
        'fourth_order_lat_screen_lorentzian_A24_w020_c114_q256_t055', ...
        'fourth_order_lat_screen_lorentzian_A28_w020_c114_q256_t055'};
    summaryStem = 'fourth_order_lat_screen_lorentzian_q256_summary.mat';
end
verificationDirectory = fullfile(projectDirectory,'result','verification');
if ~isfolder(verificationDirectory)
    mkdir(verificationDirectory);
end
summaryFile = ipm.output.uniquePath(fullfile(verificationDirectory, ...
    summaryStem),'lat_screen');

template = struct( ...
    'caseName','', 'resultFile','', 'assessmentFile','', ...
    'elapsedSeconds',NaN, 'stopReason','', 'stopTime',NaN, ...
    'trustedThroughTime',NaN, 'steps',NaN, ...
    'initialCorePointsX',NaN, 'initialCorePointsY',NaN, ...
    'finalTrustedCorePointsX',NaN, 'finalTrustedCorePointsY',NaN, ...
    'maximumTrustedWallTV',NaN, 'maximumTrustedWallLocalMaxima',NaN, ...
    'minimumTrustedGridPeakX',NaN, 'maximumTrustedGridPeakX',NaN, ...
    'minimumTrustedPhysicalPeakX',NaN, ...
    'maximumTrustedPhysicalPeakX',NaN, ...
    'minimumDx',NaN, 'globalGridRatioX',NaN, ...
    'maximumAdjacentCellRatioX',NaN, ...
    'maximumLogSpacingCurvatureX',NaN, ...
    'transitionEqualizationEfficiency',NaN, ...
    'transitionHalfVariationInterfaceFraction',NaN, ...
    'asymptoticSlopeBalance',NaN, ...
    'finePlatformSpacing',NaN, ...
    'leftFineRightCells',nan(1,3), ...
    'worstPeakPathDx',NaN, 'predictedLateCorePoints',NaN, ...
    'minimumTrustedCorePointsX',NaN, ...
    'minimumTrustedCorePointsY',NaN, ...
    'maximumTrustedSafetyFactor',NaN, ...
    'terminalStateTrusted',false, 'screenPassed',false, ...
    'profile','', 'mappingVersion',NaN, 'strength',NaN, ...
    'width',NaN, 'peakCenter',NaN, 'profileParameters',struct(), ...
    'errorIdentifier','', 'errorMessage','');
products = struct('requestedPhysicalFinalTime',0.55, ...
    'startedAt',datetime('now','TimeZone','local'), ...
    'completedAt',NaT,'summaryFile',summaryFile, ...
    'runs',repmat(template,numel(names),1));

for index = 1:numel(names)
    fprintf('\nLAT SCREEN %d/%d: %s\n',index,numel(names),names{index});
    requestedResultFile = fullfile(verificationDirectory,[stems{index},'.mat']);
    runInfo = template;
    runInfo.caseName = names{index};
    wallClock = tic;
    try
        opts = fourth_order_blowup_case(names{index},struct( ...
            'physicalFinalTime',products.requestedPhysicalFinalTime, ...
            'resultFile',requestedResultFile));
        runInfo.caseName = opts.caseMetadata.caseName;
        dx = diff(opts.customX);
        cellCenters = opts.customX(1:end-1)+0.5*dx;
        peakPath = linspace(0.97,1.28,301);
        gridInfo = opts.caseMetadata.smoothGrid;
        runInfo.minimumDx = min(dx);
        runInfo.globalGridRatioX = max(dx)/min(dx);
        runInfo.maximumAdjacentCellRatioX = ...
            gridInfo.maximumAdjacentCellRatioX;
        runInfo.maximumLogSpacingCurvatureX = ...
            gridInfo.maximumLogSpacingCurvatureX;
        if ~isempty(fieldnames(gridInfo.coordinatedDesign))
            design = gridInfo.coordinatedDesign;
            runInfo.transitionEqualizationEfficiency = ...
                design.transitionLogSpacing.equalizationEfficiency;
            runInfo.transitionHalfVariationInterfaceFraction = ...
                design.transitionLogSpacing. ...
                halfVariationInterfaceFraction;
            runInfo.asymptoticSlopeBalance = ...
                design.asymptoticSlopeBalance;
            runInfo.finePlatformSpacing = design.fineSpacing;
            runInfo.leftFineRightCells = [design.leftCells, ...
                design.fineCells,design.rightCells];
        end
        runInfo.worstPeakPathDx = max(interp1( ...
            cellCenters,dx,peakPath,'pchip'));
        runInfo.predictedLateCorePoints = ...
            0.0562/runInfo.worstPeakPathDx;
        runInfo.profile = gridInfo.profile;
        runInfo.mappingVersion = gridInfo.mappingVersion;
        runInfo.strength = gridInfo.strength;
        runInfo.width = gridInfo.width;
        runInfo.peakCenter = gridInfo.peakCenter;
        runInfo.profileParameters = gridInfo.profileParameters;
        result = ipm.solve(opts);
        runInfo.elapsedSeconds = toc(wallClock);
        runInfo.resultFile = char(result.metadata.resultFile);
        runInfo.stopReason = result.state.stopReason;
        runInfo.stopTime = result.state.physicalTime;
        runInfo.steps = result.state.steps;
        % Preserve the expensive solver product even if a later assessment
        % or plotting diagnostic fails.
        products.runs(index) = runInfo;
        save(summaryFile,'products');
        assessment = ipm_assess_fourth_order_blowup(result);
        resultFile = char(result.metadata.resultFile);
        [resultDirectory,resultStem] = fileparts(resultFile);
        assessmentFile = fullfile(resultDirectory, ...
            [resultStem,'_assessment.mat']);
        save(assessmentFile,'assessment');

        prefix = assessment.trustedPrefixMask;
        common = result.history.common;
        mesh = result.history.mesh;
        runInfo.assessmentFile = assessmentFile;
        runInfo.trustedThroughTime = assessment.trustedThroughTime;
        runInfo.initialCorePointsX = mesh.coreGridPoints(1);
        runInfo.initialCorePointsY = mesh.verticalCoreGridPoints(1);
        runInfo.finalTrustedCorePointsX = ...
            assessment.finalTrustedCorePoints;
        runInfo.finalTrustedCorePointsY = ...
            assessment.finalTrustedVerticalCorePoints;
        runInfo.terminalStateTrusted = assessment.terminalStateTrusted;
        if any(prefix)
            runInfo.maximumTrustedWallTV = max(common.wallPeakTVRatio(prefix));
            runInfo.maximumTrustedWallLocalMaxima = ...
                max(common.wallPeakLocalMaxima(prefix));
            runInfo.minimumTrustedPhysicalPeakX = ...
                min(common.physicalTrackedPeakX(prefix));
            runInfo.maximumTrustedPhysicalPeakX = ...
                max(common.physicalTrackedPeakX(prefix));
            gauge = result.history.gauge;
            runInfo.minimumTrustedGridPeakX = ...
                min(gauge.trackedPeakX(prefix));
            runInfo.maximumTrustedGridPeakX = ...
                max(gauge.trackedPeakX(prefix));
            runInfo.minimumTrustedCorePointsX = ...
                min(mesh.coreGridPoints(prefix));
            runInfo.minimumTrustedCorePointsY = ...
                min(mesh.verticalCoreGridPoints(prefix));
            runInfo.maximumTrustedSafetyFactor = ...
                max(mesh.safetyFactor(prefix));
        end
        runInfo.screenPassed = runInfo.terminalStateTrusted && ...
            runInfo.stopTime >= products.requestedPhysicalFinalTime-1e-10;
        fprintf(['LAT RESULT %s: elapsed %.3f s, raw/trusted t ' ...
            '%.9g/%.9g, stop %s, core %.3f/%.3f, max TV %.7f\n'], ...
            runInfo.caseName,runInfo.elapsedSeconds,runInfo.stopTime, ...
            runInfo.trustedThroughTime,runInfo.stopReason, ...
            runInfo.finalTrustedCorePointsX, ...
            runInfo.finalTrustedCorePointsY, ...
            runInfo.maximumTrustedWallTV);
    catch exception
        runInfo.elapsedSeconds = toc(wallClock);
        runInfo.errorIdentifier = exception.identifier;
        runInfo.errorMessage = exception.message;
        fprintf(2,'LAT ERROR %s: %s (%s)\n', ...
            runInfo.caseName,exception.message,exception.identifier);
    end
    products.runs(index) = runInfo;
    save(summaryFile,'products');
end
products.completedAt = datetime('now','TimeZone','local');
save(summaryFile,'products');
fprintf('\nLAT SCREEN COMPLETE: %s\n',summaryFile);
end
