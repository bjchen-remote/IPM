function label = input_label(input)
if ischar(input) || (isstring(input) && isscalar(input))
    label = absolute_path(char(input));
elseif isstruct(input) && isscalar(input) && ...
        isfield(input,'kind') && ...
        strcmp(input.kind,'ipm_accepted_step_checkpoint')
    label = 'in_memory_checkpoint';
else
    label = 'in_memory_result_or_dataset';
end
end

function value = stable_input_reference(value)
if ischar(value) || (isstring(value) && isscalar(value))
    value = absolute_path(char(value));
end
end

function value = absolute_path(value)
value = char(value);
isUnixAbsolute = startsWith(value,filesep);
isWindowsAbsolute = ~isempty(regexp(value,'^[A-Za-z]:[\\/]', 'once'));
if ~(isUnixAbsolute || isWindowsAbsolute)
    value = fullfile(pwd,value);
end
end

function assert_new_file(fileName,label)
