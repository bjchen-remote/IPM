record.maximumCellWidth = max(widths);
record.maximumAdjacentCellRatio = ...
    info.quality.maximumAdjacentCellRatio;
record.maximumLogSpacingCurvature = ...
    info.quality.maximumLogSpacingCurvature;
end

function [coreCounts,frontCounts] = x_resolution(axis,records)
positive = axis((numel(axis)+1)/2:end);
coreCounts = zeros(numel(records),1);
frontCounts = zeros(numel(records),1);
for index = 1:numel(records)
    profile = records(index);
    coreInterval = [ ...
        max(0,profile.safetyCoreCenter-profile.safetyCoreWidthLeft), ...
        min(positive(end),profile.safetyCoreCenter+ ...
            profile.safetyCoreWidthRight)];
    frontInterval = [ ...
        max(0,profile.leftFrontCenter-profile.leftFrontHalfWidth), ...
        min(positive(end),profile.leftFrontCenter+ ...
            profile.leftFrontHalfWidth)];
    coreCounts(index) = interval_cells(positive,coreInterval);
    frontCounts(index) = interval_cells(positive,frontInterval);
end
end

function coreCounts = y_resolution(axis,records)
coreCounts = zeros(numel(records),1);
for index = 1:numel(records)
    interval = [0,min(axis(end),records(index).yCoreWidth)];
    coreCounts(index) = interval_cells(axis,interval);
end
end

function count = interval_cells(axis,interval)
widths = diff(axis);
overlap = max(0,min(axis(2:end),interval(2))- ...
    max(axis(1:end-1),interval(1)));
count = sum(overlap./widths);
end

function name = model_name(model,index,prefix)
if isfield(model,'name') && ...
        (ischar(model.name) || ...
        (isstring(model.name) && isscalar(model.name)))
    name = char(model.name);
else
    name = sprintf('%s_candidate_%03d',prefix,index);
end
end

function [selectedIndex,order] = select_candidate(candidates)
eligible = find([candidates.meetsTargets]);
if isempty(eligible)
    selectedIndex = [];
    order = zeros(0,1);
    return
end
ranking = [[candidates(eligible).minimumCellWidth]', ...
    [candidates(eligible).maximumAdjacentCellRatio]', ...
    [candidates(eligible).maximumLogSpacingCurvature]',eligible(:)];
[~,localOrder] = sortrows( ...
    [-ranking(:,1),ranking(:,2),ranking(:,3),ranking(:,4)], ...
    [1,2,3,4]);
order = eligible(localOrder);
selectedIndex = order(1);
end

function feasibility = summarize_feasibility( ...
        xCandidates,yCandidates,options,limits)
xAdmitted = find([xCandidates.admissible]);
yAdmitted = find([yCandidates.admissible]);
xCore = candidate_bound(xCandidates,xAdmitted,'minimumCoreCells');
xFront = candidate_bound(xCandidates,xAdmitted,'minimumFrontCells');
yCore = candidate_bound(yCandidates,yAdmitted,'minimumCoreCells');
xWithFront = xAdmitted([xCandidates(xAdmitted).minimumFrontCells] >= ...
    options.minimumXFrontCells);
xCoreWithFront = candidate_bound( ...
    xCandidates,xWithFront,'minimumCoreCells');
xWithCore = xAdmitted([xCandidates(xAdmitted).minimumCoreCells] >= ...
    options.targetXCoreCells);
xFrontWithCore = candidate_bound( ...
    xCandidates,xWithCore,'minimumFrontCells');
feasibility = struct( ...
    'ratioCap',options.ratioCap,'ratioCapRelaxed',false, ...
    'meshLimits',limits, ...
    'x',struct( ...
        'candidateCount',numel(xCandidates), ...
        'admissibleCount',numel(xAdmitted), ...
        'feasibleCount',nnz([xCandidates.meetsTargets]), ...
        'requiredCoreCells',options.targetXCoreCells, ...
        'requiredFrontCells',options.minimumXFrontCells, ...
        'maximumCoreCells',xCore, ...
        'maximumFrontCells',xFront, ...
        'maximumCoreCellsWithFrontGate',xCoreWithFront, ...
        'maximumFrontCellsWithCoreGate',xFrontWithCore), ...
    'y',struct( ...
        'candidateCount',numel(yCandidates), ...
        'admissibleCount',numel(yAdmitted), ...
        'feasibleCount',nnz([yCandidates.meetsTargets]), ...
        'requiredCoreCells',options.targetYCoreCells, ...
        'maximumCoreCells',yCore));
end

function bound = candidate_bound(candidates,indices,field)
bound = struct('value',NaN,'candidateIndex',NaN, ...
    'candidateName','','candidateFamily','');
if isempty(indices)
    return
end
values = [candidates(indices).(field)];
[value,localIndex] = max(values);
index = indices(localIndex);
bound = struct('value',value,'candidateIndex',index, ...
    'candidateName',candidates(index).name, ...
    'candidateFamily',candidates(index).family);
end

