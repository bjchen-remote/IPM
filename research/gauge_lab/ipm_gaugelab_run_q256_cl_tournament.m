    'maximumOmegaGaugeResidual',maximumOmegaResidual, ...
    'maximumPeakLocationPhaseDefect',maximumPeakPhaseDefect, ...
    'maximumNormalizedFullPeakPhaseResidual', ...
        maximumNormalizedFullPhaseResidual, ...
    'minimumPeakLocationResponseCondition', ...
        minimumPeakResponseCondition, ...
    'minimumWallDensityCrossingCondition', ...
        minimumDensityCrossingCondition, ...
    'residualTolerance',tolerance);
