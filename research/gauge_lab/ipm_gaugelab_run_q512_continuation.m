    'transportAnchorVelocity','canonicalTransportAnchorVelocity', ...
    'transportAnchorX','c_lNominal','canonicalCLNominal', ...
    'lengthScaleGain','widthControlMode','widthCorrection', ...
    'canonicalWidthCorrection','omegaGaugeEnergy'};
