function campaign = ipm_gridlab_run_q512_campaign( ...
        terminalInput,referenceInput,options)
%IPM_GRIDLAB_RUN_Q512_CAMPAIGN Conservative staged q512 continuation.
%   CAMPAIGN = IPM_GRIDLAB_RUN_Q512_CAMPAIGN(TERMINAL,REFERENCE,OPTIONS)
%   repeatedly performs
%
%       global-reference design -> audited checkpoint regrid -> ipm.solve
%
%   until max|physical rho_x| reaches OPTIONS.targetPhysicalRhoX, a strict
%   terminal gate fails, or the inter-stage wall-clock budget is exhausted.
%   TERMINAL is a production schema-4 accepted-step checkpoint, a compact
%   schema-v2 result, or its MAT-file. REFERENCE is the initial schema-v2
%   frozen dataset (or its
%   MAT-file) whose axes are the primary global reference at every stage.
%   An explicitly configured, generation-limited current-axis fallback is
%   available for x and is disabled by default. A root-reference corridor
%   fallback for x is independently available and disabled by default. A
%   fixed uniform global fallback is available for y; every design records
%   which reference was actually selected.
%
%   A native terminal checkpoint is the preferred input and is required
%   between solver stages. A terminal result is accepted only through
%   ipm.output.checkpointFromResult and is prominently recorded as the
%   machine-precision result bridge, not as a bitwise native restart.
%
%   This driver is deliberately restricted to the maintained 1025-by-513
%   stored-node fourth-order isotropic tuple. The default stage is 0.35 and
%   every stage is at most 0.42 canonical-time units. Native checkpoints
%   are requested every 0.20
%   canonical-time units and at exit on trusted recorded states. Results,
%   designs, audits, checkpoints, and summary snapshots are installed under
%   a unique campaign directory; no result or checkpoint path is reused.
%
%   The wall-clock budget is a conservative inter-stage launch gate. The
%   current design, regrid, and ipm.solve interfaces have no wall-clock
%   callback, so an already running phase is allowed to finish and may
%   overrun the budget. Numerical target attainment is not a blowup proof.

if nargin < 3 || isempty(options)
    options = struct();
end
options = resolve_options(options);
[campaignDirectory,campaignId] = create_campaign_directory(options);
campaign = initialize_campaign( ...
    campaignDirectory,campaignId,terminalInput,referenceInput,options);
referenceForDesign = stable_input_reference(referenceInput);
campaign.referenceLabel = input_label(referenceForDesign);
campaignTimer = tic;
activeStage = 0;

try
    [checkpoint,currentCheckpoint,restart] = resolve_terminal_input( ...
        terminalInput,campaignDirectory);
    validate_q512_source(checkpoint,options);
    campaign.restart = restart;
    campaign.currentCheckpointFile = currentCheckpoint;
    campaign.inheritedRegridRhoXRelativeJump = ...
        inherited_regrid_jump(checkpoint);
    campaign.cumulativeRegridRhoXRelativeJump = ...
        campaign.inheritedRegridRhoXRelativeJump;
    initialMetrics = checkpoint_terminal_metrics(checkpoint);
    campaign.initialMetrics = initialMetrics;
    campaign.finalMetrics = initialMetrics;

    [sourcePassed,sourceReasons] = terminal_gate(initialMetrics,options);
    if campaign.cumulativeRegridRhoXRelativeJump > ...
            options.maximumCumulativeRegridRhoXRelativeJump
        sourcePassed = false;
        sourceReasons{end+1} = 'inherited_regrid_rho_x_jump_budget';
    end
    if ~sourcePassed
        campaign.status = 'stopped_gate';
        campaign.stopReason = strjoin(sourceReasons,',');
        campaign = finish_campaign(campaign,campaignTimer);
        campaign = save_snapshot(campaign,'source_gate_failed',0);
        return
    end
    if initialMetrics.physicalRhoX >= options.targetPhysicalRhoX
        campaign.status = 'target_reached';
        campaign.stopReason = 'target_already_reached_at_input';
        campaign.targetReached = true;
        campaign = finish_campaign(campaign,campaignTimer);
        campaign = save_snapshot(campaign,'target_reached',0);
        return
    end

    campaign.status = 'running';
    campaign.stopReason = '';
    campaign = save_snapshot(campaign,'campaign_ready',0);
    lastSolveSeconds = NaN;

    for localStage = 1:options.maximumStages
        elapsed = toc(campaignTimer);
        launchReserve = launch_reserve(options,lastSolveSeconds);
        if elapsed+launchReserve > options.wallClockBudgetSeconds
            campaign.status = 'wall_clock_budget';
            campaign.stopReason = 'insufficient_budget_before_stage_design';
            break
        end

        stageNumber = options.firstStageIndex+localStage-1;
        stage = stage_template();
        stage.index = stageNumber;
        stage.localIndex = localStage;
        stage.tag = sprintf('%s_stage_%03d',options.campaignTag,stageNumber);
        stage.status = 'designing';
        stage.phase = 'design';
        stage.startedUtc = utc_now();
        stage.inputCheckpointFile = currentCheckpoint;
        stage.inputCanonicalTime = checkpoint.payload.state.scale.canonicalTime;
        stage.inputPhysicalTime = checkpoint.payload.state.scale.physicalTime;
        stage.inputStep = checkpoint.payload.state.step;
        stage.inputPhysicalRhoX = ...
            checkpoint.payload.log.history.common.physicalRhoXInf(end);
        stage.targetCanonicalTime = stage.inputCanonicalTime + ...
            options.stageCanonicalIncrement;
        stage.configuredXSeedOptions = options.xSeedOptions;
        stage.configuredCurrentAxisXFallbackOptions = ...
            current_axis_x_fallback_options(options);
        stage.configuredRootCorridorXFallbackOptions = ...
            root_corridor_x_fallback_options(options);
        stage.selectedXIncrementalReferenceDepth = ...
            options.currentIncrementalReferenceDepth;
        campaign.stages(end+1,1) = stage;
        activeStage = numel(campaign.stages);

        designFile = fullfile(campaignDirectory,sprintf( ...
            'stage_%03d_grid_design.mat',stageNumber));
        assert_new_file(designFile,'stage design');
        designOptions = stage_design_options( ...
            options,stage.tag,designFile);
        design = ipm_gridlab_design_continuation_stage( ...
            currentCheckpoint,referenceForDesign,designOptions);
        stage.designFile = designFile;
        stage.designStatus = design.status;
        stage.pairAdmissible = isfield(design,'pairScore') && ...
            isstruct(design.pairScore) && ...
            isfield(design.pairScore,'admissible') && ...
            isequal(design.pairScore.admissible,true);

        if ~strcmp(design.status,'feasible') || ...
                isempty(design.selected.x) || isempty(design.selected.y) || ...
                ~stage.pairAdmissible
            stage.status = 'design_failed';
            stage.phase = 'design_gate';
            stage.failureMessage = sprintf( ...
                'Stage design status is %s.',design.status);
            campaign.stages(activeStage) = complete_stage(stage);
            campaign.status = 'stopped_gate';
            campaign.stopReason = 'grid_design_not_feasible';
            campaign = save_snapshot( ...
                campaign,'stage_design_failed',activeStage);
            break
        end
        stage.selectedXReferenceProvenance = ...
            design.selected.xReferenceProvenance;
        stage.selectedYReferenceProvenance = ...
            design.selected.yReferenceProvenance;
        stage.selectedXModelName = design.selected.xName;
        if isfield(design.selected.xModel,'strengthScale')
            stage.selectedXStrengthScale = ...
                design.selected.xModel.strengthScale;
        else
            stage.selectedXStrengthScale = NaN;
        end
        stage.selectedXIncrementalReferenceDepth = ...
            selected_incremental_reference_depth( ...
                design.selected.xModel, ...
                options.currentIncrementalReferenceDepth, ...
                options.maximumIncrementalReferenceDepth);

        stage.designQuadrature = quadrature_pair_quality( ...
            design.selected.x,design.selected.y);
        [quadraturePassed,quadratureReasons] = ...
            quadrature_pair_gate(stage.designQuadrature,options);
        stage.designQuadraturePassed = quadraturePassed;
        stage.designQuadratureRejection = ...
            strjoin(quadratureReasons,',');
        [stage.designGlobalQuadratureWarning,designWarningReasons] = ...
            quadrature_pair_warning(stage.designQuadrature,options);
        stage.designGlobalQuadratureWarningReasons = ...
            strjoin(designWarningReasons,',');
        if ~quadraturePassed
            stage.status = 'design_failed';
            stage.phase = 'local_quadrature_gate';
            stage.failureMessage = strjoin(quadratureReasons,',');
            campaign.stages(activeStage) = complete_stage(stage);
            campaign.status = 'stopped_gate';
            campaign.stopReason = 'design_local_quadrature_gate';
            campaign = save_snapshot( ...
                campaign,'stage_quadrature_preflight_failed',activeStage);
            break
        end

        stage.predictedRegridRhoXRelativeJump = ...
            design.pairScore.aggregate.worst.rhoXMaximumRelativeChange;
        predictedCumulative = ...
            campaign.cumulativeRegridRhoXRelativeJump + ...
            stage.predictedRegridRhoXRelativeJump;
        if ~isfinite(stage.predictedRegridRhoXRelativeJump) || ...
                stage.predictedRegridRhoXRelativeJump > ...
                options.maximumRegridRhoXRelativeChange || ...
                predictedCumulative > ...
                options.maximumCumulativeRegridRhoXRelativeJump
            stage.status = 'design_failed';
            stage.phase = 'rho_x_jump_preflight';
            stage.failureMessage = ...
                'Frozen pair score exceeds the per-regrid or cumulative jump budget.';
            campaign.stages(activeStage) = complete_stage(stage);
            campaign.status = 'stopped_gate';
            campaign.stopReason = 'predicted_regrid_rho_x_jump_budget';
            campaign = save_snapshot( ...
                campaign,'stage_jump_preflight_failed',activeStage);
            break
        end
        stage.status = 'designed';
        campaign.stages(activeStage) = stage;
        campaign = save_snapshot( ...
            campaign,'stage_design_complete',activeStage);

        stage.phase = 'transactional_regrid';
        regridBase = fullfile(campaignDirectory,sprintf( ...
            'stage_%03d_regridded_checkpoint.mat',stageNumber));
        regridOptions = transaction_options(options,stage.tag,regridBase);
        [checkpoint,regridAudit,regridFile] = ...
            ipm_gridlab_regrid_checkpoint(currentCheckpoint, ...
                design.selected.x,design.selected.y,regridOptions);
        stage.regridCheckpointFile = char(regridFile);
        stage.regridAuditPassed = regridAudit.passed;
        stage.actualRegridRhoXRelativeJump = ...
            regridAudit.rhoXMaximumRelativeChange;
        candidateCumulativeJump = ...
            campaign.cumulativeRegridRhoXRelativeJump + ...
            stage.actualRegridRhoXRelativeJump;
        stage.cumulativeRegridRhoXRelativeJump = ...
            candidateCumulativeJump;
        stage.regridQuadrature = quadrature_pair_quality( ...
            checkpoint.payload.state.x,checkpoint.payload.state.y);
        [regridQuadraturePassed,regridQuadratureReasons] = ...
            quadrature_pair_gate(stage.regridQuadrature,options);
        stage.regridQuadraturePassed = regridQuadraturePassed;
        stage.regridQuadratureRejection = ...
            strjoin(regridQuadratureReasons,',');
        [stage.regridGlobalQuadratureWarning,regridWarningReasons] = ...
            quadrature_pair_warning(stage.regridQuadrature,options);
        stage.regridGlobalQuadratureWarningReasons = ...
            strjoin(regridWarningReasons,',');
        regridAudit.campaignLocalQuadrature = stage.regridQuadrature;
        regridAudit.campaignLocalQuadraturePassed = ...
            regridQuadraturePassed;
        regridAudit.campaignLocalQuadratureRejectionReasons = ...
            regridQuadratureReasons;
        regridAudit.campaignGlobalQuadratureWarning = ...
            stage.regridGlobalQuadratureWarning;
        regridAudit.campaignGlobalQuadratureWarningReasons = ...
            regridWarningReasons;
        regridAudit.campaignGlobalQuadratureWarningThreshold = ...
            options.globalQuadratureWeightRatioWarning;
        auditFile = fullfile(campaignDirectory,sprintf( ...
            'stage_%03d_regrid_audit.mat',stageNumber));
        assert_new_file(auditFile,'regrid audit');
        write_audit(regridAudit,auditFile);
        stage.regridAuditFile = auditFile;

        if ~regridAudit.passed || ~regridQuadraturePassed || ...
                candidateCumulativeJump > ...
                options.maximumCumulativeRegridRhoXRelativeJump
            stage.status = 'regrid_failed';
            stage.phase = 'regrid_campaign_gate';
            failureReasons = regridQuadratureReasons;
            if candidateCumulativeJump > ...
                    options.maximumCumulativeRegridRhoXRelativeJump
                failureReasons{end+1} = ...
                    'cumulative_regrid_rho_x_jump_budget'; %#ok<AGROW>
            end
            if ~regridAudit.passed
                failureReasons{end+1} = 'transaction_audit'; %#ok<AGROW>
            end
            stage.failureMessage = strjoin(failureReasons,',');
            campaign.stages(activeStage) = complete_stage(stage);
            campaign.status = 'stopped_gate';
            campaign.stopReason = 'regrid_campaign_gate';
            campaign = save_snapshot( ...
                campaign,'stage_regrid_gate_failed',activeStage);
            break
        end
        campaign.cumulativeRegridRhoXRelativeJump = ...
            candidateCumulativeJump;
        options.currentIncrementalReferenceDepth = ...
            stage.selectedXIncrementalReferenceDepth;
        campaign.currentIncrementalReferenceDepth = ...
            options.currentIncrementalReferenceDepth;
        stage.regridAdopted = true;
        stage.status = 'regridded';
        campaign.stages(activeStage) = stage;
        campaign.currentCheckpointFile = char(regridFile);
        campaign = save_snapshot( ...
            campaign,'stage_regrid_complete',activeStage);

        elapsed = toc(campaignTimer);
        launchReserve = launch_reserve(options,lastSolveSeconds);
        if elapsed+launchReserve > options.wallClockBudgetSeconds
            stage.status = 'budget_stop_after_regrid';
            stage.phase = 'solve_launch_gate';
            stage.failureMessage = ...
                'Insufficient wall-clock reserve to launch the next solve segment.';
            campaign.stages(activeStage) = complete_stage(stage);
            campaign.status = 'wall_clock_budget';
            campaign.stopReason = 'insufficient_budget_after_regrid';
            campaign = save_snapshot( ...
                campaign,'stage_solve_not_launched',activeStage);
            break
        end

        resultBase = fullfile(campaignDirectory,sprintf( ...
            'stage_%03d_result.mat',stageNumber));
        nativeCheckpointBase = fullfile(campaignDirectory,sprintf( ...
            'stage_%03d_native_checkpoint.mat',stageNumber));
        assert_new_file(resultBase,'solver result');
        assert_new_file(nativeCheckpointBase,'native checkpoint base');
        solveOverrides = solve_overrides( ...
            checkpoint,options,stage,resultBase,nativeCheckpointBase, ...
            campaignId);
        stage.status = 'solving';
        stage.phase = 'ipm.solve';
        campaign.stages(activeStage) = stage;
        campaign = save_snapshot( ...
            campaign,'stage_solve_started',activeStage);

        solveTimer = tic;
        result = ipm.solve(solveOverrides,regridFile);
        stage.solveElapsedSeconds = toc(solveTimer);
        lastSolveSeconds = stage.solveElapsedSeconds;
        result = ipm.output.validate(result);
        stage.resultFile = char(result.metadata.resultFile);
        campaign.finalResultFile = stage.resultFile;
        stage.outputCanonicalTime = result.state.canonicalTime;
        stage.outputPhysicalTime = result.state.physicalTime;
        stage.outputStep = result.state.steps;
        stage.stopReason = result.state.stopReason;

        terminalMetrics = result_terminal_metrics( ...
            result,stage.targetCanonicalTime);
        stage.recordCount = terminalMetrics.recordCount;
        stage.trustedPrefixRecords = terminalMetrics.trustedPrefixRecords;
        stage.continuousTrustedPrefix = ...
            terminalMetrics.continuousTrustedPrefix;
        stage.terminalTrusted = terminalMetrics.terminalTrusted;
        stage.horizontalCoreCells = terminalMetrics.horizontalCoreCells;
        stage.verticalCoreCells = terminalMetrics.verticalCoreCells;
        stage.safetyFactor = terminalMetrics.safetyFactor;
        stage.physicalRhoX = terminalMetrics.physicalRhoX;
        stage.terminalQuadrature = terminalMetrics.quadrature;
        [stage.terminalQuadraturePassed,terminalQuadratureReasons] = ...
            quadrature_pair_gate(stage.terminalQuadrature,options);
        stage.terminalQuadratureRejection = ...
            strjoin(terminalQuadratureReasons,',');
        [stage.terminalGlobalQuadratureWarning,terminalWarningReasons] = ...
            quadrature_pair_warning(stage.terminalQuadrature,options);
        stage.terminalGlobalQuadratureWarningReasons = ...
            strjoin(terminalWarningReasons,',');
        stage.stageHorizonReached = terminalMetrics.stageHorizonReached;
        stage.targetReached = terminalMetrics.physicalRhoX >= ...
            options.targetPhysicalRhoX;
        campaign.finalMetrics = terminalMetrics;

        if terminalMetrics.terminalTrusted
            stage.phase = 'native_terminal_checkpoint';
            [terminalCheckpoint,terminalCheckpointFile] = ...
                find_terminal_checkpoint(result,nativeCheckpointBase);
            stage.terminalCheckpointFile = terminalCheckpointFile;
            checkpoint = terminalCheckpoint;
            currentCheckpoint = terminalCheckpointFile;
            campaign.currentCheckpointFile = currentCheckpoint;
        end

        stage.phase = 'terminal_gate';
        [terminalPassed,terminalReasons] = ...
            terminal_gate(terminalMetrics,options);
        if ~terminalMetrics.stageHorizonReached && ~stage.targetReached
            terminalPassed = false;
            terminalReasons{end+1} = 'stage_canonical_horizon'; %#ok<AGROW>
        end
        if ~terminalPassed
            stage.status = 'terminal_gate_failed';
            stage.phase = 'terminal_gate';
            stage.failureMessage = strjoin(terminalReasons,',');
            campaign.stages(activeStage) = complete_stage(stage);
            campaign.status = 'stopped_gate';
            campaign.stopReason = stage.failureMessage;
            campaign = save_snapshot( ...
                campaign,'stage_terminal_gate_failed',activeStage);
            break
        end

        if stage.targetReached
            stage.status = 'target_reached';
            stage.phase = 'complete';
            campaign.stages(activeStage) = complete_stage(stage);
            campaign.status = 'target_reached';
            campaign.stopReason = 'physical_rho_x_target_reached';
            campaign.targetReached = true;
            campaign = save_snapshot( ...
                campaign,'stage_target_reached',activeStage);
            break
        end

        stage.status = 'completed';
        stage.phase = 'complete';
        campaign.stages(activeStage) = complete_stage(stage);
        campaign = save_snapshot( ...
            campaign,'stage_complete',activeStage);
        activeStage = 0;
    end

    if strcmp(campaign.status,'running')
        campaign.status = 'maximum_stages';
        campaign.stopReason = 'maximum_stage_count_reached';
    end
    campaign = finish_campaign(campaign,campaignTimer);
    campaign = save_snapshot(campaign,'campaign_finished',activeStage);
catch exception
    if activeStage > 0 && activeStage <= numel(campaign.stages)
        if ~exist('stage','var') || ...
                stage.index ~= campaign.stages(activeStage).index
            stage = campaign.stages(activeStage);
        end
        stage.status = 'exception';
        stage.failureIdentifier = exception.identifier;
        stage.failureMessage = exception.message;
        campaign.stages(activeStage) = complete_stage(stage);
    end
    campaign.status = 'failed_exception';
    campaign.stopReason = exception.identifier;
    campaign.error = exception_summary(exception);
    campaign = finish_campaign(campaign,campaignTimer);
    campaign = save_snapshot(campaign,'campaign_exception',activeStage);
    if options.throwOnFailure
        rethrow(exception)
    end
end
end

function options = resolve_options(options)
if ~isstruct(options) || ~isscalar(options)
    error('ipm:gridlab:CampaignOptions', ...
        'options must be a scalar structure.');
end
defaults = struct( ...
    'outputRoot',fullfile('result','verification', ...
        'q512_continuation_campaigns'), ...
    'campaignTag','q512_rho_x', ...
    'targetPhysicalRhoX',1e3, ...
    'wallClockBudgetSeconds',8*3600, ...
    'stageCanonicalIncrement',0.35, ...
    'checkpointEvery',0.20, ...
    'maximumStages',64, ...
    'firstStageIndex',4, ...
    'maximumStepsPerStage',5000, ...
    'minimumWallTimeToLaunchSeconds',1800, ...
    'wallTimeForecastFactor',1.25, ...
    'ratioCap',1.08, ...
    'targetXCoreCells',21, ...
    'targetYCoreCells',20, ...
    'minimumXFrontCells',20, ...
    'minimumRegridXCoreCells',20, ...
    'minimumRegridYCoreCells',19, ...
    'minimumTerminalCoreCells',14, ...
    'maximumTerminalSafetyFactor',0.70, ...
    'maximumRegridRhoXRelativeChange',2e-3, ...
    'maximumCumulativeRegridRhoXRelativeJump',2e-2, ...
    'maximumMassRelativeDefect',5e-12, ...
    'maximumRelativeRangeViolation',2e-4, ...
    'maximumLogSpacingCurvature',0.01, ...
    'minimumStencilRcond',1e-9, ...
    'minimumQuadratureWeightRatio',1e-8, ...
    'globalQuadratureWeightRatioWarning',1e-4, ...
    'minimumLocalQuadratureWeightRatio',0.35, ...
    'maximumLocalQuadratureWeightRatio',1.65, ...
    'designFineCount',131073, ...
    'xSeedOptions',struct('strengthScales',1), ...
    'xEqualizationSigma',0.35, ...
    'xEqualizationPower',1, ...
    'currentAxisXFallbackEnabled',false, ...
    'currentAxisXSigmas',[1.5,2,3], ...
    'currentAxisXPower',2, ...
    'rootCorridorXFallbackEnabled',false, ...
    'rootCorridorXShoulderCells',[16 24 32], ...
    'rootCorridorXExpansionShoulders',2, ...
    'maximumIncrementalReferenceDepth',1, ...
    'currentIncrementalReferenceDepth',0, ...
    'yEqualizationSigma',0.25, ...
    'yEqualizationPower',2, ...
    'uniformFlatTailEnabled',true, ...
    'uniformFlatTailSigma',0.35, ...
    'uniformFlatTailPower',3, ...
    'equalizationInitialAmplitude',0.25, ...
    'equalizationMaximumAmplitude',16, ...
    'equalizationAmplitudeTolerance',1e-9, ...
    'equalizationMaximumIterations',80, ...
    'verbose',true, ...
    'throwOnFailure',true);
names = fieldnames(defaults);
unexpected = setdiff(fieldnames(options),names,'stable');
if ~isempty(unexpected)
    error('ipm:gridlab:CampaignOptions', ...
        'Unknown option(s): %s.',strjoin(unexpected,', '));
end
for index = 1:numel(names)
    name = names{index};
    if ~isfield(options,name)
        options.(name) = defaults.(name);
    end
end
options.xSeedOptions = validate_x_seed_options(options.xSeedOptions);

for field = {'outputRoot','campaignTag'}
    value = options.(field{1});
    if ~(ischar(value) || (isstring(value) && isscalar(value))) || ...
            isempty(char(value))
        error('ipm:gridlab:CampaignOptions', ...
            'options.%s must be nonempty text.',field{1});
    end
    options.(field{1}) = char(value);
end
for field = {'targetPhysicalRhoX','wallClockBudgetSeconds', ...
        'stageCanonicalIncrement','checkpointEvery', ...
        'minimumWallTimeToLaunchSeconds','wallTimeForecastFactor', ...
        'ratioCap','minimumTerminalCoreCells', ...
        'maximumTerminalSafetyFactor', ...
        'maximumRegridRhoXRelativeChange', ...
        'maximumCumulativeRegridRhoXRelativeJump', ...
        'maximumMassRelativeDefect', ...
        'maximumRelativeRangeViolation', ...
        'maximumLogSpacingCurvature','minimumStencilRcond', ...
        'minimumQuadratureWeightRatio', ...
        'globalQuadratureWeightRatioWarning', ...
        'minimumLocalQuadratureWeightRatio', ...
        'maximumLocalQuadratureWeightRatio','xEqualizationSigma', ...
        'xEqualizationPower','currentAxisXPower', ...
        'yEqualizationSigma', ...
        'yEqualizationPower','equalizationInitialAmplitude', ...
        'uniformFlatTailSigma','uniformFlatTailPower', ...
        'equalizationMaximumAmplitude', ...
        'equalizationAmplitudeTolerance'}
    validateattributes(options.(field{1}),{'numeric'}, ...
        {'scalar','real','finite','positive'},mfilename, ...
        ['options.' field{1}]);
end
validateattributes(options.currentAxisXSigmas,{'numeric'}, ...
    {'vector','real','finite','positive','nonempty'},mfilename, ...
    'options.currentAxisXSigmas');
validateattributes(options.rootCorridorXShoulderCells,{'numeric'}, ...
    {'vector','real','finite','positive','nonempty'},mfilename, ...
    'options.rootCorridorXShoulderCells');
if any(diff(options.rootCorridorXShoulderCells(:)) <= 0)
    error('ipm:gridlab:CampaignRootCorridorShoulderCells', ...
        'rootCorridorXShoulderCells must be strictly increasing.');
end
validateattributes(options.rootCorridorXExpansionShoulders,{'numeric'}, ...
    {'scalar','real','finite','nonnegative'},mfilename, ...
    'options.rootCorridorXExpansionShoulders');
if options.stageCanonicalIncrement > 0.42
    error('ipm:gridlab:CampaignStageLength', ...
        'stageCanonicalIncrement may not exceed 0.42.');
end
if options.checkpointEvery > 0.20
    error('ipm:gridlab:CampaignCheckpointCadence', ...
        'checkpointEvery may not exceed 0.20 canonical-time units.');
end
if options.maximumRegridRhoXRelativeChange >= 1 || ...
        options.maximumCumulativeRegridRhoXRelativeJump >= 1
    error('ipm:gridlab:CampaignJumpBudget', ...
        'The rho_x jump limits must be strictly smaller than one.');
end
if options.ratioCap < 1
    error('ipm:gridlab:CampaignRatioCap', ...
        'ratioCap must be at least one.');
end
if options.wallTimeForecastFactor < 1
    error('ipm:gridlab:CampaignWallForecast', ...
        'wallTimeForecastFactor must be at least one.');
end
if options.minimumQuadratureWeightRatio >= 1
    error('ipm:gridlab:CampaignQuadratureRatio', ...
        'minimumQuadratureWeightRatio must be smaller than one.');
end
if options.globalQuadratureWeightRatioWarning >= 1 || ...
        options.globalQuadratureWeightRatioWarning < ...
        options.minimumQuadratureWeightRatio
    error('ipm:gridlab:CampaignQuadratureWarning', ...
        ['globalQuadratureWeightRatioWarning must be smaller than one ' ...
        'and no smaller than minimumQuadratureWeightRatio.']);
end
if options.minimumLocalQuadratureWeightRatio >= 1 || ...
        options.maximumLocalQuadratureWeightRatio <= 1 || ...
        options.minimumLocalQuadratureWeightRatio >= ...
        options.maximumLocalQuadratureWeightRatio
    error('ipm:gridlab:CampaignLocalQuadratureRatio', ...
