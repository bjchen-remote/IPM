function [audits,sharedAudit,passed] = audit_registered_contracts( ...
        flatOptions,configurations,specifications,settings)
audits = repmat(struct('checks',struct(),'failures',{{}}, ...
    'passed',false,'retiredFieldsPresent',{{}}), ...
    numel(specifications),1);
for index = 1:numel(specifications)
    config = configurations{index};
    scaling = config.scaling;
    retired = retired_fields();
    retiredPresent = unique([ ...
        retired(isfield(flatOptions{index},retired)), ...
        retired(isfield(scaling,retired))],'stable');
    checks = struct();
    checks.schema4 = config.schemaVersion == 4 && config.frozen;
    checks.q512 = config.grid.nx == 1025 && config.grid.ny == 513;
    checks.largeBox = endpoint_close(config.grid.xlim,[-1e6,1e6]) && ...
        config.grid.ymax == 1e6;
    checks.activeDatum = strcmp(config.physics.initialCondition, ...
        'degenerate_primitive') && config.physics.degeneratePower == 8 && ...
        strcmp(config.physics.symmetryMode,'double_odd_omega');
    checks.greenOpen = strcmp(config.elliptic.farBoundaryMode,'green') && ...
        strcmp(config.transport.transportBoundaryMode,'open');
    checks.numericalTuple = strcmp( ...
        config.transport.spatialDiscretization,'high_order') && ...
        strcmp(config.transport.transportScheme,'weno5_fd') && ...
        strcmp(config.time.timeIntegrator,'ssprk54') && ...
        strcmp(config.remesh.remeshTransferScheme,'high_order');
    checks.fixedMesh = ~config.remesh.initialAnalyticRemesh && ...
        ~config.remesh.adaptiveRemesh;
    checks.dynamicIsotropic = strcmp(scaling.rescalingMode,'dynamic') && ...
        strcmp(scaling.dynamicScaleGeometry,'isotropic');
    checks.exactNoFeedback = strcmp(scaling.scalingContract, ...
        'exact_gauge_no_feedback_v1') && ...
        scaling.lengthScaleGain == 1 && scaling.widthGaugeGain == 0 && ...
        scaling.omegaGaugeGain == 0 && ...
        scaling.travelingWaveGain == 0;
    checks.transportAnchor = strcmp(scaling.lengthGauge, ...
        'transport_anchor') && scaling.transportAnchorX == 1;
    checks.registeredGauge = strcmp(scaling.cOmegaGauge, ...
        specifications(index).gauge);
    checks.registeredCfl = config.time.cfl == specifications(index).cfl;
    checks.shortBounds = config.time.physicalFinalTime == ...
        settings.physicalFinalTime && config.time.finalTime == ...
        settings.canonicalFinalTime && ...
        config.time.maxDt == settings.maxDt && ...
        config.time.maxSteps == settings.maxSteps;
    checks.everyStepOutput = config.time.outputEvery == ...
        settings.outputEvery && ...
        config.time.outputEvery <= config.time.minDt;
    checks.noSnapshots = ~config.output.storeSnapshots;
    checks.noSolverResultWrite = ~config.output.saveResults;
    checks.noVisualization = ~config.output.makePlots && ...
        ~config.output.livePlot && ~config.output.writeVideo;
    checks.noCheckpoint = ~isfield(config.output,'checkpoint');
    checks.noRetiredFields = isempty(retiredPresent);
    failures = failed_checks(checks);
    audits(index) = struct('checks',checks,'failures',{failures}, ...
        'passed',isempty(failures), ...
        'retiredFieldsPresent',{retiredPresent});
end

reference = normalized_config(configurations{1});
sameExceptGaugeAndCfl = true;
for index = 2:numel(configurations)
    sameExceptGaugeAndCfl = sameExceptGaugeAndCfl && isequaln( ...
        reference,normalized_config(configurations{index}));
end
checks = struct();
checks.fourFreshRoots = numel(specifications) == 4;
checks.fixedGauges = isequal(unique({specifications.gauge},'stable'), ...
    {'wall_omega_quadratic_peak','none'});
checks.fixedCflPair = isequal(unique([specifications.cfl],'stable'), ...
    [0.25,0.50]);
gauges = {'wall_omega_quadratic_peak','none'};
checks.twoRunsPerGauge = all(arrayfun(@(gaugeIndex)nnz(strcmp( ...
    {specifications.gauge},gauges{gaugeIndex})) == 2,1:2));
checks.sameExceptGaugeCflMetadata = sameExceptGaugeAndCfl;
checks.allContractsPassed = all([audits.passed]);
failures = failed_checks(checks);
sharedAudit = struct( ...
    'onlyRegisteredDifferences',{ ...
        {'scaling.cOmegaGauge','time.cfl', ...
        'output.caseMetadata','output.resultFile'}}, ...
    'checks',checks, ...
    'failures',{failures}, ...
    'passed',isempty(failures));
passed = all([audits.passed]);
end

function normalized = normalized_config(config)
normalized = config;
normalized.scaling.cOmegaGauge = '__registered_gauge__';
normalized.time.cfl = NaN;
normalized.output.resultFile = '__disabled_result_file__';
normalized.output.caseMetadata = struct();
normalized = orderfields(normalized);
end

function [audit,passed] = audit_mesh(options,halfWidth)
x = options.customX(:)';
y = options.customY(:);
weightsX = ipm.mesh.quadrature(x);
weightsY = ipm.mesh.quadrature(y);
qualityX = ipm.mesh.quality(x,7,weightsX);
qualityY = ipm.mesh.quality(y,7,weightsY);
[anchorDistance,anchorIndex] = min(abs(x-1));
anchorTolerance = 128*eps(max(1,max(abs(x))));
checks = struct();
checks.nodeCounts = numel(x) == 1025 && numel(y) == 513;
checks.endpoints = endpoint_close(x([1,end]),[-halfWidth,halfWidth]) && ...
    endpoint_close(y([1,end]),[0,halfWidth]);
checks.anchorExact = anchorDistance <= anchorTolerance;
checks.positiveQuadrature = ...
    qualityX.quadratureWeightsStrictlyPositive && ...
    qualityY.quadratureWeightsStrictlyPositive;
checks.adjacentCellRatio = max([qualityX.maximumAdjacentCellRatio, ...
    qualityY.maximumAdjacentCellRatio]) <= 1.08*(1+1e-12);
checks.logSpacingCurvature = max([ ...
    qualityX.maximumLogSpacingCurvature, ...
    qualityY.maximumLogSpacingCurvature]) <= 0.01*(1+1e-12);
checks.stencilRcond = min([qualityX.minimumStencilRcond, ...
    qualityY.minimumStencilRcond]) >= 1e-9*(1-1e-12);
checks.globalQuadrature = min([ ...
    qualityX.minimumQuadratureWeightRatio, ...
    qualityY.minimumQuadratureWeightRatio]) >= 1e-8*(1-1e-12);
checks.localQuadratureLower = min([ ...
    qualityX.minimumQuadratureWeightToControlWidthRatio, ...
    qualityY.minimumQuadratureWeightToControlWidthRatio]) >= ...
    0.35*(1-1e-12);
checks.localQuadratureUpper = max([ ...
    qualityX.maximumQuadratureWeightToControlWidthRatio, ...
    qualityY.maximumQuadratureWeightToControlWidthRatio]) <= ...
    1.65*(1+1e-12);
failures = failed_checks(checks);
passed = isempty(failures);
audit = struct('x',qualityX,'y',qualityY,'checks',checks, ...
