optionNames = fieldnames(schema.options);
descriptorFields = {'domain','default','hasDefault','kind','rule', ...
    'allowed','errorId'};
allowedKinds = {'numeric','boolean','enum','initial_condition','path', ...
    'metadata','checkpoint','autonomous_mesh','initial_mesh_observation','custom_coordinate'};
defaultMask = false(size(optionNames));
kindNames = cell(size(optionNames));
for optionIndex = 1:numel(optionNames)
    name = optionNames{optionIndex};
    descriptor = schema.options.(name);
    assert(isstruct(descriptor) && isscalar(descriptor) && ...
        isequal(sort(fieldnames(descriptor)),sort(descriptorFields(:))) && ...
        ischar(descriptor.domain) && ...
        any(strcmp(descriptor.domain,schema.domainNames)) && ...
        islogical(descriptor.hasDefault) && isscalar(descriptor.hasDefault) && ...
        ischar(descriptor.kind) && any(strcmp(descriptor.kind,allowedKinds)) && ...
        ischar(descriptor.rule) && iscell(descriptor.allowed) && ...
        ischar(descriptor.errorId), ...
        'ipm:ConfigSchemaDescriptor', ...
        'Option "%s" has incomplete declarative metadata.',name);
    if strcmp(descriptor.kind,'numeric')
        assert(isfield(schema.rules,descriptor.rule), ...
            'ipm:ConfigSchemaRule', ...
            'Numeric option "%s" refers to an unknown rule.',name);
    end
    defaultMask(optionIndex) = descriptor.hasDefault;
    kindNames{optionIndex} = descriptor.kind;
end
assert(numel(optionNames) == 106 && sum(defaultMask) == 101 && ...
    isequal(sort(optionNames(~defaultMask)), ...
    sort({'checkpoint';'autonomousMesh';'initialMeshObservationFallback';'customX';'customY'})), ...
    'ipm:ConfigSchemaCoverage', ...
