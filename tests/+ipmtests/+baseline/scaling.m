function [formulaError,reconstructedResidual] = ...
        anchor_formula_error(rho,rhs,flow,ops)
baseRhs = rhs/flow.timeSpeed-flow.canonicalCOmega*rho;
baseRhsX = baseRhs*ops.Dx';
samples = interp1(ops.x,[flow.source(1,:);baseRhsX(1,:)]', ...
    ops.rescaling.transportAnchorX,'linear');
anchorValue = samples(1);
anchorForcing = samples(2);
expected = -anchorForcing/anchorValue;
formulaError = abs(flow.canonicalCOmega-expected);
reconstructedResidual = flow.timeSpeed*(anchorForcing + ...
    flow.canonicalCOmega*anchorValue);
end

