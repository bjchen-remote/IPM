    'ops',ops,'config',options,'mass0', ...
    sum(rho.*ops.integrationWeights,'all'),'rhoRange0', ...
    [min(rho,[],'all'),max(rho,[],'all')], ...
    'normalizedTime',stepSize,'step',1);
[recorded,~] = ipm.output.record(ipm.output.initializeLog(),state);
requiredHistory = {'omegaGaugeTemplateCenter', ...
    'omegaGaugeTemplateRadius','omegaGaugeTemplateSupportPoints', ...
    'omegaGaugeTemplateValue','omegaGaugeTemplateCondition', ...
    'omegaGaugeTemplateRateResidual','omegaGaugeTemplateRateScale', ...
    'omegaGaugeReferenceTemplateValue'};
historyFieldsPresent = all(isfield(recorded.history.gauge,requiredHistory));

check = struct('formulaError',formulaError, ...
    'normalizedRateResidual',normalizedRateResidual, ...
    'residualReconstructionError',abs( ...
        flow.omegaGaugeTemplateRateResidual - ...
        (forcing+flow.canonicalCOmega*projection)), ...
    'condition',flow.omegaGaugeTemplateCondition, ...
    'amplitudeRateError',amplitudeRateError, ...
    'amplitudeRhsError',amplitudeRhsError, ...
    'historyFieldsPresent',historyFieldsPresent, ...
    'referencePreserved', ...
        flow.omegaGaugeReferenceTemplateValue == reference && ...
        flowAfter.omegaGaugeReferenceTemplateValue == reference && ...
        flow.omegaGaugeTemplateValue == projection && ...
        flow.omegaGaugeTemplateSupportPoints == geometry.supportPoints, ...
    'shortStepFinite',all(isfinite(rhoAfter),'all') && ...
        all(cellfun(@(value)isnumeric(value) && isscalar(value) && ...
        isfinite(value),struct2cell(scaleAfter))) && ...
        isfinite(flowAfter.canonicalCOmega));
end

