function [passed,reasons] = terminal_gate(metrics,options)
reasons = {};
if ~metrics.continuousTrustedPrefix
    reasons{end+1} = 'continuous_trusted_prefix';
end
if ~metrics.terminalTrusted
    reasons{end+1} = 'terminal_trusted';
end
if ~isfinite(metrics.horizontalCoreCells) || ...
        metrics.horizontalCoreCells < options.minimumTerminalCoreCells
    reasons{end+1} = 'horizontal_core_gate';
end
if ~isfinite(metrics.verticalCoreCells) || ...
        metrics.verticalCoreCells < options.minimumTerminalCoreCells
    reasons{end+1} = 'vertical_core_gate';
end
if ~isfinite(metrics.safetyFactor) || ...
        metrics.safetyFactor >= options.maximumTerminalSafetyFactor
    reasons{end+1} = 'safety_factor_gate';
end
if ~isfinite(metrics.physicalRhoX) || metrics.physicalRhoX <= 0
    reasons{end+1} = 'physical_rho_x_invalid';
end
[quadraturePassed,quadratureReasons] = ...
    quadrature_pair_gate(metrics.quadrature,options);
if ~quadraturePassed
    reasons = [reasons,quadratureReasons];
end
passed = isempty(reasons);
end

function quality = quadrature_pair_quality(x,y)
