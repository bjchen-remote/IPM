function rebuilt = refinalize_quadratic_history(result,names,mode)
outputLog = ipm.output.initializeLog();
outputLog.history = result.history;
switch mode
    case 'missing'
        outputLog.history.common = rmfield(outputLog.history.common,names);
    case 'nan'
        for index = 1:numel(names)
            outputLog.history.common.(names{index})(:) = NaN;
        end
end
ops = ipm.mesh.build(result.config);
state = struct( ...
    'rho',result.state.rho, ...
    'flow',struct('psi',result.state.psi,'source',result.state.omega, ...
        'u1',result.state.velocity.x,'u2',result.state.velocity.y, ...
        'trackedPeakX',result.grid.trackedPeakX, ...
        'poissonSolveInfo',result.elliptic.solveInfo), ...
    'scale',struct('logC_l',log(result.scale.Cx), ...
        'logC_omega',log(result.scale.Comega), ...
        'physicalTime',result.state.physicalTime, ...
        'X_shift',result.scale.Xshift, ...
        'canonicalTime',result.state.canonicalTime), ...
    'ops',ops,'config',result.config, ...
    'normalizedTime',result.state.normalizedTime, ...
    'step',result.state.steps,'runMetadata',result.metadata);
rebuilt = ipm.output.finalize(state,outputLog,result.state.stopReason);
end

function assert_schema_rejected(action)
try
    action();
catch exception
    assert(strcmp(exception.identifier,'ipm:ResultSchemaVersion') && ...
        contains(exception.message,'schemaVersion=2'), ...
        'ipm:OutputSchemaError', ...
        'Expected a clear schemaVersion=2 rejection, received %s: %s.', ...
        exception.identifier,exception.message);
    return;
end
error('ipm:OutputSchemaAcceptance', ...
    'A legacy, unversioned, or unsupported result schema was accepted.');
end

function assert_throws(action,identifier)
try
    action();
catch exception
    assert(strcmp(exception.identifier,identifier), ...
        'ipm:OutputUnexpectedError', ...
        'Expected %s but received %s.',identifier,exception.identifier);
    return;
end
error('ipm:OutputMissingError','Expected error %s was not raised.',identifier);
end

