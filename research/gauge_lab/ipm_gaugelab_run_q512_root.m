function rootRun = ipm_gaugelab_run_q512_root(options)
%IPM_GAUGELAB_RUN_Q512_ROOT Start a fresh schema-4 q512 gauge run.
%   ROOTRUN = IPM_GAUGELAB_RUN_Q512_ROOT() runs a deliberately short,
%   at-most-two-step matched-box smoke calculation.  It never resumes an
%   older artifact: the physical datum and both scale clocks start at zero.
%
%   OPTIONS.boxMode is 'matched' (the registered x=[-281,281], y=[0,132]
%   q512 refinement) or 'large_box'.  The latter defaults to half-width
%   1e6 in both directions; OPTIONS.boxHalfWidth can select another rung of
%   the same fresh-root box ladder.
%
%   A long root segment is intentionally opt-in:
%
%       options.runMode = 'campaign';
%       options.confirmLongRun = true;
%
%   Campaign defaults define a discovery window rather than a blowup
%   claim: canonical tau=12 with physical time 4 as a safety ceiling.  The
%   former t=2.1 ceiling stopped near tau=3 on the q256 trajectory and was
%   too short to expose three e-folds of gradient amplification.
%
%   OPTIONS.preflightOnly=true resolves and audits the complete q512
%   configuration, writes its registered summary/manifest, and performs no
%   PDE solve.  Every executed run uses configuration/checkpoint schema 4,
%   exact_gauge_no_feedback_v1, the X=1 transport anchor, the selected exact
%   amplitude gauge, the high_order/WENO5-FD/SSPRK(5,4)/high_order tuple,
%   and a fixed mesh. OPTIONS.cOmegaGauge is either gradient_energy (the
%   backward-compatible default) or wall_omega_quadratic_peak.

if nargin < 1 || isempty(options)
    options = struct();
end
settings = resolve_options(options);
require_factory();

[outputDirectory,runId] = create_output_directory(settings);
summaryFile = fullfile(outputDirectory,'root_summary.mat');
manifestFile = fullfile(outputDirectory,'root_manifest.jsonl');
resultFile = fullfile(outputDirectory,'result.mat');
checkpointFile = fullfile(outputDirectory,'checkpoint.mat');

[opts,baseCaseName,domain] = registered_options( ...
    settings,resultFile,checkpointFile,runId);
config = ipm.config.resolve(opts);
gates = registered_mesh_gates();
[meshAudit,meshPassed] = audit_mesh( ...
    opts,config,gates,domain,settings.boxMode);
[contractAudit,contractPassed] = audit_config_contract( ...
    config,opts,settings.cOmegaGauge);

registeredUtc = utc_stamp();
rootRun = struct( ...
    'schemaVersion',4, ...
    'kind','q512_fresh_exact_gauge_root', ...
    'runId',runId, ...
    'status','registered', ...
    'registeredUtc',registeredUtc, ...
    'startedUtc','', ...
    'completedUtc','', ...
    'freshStart',true, ...
    'restartInput','none', ...
    'baseCaseName',baseCaseName, ...
    'boxMode',settings.boxMode, ...
    'runMode',settings.runMode, ...
    'cOmegaGauge',settings.cOmegaGauge, ...
    'preflightOnly',settings.preflightOnly, ...
    'domain',domain, ...
    'requested',requested_summary(settings), ...
    'gaugeRules',registered_gauge_rules(settings.cOmegaGauge), ...
    'meshGates',gates, ...
    'meshAudit',meshAudit, ...
    'meshPassed',meshPassed, ...
    'contractAudit',contractAudit, ...
    'contractPassed',contractPassed, ...
    'config',config, ...
    'outputDirectory',outputDirectory, ...
    'summaryFile',summaryFile, ...
    'manifestFile',manifestFile, ...
    'requestedResultFile',resultFile, ...
    'requestedCheckpointFile',checkpointFile, ...
    'resultFile','', ...
    'checkpointFile','', ...
    'wallSeconds',NaN, ...
    'steps',NaN, ...
    'wallSecondsPerStep',NaN, ...
    'stopReason','', ...
    'postAudit',struct(), ...
    'errorIdentifier','', ...
    'errorMessage','');
save_summary(summaryFile,rootRun);
append_manifest(manifestFile,struct( ...
    'event','root_registered', ...
    'timestampUtc',registeredUtc, ...
    'runId',runId, ...
    'freshStart',true, ...
    'baseCaseName',baseCaseName, ...
    'boxMode',settings.boxMode, ...
    'runMode',settings.runMode, ...
    'cOmegaGauge',settings.cOmegaGauge, ...
    'preflightOnly',settings.preflightOnly, ...
    'domain',domain, ...
    'requested',rootRun.requested, ...
    'gaugeRules',rootRun.gaugeRules, ...
    'meshGates',gates, ...
    'meshPassed',meshPassed, ...
    'contractPassed',contractPassed, ...
    'retiredFieldsPresent',{contractAudit.retiredFieldsPresent}, ...
    'summaryFile',summaryFile, ...
    'resultFile',resultFile, ...
    'checkpointFile',checkpointFile));

if ~(meshPassed && contractPassed)
    rootRun.status = 'preflight_rejected';
    rootRun.completedUtc = utc_stamp();
    save_summary(summaryFile,rootRun);
    append_manifest(manifestFile,struct( ...
        'event','root_preflight_rejected', ...
        'timestampUtc',rootRun.completedUtc, ...
        'runId',runId, ...
        'meshFailures',{meshAudit.failures}, ...
        'contractFailures',{contractAudit.failures}));
    error('ipm:GaugeLabQ512PreflightGate', ...
        'The registered q512 root failed preflight; inspect %s.', ...
        summaryFile);
end

if settings.preflightOnly
    rootRun.status = 'preflight_only';
    rootRun.completedUtc = utc_stamp();
    save_summary(summaryFile,rootRun);
    append_manifest(manifestFile,struct( ...
        'event','root_preflight_complete', ...
        'timestampUtc',rootRun.completedUtc, ...
        'runId',runId, ...
        'solveExecuted',false));
    fprintf(['Q512 ROOT PREFLIGHT: mode=%s, box=%s, ' ...
        'mesh/contract=pass, summary=%s\n'], ...
        settings.runMode,settings.boxMode,summaryFile);
    return
end

rootRun.status = 'running';
rootRun.startedUtc = utc_stamp();
save_summary(summaryFile,rootRun);
append_manifest(manifestFile,struct( ...
    'event','root_solve_started', ...
    'timestampUtc',rootRun.startedUtc, ...
    'runId',runId, ...
    'cOmegaGauge',settings.cOmegaGauge, ...
    'freshStart',true));

wallClock = tic;
try
    % Deliberately use the one-argument entry point.  No result or
    % checkpoint can enter this fresh-root transaction.
    result = ipm.solve(opts);
    rootRun.wallSeconds = toc(wallClock);
catch exception
    rootRun.wallSeconds = toc(wallClock);
    rootRun.status = 'solver_failed';
    rootRun.completedUtc = utc_stamp();
    rootRun.errorIdentifier = exception.identifier;
    rootRun.errorMessage = exception.message;
    save_summary(summaryFile,rootRun);
    append_manifest(manifestFile,struct( ...
        'event','root_solve_failed', ...
        'timestampUtc',rootRun.completedUtc, ...
        'runId',runId, ...
        'wallSeconds',rootRun.wallSeconds, ...
        'errorIdentifier',exception.identifier, ...
        'errorMessage',exception.message));
    rethrow(exception)
end

try
    result = ipm.output.validate(result);
    [postAudit,checkpointPath] = audit_result( ...
        result,config,settings,rootRun.wallSeconds,checkpointFile);
catch exception
    rootRun.status = 'postprocess_failed';
    rootRun.completedUtc = utc_stamp();
    rootRun.errorIdentifier = exception.identifier;
    rootRun.errorMessage = exception.message;
    if exist('result','var') && isstruct(result) && ...
            isfield(result,'metadata') && ...
            isfield(result.metadata,'resultFile')
        rootRun.resultFile = char(result.metadata.resultFile);
    end
    save_summary(summaryFile,rootRun);
    append_manifest(manifestFile,struct( ...
        'event','root_postprocess_failed', ...
        'timestampUtc',rootRun.completedUtc, ...
        'runId',runId, ...
        'wallSeconds',rootRun.wallSeconds, ...
        'errorIdentifier',exception.identifier, ...
        'errorMessage',exception.message, ...
        'resultFile',rootRun.resultFile));
    rethrow(exception)
end
rootRun.steps = result.state.steps;
rootRun.wallSecondsPerStep = postAudit.wallSecondsPerStep;
rootRun.stopReason = result.state.stopReason;
rootRun.resultFile = char(result.metadata.resultFile);
rootRun.checkpointFile = checkpointPath;
rootRun.postAudit = postAudit;
rootRun.completedUtc = utc_stamp();
if postAudit.hardPassed
    rootRun.status = 'completed';
else
    rootRun.status = 'postrun_rejected';
end
save_summary(summaryFile,rootRun);
append_manifest(manifestFile,struct( ...
    'event','root_solve_finished', ...
    'timestampUtc',rootRun.completedUtc, ...
    'runId',runId, ...
    'status',rootRun.status, ...
    'cOmegaGauge',settings.cOmegaGauge, ...
    'stopReason',rootRun.stopReason, ...
    'steps',rootRun.steps, ...
    'wallSeconds',rootRun.wallSeconds, ...
    'wallSecondsPerStep',rootRun.wallSecondsPerStep, ...
    'postrunPassed',postAudit.hardPassed, ...
    'postrunFailures',{postAudit.failures}, ...
    'resultFile',rootRun.resultFile, ...
    'checkpointFile',rootRun.checkpointFile));

fprintf(['Q512 ROOT RESULT: status=%s, stop=%s, steps=%d, ' ...
    'wall=%.3f s, %.3f s/step\n'],rootRun.status, ...
    rootRun.stopReason,rootRun.steps,rootRun.wallSeconds, ...
    rootRun.wallSecondsPerStep);
if ~postAudit.hardPassed
    error('ipm:GaugeLabQ512PostrunGate', ...
        'The q512 result failed postrun gate(s): %s. See %s.', ...
        strjoin(postAudit.failures,','),summaryFile);
end
end

function settings = resolve_options(options)
if ~isstruct(options) || ~isscalar(options)
    error('ipm:GaugeLabQ512Options', ...
        'options must be a scalar structure.');
end
allowed = {'boxMode','boxHalfWidth','runMode','confirmLongRun', ...
    'preflightOnly','outputRoot','verbose','cfl','maxDt', ...
    'physicalFinalTime','canonicalFinalTime','maxSteps', ...
    'outputEvery','checkpointEvery','cOmegaGauge'};
unknown = setdiff(fieldnames(options),allowed,'stable');
if ~isempty(unknown)
    error('ipm:GaugeLabQ512Options', ...
        'Unknown option(s): %s.',strjoin(unknown,', '));
end

settings = struct();
settings.boxMode = text_option(options,'boxMode','matched');
settings.runMode = text_option(options,'runMode','smoke');
settings.cOmegaGauge = text_option( ...
    options,'cOmegaGauge','gradient_energy');
settings.confirmLongRun = logical_option( ...
    options,'confirmLongRun',false);
settings.preflightOnly = logical_option(options,'preflightOnly',false);
settings.verbose = logical_option(options,'verbose',true);
settings.outputRoot = path_option(options,'outputRoot',default_output_root());
settings.boxHalfWidth = numeric_option(options,'boxHalfWidth',[]);
settings.cfl = numeric_option(options,'cfl',0.25);

if strcmp(settings.runMode,'smoke')
    settings.physicalFinalTime = numeric_option( ...
        options,'physicalFinalTime',1e-4);
    settings.canonicalFinalTime = numeric_option( ...
        options,'canonicalFinalTime',1e-3);
    settings.maxDt = numeric_option(options,'maxDt',1e-4);
    settings.maxSteps = numeric_option(options,'maxSteps',2);
    settings.outputEvery = numeric_option(options,'outputEvery',1e-4);
    settings.checkpointEvery = numeric_option( ...
        options,'checkpointEvery',1e-4);
elseif strcmp(settings.runMode,'campaign')
    settings.physicalFinalTime = numeric_option( ...
        options,'physicalFinalTime',4.0);
    settings.canonicalFinalTime = numeric_option( ...
        options,'canonicalFinalTime',12);
    settings.maxDt = numeric_option(options,'maxDt',2e-3);
    settings.maxSteps = numeric_option(options,'maxSteps',30000);
    settings.outputEvery = numeric_option(options,'outputEvery',5e-3);
    settings.checkpointEvery = numeric_option( ...
        options,'checkpointEvery',0.20);
else
    error('ipm:GaugeLabQ512RunMode', ...
        'runMode must be ''smoke'' or ''campaign''.');
end
if ~any(strcmp(settings.boxMode,{'matched','large_box'}))
    error('ipm:GaugeLabQ512BoxMode', ...
        'boxMode must be ''matched'' or ''large_box''.');
end
if ~any(strcmp(settings.cOmegaGauge, ...
        {'gradient_energy','wall_omega_quadratic_peak'}))
    error('ipm:GaugeLabQ512COmegaGauge', ...
        ['cOmegaGauge must be ''gradient_energy'' or ' ...
        '''wall_omega_quadratic_peak''.']);
end

validateattributes(settings.cfl,{'numeric'}, ...
    {'scalar','real','finite','>',0,'<=',0.5},mfilename,'cfl');
validateattributes(settings.physicalFinalTime,{'numeric'}, ...
    {'scalar','real','finite','positive'},mfilename, ...
    'physicalFinalTime');
validateattributes(settings.canonicalFinalTime,{'numeric'}, ...
    {'scalar','real','finite','positive'},mfilename, ...
    'canonicalFinalTime');
validateattributes(settings.maxDt,{'numeric'}, ...
    {'scalar','real','finite','positive'},mfilename,'maxDt');
validateattributes(settings.maxSteps,{'numeric'}, ...
    {'scalar','real','finite','integer','positive'},mfilename,'maxSteps');
validateattributes(settings.outputEvery,{'numeric'}, ...
    {'scalar','real','finite','positive'},mfilename,'outputEvery');
validateattributes(settings.checkpointEvery,{'numeric'}, ...
    {'scalar','real','finite','positive'},mfilename,'checkpointEvery');

if strcmp(settings.boxMode,'matched')
    if isempty(settings.boxHalfWidth)
        settings.boxHalfWidth = 281;
    else
        validateattributes(settings.boxHalfWidth,{'numeric'}, ...
            {'scalar','real','finite','positive'},mfilename, ...
            'boxHalfWidth');
        if settings.boxHalfWidth ~= 281
            error('ipm:GaugeLabQ512MatchedBox', ...
                ['The matched factory is registered only at x half-width ' ...
                '281; use boxMode=''large_box'' for a box ladder rung.']);
        end
    end
else
    if isempty(settings.boxHalfWidth)
        settings.boxHalfWidth = 1e6;
    end
    validateattributes(settings.boxHalfWidth,{'numeric'}, ...
        {'scalar','real','finite','>',2},mfilename,'boxHalfWidth');
end

if strcmp(settings.runMode,'smoke') && ...
        (settings.physicalFinalTime > 1e-3 || ...
        settings.canonicalFinalTime > 1e-2 || ...
        settings.maxSteps > 10)
    error('ipm:GaugeLabQ512SmokeBudget', ...
        ['Smoke mode is capped at physical time 1e-3, canonical time ' ...
        '1e-2, and 10 steps.  Use the explicitly confirmed campaign mode.']);
end
if strcmp(settings.runMode,'campaign') && ...
        ~settings.preflightOnly && ~settings.confirmLongRun
    error('ipm:GaugeLabQ512LongRunConfirmation', ...
        ['A campaign root may take hours.  Set confirmLongRun=true ' ...
        'explicitly, or use preflightOnly=true.']);
end
end

function [opts,baseCaseName,domain] = registered_options( ...
        settings,resultFile,checkpointFile,runId)
if strcmp(settings.boxMode,'matched')
    baseCaseName = 'coordinated_log_F80_R20_c114_quadrant_512';
    domain = struct('x',[-281,281],'y',[0,132], ...
        'initialPhysicalX',[-281,281], ...
        'initialPhysicalY',[0,132]);
    boxOverrides = struct();
else
    baseCaseName = ...
        'coordinated_log_anchor_F80_R20_large_box_quadrant_512';
    halfWidth = settings.boxHalfWidth;
    domain = struct('x',[-halfWidth,halfWidth], ...
        'y',[0,halfWidth], ...
        'initialPhysicalX',[-halfWidth,halfWidth], ...
        'initialPhysicalY',[0,halfWidth]);
    boxOverrides = struct('xlim',[-halfWidth,halfWidth], ...
        'ymax',halfWidth);
end

metadata = struct('q512GaugeRoot',struct( ...
    'schemaVersion',4, ...
    'runId',runId, ...
    'freshStart',true, ...
    'restartInput','none', ...
    'boxMode',settings.boxMode, ...
    'boxHalfWidth',settings.boxHalfWidth, ...
    'runMode',settings.runMode, ...
    'configurationContract','exact_gauge_no_feedback_v1', ...
    'lengthGauge','transport_anchor', ...
    'transportAnchorX',1, ...
    'cOmegaGauge',settings.cOmegaGauge));
overrides = struct( ...
    'rescalingMode','dynamic', ...
    'dynamicScaleGeometry','isotropic', ...
    'scalingContract','exact_gauge_no_feedback_v1', ...
    'lengthGauge','transport_anchor', ...
    'transportAnchorX',1, ...
    'cOmegaGauge',settings.cOmegaGauge, ...
    'lengthScaleGain',1, ...
    'widthGaugeGain',0, ...
    'omegaGaugeGain',0, ...
    'travelingWaveGain',0, ...
    'omegaGaugeWindowRadius',0.75, ...
    'pointStrainConditionFloor',0.25, ...
    'spatialDiscretization','high_order', ...
    'transportScheme','weno5_fd', ...
    'timeIntegrator','ssprk54', ...
    'remeshTransferScheme','high_order', ...
    'initialAnalyticRemesh',false, ...
    'adaptiveRemesh',false, ...
    'remeshMaximumCellRatio',1.08, ...
    'physicalFinalTime',settings.physicalFinalTime, ...
    'finalTime',settings.canonicalFinalTime, ...
    'cfl',settings.cfl, ...
    'maxDt',settings.maxDt, ...
    'maxSteps',settings.maxSteps, ...
    'outputEvery',settings.outputEvery, ...
    'checkpoint',struct('enabled',true,'file',checkpointFile, ...
        'every',settings.checkpointEvery,'atExit',true), ...
    'caseMetadata',metadata, ...
    'resultFile',resultFile, ...
    'saveResults',true, ...
    'storeSnapshots',false, ...
    'makePlots',false, ...
    'livePlot',false, ...
    'writeVideo',false, ...
    'verbose',settings.verbose);
names = fieldnames(boxOverrides);
for index = 1:numel(names)
    overrides.(names{index}) = boxOverrides.(names{index});
end
opts = fourth_order_blowup_case(baseCaseName,overrides);
end

function gates = registered_mesh_gates()
gates = struct( ...
    'maximumAdjacentCellRatio',1.08, ...
    'maximumLogSpacingCurvature',0.01, ...
    'minimumStencilRcond',1e-9, ...
    'minimumQuadratureWeightRatio',1e-8, ...
    'minimumLocalQuadratureWeightRatio',0.35, ...
    'maximumLocalQuadratureWeightRatio',1.65, ...
    'stencilWidth',7);
end

function [audit,passed] = audit_mesh(opts,config,gates,domain,boxMode)
weightsX = ipm.mesh.quadrature(opts.customX);
weightsY = ipm.mesh.quadrature(opts.customY);
qualityX = ipm.mesh.quality( ...
    opts.customX,gates.stencilWidth,weightsX);
qualityY = ipm.mesh.quality( ...
    opts.customY,gates.stencilWidth,weightsY);
[anchorDistance,anchorIndex] = min(abs(opts.customX-1));
anchorTolerance = 128*eps(max(1,max(abs(opts.customX))));

checks = struct();
checks.nodeCounts = numel(opts.customX) == 1025 && ...
    numel(opts.customY) == 513 && config.grid.nx == 1025 && ...
    config.grid.ny == 513;
checks.endpoints = endpoint_close(opts.customX([1,end]),domain.x) && ...
    endpoint_close(opts.customY([1,end]),domain.y);
anchorIsGridNode = anchorDistance <= anchorTolerance;
exactAnchorRequired = strcmp(boxMode,'large_box');
checks.transportAnchorNodePolicy = ...
    ~exactAnchorRequired || anchorIsGridNode;
checks.positiveQuadrature = qualityX.quadratureWeightsStrictlyPositive && ...
    qualityY.quadratureWeightsStrictlyPositive;
checks.adjacentCellRatio = max([qualityX.maximumAdjacentCellRatio, ...
    qualityY.maximumAdjacentCellRatio]) <= ...
    gates.maximumAdjacentCellRatio*(1+1e-12);
checks.logSpacingCurvature = max([ ...
    qualityX.maximumLogSpacingCurvature, ...
    qualityY.maximumLogSpacingCurvature]) <= ...
    gates.maximumLogSpacingCurvature*(1+1e-12);
checks.stencilRcond = min([qualityX.minimumStencilRcond, ...
    qualityY.minimumStencilRcond]) >= ...
    gates.minimumStencilRcond*(1-1e-12);
checks.globalQuadrature = min([ ...
    qualityX.minimumQuadratureWeightRatio, ...
    qualityY.minimumQuadratureWeightRatio]) >= ...
    gates.minimumQuadratureWeightRatio*(1-1e-12);
checks.localQuadratureLower = min([ ...
    qualityX.minimumQuadratureWeightToControlWidthRatio, ...
    qualityY.minimumQuadratureWeightToControlWidthRatio]) >= ...
    gates.minimumLocalQuadratureWeightRatio*(1-1e-12);
checks.localQuadratureUpper = max([ ...
    qualityX.maximumQuadratureWeightToControlWidthRatio, ...
    qualityY.maximumQuadratureWeightToControlWidthRatio]) <= ...
    gates.maximumLocalQuadratureWeightRatio*(1+1e-12);
failures = failed_checks(checks);
passed = isempty(failures);
audit = struct( ...
    'x',qualityX, ...
    'y',qualityY, ...
    'checks',checks, ...
    'failures',{failures}, ...
    'passed',passed, ...
    'anchorX',1, ...
    'nearestAnchorNode',opts.customX(anchorIndex), ...
    'anchorNodeDistance',anchorDistance, ...
    'anchorIsGridNode',anchorIsGridNode, ...
    'exactAnchorRequired',exactAnchorRequired, ...
    'anchorNodeTolerance',anchorTolerance);
end

function [audit,passed] = audit_config_contract(config,opts,expectedGauge)
scaling = config.scaling;
retired = retired_fields();
retiredInOptions = retired(isfield(opts,retired));
retiredInScaling = retired(isfield(scaling,retired));
retiredPresent = unique([retiredInOptions,retiredInScaling],'stable');

checks = struct();
checks.configSchema4 = config.schemaVersion == 4 && config.frozen;
checks.q512 = config.grid.nx == 1025 && config.grid.ny == 513;
checks.numericalTuple = ...
    strcmp(config.transport.spatialDiscretization,'high_order') && ...
    strcmp(config.transport.transportScheme,'weno5_fd') && ...
    strcmp(config.time.timeIntegrator,'ssprk54') && ...
    strcmp(config.remesh.remeshTransferScheme,'high_order');
checks.dynamicIsotropic = ...
    strcmp(scaling.rescalingMode,'dynamic') && ...
    strcmp(scaling.dynamicScaleGeometry,'isotropic');
checks.exactScalingContract = strcmp( ...
    scaling.scalingContract,'exact_gauge_no_feedback_v1');
checks.transportAnchorX1 = strcmp(scaling.lengthGauge, ...
    'transport_anchor') && scaling.transportAnchorX == 1;
checks.registeredAmplitudeGauge = ...
    strcmp(scaling.cOmegaGauge,expectedGauge);
checks.noFeedback = scaling.lengthScaleGain == 1 && ...
    scaling.widthGaugeGain == 0 && scaling.omegaGaugeGain == 0 && ...
    scaling.travelingWaveGain == 0;
checks.noRetiredFields = isempty(retiredPresent);
checks.fixedMesh = ~config.remesh.initialAnalyticRemesh && ...
    ~config.remesh.adaptiveRemesh;
checks.checkpointSchema4Policy = ...
    isfield(config.output,'checkpoint') && ...
    config.output.checkpoint.enabled && config.output.checkpoint.atExit;
failures = failed_checks(checks);
passed = isempty(failures);
audit = struct('checks',checks,'failures',{failures}, ...
    'passed',passed,'retiredFieldsPresent',{retiredPresent});
end

function [audit,checkpointPath] = audit_result( ...
        result,registeredConfig,settings,wallSeconds,requestedCheckpoint)
common = result.history.common;
gauge = result.history.gauge;
[rawTrusted,trustChecks] = ipm.output.trustedMask(result);
trusted = ipm.output.continuousTrustedPrefix(rawTrusted);

requiredGauge = {'omegaGaugeResidual','lengthGaugeResidual', ...
    'transportAnchorVelocity','canonicalTransportAnchorVelocity', ...
    'transportAnchorX','c_lNominal','canonicalCLNominal', ...
    'lengthScaleGain','widthControlMode','widthCorrection', ...
    'canonicalWidthCorrection'};
if strcmp(settings.cOmegaGauge,'gradient_energy')
    requiredGauge = [requiredGauge,gradient_history_fields()];
else
    requiredGauge = [requiredGauge,quadratic_history_fields()];
end
gaugeHistoryComplete = all(isfield(gauge,requiredGauge));
if gaugeHistoryComplete
    gaugeFinite = true;
    for fieldIndex = 1:numel(requiredGauge)
        values = gauge.(requiredGauge{fieldIndex});
        gaugeFinite = gaugeFinite && isnumeric(values) && ...
            isreal(values) && isvector(values) && ...
            numel(values) == numel(common.t) && all(isfinite(values));
    end
else
    gaugeFinite = false;
end

maximumOmegaGaugeResidual = Inf;
maximumLengthGaugeResidual = Inf;
maximumTransportAnchorDefect = Inf;
maximumCanonicalTransportAnchorDefect = Inf;
if gaugeHistoryComplete && gaugeFinite
    maximumOmegaGaugeResidual = max(abs(gauge.omegaGaugeResidual));
    maximumLengthGaugeResidual = max(normalized_anchor_residual( ...
        gauge.lengthGaugeResidual,gauge.c_lNominal, ...
        gauge.transportAnchorX));
    maximumTransportAnchorDefect = max(normalized_anchor_residual( ...
        gauge.transportAnchorVelocity,gauge.c_lNominal, ...
        gauge.transportAnchorX));
    maximumCanonicalTransportAnchorDefect = max( ...
        normalized_anchor_residual( ...
        gauge.canonicalTransportAnchorVelocity, ...
        gauge.canonicalCLNominal,gauge.transportAnchorX));
end

checkpointPath = locate_checkpoint(result,requestedCheckpoint);
checkpointValidated = false;
checkpointMatchesTerminal = false;
checkpointContractPassed = false;
checkpointRetiredFields = retired_fields();
if ~isempty(checkpointPath)
    checkpoint = ipm.output.readCheckpoint(checkpointPath);
    checkpointValidated = true;
    checkpointRetiredFields = checkpoint_retired_fields(checkpoint);
    state = checkpoint.payload.state;
    checkpointMatchesTerminal = state.step == result.state.steps && ...
        scalar_close(state.scale.canonicalTime, ...
            result.state.canonicalTime) && ...
        scalar_close(state.scale.physicalTime,result.state.physicalTime) && ...
        isequaln(state.rho,result.state.rho) && ...
        isequaln(state.x,result.grid.x) && ...
