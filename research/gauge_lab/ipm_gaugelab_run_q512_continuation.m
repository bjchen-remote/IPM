function passed = amplitude_contract_matches(amplitude,gaugeName)
switch char(gaugeName)
    case 'gradient_energy'
        passed = strcmp(amplitude.formula,[ ...
            'c_omega=-sum(w*(R_X*B_X+R_Y*B_Y))/' ...
            'sum(w*(R_X^2+R_Y^2))']) && ...
            strcmp(amplitude.observable, ...
                'global_discrete_gradient_energy') && ...
            strcmp(amplitude.evaluation,'fixed_grid_quadrature');
