    return
end
for index = 1:numel(names)
    values = group.(names{index});
    finite = finite && isnumeric(values) && isreal(values) && ...
        isvector(values) && numel(values) == count && ...
        all(isfinite(values));
end
end

function audit = audit_gradient_gauge_algebra(common,gauge)
tolerance = 1e-10;
energy = gauge.omegaGaugeEnergy(:);
energyX = gauge.omegaGaugeEnergyX(:);
energyY = gauge.omegaGaugeEnergyY(:);
forcing = gauge.omegaGaugeForcing(:);
forcingX = gauge.omegaGaugeForcingX(:);
forcingY = gauge.omegaGaugeForcingY(:);
absoluteForcing = gauge.omegaGaugeAbsoluteForcing(:);
cancellation = gauge.omegaGaugeForcingCancellationRatio(:);
recordedResidual = gauge.omegaGaugeResidual(:);
checks = struct();
checks.cOmegaHistoryAvailable = isfield(common,'c_omega') && ...
    isnumeric(common.c_omega) && isreal(common.c_omega) && ...
    isvector(common.c_omega) && ...
    numel(common.c_omega) == numel(energy) && ...
    all(isfinite(common.c_omega));
checks.energyStrictlyPositive = all(energy > 0);
checks.energyPartsNonnegative = all(energyX >= 0) && all(energyY >= 0);
energyDefect = normalized_identity_defect(energy,energyX+energyY);
forcingDefect = normalized_identity_defect(forcing,forcingX+forcingY);
checks.energyPartsIdentity = max(energyDefect) <= tolerance;
checks.forcingPartsIdentity = max(forcingDefect) <= tolerance;
absoluteTolerance = tolerance*max([ones(size(forcing)), ...
    abs(forcing),absoluteForcing],[],2);
