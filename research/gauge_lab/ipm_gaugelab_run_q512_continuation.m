    cancellation,expectedCancellation);
checks.cancellationRatioIdentity = ...
    max(cancellationDefect) <= tolerance;
checks.cancellationRatioRange = all(cancellation >= 0) && ...
    all(cancellation <= 1+tolerance);
equationResidual = Inf(size(energy));
residualIdentityDefect = Inf(size(energy));
if checks.cOmegaHistoryAvailable
    cOmega = common.c_omega(:);
    equationResidual = abs(forcing+cOmega.*energy)./max([ ...
        abs(forcing),abs(cOmega.*energy), ...
        realmin*ones(size(energy))],[],2);
    expectedSignedResidual = (forcing+cOmega.*energy)./max([ ...
        abs(forcing),abs(cOmega.*energy), ...
        realmin*ones(size(energy))],[],2);
    residualIdentityDefect = normalized_identity_defect( ...
        recordedResidual,expectedSignedResidual);
end
checks.gaugeEquationResidual = max(equationResidual) <= tolerance;
checks.recordedResidualIdentity = ...
    max(residualIdentityDefect) <= tolerance;
failures = failed_checks(checks);
audit = struct('passed',isempty(failures),'checks',checks, ...
    'failures',{failures},'tolerance',tolerance, ...
    'minimumEnergy',min(energy), ...
    'maximumEnergyPartsDefect',max(energyDefect), ...
    'maximumForcingPartsDefect',max(forcingDefect), ...
    'maximumCancellationRatioDefect',max(cancellationDefect), ...
    'maximumGaugeEquationResidual',max(equationResidual), ...
    'maximumRecordedResidualIdentityDefect', ...
        max(residualIdentityDefect));
end

