function [passed,maximumLengthResidual,maximumOmegaResidual] = ...
        residual_field_audit(gauge,count)
required = {'c_lNominal','lengthGaugeStrain','widthRateScale', ...
    'lengthGaugeResidual','omegaGaugeResidual'};
passed = has_finite_equal_length_fields(gauge,required,count);
maximumLengthResidual = Inf;
maximumOmegaResidual = Inf;
