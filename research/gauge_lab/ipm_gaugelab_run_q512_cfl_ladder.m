function diagnostic = rate_diagnostic_comparison(reference,candidate,limits)
diagnostic = struct( ...
    'available',false, ...
    'status','invalid_or_insufficient_short_window', ...
    'appliedToHardGate',false, ...
    'series',struct(), ...
    'hardPassed',false);
if ~isstruct(reference) || ~isstruct(candidate) || ...
        ~isfield(reference,'valid') || ~isfield(candidate,'valid') || ...
        ~reference.valid || ~candidate.valid || ...
        ~isequal(reference.windowFractions,candidate.windowFractions)
    return
end
names = {'cL','cOmega','cOmegaOverCL','cLMinusCOmegaOverCL'};
series = struct();
passed = true;
for index = 1:numel(names)
    name = names{index};
    left = reference.seriesSummary.(name);
    right = candidate.seriesSummary.(name);
    if ~(left.valid && right.valid)
        passed = false;
        series.(name) = struct('available',false);
        continue
    end
    meanDifference = vector_relative_difference( ...
        left.windowWeightedMeans,right.windowWeightedMeans);
    trendDifference = right.windowRelativeTrends- ...
        left.windowRelativeTrends;
    rmsDifference = right.windowRelativeDetrendedRms- ...
        left.windowRelativeDetrendedRms;
    seriesPassed = ...
        max(abs(meanDifference)) <= ...
        limits.maximumRateWindowMeanRelativeDifference && ...
        max(abs(trendDifference)) <= ...
        limits.maximumRateRelativeTrendDifference && ...
        max(abs(rmsDifference)) <= ...
        limits.maximumRateRelativeRmsDifference;
    series.(name) = struct( ...
        'available',true, ...
        'windowMeanRelativeDifference',meanDifference, ...
        'windowRelativeTrendDifference',trendDifference, ...
        'windowRelativeDetrendedRmsDifference',rmsDifference, ...
        'maximumWindowMeanRelativeDifference', ...
            max(abs(meanDifference)), ...
        'maximumRelativeTrendDifference',max(abs(trendDifference)), ...
        'maximumRelativeDetrendedRmsDifference', ...
            max(abs(rmsDifference)), ...
        'hardPassed',seriesPassed);
    passed = passed && seriesPassed;
end
diagnostic.available = true;
diagnostic.status = ternary(passed,'passed','gate_failed');
diagnostic.appliedToHardGate = true;
diagnostic.series = series;
diagnostic.hardPassed = passed;
end

