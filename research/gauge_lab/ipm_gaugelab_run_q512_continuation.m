valid = isstruct(event) && isscalar(event) && all(isfield(event,required));
if ~valid
    return
end
try
    valid = any(event.schemaVersion == [2,3]) && ...
        is_text(event.runId) && ...
        ~isempty(char(event.runId)) && is_text(event.registeredUtc) && ...
        is_text(event.parentCheckpointSource) && ...
        is_text(event.parentCheckpointToken) && ...
        ~isempty(char(event.parentCheckpointToken)) && ...
        complete_checkpoint_signature(event.parentCheckpointSignature) && ...
        isnumeric(event.parentStep) && isreal(event.parentStep) && ...
        isscalar(event.parentStep) && isfinite(event.parentStep) && ...
        event.parentStep >= 0 && ...
        event.parentStep == fix(event.parentStep) && ...
        isnumeric(event.parentCanonicalTime) && ...
        isreal(event.parentCanonicalTime) && ...
        isscalar(event.parentCanonicalTime) && ...
        isfinite(event.parentCanonicalTime) && ...
        event.parentCanonicalTime >= 0 && ...
        isnumeric(event.parentPhysicalTime) && ...
        isreal(event.parentPhysicalTime) && ...
        isscalar(event.parentPhysicalTime) && ...
        isfinite(event.parentPhysicalTime) && ...
        event.parentPhysicalTime >= 0 && ...
        isnumeric(event.requestedFinalTime) && ...
        isreal(event.requestedFinalTime) && ...
        isscalar(event.requestedFinalTime) && ...
        ~isnan(event.requestedFinalTime) && event.requestedFinalTime > 0 && ...
        isnumeric(event.requestedPhysicalFinalTime) && ...
        isreal(event.requestedPhysicalFinalTime) && ...
        isscalar(event.requestedPhysicalFinalTime) && ...
        ~isnan(event.requestedPhysicalFinalTime) && ...
        event.requestedPhysicalFinalTime > 0 && ...
        isnumeric(event.requestedMaxSteps) && ...
        isreal(event.requestedMaxSteps) && ...
        isscalar(event.requestedMaxSteps) && ...
        isfinite(event.requestedMaxSteps) && ...
        event.requestedMaxSteps == fix(event.requestedMaxSteps) && ...
        event.requestedMaxSteps > event.parentStep && ...
        isscalar(event.parentRootSummaryProvided) && ...
        (islogical(event.parentRootSummaryProvided) || ...
        any(event.parentRootSummaryProvided == [0,1])) && ...
        logical(event.parentRootSummaryProvided) && ...
        is_text(event.parentSummarySource) && ...
        ~isempty(char(event.parentSummarySource)) && ...
        is_text(event.parentSummaryKind) && ...
        ~isempty(char(event.parentSummaryKind)) && ...
        is_text(event.parentSummaryRunId) && ...
        ~isempty(char(event.parentSummaryRunId)) && ...
        is_text(event.parentRootRunId) && ...
        ~isempty(char(event.parentRootRunId));
catch
    valid = false;
end
if valid
    signatureGauge = checkpoint_signature_c_omega_gauge( ...
        event.parentCheckpointSignature);
    explicitGaugeValid = true;
    if event.schemaVersion >= 3
        explicitGaugeValid = isfield(event,'cOmegaGauge') && ...
            is_text(event.cOmegaGauge) && ...
            strcmp(char(event.cOmegaGauge),signatureGauge);
    elseif isfield(event,'cOmegaGauge')
        explicitGaugeValid = is_text(event.cOmegaGauge) && ...
            strcmp(char(event.cOmegaGauge),signatureGauge);
    end
    valid = explicitGaugeValid && allowed_c_omega_gauge(signatureGauge);
end
if valid
    values = event;
    values.runId = char(event.runId);
    values.cOmegaGauge = signatureGauge;
end
end

