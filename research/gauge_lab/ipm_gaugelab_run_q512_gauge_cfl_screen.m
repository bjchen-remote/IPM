function trend = linear_trend(x,y)
x = x(:);
y = y(:);
valid = isfinite(x) & isfinite(y);
x = x(valid);
y = y(valid);
trend = struct('valid',false,'count',numel(x),'slope',NaN, ...
    'intercept',NaN,'residualRms',NaN,'relativeResidualRms',NaN, ...
    'rSquared',NaN);
if numel(x) < 3 || x(end) <= x(1)
    return
end
xCenter = mean(x);
design = [ones(size(x)),x-xCenter];
coefficients = design\y;
fitted = design*coefficients;
residual = y-fitted;
centered = y-mean(y);
denominator = sum(centered.^2);
if denominator > 0
    rSquared = 1-sum(residual.^2)/denominator;
else
    rSquared = NaN;
end
trend.valid = true;
trend.slope = coefficients(2);
trend.intercept = coefficients(1)-coefficients(2)*xCenter;
trend.residualRms = sqrt(mean(residual.^2));
trend.relativeResidualRms = trend.residualRms / ...
    max(mean(abs(y)),realmin);
trend.rSquared = rSquared;
end

