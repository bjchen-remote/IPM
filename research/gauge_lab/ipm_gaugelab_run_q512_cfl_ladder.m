end

function comparison = bidirectional_comparison( ...
        reference,candidate,referenceRecord,candidateRecord,cap,limits)
endpointDifference = candidate.state.physicalTime- ...
    reference.state.physicalTime;
endpointTolerance = max(limits.maximumPhysicalEndpointDifference, ...
    100*eps(max([1,abs(reference.state.physicalTime), ...
    abs(candidate.state.physicalTime)])));
if abs(endpointDifference) > endpointTolerance
    error('ipm:GaugeLabQ512CflLadderEndpoint', ...
        ['Terminal physical times differ by %.3e, exceeding the common-' ...
        'endpoint tolerance %.3e.'],endpointDifference,endpointTolerance);
end
window = common_window(reference,candidate,cap);
forward = directional_comparison(reference,candidate,window);
reverse = directional_comparison(candidate,reference,window);
names = physical_metric_names();
worst = struct();
for index = 1:numel(names)
    name = names{index};
    worst.(name) = max(abs([forward.(name),reverse.(name)]));
