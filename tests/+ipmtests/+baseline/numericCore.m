function formulaError = isotropic_gauge_formula_check()
userOpts = struct('nx',33,'ny',17,'xlim',[-4,4],'ymax',4, ...
    'gridMode','uniform','gridStretch',0, ...
    'farBoundaryMode','dirichlet_zero', ...
    'transportScheme','muscl_minmod', ...
    'symmetryMode','double_odd_omega', ...
    'rescalingMode','dynamic','dynamicScaleGeometry','isotropic', ...
    'lengthGauge','transport_anchor','transportAnchorX',1, ...
