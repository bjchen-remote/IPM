    'x',quadrature_axis_quality(x), ...
    'y',quadrature_axis_quality(y));
end

function quality = quadrature_axis_quality(axis)
axis = double(axis(:));
weights = double(ipm.mesh.quadrature(axis));
weights = weights(:);
meshQuality = ipm.mesh.quality(axis,7,weights);
faces = diff(axis);
controlWidths = [0.5*faces(1); ...
    0.5*(faces(1:end-1)+faces(2:end));0.5*faces(end)];
localRatios = weights./controlWidths;
[~,minimumIndex] = min(localRatios);
[~,maximumIndex] = max(localRatios);
maximumLocalDeviation = ...
    meshQuality.maximumQuadratureWeightToControlWidthAbsoluteDeviationFromUnity;
quality = struct( ...
    'quadratureWeightsStrictlyPositive', ...
        meshQuality.quadratureWeightsStrictlyPositive, ...
    'minimumQuadratureWeight',meshQuality.minimumQuadratureWeight, ...
    'minimumQuadratureWeightRatio', ...
        meshQuality.minimumQuadratureWeightRatio, ...
    'minimumQuadratureWeightToControlWidthRatio', ...
        meshQuality.minimumQuadratureWeightToControlWidthRatio, ...
    'maximumQuadratureWeightToControlWidthRatio', ...
        meshQuality.maximumQuadratureWeightToControlWidthRatio, ...
    'maximumQuadratureWeightToControlWidthAbsoluteDeviationFromUnity', ...
        maximumLocalDeviation, ...
    'minimumQuadratureWeightToControlWidthRatioNodeIndex',minimumIndex, ...
    'maximumQuadratureWeightToControlWidthRatioNodeIndex',maximumIndex, ...
    'minimumControlWidth',min(controlWidths), ...
    'maximumControlWidth',max(controlWidths), ...
    'quadratureSumRelativeDefect', ...
        abs(sum(weights)-(axis(end)-axis(1))) / ...
        max(abs(axis(end)-axis(1)),eps));
end

function [passed,reasons] = quadrature_pair_gate(quality,options)
reasons = {};
for field = {'x','y'}
    label = field{1};
    axisQuality = quality.(label);
    if ~axisQuality.quadratureWeightsStrictlyPositive
        reasons{end+1} = ...
            [label ':quadrature_not_strictly_positive']; %#ok<AGROW>
    end
    if ~isfinite(axisQuality.minimumQuadratureWeightRatio) || ...
            axisQuality.minimumQuadratureWeightRatio < ...
            options.minimumQuadratureWeightRatio
        reasons{end+1} = ...
            [label ':global_quadrature_weight_ratio']; %#ok<AGROW>
    end
    if ~isfinite( ...
            axisQuality.minimumQuadratureWeightToControlWidthRatio) || ...
            axisQuality.minimumQuadratureWeightToControlWidthRatio < ...
            options.minimumLocalQuadratureWeightRatio
        reasons{end+1} = ...
            [label ':minimum_local_quadrature_ratio']; %#ok<AGROW>
    end
    if ~isfinite( ...
            axisQuality.maximumQuadratureWeightToControlWidthRatio) || ...
            axisQuality.maximumQuadratureWeightToControlWidthRatio > ...
            options.maximumLocalQuadratureWeightRatio
        reasons{end+1} = ...
            [label ':maximum_local_quadrature_ratio']; %#ok<AGROW>
    end
end
passed = isempty(reasons);
end

function [active,reasons] = quadrature_pair_warning(quality,options)
reasons = {};
for field = {'x','y'}
    label = field{1};
    ratio = quality.(label).minimumQuadratureWeightRatio;
    if isfinite(ratio) && ...
            ratio < options.globalQuadratureWeightRatioWarning
        reasons{end+1} = ...
            [label ':global_quadrature_weight_ratio_warning']; %#ok<AGROW>
    end
end
active = ~isempty(reasons);
end

function reserve = launch_reserve(options,lastSolveSeconds)
reserve = options.minimumWallTimeToLaunchSeconds;
if isfinite(lastSolveSeconds) && lastSolveSeconds > 0
    reserve = max(reserve, ...
        options.wallTimeForecastFactor*lastSolveSeconds);
end
end

function [checkpoint,fileName] = ...
        find_terminal_checkpoint(result,requestedBase)
candidates = {};
if isfield(result.metadata,'latestCheckpointFile') && ...
        strlength(string(result.metadata.latestCheckpointFile)) > 0
    candidates{end+1} = char(result.metadata.latestCheckpointFile);
end
[folder,stem] = fileparts(requestedBase);
listing = dir(fullfile(folder,[stem,'*.mat']));
if ~isempty(listing)
    [~,order] = sort([listing.datenum],'descend');
    for index = order
        candidates{end+1} = ...
            fullfile(listing(index).folder, ...
            listing(index).name); %#ok<AGROW>
    end
end
candidates = unique(candidates,'stable');
for index = 1:numel(candidates)
    candidate = candidates{index};
    if ~isfile(candidate)
        continue
    end
    try
        probe = ipm.output.readCheckpoint(candidate);
    catch
        continue
    end
    if checkpoint_matches_result(probe,result)
        checkpoint = probe;
        fileName = absolute_path(candidate);
        return
    end
end
error('ipm:gridlab:CampaignTerminalCheckpoint', ...
    ['A terminal-trusted solve did not expose a native exit checkpoint ' ...
    'matching its exact step, clocks, grid, and rho field.']);
end

function answer = checkpoint_matches_result(checkpoint,result)
state = checkpoint.payload.state;
scale = max([1,abs(state.scale.canonicalTime), ...
    abs(result.state.canonicalTime),abs(state.scale.physicalTime), ...
    abs(result.state.physicalTime)]);
tolerance = 64*eps(scale);
answer = state.step == result.state.steps && ...
    abs(state.scale.canonicalTime-result.state.canonicalTime) <= tolerance && ...
    abs(state.scale.physicalTime-result.state.physicalTime) <= tolerance && ...
    isequal(state.x,result.grid.x) && isequal(state.y,result.grid.y) && ...
    isequal(state.rho,result.state.rho);
end

