    isfield(quality,'omegaGaugeWindowCondition') && ...
    isfield(quality,'omegaGaugeWindowRateResidual') && ...
    quality.omegaGaugeWindowCondition == ...
        flowAfter.omegaGaugeWindowCondition && ...
    quality.omegaGaugeWindowRateResidual == ...
        flowAfter.omegaGaugeWindowRateResidual;
recordedResidualError = abs( ...
    recorded.history.gauge.omegaGaugeWindowRateResidual(end) - ...
    flowAfter.omegaGaugeWindowRateResidual);

check = struct('formulaError',formulaError, ...
    'rateResidual',abs(flow.omegaGaugeWindowRateResidual), ...
    'residualReconstructionError',abs( ...
        flow.omegaGaugeWindowRateResidual-reconstructedResidual), ...
    'recordedResidualError',recordedResidualError, ...
    'condition',flow.omegaGaugeWindowCondition, ...
    'energy',flow.omegaGaugeWindowEnergy, ...
    'order',flow.omegaGaugeWindowMomentOrder, ...
    'momentIdentityError',abs(flow.omegaGaugeWindowMoment- ...
        flow.omegaGaugeWindowValue^momentOrder) / ...
        max(flow.omegaGaugeWindowMoment,realmin), ...
    'amplitudeRateError',amplitudeRateError, ...
    'amplitudeRhsError',amplitudeRhsError, ...
    'amplitudeNormalizedResidualMagnitude', ...
        max(abs(normalizedResiduals)), ...
    'amplitudeNormalizedResidualSpread',normalizedResidualSpread, ...
    'shortStepRelativeValueDrift',abs( ...
        flowAfter.omegaGaugeWindowValue-reference)/reference, ...
    'historyFieldsPresent',historyFieldsPresent, ...
    'finalQualityFieldsPresent',finalQualityFieldsPresent, ...
    'referencePreserved', ...
        flow.omegaGaugeReferenceWindowValue == reference && ...
        flowAfter.omegaGaugeReferenceWindowValue == reference && ...
        flow.omegaGaugeWindowCenter == ops.rescaling.transportAnchorX && ...
        flow.omegaGaugeWindowRadius == ...
            ops.rescaling.omegaGaugeWindowRadius && ...
        flow.omegaGaugeWindowMoment == flow.omegaGaugeEnergy, ...
    'shortStepFinite',all(isfinite(rhoAfter),'all') && ...
        all(cellfun(@(value)isnumeric(value) && isscalar(value) && ...
        isfinite(value),struct2cell(scaleAfter))) && ...
        isfinite(flowAfter.canonicalCOmega));
end

function [formulaError,reconstructedResidual] = ...
        window_formula_error(rho,rhs,flow,ops,momentOrder)
baseRhs = rhs-flow.canonicalCOmega*rho;
baseRhsX = baseRhs*ops.Dx';
window = ipm.evolve.wallWindowMoment( ...
    flow.source(1,:),ops,ops.rescaling,momentOrder);
forcing = sum(window.normalizedWeights .* ...
    flow.source(1,:).^(momentOrder-1).*baseRhsX(1,:));
expected = -forcing/window.moment;
formulaError = abs(flow.canonicalCOmega-expected);
reconstructedResidual = forcing + flow.canonicalCOmega*window.moment;
end

function check = anchor_wall_template_check(options)
options.scaling.cOmegaGauge = 'anchor_wall_template_projection';
options.transport.spatialDiscretization = 'high_order';
options.transport.transportScheme = 'weno5_fd';
options.time.timeIntegrator = 'ssprk54';
options.remesh.remeshTransferScheme = 'high_order';
options.remesh.adaptiveRemesh = false;
ops = ipm.mesh.build(options);
rho = ipm.field.initialDensity(ops,options.physics);
ops = ipm.evolve.initializeScaling(rho,ops);
[rhs,flow] = ipm.evolve.rhs(rho,ops);

geometry = ipm.evolve.wallWindowGeometry(ops,ops.rescaling);
template = ops.rescaling.referenceAnchorWallTemplate;
baseRhs = rhs-flow.canonicalCOmega*rho;
baseRhsX = baseRhs*ops.Dx';
projection = sum(geometry.normalizedWeights.*flow.source(1,:).*template);
forcing = sum(geometry.normalizedWeights.*baseRhsX(1,:).*template);
expected = -forcing/projection;
formulaError = abs(flow.canonicalCOmega-expected);
normalizedRateResidual = abs(flow.omegaGaugeTemplateRateResidual) / ...
    max(flow.omegaGaugeTemplateRateScale,realmin);
reference = ops.rescaling.referenceAnchorWallTemplateProjection;

amplitudeFactor = 3;
scaledOps = ops;
scaledOps.rescaling.referenceAnchorWallTemplateProjection = ...
    amplitudeFactor*reference;
[scaledRhs,scaledFlow] = ipm.evolve.rhs(amplitudeFactor*rho,scaledOps);
amplitudeRateError = max(abs([scaledFlow.canonicalCL, ...
    scaledFlow.canonicalCOmega,scaledFlow.canonicalCR] - ...
    amplitudeFactor*[flow.canonicalCL,flow.canonicalCOmega, ...
    flow.canonicalCR]));
amplitudeRhsError = weighted_l2( ...
    scaledRhs-amplitudeFactor^2*rhs,ops) / ...
    max(weighted_l2(amplitudeFactor^2*rhs,ops),eps);

scale = struct('logC_l',0,'logC_omega',0,'physicalTime',0, ...
    'X_shift',0,'canonicalTime',0);
stepSize = 1e-5;
[rhoAfter,flowAfter,scaleAfter] = ipm.evolve.stepSsprk54( ...
    rho,stepSize,ops,scale);
