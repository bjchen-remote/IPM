function screen = ipm_gaugelab_screen_q512_comega_box(options)
%IPM_GAUGELAB_SCREEN_Q512_COMEGA_BOX Initial-RHS q512 box screen.
%   SCREEN = IPM_GAUGELAB_SCREEN_Q512_COMEGA_BOX() evaluates only the
%   initial right-hand side--it never advances the PDE--on the registered
%   anchor-aligned q512 large-box family with half-widths
%       [281, 1e3, 1e4, 1e5, 1e6].
%   The length gauge is fixed to transport_anchor at X=1.  The only
%   amplitude gauges are the negative control gradient_energy, the local
%   wall_omega_quadratic_peak candidate, and the exploratory exact `none`
%   gauge (c_omega=0).  All use the exact no-feedback contract and the
%   registered high-order numerical tuple.
%
%   The default is preflight-only: it registers and audits every schema-4
%   configuration without building a Poisson solver or evaluating an RHS.
%   Set OPTIONS.execute=true explicitly to evaluate the initial RHS.  Even
%   then, the runner performs no time step, checkpoint operation, or solver
%   result-file write.  Every call writes a new immutable
%   summary/JSONL-manifest directory.
%
%   This is a normalization screen, not truncation or late-time evidence.
%   Its hard gate requires the full-gradient negative control to expose its
%   extensive energy/forcing and requires the quadratic-peak rate and
%   local functional to converge on the final 1e5 -> 1e6 box comparison.
%   The identically-zero `none` rate is never promoted by this screen: it
%   remains ineligible until time-evolved field, box, and CFL evidence is
%   available.  Its exact-zero implementation and shared c_l box
%   consistency must nevertheless pass for the screen itself to be valid.

if nargin < 1 || isempty(options)
    options = struct();
end
settings = resolve_options(options);
require_factory();

[outputDirectory,screenId] = create_output_directory(settings.outputRoot);
summaryFile = fullfile(outputDirectory,'comega_box_screen_summary.mat');
manifestFile = fullfile(outputDirectory,'comega_box_screen_manifest.jsonl');
boxHalfWidths = [281,1e3,1e4,1e5,1e6];
gauges = {'gradient_energy','wall_omega_quadratic_peak','none'};
limits = registered_limits();

records = repmat(empty_box_record(gauges),numel(boxHalfWidths),1);
for index = 1:numel(boxHalfWidths)
    records(index).index = index;
    records(index).boxHalfWidth = boxHalfWidths(index);
    records(index).domain = struct( ...
        'x',[-boxHalfWidths(index),boxHalfWidths(index)], ...
        'y',[0,boxHalfWidths(index)]);
    records(index).status = 'pending';
end

startedUtc = utc_stamp();
screen = struct( ...
    'schemaVersion',4, ...
    'kind','q512_initial_rhs_comega_box_screen', ...
    'screenId',screenId, ...
    'status','registered', ...
    'startedUtc',startedUtc, ...
    'completedUtc','', ...
    'executionMode',execution_mode(settings), ...
    'initialRhsOnly',true, ...
    'solveExecuted',false, ...
    'pdeStepsExecuted',0, ...
    'freshInitialData',true, ...
    'checkpointInputsAccepted',false, ...
    'lateTimeEvidence',false, ...
    'truncationEvidence',false, ...
    'noneGaugePromotionEvidenceRequired',{ ...
        {'time_evolved_fields','box_refinement','cfl_refinement'}}, ...
    'interpretation',[ ...
        'initial_normalization_box_screen_only_not_late_time_or_' ...
        'truncation_evidence'], ...
    'boxFamily','anchor_aligned_q512_large_box_factory', ...
    'boxHalfWidths',boxHalfWidths, ...
    'gauges',{gauges}, ...
    'requested',requested_summary(settings), ...
    'registeredGaugeRules',registered_gauge_rules(), ...
    'hardLimits',limits, ...
    'outputDirectory',outputDirectory, ...
    'summaryFile',summaryFile, ...
    'manifestFile',manifestFile, ...
    'boxes',records, ...
    'successiveComparisons', ...
        repmat(empty_comparison(),0,1), ...
    'preflightPassed',false, ...
    'screeningGate',empty_screening_gate(), ...
    'hardPassed',false, ...
    'totalWallSeconds',NaN, ...
    'totalRhsWallSeconds',NaN, ...
    'failures',{{}});
save_summary(summaryFile,screen);
append_manifest(manifestFile,struct( ...
    'event','screen_registered', ...
    'timestampUtc',startedUtc, ...
    'screenId',screenId, ...
    'schemaVersion',screen.schemaVersion, ...
    'executionMode',screen.executionMode, ...
    'initialRhsOnly',true, ...
    'solveExecuted',false, ...
    'pdeStepsExecuted',0, ...
    'boxHalfWidths',boxHalfWidths, ...
    'gauges',{gauges}, ...
    'requested',screen.requested, ...
    'hardLimits',limits, ...
    'summaryFile',summaryFile));

totalClock = tic;
for boxIndex = 1:numel(boxHalfWidths)
    halfWidth = boxHalfWidths(boxIndex);
    record = screen.boxes(boxIndex);
    record.status = 'preflighting';
    record.startedUtc = utc_stamp();
    screen.boxes(boxIndex) = record;
    save_summary(summaryFile,screen);
    append_manifest(manifestFile,struct( ...
        'event','box_started', ...
        'timestampUtc',record.startedUtc, ...
        'screenId',screenId, ...
        'boxHalfWidth',halfWidth, ...
        'executeInitialRhs',settings.execute));

    try
        [flatOptions,configurations] = registered_configurations( ...
            halfWidth,gauges,screenId,outputDirectory);
        record.configurations = configurations;
        [record.meshAudit,record.meshPassed] = audit_mesh_axes( ...
            flatOptions.(gauges{1}),halfWidth);
        record.contractAudits = struct();
        for gaugeIndex = 1:numel(gauges)
            gauge = gauges{gaugeIndex};
            [audit,passed] = audit_config_contract( ...
                configurations.(gauge),flatOptions.(gauge), ...
                gauge,halfWidth);
            record.contractAudits.(gauge) = audit;
            record.gaugeRuns.(gauge).contractPassed = passed;
        end
        record.sharedCandidateAudit = audit_candidate_identity( ...
            configurations,gauges);
        contractPasses = cellfun(@(gauge) ...
            record.gaugeRuns.(gauge).contractPassed,gauges);
        record.preflightPassed = record.meshPassed && ...
            all(contractPasses) && record.sharedCandidateAudit.passed;
        if ~record.preflightPassed
            record.status = 'preflight_rejected';
        elseif ~settings.execute
            record.status = 'preflight_only';
        else
            [record.gaugeRuns,record.executionAudit] = ...
                execute_initial_rhs(configurations,record.gaugeRuns, ...
                gauges,limits);
            runPasses = cellfun(@(gauge)strcmp( ...
                record.gaugeRuns.(gauge).status,'completed'),gauges);
            if all(runPasses) && record.executionAudit.passed
                record.status = 'initial_rhs_complete';
            else
                record.status = 'initial_rhs_rejected';
            end
        end
    catch exception
        record.status = 'failed';
        record.errorIdentifier = exception.identifier;
        record.errorMessage = exception.message;
    end
    record.completedUtc = utc_stamp();
    screen.boxes(boxIndex) = record;
    save_summary(summaryFile,screen);
    if settings.execute
        for gaugeIndex = 1:numel(gauges)
            gauge = gauges{gaugeIndex};
            run = record.gaugeRuns.(gauge);
            append_manifest(manifestFile,struct( ...
                'event','initial_rhs_sample', ...
                'timestampUtc',record.completedUtc, ...
                'screenId',screenId, ...
                'boxHalfWidth',halfWidth, ...
                'gauge',gauge, ...
                'status',run.status, ...
                'rhsWallSeconds',run.rhsWallSeconds, ...
                'rates',run.rates, ...
                'wallQuadraticPeak',run.wallQuadraticPeak, ...
                'gradientEnergy',run.gradientEnergy, ...
                'farBoundary',run.farBoundary, ...
                'baseRhsCrossGaugeRelativeL2', ...
                    run.baseRhsCrossGaugeRelativeL2, ...
                'errorIdentifier',run.errorIdentifier, ...
                'errorMessage',run.errorMessage));
        end
    end
    append_manifest(manifestFile,struct( ...
        'event','box_finished', ...
        'timestampUtc',record.completedUtc, ...
        'screenId',screenId, ...
        'boxHalfWidth',halfWidth, ...
        'status',record.status, ...
        'meshPassed',record.meshPassed, ...
        'preflightPassed',record.preflightPassed, ...
        'rhsWallSeconds',box_rhs_wall_seconds(record,gauges), ...
        'errorIdentifier',record.errorIdentifier, ...
        'errorMessage',record.errorMessage));
end

screen.preflightPassed = all([screen.boxes.preflightPassed]);
if settings.execute
    screen.successiveComparisons = successive_comparisons( ...
        screen.boxes,gauges);
    screen.screeningGate = assess_screening_gate(screen,limits,gauges);
end
screen.totalWallSeconds = toc(totalClock);
rhsTimes = zeros(0,1);
for boxIndex = 1:numel(screen.boxes)
    for gaugeIndex = 1:numel(gauges)
        value = screen.boxes(boxIndex).gaugeRuns.( ...
            gauges{gaugeIndex}).rhsWallSeconds;
        if isfinite(value)
            rhsTimes(end+1,1) = value; %#ok<AGROW>
        end
    end
end
screen.totalRhsWallSeconds = sum(rhsTimes);
screen.failures = screen_failures(screen,settings,gauges);
if ~settings.execute
    screen.hardPassed = false;
    if screen.preflightPassed && isempty(screen.failures)
        screen.status = 'preflight_complete';
    else
        screen.status = 'preflight_rejected';
    end
else
    screen.hardPassed = screen.preflightPassed && ...
        screen.screeningGate.passed && isempty(screen.failures);
    if screen.hardPassed
        screen.status = 'screen_complete';
    elseif screen.preflightPassed && ...
            ~screen.screeningGate.checks.allInitialRhsCompleted
        screen.status = 'execution_failure';
    elseif screen.preflightPassed
        screen.status = 'screen_gate_failed';
    else
        screen.status = 'partial_failure';
    end
end
screen.completedUtc = utc_stamp();
save_summary(summaryFile,screen);
append_manifest(manifestFile,struct( ...
    'event','screen_finished', ...
    'timestampUtc',screen.completedUtc, ...
    'screenId',screenId, ...
    'status',screen.status, ...
    'preflightPassed',screen.preflightPassed, ...
    'hardPassed',screen.hardPassed, ...
    'screeningGateStatus',screen.screeningGate.status, ...
    'screeningGate',screen.screeningGate, ...
    'totalWallSeconds',screen.totalWallSeconds, ...
    'totalRhsWallSeconds',screen.totalRhsWallSeconds, ...
    'solveExecuted',false, ...
    'pdeStepsExecuted',0, ...
    'failures',{screen.failures}));

if settings.verbose
    fprintf(['Q512 C_OMEGA BOX SCREEN: status=%s, mode=%s, ' ...
        'RHS wall=%.3f s, summary=%s\n'],screen.status, ...
        screen.executionMode,screen.totalRhsWallSeconds,summaryFile);
end
end

function settings = resolve_options(options)
if ~isstruct(options) || ~isscalar(options)
    error('ipm:GaugeLabQ512COmegaBoxOptions', ...
        'options must be a scalar structure.');
end
allowed = {'execute','preflightOnly','outputRoot','verbose'};
unknown = setdiff(fieldnames(options),allowed,'stable');
if ~isempty(unknown)
    error('ipm:GaugeLabQ512COmegaBoxOptions', ...
        'Unknown option(s): %s.',strjoin(unknown,', '));
end
executeWasSpecified = isfield(options,'execute');
settings.execute = logical_option(options,'execute',false);
settings.preflightOnly = logical_option(options,'preflightOnly',false);
if settings.preflightOnly
    if executeWasSpecified && settings.execute
        error('ipm:GaugeLabQ512COmegaBoxOptions', ...
            'execute=true and preflightOnly=true are contradictory.');
    end
    settings.execute = false;
elseif ~settings.execute
    settings.preflightOnly = true;
end
settings.outputRoot = path_option( ...
    options,'outputRoot',default_output_root());
settings.verbose = logical_option(options,'verbose',true);
end

function [flatOptions,configurations] = registered_configurations( ...
        halfWidth,gauges,screenId,outputDirectory)
flatOptions = struct();
configurations = struct();
for gaugeIndex = 1:numel(gauges)
    gauge = gauges{gaugeIndex};
    metadata = struct('q512COmegaInitialBoxScreen',struct( ...
        'schemaVersion',4, ...
        'screenId',screenId, ...
        'initialRhsOnly',true, ...
        'pdeStepsExecuted',0, ...
        'boxMode','large_box', ...
        'boxHalfWidth',halfWidth, ...
        'configurationContract','exact_gauge_no_feedback_v1', ...
        'lengthGauge','transport_anchor', ...
        'transportAnchorX',1, ...
        'cOmegaGauge',gauge));
    overrides = struct( ...
        'xlim',[-halfWidth,halfWidth], ...
        'ymax',halfWidth, ...
        'rescalingMode','dynamic', ...
        'dynamicScaleGeometry','isotropic', ...
        'scalingContract','exact_gauge_no_feedback_v1', ...
        'lengthGauge','transport_anchor', ...
        'transportAnchorX',1, ...
        'cOmegaGauge',gauge, ...
        'lengthScaleGain',1, ...
        'widthGaugeGain',0, ...
        'omegaGaugeGain',0, ...
        'travelingWaveGain',0, ...
        'spatialDiscretization','high_order', ...
        'transportScheme','weno5_fd', ...
        'timeIntegrator','ssprk54', ...
        'remeshTransferScheme','high_order', ...
        'initialAnalyticRemesh',false, ...
        'adaptiveRemesh',false, ...
        'remeshMaximumCellRatio',1.08, ...
        'resultFile',fullfile(outputDirectory,sprintf( ...
            'solver_result_must_not_exist_H%.17g.mat',halfWidth)), ...
        'saveResults',false, ...
        'storeSnapshots',false, ...
        'makePlots',false, ...
        'livePlot',false, ...
        'writeVideo',false, ...
        'verbose',false, ...
        'caseMetadata',metadata);
    if gaugeIndex == 1
        flatOptions.(gauge) = fourth_order_blowup_case( ...
            ['coordinated_log_anchor_F80_R20_large_box_' ...
            'quadrant_512'],overrides);
    else
        % The box axes and every protected option are shared exactly.  A
        % shallow configuration copy avoids regenerating the same custom
        % q512 grid merely to change the registered amplitude functional.
        flatOptions.(gauge) = flatOptions.(gauges{1});
        flatOptions.(gauge).cOmegaGauge = gauge;
        flatOptions.(gauge).caseMetadata. ...
            q512COmegaInitialBoxScreen.cOmegaGauge = gauge;
    end
    configurations.(gauge) = ipm.config.resolve( ...
        flatOptions.(gauge));
end
end

function [audit,passed] = audit_mesh_axes(options,halfWidth)
x = options.customX(:)';
y = options.customY(:);
weightsX = ipm.mesh.quadrature(x);
weightsY = ipm.mesh.quadrature(y);
qualityX = ipm.mesh.quality(x,7,weightsX);
qualityY = ipm.mesh.quality(y,7,weightsY);
[anchorDistance,anchorIndex] = min(abs(x-1));
anchorTolerance = 128*eps(max(1,max(abs(x))));
checks = struct();
checks.nodeCounts = numel(x) == 1025 && numel(y) == 513;
checks.endpoints = endpoint_close(x([1,end]),[-halfWidth,halfWidth]) && ...
    endpoint_close(y([1,end]),[0,halfWidth]);
checks.anchorExact = anchorDistance <= anchorTolerance;
checks.positiveQuadrature = ...
    qualityX.quadratureWeightsStrictlyPositive && ...
    qualityY.quadratureWeightsStrictlyPositive;
checks.adjacentCellRatio = max([qualityX.maximumAdjacentCellRatio, ...
    qualityY.maximumAdjacentCellRatio]) <= 1.08*(1+1e-12);
checks.logSpacingCurvature = max([ ...
    qualityX.maximumLogSpacingCurvature, ...
    qualityY.maximumLogSpacingCurvature]) <= 0.01*(1+1e-12);
checks.stencilRcond = min([qualityX.minimumStencilRcond, ...
    qualityY.minimumStencilRcond]) >= 1e-9*(1-1e-12);
checks.globalQuadrature = min([ ...
    qualityX.minimumQuadratureWeightRatio, ...
    qualityY.minimumQuadratureWeightRatio]) >= 1e-8*(1-1e-12);
checks.localQuadratureLower = min([ ...
    qualityX.minimumQuadratureWeightToControlWidthRatio, ...
    qualityY.minimumQuadratureWeightToControlWidthRatio]) >= ...
    0.35*(1-1e-12);
checks.localQuadratureUpper = max([ ...
    qualityX.maximumQuadratureWeightToControlWidthRatio, ...
    qualityY.maximumQuadratureWeightToControlWidthRatio]) <= ...
    1.65*(1+1e-12);
failures = failed_checks(checks);
passed = isempty(failures);
audit = struct( ...
    'x',qualityX, ...
    'y',qualityY, ...
    'checks',checks, ...
    'failures',{failures}, ...
    'passed',passed, ...
    'anchorX',1, ...
    'nearestAnchorNode',x(anchorIndex), ...
    'anchorNodeDistance',anchorDistance, ...
    'anchorNodeTolerance',anchorTolerance, ...
    'anchorIsGridNode',checks.anchorExact);
end

function [audit,passed] = audit_config_contract( ...
        config,options,gauge,halfWidth)
scaling = config.scaling;
retired = retired_fields();
retiredPresent = unique([retired(isfield(options,retired)), ...
    retired(isfield(scaling,retired))],'stable');
checks = struct();
checks.schema4 = config.schemaVersion == 4 && config.frozen;
checks.q512 = config.grid.nx == 1025 && config.grid.ny == 513;
checks.domain = endpoint_close(config.grid.xlim, ...
    [-halfWidth,halfWidth]) && config.grid.ymax == halfWidth;
checks.numericalTuple = ...
    strcmp(config.transport.spatialDiscretization,'high_order') && ...
    strcmp(config.transport.transportScheme,'weno5_fd') && ...
    strcmp(config.time.timeIntegrator,'ssprk54') && ...
    strcmp(config.remesh.remeshTransferScheme,'high_order');
checks.dynamicIsotropic = ...
    strcmp(scaling.rescalingMode,'dynamic') && ...
    strcmp(scaling.dynamicScaleGeometry,'isotropic');
checks.exactNoFeedback = strcmp(scaling.scalingContract, ...
    'exact_gauge_no_feedback_v1') && ...
    scaling.lengthScaleGain == 1 && scaling.widthGaugeGain == 0 && ...
    scaling.omegaGaugeGain == 0 && scaling.travelingWaveGain == 0;
checks.transportAnchor = strcmp(scaling.lengthGauge, ...
    'transport_anchor') && scaling.transportAnchorX == 1;
checks.amplitudeGauge = strcmp(scaling.cOmegaGauge,gauge);
checks.activeDatum = strcmp(config.physics.initialCondition, ...
    'degenerate_primitive') && config.physics.degeneratePower == 8 && ...
    strcmp(config.physics.symmetryMode,'double_odd_omega');
checks.greenOpen = strcmp(config.elliptic.farBoundaryMode,'green') && ...
    strcmp(config.transport.transportBoundaryMode,'open');
checks.fixedMesh = ~config.remesh.initialAnalyticRemesh && ...
    ~config.remesh.adaptiveRemesh;
checks.diagnosticsOnlyOutput = ~config.output.saveResults && ...
    ~config.output.storeSnapshots && ~config.output.makePlots && ...
    ~config.output.livePlot && ~config.output.writeVideo;
checks.noRetiredFields = isempty(retiredPresent);
failures = failed_checks(checks);
passed = isempty(failures);
audit = struct('checks',checks,'failures',{failures}, ...
    'passed',passed,'retiredFieldsPresent',{retiredPresent});
end

function audit = audit_candidate_identity(configurations,gauges)
reference = configurations.(gauges{1});
passed = true;
for index = 2:numel(gauges)
    candidate = configurations.(gauges{index});
    candidate.scaling.cOmegaGauge = reference.scaling.cOmegaGauge;
    candidate.output.caseMetadata = reference.output.caseMetadata;
    passed = passed && ...
        isequaln(orderfields(candidate),orderfields(reference));
end
audit = struct( ...
    'onlyRegisteredDifferences',{ ...
        {'scaling.cOmegaGauge','output.caseMetadata'}}, ...
    'passed',passed);
end

function [gaugeRuns,executionAudit] = execute_initial_rhs( ...
        configurations,gaugeRuns,gauges,limits)
baseConfig = configurations.(gauges{1});
meshClock = tic;
baseOps = ipm.mesh.build(baseConfig);
meshBuildWallSeconds = toc(meshClock);
rho = ipm.field.initialDensity(baseOps,baseConfig.physics);
initializationClock = tic;
baseOps = ipm.evolve.initializeScaling(rho,baseOps);
initializationWallSeconds = toc(initializationClock);

referenceBaseRhs = [];
for gaugeIndex = 1:numel(gauges)
    gauge = gauges{gaugeIndex};
    run = gaugeRuns.(gauge);
    run.status = 'rhs_running';
    rhsClock = tic;
    try
        gaugeOps = baseOps;
        gaugeOps.rescaling.cOmegaGauge = gauge;
        [rhs,flow] = ipm.evolve.rhs(rho,gaugeOps);
        run.rhsWallSeconds = toc(rhsClock);
        baseRhs = rhs-flow.canonicalCOmega*rho;
        run.rates = rate_metrics(flow);
        run.gradientEnergy = gradient_energy_metrics( ...
            rho,baseRhs,flow,gaugeOps);
        run.wallQuadraticPeak = wall_quadratic_metrics( ...
            baseRhs,flow,gaugeOps);
        run.farBoundary = far_boundary_metrics(flow,gaugeOps);
        run.field = field_metrics(rho,flow,gaugeOps);
        run.gaugeContract = ipm.evolve.gaugeContract( ...
            configurations.(gauge),gaugeOps);
        run.runtimeChecks = runtime_checks(run,gauge,limits);
        if isempty(referenceBaseRhs)
            referenceBaseRhs = baseRhs;
            run.baseRhsCrossGaugeRelativeL2 = 0;
        else
            run.baseRhsCrossGaugeRelativeL2 = norm( ...
                baseRhs(:)-referenceBaseRhs(:)) / ...
                max(norm(referenceBaseRhs(:)),realmin);
        end
        if isempty(failed_checks(run.runtimeChecks))
            run.status = 'completed';
        else
            run.status = 'runtime_rejected';
        end
    catch exception
        run.status = 'rhs_failed';
        run.errorIdentifier = exception.identifier;
        run.errorMessage = exception.message;
        if ~isfinite(run.rhsWallSeconds)
            run.rhsWallSeconds = toc(rhsClock);
        end
    end
    gaugeRuns.(gauge) = run;
end

crossGaugeValues = cellfun(@(gauge) ...
    gaugeRuns.(gauge).baseRhsCrossGaugeRelativeL2,gauges(2:end));
checks = struct();
checks.noPdeStep = true;
checks.sharedMeshBuiltOnce = isfinite(meshBuildWallSeconds);
checks.sharedInitialization = isfinite(initializationWallSeconds);
checks.bothRhsCompleted = all(cellfun(@(gauge)strcmp( ...
    gaugeRuns.(gauge).status,'completed'),gauges));
checks.baseRhsGaugeIndependent = all(isfinite(crossGaugeValues)) && ...
    max(crossGaugeValues) <= ...
    limits.maximumBaseRhsCrossGaugeRelativeL2;
executionAudit = struct( ...
    'meshBuildWallSeconds',meshBuildWallSeconds, ...
    'initializationWallSeconds',initializationWallSeconds, ...
    'meshBuildCount',1, ...
    'initializationCount',1, ...
    'rhsEvaluationCount',numel(gauges), ...
    'maximumBaseRhsCrossGaugeRelativeL2',max(crossGaugeValues), ...
    'ipmSolveCalled',false, ...
    'pdeStepsExecuted',0, ...
    'sharedInitializationJustification',[ ...
        'the_three_registered_amplitude_gauges_require_no_' ...
        'gauge_specific_initial_reference'], ...
    'checks',checks, ...
    'failures',{failed_checks(checks)}, ...
    'passed',isempty(failed_checks(checks)));
end

function metrics = rate_metrics(flow)
metrics = struct( ...
    'c_l',flow.c_l, ...
    'c_omega',flow.c_omega, ...
    'c_r',flow.c_r, ...
    'canonicalCL',flow.canonicalCL, ...
    'canonicalCOmega',flow.canonicalCOmega, ...
    'canonicalCR',flow.canonicalCR, ...
    'kappa',flow.canonicalCL-flow.canonicalCOmega, ...
    'timeSpeed',flow.timeSpeed, ...
    'lengthGaugeResidual',flow.lengthGaugeResidual, ...
    'transportAnchorVelocity',flow.transportAnchorVelocity, ...
    'omegaGaugeResidual',flow.omegaGaugeResidual);
end

function metrics = gradient_energy_metrics(rho,baseRhs,flow,ops)
rhoX = flow.source;
rhoY = ops.Dy*rho;
baseRhsX = baseRhs*ops.Dx';
baseRhsY = ops.Dy*baseRhs;
weights = ops.integrationWeights;
energyX = sum(rhoX.^2.*weights,'all');
energyY = sum(rhoY.^2.*weights,'all');
forcingX = sum(rhoX.*baseRhsX.*weights,'all');
forcingY = sum(rhoY.*baseRhsY.*weights,'all');
energy = energyX+energyY;
forcing = forcingX+forcingY;
absoluteForcing = sum(abs(rhoX.*baseRhsX+rhoY.*baseRhsY) .* ...
    weights,'all');
cancellation = forcing+flow.canonicalCOmega*energy;
cancellationScale = max([abs(forcing), ...
    abs(flow.canonicalCOmega*energy),realmin]);
metrics = struct( ...
    'energyX',energyX, ...
    'energyY',energyY, ...
    'energy',energy, ...
    'forcingX',forcingX, ...
    'forcingY',forcingY, ...
    'forcing',forcing, ...
    'absoluteForcing',absoluteForcing, ...
    'impliedCOmega',-forcing/energy, ...
    'candidateCancellation',cancellation, ...
    'candidateNormalizedCancellation',cancellation/cancellationScale, ...
    'energyYFraction',energyY/energy, ...
    'forcingYFraction',abs(forcingY)/max(abs(forcing),realmin), ...
    'energyPerXWidth',energy/(ops.x(end)-ops.x(1)), ...
    'forcingPerXWidth',forcing/(ops.x(end)-ops.x(1)));
end

function metrics = wall_quadratic_metrics(baseRhs,flow,ops)
trackingMask = abs(ops.x-ops.rescaling.pinX) <= ...
    ops.rescaling.peakTrackingHalfWidth;
feature = max(flow.source(1,:),0);
feature(~trackingMask) = 0;
[~,peakIndex] = max(feature);
peak = ipm.evolve.quadraticPeakFunctional( ...
    flow.source(1,:),ops.x,peakIndex);
stencilForcing = baseRhs(1,:)*ops.Dx(peak.indices,:)';
forcing = sum(peak.weights.*stencilForcing);
impliedCOmega = -forcing/peak.value;
rateResidual = forcing+flow.canonicalCOmega*peak.value;
rateScale = max([abs(forcing), ...
    abs(flow.canonicalCOmega*peak.value),realmin]);
competitorMask = trackingMask;
competitorMask(peakIndex) = false;
competitors = flow.source(1,competitorMask);
activeSelectionMargin = (flow.source(1,peakIndex)- ...
    max(competitors))/peak.value;
runtimeAgreement = NaN;
if isfinite(flow.omegaGaugeQuadraticPeakValue)
    scales = max(abs([peak.x,peak.value,forcing,peak.curvature, ...
        peak.curvatureCondition,peak.weightCondition, ...
        peak.activeNodeMargin,peak.vertexInteriorFraction, ...
        peak.relativeSubgridLift,rateResidual]),1);
    runtimeValues = [flow.omegaGaugeQuadraticPeakX, ...
        flow.omegaGaugeQuadraticPeakValue, ...
        flow.omegaGaugeQuadraticForcing, ...
        flow.omegaGaugeQuadraticCurvature, ...
        flow.omegaGaugeQuadraticCurvatureCondition, ...
        flow.omegaGaugeQuadraticWeightCondition, ...
        flow.omegaGaugeQuadraticActiveNodeMargin, ...
        flow.omegaGaugeQuadraticVertexInteriorFraction, ...
        flow.omegaGaugeQuadraticRelativeSubgridLift, ...
        flow.omegaGaugeQuadraticRateResidual];
    localValues = [peak.x,peak.value,forcing,peak.curvature, ...
        peak.curvatureCondition,peak.weightCondition, ...
        peak.activeNodeMargin,peak.vertexInteriorFraction, ...
        peak.relativeSubgridLift,rateResidual];
    runtimeAgreement = max(abs(runtimeValues-localValues)./scales);
end
metrics = struct( ...
    'peakIndex',peakIndex, ...
    'stencilIndices',peak.indices, ...
    'stencilWeights',peak.weights, ...
    'peakX',peak.x, ...
    'peakValue',peak.value, ...
    'forcing',forcing, ...
    'impliedCOmega',impliedCOmega, ...
    'candidateRateResidual',rateResidual, ...
    'candidateNormalizedRateResidual',rateResidual/rateScale, ...
    'curvature',peak.curvature, ...
    'normalizedStationarityResidual', ...
        peak.normalizedStationarityResidual, ...
    'curvatureCondition',peak.curvatureCondition, ...
    'weightCondition',peak.weightCondition, ...
    'activeNodeMargin',peak.activeNodeMargin, ...
    'activeSelectionMargin',activeSelectionMargin, ...
    'stencilCenterX',ops.x(peakIndex), ...
    'vertexInteriorFraction',peak.vertexInteriorFraction, ...
    'relativeSubgridLift',peak.relativeSubgridLift, ...
    'runtimeAgreementMaximumRelativeError',runtimeAgreement);
end

function metrics = far_boundary_metrics(flow,ops)
