function ladder = ipm_gaugelab_run_q512_cfl_ladder(options)
%IPM_GAUGELAB_RUN_Q512_CFL_LADDER Register two fresh q512 CFL roots.
%   LADDER = IPM_GAUGELAB_RUN_Q512_CFL_LADDER() preregisters independent
%   cfl=0.25 and cfl=0.50 roots on the same large box, whose default
%   half-width is 1e6.  The default is preflight-only and executes no PDE.
%
%   OPTIONS.execute=true runs both bounded short campaigns from the
%   analytic datum.  The orchestrator supplies runMode='campaign' and
%   confirmLongRun=true internally to ipm_gaugelab_run_q512_root.  It has
%   no checkpoint or restart input, and neither candidate may resume an
%   artifact.
%
%   Executed roots record endpoint/cost summaries, every accepted step's
%   timestep telemetry, and the complete gauge-rate and maximum-
%   growth diagnostics.  Terminal fields are compared in both
%   interpolation directions on one common physical window.  Registered
%   tolerances are short-window CFL-consistency gates only; passing them is
%   not late-time or asymptotic evidence.

if nargin < 1 || isempty(options)
    options = struct();
end
settings = resolve_options(options);
require_root_runner();

[outputDirectory,ladderId] = create_output_directory(settings.outputRoot);
summaryFile = fullfile(outputDirectory,'cfl_ladder_summary.mat');
manifestFile = fullfile(outputDirectory,'cfl_ladder_manifest.jsonl');
rootOutputDirectory = fullfile(outputDirectory,'roots');
mkdir(rootOutputDirectory);

specifications = cfl_specifications();
roots = repmat(empty_root_record(),numel(specifications),1);
for index = 1:numel(specifications)
    roots(index).index = index;
    roots(index).name = specifications(index).name;
    roots(index).cfl = specifications(index).cfl;
    roots(index).status = 'pending';
end

startedUtc = utc_stamp();
ladder = struct( ...
    'schemaVersion',4, ...
    'kind','q512_fresh_exact_gauge_cfl_ladder', ...
    'ladderId',ladderId, ...
    'status','registered', ...
    'startedUtc',startedUtc, ...
    'completedUtc','', ...
    'executionMode',execution_mode(settings), ...
    'freshRootsOnly',true, ...
    'checkpointInputsAccepted',false, ...
    'rootRunMode','campaign', ...
    'internalConfirmLongRun',true, ...
    'cflCandidates',[specifications.cfl], ...
    'onlyConfigurationVariable','time.cfl', ...
    'sameBoxRequired',true, ...
    'gaugeContract',gauge_contract(), ...
    'numericalTuple',numerical_tuple(), ...
    'requested',requested_summary(settings), ...
    'comparisonMethod','bidirectional_common_physical_window', ...
    'comparisonWindowCap',settings.comparisonWindowCap, ...
    'hardLimits',hard_limits(), ...
    'interpretation', ...
        'short_window_cfl_consistency_only_not_late_time_evidence', ...
    'lateTimeEvidence',false, ...
    'outputDirectory',outputDirectory, ...
    'rootOutputDirectory',rootOutputDirectory, ...
    'summaryFile',summaryFile, ...
    'manifestFile',manifestFile, ...
    'roots',roots, ...
    'sharedContractAudit',empty_shared_contract_audit(), ...
    'comparison',empty_comparison(), ...
    'completedRoots',0, ...
    'successfulRoots',0, ...
    'preflightPassed',false, ...
    'hardPassed',false, ...
    'orchestrationWallSeconds',NaN, ...
    'sumRootSolveWallSeconds',NaN, ...
    'failures',{{}});
save_summary(summaryFile,ladder);
append_manifest(manifestFile,struct( ...
    'event','cfl_ladder_registered', ...
    'timestampUtc',startedUtc, ...
    'ladderId',ladderId, ...
    'executionMode',ladder.executionMode, ...
    'freshRootsOnly',true, ...
    'checkpointInputsAccepted',false, ...
    'rootRunMode','campaign', ...
    'internalConfirmLongRun',true, ...
    'cflCandidates',ladder.cflCandidates, ...
    'onlyConfigurationVariable',ladder.onlyConfigurationVariable, ...
    'requested',ladder.requested, ...
    'hardLimits',ladder.hardLimits, ...
    'interpretation',ladder.interpretation, ...
    'summaryFile',summaryFile));

orchestrationClock = tic;
for index = 1:numel(specifications)
    specification = specifications(index);
    record = ladder.roots(index);
    record.status = 'root_running';
    record.startedUtc = utc_stamp();
    record.rootOutputRoot = fullfile( ...
        rootOutputDirectory,specification.name);
    ladder.roots(index) = record;
    save_summary(summaryFile,ladder);
    append_manifest(manifestFile,struct( ...
        'event','cfl_root_started', ...
        'timestampUtc',record.startedUtc, ...
        'ladderId',ladderId, ...
        'root',record.name, ...
        'cfl',record.cfl, ...
        'boxMode',settings.boxMode, ...
        'boxHalfWidth',settings.boxHalfWidth, ...
        'execute',settings.execute, ...
        'freshStart',true, ...
        'restartInput','none'));

    rootOptions = root_options( ...
        settings,specification,record.rootOutputRoot);
    try
        rootRun = ipm_gaugelab_run_q512_root(rootOptions);
        record = populate_from_root(record,rootRun,settings.execute);
    catch exception
        record.status = 'root_failed';
        record.errorIdentifier = exception.identifier;
        record.errorMessage = exception.message;
        recovered = recover_root_summary(record.rootOutputRoot);
        if ~isempty(recovered)
            try
                record = populate_from_root( ...
                    record,recovered,settings.execute);
            catch recoveryException
                record.errorMessage = sprintf('%s | recovery: %s', ...
                    record.errorMessage,recoveryException.message);
            end
            record.status = 'root_failed';
            record.errorIdentifier = exception.identifier;
        end
    end
    record.completedUtc = utc_stamp();
    ladder.roots(index) = record;
    ladder.completedRoots = index;
    save_summary(summaryFile,ladder);
    append_manifest(manifestFile,struct( ...
        'event','cfl_root_finished', ...
        'timestampUtc',record.completedUtc, ...
        'ladderId',ladderId, ...
        'root',record.name, ...
        'cfl',record.cfl, ...
        'status',record.status, ...
        'rootStatus',record.rootStatus, ...
        'freshStart',record.freshStart, ...
        'restartInput',record.restartInput, ...
        'meshPassed',record.meshPassed, ...
        'contractPassed',record.contractPassed, ...
        'resultAvailable',record.resultAvailable, ...
        'steps',record.cost.steps, ...
        'wallSeconds',record.cost.wallSeconds, ...
        'rootSummaryFile',record.rootSummaryFile, ...
        'resultFile',record.resultFile, ...
        'errorIdentifier',record.errorIdentifier, ...
        'errorMessage',record.errorMessage));
end

ladder.sharedContractAudit = shared_contract_audit( ...
    ladder.roots,settings,specifications);
if settings.execute && all([ladder.roots.resultAvailable])
    try
        reference = ipm.output.validate(ladder.roots(1).resultFile);
        candidate = ipm.output.validate(ladder.roots(2).resultFile);
        ladder.comparison = bidirectional_comparison( ...
            reference,candidate,ladder.roots(1),ladder.roots(2), ...
            settings.comparisonWindowCap,ladder.hardLimits);
    catch exception
        ladder.comparison.status = 'comparison_failed';
        ladder.comparison.errorIdentifier = exception.identifier;
        ladder.comparison.errorMessage = exception.message;
    end
elseif settings.execute
    ladder.comparison.status = 'root_result_unavailable';
else
    ladder.comparison.status = 'preflight_only_not_executed';
end

ladder.orchestrationWallSeconds = toc(orchestrationClock);
rootTimes = arrayfun(@(record)record.cost.wallSeconds,ladder.roots);
rootTimes = rootTimes(isfinite(rootTimes));
if isempty(rootTimes)
    ladder.sumRootSolveWallSeconds = 0;
else
    ladder.sumRootSolveWallSeconds = sum(rootTimes);
end
expected = expected_root_status(settings);
ladder.successfulRoots = nnz(strcmp({ladder.roots.status},expected));
ladder.preflightPassed = ...
    ladder.successfulRoots == numel(ladder.roots) && ...
    ladder.sharedContractAudit.passed;
ladder.hardPassed = settings.execute && ladder.preflightPassed && ...
    ladder.comparison.available && ladder.comparison.hardPassed;
ladder.failures = ladder_failures(ladder,settings);
if ~ladder.preflightPassed
    ladder.status = 'partial_failure';
elseif ~settings.execute
    ladder.status = 'preflight_complete';
elseif ladder.hardPassed
    ladder.status = 'short_cfl_passed';
else
    ladder.status = 'short_cfl_gate_failed';
end
ladder.completedUtc = utc_stamp();
save_summary(summaryFile,ladder);
append_manifest(manifestFile,struct( ...
    'event','cfl_ladder_finished', ...
    'timestampUtc',ladder.completedUtc, ...
    'ladderId',ladderId, ...
    'status',ladder.status, ...
    'successfulRoots',ladder.successfulRoots, ...
    'preflightPassed',ladder.preflightPassed, ...
    'hardPassed',ladder.hardPassed, ...
    'comparisonStatus',ladder.comparison.status, ...
    'comparisonAvailable',ladder.comparison.available, ...
    'orchestrationWallSeconds',ladder.orchestrationWallSeconds, ...
    'sumRootSolveWallSeconds',ladder.sumRootSolveWallSeconds, ...
    'interpretation',ladder.interpretation, ...
    'failures',{ladder.failures}));

fprintf(['Q512 CFL LADDER: status=%s, roots=%d/%d, ' ...
    'comparison=%s, wall=%.3f s, summary=%s\n'], ...
    ladder.status,ladder.successfulRoots,numel(ladder.roots), ...
    ladder.comparison.status,ladder.orchestrationWallSeconds,summaryFile);
end

function settings = resolve_options(options)
if ~isstruct(options) || ~isscalar(options)
    error('ipm:GaugeLabQ512CflLadderOptions', ...
        'options must be a scalar structure.');
end
allowed = {'execute','boxMode','boxHalfWidth','outputRoot','verbose', ...
    'physicalFinalTime','canonicalFinalTime','maxDt','maxSteps', ...
    'outputEvery','checkpointEvery','comparisonWindowCap'};
unknown = setdiff(fieldnames(options),allowed,'stable');
if ~isempty(unknown)
    error('ipm:GaugeLabQ512CflLadderOptions', ...
        'Unknown option(s): %s.',strjoin(unknown,', '));
end

settings = struct();
settings.execute = logical_option(options,'execute',false);
settings.boxMode = text_option(options,'boxMode','large_box');
settings.boxHalfWidth = numeric_option(options,'boxHalfWidth',[]);
settings.outputRoot = path_option( ...
    options,'outputRoot',default_output_root());
settings.verbose = logical_option(options,'verbose',false);
settings.physicalFinalTime = numeric_option( ...
    options,'physicalFinalTime',0.03);
settings.canonicalFinalTime = numeric_option( ...
    options,'canonicalFinalTime',0.05);
settings.maxDt = numeric_option(options,'maxDt',0.004);
settings.maxSteps = numeric_option(options,'maxSteps',512);
settings.outputEvery = numeric_option(options,'outputEvery',1e-10);
settings.checkpointEvery = numeric_option( ...
    options,'checkpointEvery',0.01);
settings.comparisonWindowCap = numeric_option( ...
    options,'comparisonWindowCap',[-2,2,2]);

if ~any(strcmp(settings.boxMode,{'matched','large_box'}))
    error('ipm:GaugeLabQ512CflLadderBoxMode', ...
        'boxMode must be ''matched'' or ''large_box''.');
end
if strcmp(settings.boxMode,'matched')
    if isempty(settings.boxHalfWidth)
        settings.boxHalfWidth = 281;
    else
        validateattributes(settings.boxHalfWidth,{'numeric'}, ...
            {'scalar','real','finite','positive'},mfilename, ...
            'boxHalfWidth');
        if settings.boxHalfWidth ~= 281
            error('ipm:GaugeLabQ512CflLadderMatchedBox', ...
                ['The matched q512 factory is registered only at half-' ...
                'width 281.']);
        end
    end
else
    if isempty(settings.boxHalfWidth)
        settings.boxHalfWidth = 1e6;
    end
    validateattributes(settings.boxHalfWidth,{'numeric'}, ...
        {'scalar','real','finite','>',2},mfilename,'boxHalfWidth');
end

validateattributes(settings.physicalFinalTime,{'numeric'}, ...
    {'scalar','real','finite','positive','<=',0.03},mfilename, ...
    'physicalFinalTime');
validateattributes(settings.canonicalFinalTime,{'numeric'}, ...
    {'scalar','real','finite','positive','<=',0.05},mfilename, ...
    'canonicalFinalTime');
validateattributes(settings.maxDt,{'numeric'}, ...
    {'scalar','real','finite','positive','<=',0.004},mfilename,'maxDt');
validateattributes(settings.maxSteps,{'numeric'}, ...
    {'scalar','real','finite','integer','positive','<=',1024}, ...
    mfilename,'maxSteps');
validateattributes(settings.outputEvery,{'numeric'}, ...
    {'scalar','real','finite','positive'},mfilename,'outputEvery');
validateattributes(settings.checkpointEvery,{'numeric'}, ...
    {'scalar','real','finite','positive'},mfilename,'checkpointEvery');
validateattributes(settings.comparisonWindowCap,{'numeric'}, ...
    {'vector','numel',3,'real','finite'},mfilename, ...
    'comparisonWindowCap');
settings.comparisonWindowCap = settings.comparisonWindowCap(:)';
if settings.comparisonWindowCap(2) <= ...
        settings.comparisonWindowCap(1) || ...
        settings.comparisonWindowCap(3) <= 0
    error('ipm:GaugeLabQ512CflLadderWindow', ...
        'comparisonWindowCap must be [xMin,xMax,yMax] with nonempty area.');
end
end

