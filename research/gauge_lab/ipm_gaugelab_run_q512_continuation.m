        passed = strcmp(amplitude.formula, ...
            'c_omega=-Q[B_X](X_vertex)/Q[R_X](X_vertex)') && ...
            strcmp(amplitude.observable, ...
                'tracked_wall_omega_quadratic_peak') && ...
            strcmp(amplitude.evaluation, ...
                'active_nonuniform_three_node_quadratic_vertex');
