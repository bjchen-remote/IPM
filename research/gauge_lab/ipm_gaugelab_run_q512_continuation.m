canonicalRemainder = requested.finalTime-state.canonicalTime;
physicalRemainder = requested.physicalFinalTime-state.physicalTime;
canonicalOpen = canonicalRemainder > config.time.minDt;
physicalOpen = physicalRemainder > ...
    config.time.minDt*physicalClockSpeed;
checks = struct( ...
    'stopReason',strcmp(state.stopReason,'maximum_steps'), ...
    'exactStepBudget',state.steps == requested.maxSteps, ...
    'advancedFromParent',state.steps > parentStep, ...
    'canonicalHorizonStillOpen',canonicalOpen, ...
    'physicalHorizonStillOpen',physicalOpen);
failures = failed_checks(checks);
audit = struct('passed',isempty(failures),'checks',checks, ...
    'failures',{failures},'canonicalRemainder',canonicalRemainder, ...
    'physicalRemainder',physicalRemainder);
end

