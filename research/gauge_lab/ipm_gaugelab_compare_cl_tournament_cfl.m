        strcmp(secondClass,'strengthened_current')
    relation = 'first_legacy_second_strengthened';
elseif strcmp(firstClass,'strengthened_current') && ...
        strcmp(secondClass,'legacy_core_only')
    relation = 'first_strengthened_second_legacy';
elseif strcmp(firstClass,secondClass) && sameMetadataFields && ...
        sameRecordedFields
    relation = 'same_metadata_and_recorded_evidence_fields';
elseif strcmp(firstClass,secondClass) && sameMetadataFields
    relation = 'same_metadata_fields_recorded_evidence_differs_or_missing';
else
    relation = 'different_or_invalid_evidence_schema';
end
end

