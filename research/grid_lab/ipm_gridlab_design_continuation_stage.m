function design = ipm_gridlab_design_continuation_stage( ...
        currentInput,referenceInput,options)
%IPM_GRIDLAB_DESIGN_CONTINUATION_STAGE Design a global-reference x/y regrid.
%   DESIGN = IPM_GRIDLAB_DESIGN_CONTINUATION_STAGE(CURRENT,REFERENCE,OPTIONS)
%   freezes the terminal accepted field in CURRENT, extracts strict 0.9
%   source cores, builds analytic x/y monitor families, and applies every
%   monitor to axes taken from the external schema-version-2 REFERENCE
%   dataset.  Optional x fallbacks preserve a strict tier order: anchored
%   Gaussian equalization of the original reference, then independent
%   corridor equalizations of that same immutable reference, and finally
%   depth-limited anchored equalization of an immutable copy of the trusted
%   terminal x axis.  A later tier is attempted only after all preceding
%   tiers fail their unchanged targets.  CURRENT may be a version-2 result,
%   an accepted-step checkpoint, or a MAT-file containing either contract.
%   REFERENCE may be a schema-version-2 frozen dataset or its MAT-file.
%
%   Required continuation controls are OPTIONS.ratioCap,
%   OPTIONS.targetXCoreCells, and OPTIONS.targetYCoreCells.  The adjacent
%   ratio cap is authoritative: this routine never raises it to make a
%   target feasible.  An infeasible design is saved and returned with the
%   best attainable core/front cell counts at that exact cap.
%
%   OPTIONS.outputFile saves DESIGN with -v7.3.  No PDE step is advanced
%   and no production solver file is modified.

if nargin < 3 || isempty(options)
    options = struct();
end
options = resolve_options(options);

[currentResult,currentKind,currentLabel] = resolve_current(currentInput);
collectOptions = options.collectOptions;
if ~isfield(collectOptions,'targetCanonicalTimes')
    collectOptions.targetCanonicalTimes = ...
        currentResult.state.canonicalTime;
end
if ~isfield(collectOptions,'trustedOnly')
    collectOptions.trustedOnly = true;
end
if ~isfield(collectOptions,'tag') || isempty(collectOptions.tag)
    collectOptions.tag = options.tag;
end
if isfield(collectOptions,'outputFile') && ...
        ~isempty(collectOptions.outputFile)
    error('ipm:gridlab:StageDesignCollectOutput', ...
        ['The stage designer keeps its frozen dataset in the final design; ' ...
        'collectOptions.outputFile must be empty or absent.']);
end
collectOptions.outputFile = '';
dataset = ipm_gridlab_collect_dataset(currentResult,collectOptions);

featureOptions = strict_feature_options(options.featureOptions);
profiles = ipm_gridlab_feature_profiles(dataset,featureOptions);
xSeeds = ipm_gridlab_seed_models(profiles,options.xSeedOptions);
ySeeds = ipm_gridlab_seed_y_models(profiles,options.ySeedOptions);

[referenceDataset,referenceLabel] = resolve_reference(referenceInput);
[referenceX,referenceY,referenceIndex] = select_reference_axes( ...
    referenceDataset,dataset,options.referenceSnapshotIndex);

meshLimits = options.meshLimits;
meshLimits.maxAdjacentCellRatio = options.ratioCap;
xAxisOptions = axis_options( ...
    options.axisOptions,referenceX,meshLimits);
yAxisOptions = axis_options( ...
    options.axisOptions,referenceY,meshLimits);

nx = numel(dataset.snapshots(1).x);
ny = numel(dataset.snapshots(1).y);
xCandidates = build_x_candidates(dataset,profiles,xSeeds.candidates, ...
    nx,xAxisOptions,options);
yCandidates = build_y_candidates(dataset,profiles,ySeeds.candidates, ...
    ny,yAxisOptions,options);
rootCorridorXFallback = initialize_root_corridor_x_fallback( ...
    options.equalizationOptions,referenceX,referenceIndex);
currentXReferenceFallback = initialize_current_x_reference_fallback( ...
    options.equalizationOptions);
if options.equalizationOptions.enabled && ...
        ~any([xCandidates.meetsTargets])
    fallback = build_equalized_x_candidate( ...
        referenceX,profiles,meshLimits,options);
    fallback.index = numel(xCandidates)+1;
    xCandidates(end+1,1) = fallback;
end
if options.equalizationOptions.enabled && ...
        options.equalizationOptions.rootCorridorXFallbackEnabled
    if any([xCandidates.meetsTargets])
        rootCorridorXFallback.status = ...
            'not_needed_preceding_tier_met_targets';
    else
        [corridorCandidates,rootCorridorXFallback] = ...
            build_root_corridor_x_fallbacks( ...
                referenceX,referenceIndex,profiles,meshLimits,options, ...
                rootCorridorXFallback);
        candidateIndices = zeros(numel(corridorCandidates),1);
        for candidateIndex = 1:numel(corridorCandidates)
            corridorCandidates(candidateIndex).index = ...
                numel(xCandidates)+1;
            candidateIndices(candidateIndex) = ...
                corridorCandidates(candidateIndex).index;
            xCandidates(end+1,1) = ...
                corridorCandidates(candidateIndex); %#ok<AGROW>
        end
        rootCorridorXFallback.candidateIndices = candidateIndices;
    end
end
if options.equalizationOptions.enabled && ...
        options.equalizationOptions.currentAxisXFallbackEnabled
    if any([xCandidates.meetsTargets])
        currentXReferenceFallback.status = ...
            'not_needed_preceding_tier_met_targets';
    else
        [incrementalCandidates,currentXReferenceFallback] = ...
            build_current_axis_x_fallbacks( ...
                dataset,referenceX,profiles,meshLimits,options, ...
                currentXReferenceFallback);
        candidateIndices = zeros(numel(incrementalCandidates),1);
        for candidateIndex = 1:numel(incrementalCandidates)
            incrementalCandidates(candidateIndex).index = ...
                numel(xCandidates)+1;
            candidateIndices(candidateIndex) = ...
                incrementalCandidates(candidateIndex).index;
            xCandidates(end+1,1) = ...
                incrementalCandidates(candidateIndex); %#ok<AGROW>
        end
        currentXReferenceFallback.candidateIndices = candidateIndices;
    end
end
if options.equalizationOptions.enabled && ...
        ~any([yCandidates.meetsTargets])
    fallback = build_equalized_y_candidate( ...
        referenceY,profiles,meshLimits,options, ...
        'external_original_reference');
    fallback.index = numel(yCandidates)+1;
    yCandidates(end+1,1) = fallback;
end
if options.equalizationOptions.enabled && ...
        options.equalizationOptions.uniformFlatTailEnabled && ...
        ~any([yCandidates.meetsTargets])
    flatTailReference = linspace( ...
        referenceY(1),referenceY(end),numel(referenceY));
    fallback = build_equalized_y_candidate( ...
        flatTailReference,profiles,meshLimits,options, ...
        'uniform_flat_tail_global_reference');
    fallback.index = numel(yCandidates)+1;
    yCandidates(end+1,1) = fallback;
end
[selectedXIndex,xOrder] = select_candidate(xCandidates);
[selectedYIndex,yOrder] = select_candidate(yCandidates);
feasibility = summarize_feasibility( ...
    xCandidates,yCandidates,options,meshLimits);

pairScore = struct();
selected = empty_selection();
if ~isempty(selectedXIndex) && ~isempty(selectedYIndex)
    selectedX = xCandidates(selectedXIndex);
    selectedY = yCandidates(selectedYIndex);
    pairOptions = pair_score_options( ...
        options.pairScoreOptions,profiles,meshLimits,options);
    pairScore = ipm_gridlab_score_frozen_pair( ...
        dataset,selectedX.axis,selectedY.axis,pairOptions);
    selected = struct( ...
        'xIndex',selectedXIndex,'yIndex',selectedYIndex, ...
        'xName',selectedX.name,'yName',selectedY.name, ...
        'x',selectedX.axis,'y',selectedY.axis, ...
        'xModel',selectedX.model,'yModel',selectedY.model, ...
        'xReferenceProvenance',candidate_reference_provenance( ...
            selectedX), ...
        'yReferenceProvenance',candidate_reference_provenance( ...
            selectedY));
    if pairScore.admissible
        status = 'feasible';
    else
        status = 'pair_score_rejected';
    end
elseif isempty(selectedXIndex) && isempty(selectedYIndex)
    status = 'infeasible_xy';
elseif isempty(selectedXIndex)
    status = 'infeasible_x';
else
    status = 'infeasible_y';
end

referenceRecord = referenceDataset.snapshots(referenceIndex);
xCandidateReferencePolicy = x_candidate_reference_policy( ...
    options.equalizationOptions);
referenceSummary = struct( ...
    'sourceLabel',referenceLabel,'datasetTag',referenceDataset.tag, ...
    'snapshotIndex',referenceIndex, ...
    'datasetIndex',referenceRecord.datasetIndex, ...
    'canonicalTime',referenceRecord.canonicalTime, ...
    'nodeCount',[numel(referenceX),numel(referenceY)], ...
    'xSignature',axis_signature(referenceX), ...
    'ySignature',axis_signature(referenceY), ...
    'construction','external_global_reference_multiplier', ...
    'xCandidateReferencePolicy',xCandidateReferencePolicy, ...
    'yCandidateReferencePolicy', ...
        'external_original_reference_then_uniform_flat_tail_fallback', ...
    'usesExternalOriginalReferenceCorridor', ...
        rootCorridorXFallback.usedAsReference, ...
    'usesCurrentAxesAsReference', ...
        currentXReferenceFallback.usedAsReference, ...
    'rootCorridorXFallback',rootCorridorXFallback, ...
    'currentAxisXFallback',currentXReferenceFallback);
storedOptions = rmfield(options,'outputFile');
design = struct( ...
    'schemaVersion',1, ...
    'kind','ipm_gridlab_continuation_stage_design', ...
    'createdUtc',char(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd''T''HH:mm:ss''Z''')), ...
    'status',status,'tag',options.tag, ...
    'currentInputKind',currentKind, ...
    'currentInputLabel',currentLabel, ...
    'ratioCap',options.ratioCap, ...
    'ratioCapRelaxed',false, ...
    'strictCoreLevel',0.9, ...
    'targets',struct('xCoreCells',options.targetXCoreCells, ...
        'yCoreCells',options.targetYCoreCells, ...
        'xFrontCells',options.minimumXFrontCells), ...
    'reference',referenceSummary, ...
    'dataset',dataset,'profiles',profiles, ...
    'seeds',struct('x',xSeeds,'y',ySeeds), ...
    'xCandidates',xCandidates,'yCandidates',yCandidates, ...
    'xOrder',xOrder,'yOrder',yOrder, ...
    'feasibility',feasibility,'selected',selected, ...
    'pairScore',pairScore,'options',storedOptions);
write_design(design,options.outputFile);
end

function options = resolve_options(options)
if ~isstruct(options) || ~isscalar(options)
    error('ipm:gridlab:StageDesignOptions', ...
        'options must be a scalar structure.');
end
defaultMeshLimits = struct( ...
    'maxAdjacentCellRatio',1.08, ...
    'maxLogSpacingCurvature',0.03, ...
    'minStencilRcond',1e-9, ...
    'minQuadratureWeightRatio',1e-4);
defaults = struct( ...
    'ratioCap',1.08, ...
    'targetXCoreCells',18, ...
    'targetYCoreCells',18, ...
    'minimumXFrontCells',8, ...
    'referenceSnapshotIndex',[], ...
    'tag','', ...
    'outputFile','', ...
    'collectOptions',struct(), ...
    'featureOptions',struct(), ...
    'xSeedOptions',struct(), ...
    'ySeedOptions',struct(), ...
    'equalizationOptions',struct( ...
        'enabled',true,'uniformFlatTailEnabled',true, ...
        'rootCorridorXFallbackEnabled',false, ...
        'rootCorridorXShoulderCells',[16,24,32], ...
        'rootCorridorXExpansionShoulders',2, ...
        'currentAxisXFallbackEnabled',false, ...
        'currentAxisXSigmas',[1.5,2,3], ...
        'currentAxisXPower',2, ...
        'maximumIncrementalReferenceDepth',1, ...
        'currentIncrementalReferenceDepth',0, ...
        'xSigma',0.35,'ySigma',0.35, ...
        'xPower',1,'yPower',1, ...
        'uniformFlatTailSigma',0.35, ...
        'uniformFlatTailPower',3, ...
        'initialAmplitude',0.25,'maximumAmplitude',16, ...
        'amplitudeTolerance',1e-9,'maxIterations',80), ...
    'axisOptions',struct('fineCount',131073, ...
        'projectToAdmissible',true), ...
    'pairScoreOptions',struct(), ...
    'meshLimits',defaultMeshLimits);
names = fieldnames(defaults);
unexpected = setdiff(fieldnames(options),names,'stable');
if ~isempty(unexpected)
    error('ipm:gridlab:StageDesignOptions', ...
        'Unknown option(s): %s.',strjoin(unexpected,', '));
end
for index = 1:numel(names)
    name = names{index};
    if ~isfield(options,name)
        options.(name) = defaults.(name);
    end
end
validateattributes(options.ratioCap,{'numeric'}, ...
    {'scalar','real','finite','>=',1},mfilename,'options.ratioCap');
for field = {'targetXCoreCells','targetYCoreCells', ...
        'minimumXFrontCells'}
    validateattributes(options.(field{1}),{'numeric'}, ...
        {'scalar','integer','positive'},mfilename, ...
        ['options.' field{1}]);
end
if ~isempty(options.referenceSnapshotIndex)
    validateattributes(options.referenceSnapshotIndex,{'numeric'}, ...
        {'scalar','integer','positive'},mfilename, ...
        'options.referenceSnapshotIndex');
elseif ~isnumeric(options.referenceSnapshotIndex)
    error('ipm:gridlab:StageDesignOptions', ...
        'options.referenceSnapshotIndex must be numeric or empty.');
end
for field = {'tag','outputFile'}
    value = options.(field{1});
    if ~(ischar(value) || (isstring(value) && isscalar(value)))
        error('ipm:gridlab:StageDesignOptions', ...
            'options.%s must be text.',field{1});
    end
    options.(field{1}) = char(value);
end
for field = {'collectOptions','featureOptions','xSeedOptions', ...
        'ySeedOptions','equalizationOptions','axisOptions', ...
        'pairScoreOptions'}
    if ~isstruct(options.(field{1})) || ...
            ~isscalar(options.(field{1}))
        error('ipm:gridlab:StageDesignOptions', ...
            'options.%s must be a scalar structure.',field{1});
    end
end
options.equalizationOptions = validate_equalization_options( ...
    options.equalizationOptions);
options.meshLimits = merge_mesh_limits( ...
    options.meshLimits,defaultMeshLimits);
if isfield(options.axisOptions,'referenceAxis') && ...
        ~isempty(options.axisOptions.referenceAxis)
    error('ipm:gridlab:StageDesignReferenceOverride', ...
        ['axisOptions.referenceAxis is owned by referenceInput; pass the ' ...
        'initial global-reference dataset instead.']);
end
end

function options = validate_equalization_options(options)
defaults = struct('enabled',true, ...
    'uniformFlatTailEnabled',true, ...
    'rootCorridorXFallbackEnabled',false, ...
    'rootCorridorXShoulderCells',[16,24,32], ...
    'rootCorridorXExpansionShoulders',2, ...
    'currentAxisXFallbackEnabled',false, ...
    'currentAxisXSigmas',[1.5,2,3], ...
    'currentAxisXPower',2, ...
    'maximumIncrementalReferenceDepth',1, ...
    'currentIncrementalReferenceDepth',0, ...
    'xSigma',0.35,'ySigma',0.35,'xPower',1,'yPower',1, ...
    'uniformFlatTailSigma',0.35,'uniformFlatTailPower',3, ...
    'initialAmplitude',0.25,'maximumAmplitude',16, ...
    'amplitudeTolerance',1e-9,'maxIterations',80);
names = fieldnames(defaults);
unexpected = setdiff(fieldnames(options),names,'stable');
if ~isempty(unexpected)
    error('ipm:gridlab:StageDesignEqualizationOptions', ...
        'Unknown equalization option(s): %s.',strjoin(unexpected,', '));
end
for index = 1:numel(names)
    name = names{index};
    if ~isfield(options,name)
        options.(name) = defaults.(name);
    end
end
if ~(islogical(options.enabled) && isscalar(options.enabled))
    error('ipm:gridlab:StageDesignEqualizationOptions', ...
        'equalizationOptions.enabled must be a logical scalar.');
end
if ~(islogical(options.uniformFlatTailEnabled) && ...
        isscalar(options.uniformFlatTailEnabled))
    error('ipm:gridlab:StageDesignEqualizationOptions', ...
        ['equalizationOptions.uniformFlatTailEnabled must be a ' ...
        'logical scalar.']);
end
if ~(islogical(options.rootCorridorXFallbackEnabled) && ...
        isscalar(options.rootCorridorXFallbackEnabled))
    error('ipm:gridlab:StageDesignEqualizationOptions', ...
        ['equalizationOptions.rootCorridorXFallbackEnabled must be a ' ...
        'logical scalar.']);
end
validateattributes(options.rootCorridorXShoulderCells,{'numeric'}, ...
    {'vector','nonempty','real','finite','positive'}, ...
    mfilename,'equalizationOptions.rootCorridorXShoulderCells');
options.rootCorridorXShoulderCells = ...
    double(options.rootCorridorXShoulderCells(:)');
if any(diff(options.rootCorridorXShoulderCells) <= 0)
    error('ipm:gridlab:StageDesignEqualizationOptions', ...
        ['equalizationOptions.rootCorridorXShoulderCells must be ' ...
        'strictly increasing and contain no duplicates.']);
end
validateattributes(options.rootCorridorXExpansionShoulders,{'numeric'}, ...
    {'scalar','real','finite','nonnegative'},mfilename, ...
    'equalizationOptions.rootCorridorXExpansionShoulders');
options.rootCorridorXExpansionShoulders = ...
    double(options.rootCorridorXExpansionShoulders);
if ~(islogical(options.currentAxisXFallbackEnabled) && ...
        isscalar(options.currentAxisXFallbackEnabled))
    error('ipm:gridlab:StageDesignEqualizationOptions', ...
        ['equalizationOptions.currentAxisXFallbackEnabled must be a ' ...
        'logical scalar.']);
end
validateattributes(options.currentAxisXSigmas,{'numeric'}, ...
    {'vector','nonempty','real','finite','positive'},mfilename, ...
    'equalizationOptions.currentAxisXSigmas');
options.currentAxisXSigmas = ...
    double(options.currentAxisXSigmas(:)');
validateattributes(options.currentAxisXPower,{'numeric'}, ...
    {'scalar','real','finite','positive'},mfilename, ...
    'equalizationOptions.currentAxisXPower');
for field = {'maximumIncrementalReferenceDepth', ...
        'currentIncrementalReferenceDepth'}
    validateattributes(options.(field{1}),{'numeric'}, ...
        {'scalar','integer','nonnegative'},mfilename, ...
        ['equalizationOptions.' field{1}]);
end
for field = {'xSigma','ySigma','xPower','yPower', ...
        'uniformFlatTailSigma','uniformFlatTailPower', ...
        'initialAmplitude','maximumAmplitude','amplitudeTolerance'}
    validateattributes(options.(field{1}),{'numeric'}, ...
        {'scalar','real','finite','positive'},mfilename, ...
        ['equalizationOptions.' field{1}]);
end
if options.initialAmplitude > options.maximumAmplitude
    error('ipm:gridlab:StageDesignEqualizationOptions', ...
        'initialAmplitude must not exceed maximumAmplitude.');
end
validateattributes(options.maxIterations,{'numeric'}, ...
    {'scalar','integer','positive'},mfilename, ...
    'equalizationOptions.maxIterations');
end

function limits = merge_mesh_limits(limits,defaults)
if ~isstruct(limits) || ~isscalar(limits)
    error('ipm:gridlab:StageDesignOptions', ...
        'options.meshLimits must be a scalar structure.');
end
names = fieldnames(defaults);
unexpected = setdiff(fieldnames(limits),names,'stable');
if ~isempty(unexpected)
    error('ipm:gridlab:StageDesignOptions', ...
        'Unknown meshLimits field(s): %s.',strjoin(unexpected,', '));
end
for index = 1:numel(names)
    name = names{index};
    if ~isfield(limits,name)
        limits.(name) = defaults.(name);
    end
    validateattributes(limits.(name),{'numeric'}, ...
        {'scalar','real','finite','positive'},mfilename, ...
        ['options.meshLimits.' name]);
end
end

function featureOptions = strict_feature_options(featureOptions)
if isfield(featureOptions,'safetyCoreLevel') && ...
        featureOptions.safetyCoreLevel ~= 0.9
    error('ipm:gridlab:StageDesignCoreLevel', ...
        'Continuation stage design fixes safetyCoreLevel at 0.9.');
end
featureOptions.safetyCoreLevel = 0.9;
if isfield(featureOptions,'resolutionLevels') && ...
        ~any(abs(featureOptions.resolutionLevels-0.9) <= 16*eps)
    error('ipm:gridlab:StageDesignCoreLevel', ...
        'featureOptions.resolutionLevels must contain the strict 0.9 level.');
end
end

function [result,kind,label] = resolve_current(input)
label = input_label(input);
if ischar(input) || (isstring(input) && isscalar(input))
    fileName = char(input);
    if ~isfile(fileName)
        error('ipm:gridlab:StageDesignCurrentMissing', ...
            'Current result/checkpoint does not exist: %s',fileName);
    end
    variables = whos('-file',fileName);
    names = {variables.name};
    hasResult = ismember('result',names);
    hasCheckpoint = ismember('checkpoint',names);
    if hasResult == hasCheckpoint
        error('ipm:gridlab:StageDesignCurrentFile', ...
            ['Current MAT-file must contain exactly one recognized variable: ' ...
            'result or checkpoint.']);
    end
    if hasResult
        result = ipm.output.validate(fileName);
        kind = 'result_file';
    else
        result = checkpoint_result(fileName);
        kind = 'checkpoint_file';
    end
elseif isstruct(input) && isscalar(input) && ...
        isfield(input,'kind') && ...
        strcmp(input.kind,'ipm_accepted_step_checkpoint')
    result = checkpoint_result(input);
    kind = 'checkpoint_structure';
elseif isstruct(input) && isscalar(input)
    result = ipm.output.validate(input);
    kind = 'result_structure';
else
    error('ipm:gridlab:StageDesignCurrentInput', ...
        'CURRENT must be a version-2 result/checkpoint or its MAT-file.');
end
end

function result = checkpoint_result(input)
[state,log,~] = ipm.output.restoreCheckpoint(input,struct());
result = ipm.output.finalize(state,log,'accepted_checkpoint_snapshot');
end

function [dataset,label] = resolve_reference(input)
label = input_label(input);
if ischar(input) || (isstring(input) && isscalar(input))
    fileName = char(input);
    if ~isfile(fileName)
        error('ipm:gridlab:StageDesignReferenceMissing', ...
            'Reference dataset does not exist: %s',fileName);
    end
    loaded = load(fileName,'dataset');
    if ~isfield(loaded,'dataset')
        error('ipm:gridlab:StageDesignReferenceFile', ...
            'Reference MAT-file must contain a variable named dataset.');
    end
    dataset = loaded.dataset;
else
    dataset = input;
end
if ~isstruct(dataset) || ~isscalar(dataset) || ...
        ~all(isfield(dataset,{'schemaVersion','kind','tag', ...
            'snapshotCount','snapshots'})) || ...
        dataset.schemaVersion ~= 2 || ...
        ~strcmp(dataset.kind,'ipm_frozen_grid_dataset') || ...
        dataset.snapshotCount ~= numel(dataset.snapshots) || ...
        isempty(dataset.snapshots)
    error('ipm:gridlab:StageDesignReference', ...
        'REFERENCE must be a nonempty schema-version-2 frozen dataset.');
end
end

function label = input_label(input)
if ischar(input) || (isstring(input) && isscalar(input))
    label = char(input);
else
    label = 'in_memory_structure';
end
end

function [x,y,index] = select_reference_axes(reference,current,requested)
nx = numel(current.snapshots(1).x);
ny = numel(current.snapshots(1).y);
if isempty(requested)
    nodeCounts = arrayfun(@(value) ...
        numel(value.x) == nx && numel(value.y) == ny, ...
        reference.snapshots);
    index = find(nodeCounts,1,'first');
    if isempty(index)
        error('ipm:gridlab:StageDesignReferenceResolution', ...
            ['The reference dataset has no snapshot with the current ' ...
            '%d-by-%d node counts.'],nx,ny);
    end
else
    if requested > numel(reference.snapshots)
        error('ipm:gridlab:StageDesignReferenceIndex', ...
            'referenceSnapshotIndex exceeds the reference snapshot count.');
    end
    index = requested;
end
record = reference.snapshots(index);
x = double(record.x(:)');
y = double(record.y(:));
if numel(x) ~= nx || numel(y) ~= ny
    error('ipm:gridlab:StageDesignReferenceResolution', ...
        'The selected reference axes must exactly match current node counts.');
end
currentX = double(current.snapshots(1).x(:)');
currentY = double(current.snapshots(1).y(:));
if ~matching_endpoints(x,currentX) || ~matching_endpoints(y,currentY)
    error('ipm:gridlab:StageDesignReferenceDomain', ...
        'Reference and current axes must have identical endpoints.');
end
if mod(numel(x),2) ~= 1 || any(diff(x) <= 0) || ...
        any(diff(y) <= 0) || y(1) ~= 0
    error('ipm:gridlab:StageDesignReferenceAxis', ...
        'Reference axes do not satisfy the double-odd grid contract.');
end
tolerance = 1e3*eps(max(1,max(abs(x))));
if max(abs(x+fliplr(x))) > tolerance
    error('ipm:gridlab:StageDesignReferenceAxis', ...
        'The reference x axis is not symmetric.');
end
end

function tf = matching_endpoints(first,second)
first = double(first(:));
second = double(second(:));
scale = max([1;abs(first([1,end]));abs(second([1,end]))]);
tf = max(abs(first([1,end])-second([1,end]))) <= 1e3*eps(scale);
end

function axisOptions = axis_options(input,reference,limits)
axisOptions = input;
axisOptions.referenceAxis = reference;
axisOptions.maxAdjacentCellRatio = limits.maxAdjacentCellRatio;
axisOptions.maxLogSpacingCurvature = limits.maxLogSpacingCurvature;
axisOptions.minStencilRcond = limits.minStencilRcond;
axisOptions.minQuadratureWeightRatio = limits.minQuadratureWeightRatio;
end

function summary = initialize_root_corridor_x_fallback( ...
        options,referenceX,referenceIndex)
if ~options.enabled
    status = 'disabled_by_equalization_master';
elseif options.rootCorridorXFallbackEnabled
    status = 'pending_preceding_tiers';
else
    status = 'not_requested';
end
summary = struct( ...
    'enabled',options.rootCorridorXFallbackEnabled, ...
    'masterEqualizationEnabled',options.enabled, ...
    'attempted',false,'usedAsReference',false, ...
    'status',status, ...
    'kernelKind','corridor', ...
    'referenceProvenance','external_original_reference_corridor', ...
    'referencePolicy', ...
        'immutable_copy_of_selected_external_reference_snapshot_x', ...
