function record = fill_candidate(record,axis,info,coreCounts,frontCounts)
record.status = 'generated';
record.admissible = info.admissible;
record.axis = axis;
record.axisInfo = info;
record.coreCellsBySnapshot = coreCounts(:)';
record.minimumCoreCells = min(coreCounts);
record.frontCellsBySnapshot = frontCounts(:)';
if isempty(frontCounts)
    record.minimumFrontCells = NaN;
else
    record.minimumFrontCells = min(frontCounts);
end
widths = diff(axis);
