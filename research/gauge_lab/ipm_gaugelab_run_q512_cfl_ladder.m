function value = relative_difference(reference,candidate)
if ~isfinite(reference) || ~isfinite(candidate)
    value = NaN;
    return
end
scale = max([abs(reference),abs(candidate),eps]);
value = (candidate-reference)/scale;
end

function value = vector_relative_difference(reference,candidate)
scale = max(cat(1,abs(reference),abs(candidate), ...
    eps*ones(size(reference))),[],1);
value = (candidate-reference)./scale;
end

function value = safe_ratio(numerator,denominator)
scale = max([1,abs(numerator),abs(denominator)]);
if abs(denominator) <= 100*eps(scale)
    value = NaN;
else
    value = numerator/denominator;
end
end

