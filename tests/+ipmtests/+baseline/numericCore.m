    ipm.evolve.isotropicGauge(rho,physicalRhs,flow,ops,tracking);

r = ops.rescaling;
anchorU1 = interp1(ops.x,u1(1,:),r.transportAnchorX,'linear');
expectedNominal = -anchorU1/r.transportAnchorX;
expectedCL = expectedNominal;
expectedCR = 0;
expectedTransportU1 = u1+expectedCL*ops.X+expectedCR;
expectedTransportU2 = u2+expectedCL*ops.Y;
expectedBase = ipm.field.transport( ...
    rho,expectedTransportU1,expectedTransportU2,ops,'open') + ...
    2*expectedCL*rho;
expectedLengthResidual = ...
    anchorU1+expectedNominal*r.transportAnchorX;
formulaError = max([abs(cL-expectedCL),abs(cOmega),abs(cR-expectedCR), ...
    max(abs(baseRhs-expectedBase),[],'all'), ...
    abs(details.c_lNominal-expectedNominal), ...
    abs(details.lengthGaugeStrain-r.transportAnchorX), ...
    abs(details.lengthGaugeResidual-expectedLengthResidual), ...
    abs(details.widthCorrection),abs(details.omegaGaugeResidual)]);
