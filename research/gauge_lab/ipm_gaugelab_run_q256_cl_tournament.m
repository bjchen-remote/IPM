function value = guarded_ratio(numerator,denominator)
scale = max([1,abs(numerator),abs(denominator)]);
if abs(denominator) <= 100*eps(scale)
    value = NaN;
else
    value = numerator/denominator;
end
end

function value = relative_difference(reference,candidate)
value = (candidate-reference)/max(abs(reference),eps);
end

function classification = classify_exception(exception)
identifier = char(exception.identifier);
if any(startsWith(identifier,{'ipm:DegenerateLengthGauge', ...
        'ipm:BadLengthGauge','ipm:SymmetryLengthGauge'}))
    classification = 'designed_gauge_failure';
else
    classification = 'unexpected_error';
end
end

function value = normalize_flag(value,name)
validLogical = islogical(value) && isscalar(value);
validNumeric = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && any(value == [0,1]);
if ~(validLogical || validNumeric)
    error('ipm:GaugeLabCLBoolean', ...
        '%s must be scalar logical or numeric 0/1.',name);
end
value = logical(value);
end

