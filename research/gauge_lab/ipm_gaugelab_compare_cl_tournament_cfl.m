function report = ipm_gaugelab_compare_cl_tournament_cfl(firstInput,secondInput)
%IPM_GAUGELAB_COMPARE_CL_TOURNAMENT_CFL Compare two c_l CFL artifacts.
%   REPORT = IPM_GAUGELAB_COMPARE_CL_TOURNAMENT_CFL(FIRST,SECOND) is a
%   read-only postprocessor. FIRST and SECOND may each name a
%   cl_tournament_summary.mat file, its containing directory, or one
%   candidate result MAT file. Tournament inputs are matched by
%   scaling.lengthGauge; result inputs compare their single common gauge.
%
%   Every matched pair must share a physical endpoint before its terminal
%   fields are compared in both interpolation directions with
%   ipm.output.compare. The report also retains endpoint rates, the fixed
%   canonical-tail diagnostics, accepted-step/wall-time data, and a
%   distinction between the unchanged evolution contract and the stronger
%   gauge-contract/phase evidence fields added after older campaigns.
%   This function advances no PDE and writes no file.

narginchk(2,2);
laboratoryDirectory = fileparts(mfilename('fullpath'));
researchDirectory = fileparts(laboratoryDirectory);
projectDirectory = fileparts(researchDirectory);
addpath(projectDirectory,laboratoryDirectory);

first = read_campaign_input(firstInput,'first');
second = read_campaign_input(secondInput,'second');
specifications = ipm_gaugelab_length_candidate_specifications();
[candidateNames,firstOnly,secondOnly] = shared_candidates(first,second);
if isempty(candidateNames)
    error('ipm:GaugeLabCLCflNoCommonCandidate', ...
        'The two inputs contain no common length-gauge candidate.');
end
comparisonWindow = common_comparison_window(first,second);

records = repmat(empty_record(),numel(candidateNames),1);
for candidateIndex = 1:numel(candidateNames)
    name = candidateNames{candidateIndex};
    firstRun = find_run(first,name);
    secondRun = find_run(second,name);
    firstResult = ipm.output.validate(firstRun.resultFile);
    secondResult = ipm.output.validate(secondRun.resultFile);
    specification = find_specification(specifications,name);
    records(candidateIndex) = compare_candidate( ...
        name,firstRun,secondRun,firstResult,secondResult, ...
        specification,comparisonWindow,first,second);
end

report = struct( ...
    'schemaVersion',1, ...
    'kind','q256_cl_tournament_cross_cfl_read_only', ...
    'generatedAt',datetime('now','TimeZone','local'), ...
    'first',campaign_description(first), ...
    'second',campaign_description(second), ...
    'comparisonWindow',comparisonWindow, ...
    'candidateNames',{candidateNames}, ...
    'firstOnlyCandidates',{firstOnly}, ...
    'secondOnlyCandidates',{secondOnly}, ...
    'sameCandidateSet',isempty(firstOnly) && isempty(secondOnly), ...
    'records',{records}, ...
    'summary',summarize_records(records));
print_report(report);
end

function campaign = read_campaign_input(inputValue,label)
pathName = normalize_input_path(inputValue,label);
if isfolder(pathName)
    pathName = fullfile(pathName,'cl_tournament_summary.mat');
end
if ~isfile(pathName)
    error('ipm:GaugeLabCLCflInputMissing', ...
        '%s input does not exist: %s.',label,pathName);
end
loaded = load(pathName);
if isfield(loaded,'products') && isstruct(loaded.products) && ...
        isscalar(loaded.products)
    products = loaded.products;
    if ~isfield(products,'runs') || isempty(products.runs)
        error('ipm:GaugeLabCLCflSummaryRuns', ...
            'Tournament summary has no candidate runs: %s.',pathName);
    end
    runs = normalize_summary_runs(products.runs,pathName);
    protocol = struct();
    status = '';
    if isfield(products,'protocol') && isstruct(products.protocol) && ...
            isscalar(products.protocol)
        protocol = products.protocol;
    end
    if isfield(products,'status')
        status = scalar_text(products.status,'products.status');
    end
    campaign = struct('inputPath',pathName,'inputKind','tournament_summary', ...
        'status',status,'protocol',protocol,'runs',{runs});
elseif isfield(loaded,'result') && isstruct(loaded.result) && ...
        isscalar(loaded.result)
    result = ipm.output.validate(loaded.result);
    run = empty_source_run();
    run.lengthGauge = result.config.scaling.lengthGauge;
    run.resultFile = pathName;
    campaign = struct('inputPath',pathName,'inputKind','single_result', ...
        'status',result.state.stopReason,'protocol',struct(),'runs',{run});
else
    error('ipm:GaugeLabCLCflInputType', ...
        '%s input must contain scalar variable products or result: %s.', ...
        label,pathName);
end
assert_unique_candidates(campaign.runs,pathName);
end

function pathName = normalize_input_path(value,label)
if isstring(value)
    if ~isscalar(value) || ismissing(value)
        error('ipm:GaugeLabCLCflInputText', ...
            '%s input must be scalar text.',label);
    end
    value = char(value);
end
if ~ischar(value) || ~isrow(value) || isempty(strtrim(value))
    error('ipm:GaugeLabCLCflInputText', ...
        '%s input must be nonempty scalar text.',label);
end
pathName = strtrim(value);
end

function runs = normalize_summary_runs(sourceRuns,summaryFile)
runs = repmat(empty_source_run(),numel(sourceRuns),1);
for index = 1:numel(sourceRuns)
    source = sourceRuns(index);
    if ~isfield(source,'lengthGauge')
        error('ipm:GaugeLabCLCflRunGauge', ...
            'A summary run lacks lengthGauge: %s.',summaryFile);
    end
    runs(index).lengthGauge = scalar_text( ...
        source.lengthGauge,'run.lengthGauge');
    runs(index).resultFile = resolve_result_file( ...
        source,summaryFile,runs(index).lengthGauge);
    runs(index).elapsedSeconds = optional_numeric_scalar( ...
        source,'elapsedSeconds',NaN);
    runs(index).acceptedSteps = optional_numeric_scalar( ...
        source,'acceptedSteps',NaN);
    runs(index).secondsPerStep = optional_numeric_scalar( ...
        source,'secondsPerStep',NaN);
    runs(index).recordedExactContractPassed = optional_logical_scalar( ...
        source,'exactContractPassed');
    if isfield(source,'exactEvidence') && isstruct(source.exactEvidence) && ...
            isscalar(source.exactEvidence)
        runs(index).recordedExactEvidenceFields = ...
            sort(fieldnames(source.exactEvidence));
    end
end
end

function resultFile = resolve_result_file(source,summaryFile,candidate)
candidates = {};
if isfield(source,'resultFile')
    candidates{end+1} = source.resultFile;
end
if isfield(source,'requestedResultFile')
    candidates{end+1} = source.requestedResultFile;
end
summaryDirectory = fileparts(summaryFile);
candidates{end+1} = fullfile(summaryDirectory,candidate,'result.mat');
for index = 1:numel(candidates)
    value = candidates{index};
    if isstring(value)
        if ~isscalar(value) || ismissing(value)
            continue;
        end
        value = char(value);
    end
    if ~ischar(value) || ~isrow(value) || isempty(strtrim(value))
        continue;
    end
    value = strtrim(value);
    trials = {value};
    if ~startsWith(value,filesep)
        trials{end+1} = fullfile(summaryDirectory,value); %#ok<AGROW>
    end
    for trialIndex = 1:numel(trials)
        if isfile(trials{trialIndex})
            resultFile = trials{trialIndex};
            return;
        end
    end
end
error('ipm:GaugeLabCLCflResultMissing', ...
    'Cannot locate result for candidate %s from %s.',candidate,summaryFile);
end

function assert_unique_candidates(runs,pathName)
names = {runs.lengthGauge};
if numel(unique(names)) ~= numel(names)
    error('ipm:GaugeLabCLCflDuplicateCandidate', ...
        'Input contains duplicate length-gauge candidates: %s.',pathName);
end
end

function [shared,firstOnly,secondOnly] = shared_candidates(first,second)
firstNames = {first.runs.lengthGauge};
secondNames = {second.runs.lengthGauge};
shared = firstNames(ismember(firstNames,secondNames));
firstOnly = firstNames(~ismember(firstNames,secondNames));
secondOnly = secondNames(~ismember(secondNames,firstNames));
end

function window = common_comparison_window(first,second)
firstWindow = protocol_value(first.protocol,'comparisonWindow',[]);
secondWindow = protocol_value(second.protocol,'comparisonWindow',[]);
if isempty(firstWindow) && isempty(secondWindow)
    window = [-2,2,2];
elseif isempty(firstWindow)
    window = secondWindow;
elseif isempty(secondWindow)
    window = firstWindow;
elseif isequaln(firstWindow,secondWindow)
    window = firstWindow;
else
    error('ipm:GaugeLabCLCflWindowMismatch', ...
        'Tournament comparison windows differ between the two inputs.');
end
validateattributes(window,{'numeric'}, ...
    {'vector','numel',3,'real','finite'},mfilename,'comparisonWindow');
window = window(:)';
end

function run = find_run(campaign,name)
index = find(strcmp({campaign.runs.lengthGauge},name),1,'first');
if isempty(index)
    error('ipm:GaugeLabCLCflCandidateLookup', ...
        'Candidate %s is absent from %s.',name,campaign.inputPath);
end
run = campaign.runs(index);
end

function specification = find_specification(specifications,name)
index = find(strcmp({specifications.lengthGauge},name),1,'first');
if isempty(index)
    error('ipm:GaugeLabCLCflUnregisteredGauge', ...
        'Length gauge %s is not in the current registry.',name);
end
specification = specifications(index);
end

function record = compare_candidate(name,firstRun,secondRun, ...
        firstResult,secondResult,specification,window,firstCampaign, ...
        secondCampaign)
if ~strcmp(firstResult.config.scaling.lengthGauge,name) || ...
        ~strcmp(secondResult.config.scaling.lengthGauge,name)
    error('ipm:GaugeLabCLCflResultGaugeMismatch', ...
        'Saved result lengthGauge does not match candidate %s.',name);
end
record = empty_record();
record.lengthGauge = name;
record.firstResultFile = firstRun.resultFile;
record.secondResultFile = secondRun.resultFile;
record.endpoint = compare_endpoints(firstResult,secondResult);
record.firstRun = run_statistics(firstResult,firstRun);
record.secondRun = run_statistics(secondResult,secondRun);
if record.endpoint.samePhysicalEndpoint
    record.physicalFields = compare_physical_fields( ...
        firstResult,secondResult,window, ...
        common_covariance_limits(firstCampaign,secondCampaign));
else
    record.physicalFields.errorIdentifier = ...
        'ipm:GaugeLabCLCflPhysicalEndpointMismatch';
    record.physicalFields.errorMessage = ...
        'Terminal fields were not compared because physical endpoints differ.';
end
record.endpointRates = compare_endpoint_rates(firstResult,secondResult);
record.tailRates = compare_tail_rates(firstResult,secondResult);
record.firstContract = contract_audit( ...
        firstResult,firstRun,specification);
record.secondContract = contract_audit( ...
        secondResult,secondRun,specification);
record.contractComparison = compare_contracts( ...
        firstResult,secondResult,record.firstContract, ...
        record.secondContract);
end

function endpoint = compare_endpoints(first,second)
firstTime = first.state.physicalTime;
secondTime = second.state.physicalTime;
firstTarget = first.config.time.physicalFinalTime;
secondTarget = second.config.time.physicalFinalTime;
tolerance = 1e-10*max([1,abs(firstTime),abs(secondTime), ...
    abs(firstTarget),abs(secondTarget)]);
endpoint = struct( ...
    'firstPhysicalTime',firstTime, ...
    'secondPhysicalTime',secondTime, ...
    'signedPhysicalTimeDifference',secondTime-firstTime, ...
    'firstConfiguredTarget',firstTarget, ...
    'secondConfiguredTarget',secondTarget, ...
    'tolerance',tolerance, ...
    'sameConfiguredTarget',isfinite(firstTarget) && ...
        isfinite(secondTarget) && abs(secondTarget-firstTarget) <= tolerance, ...
    'firstReachedTarget',isfinite(firstTime) && isfinite(firstTarget) && ...
        abs(firstTime-firstTarget) <= tolerance, ...
    'secondReachedTarget',isfinite(secondTime) && isfinite(secondTarget) && ...
        abs(secondTime-secondTarget) <= tolerance, ...
    'samePhysicalEndpoint',isfinite(firstTime) && isfinite(secondTime) && ...
        abs(secondTime-firstTime) <= tolerance);
end

function statistics = run_statistics(result,run)
common = result.history.common;
statistics = struct( ...
    'cfl',result.config.time.cfl, ...
    'maximumDt',result.config.time.maxDt, ...
    'acceptedSteps',result.state.steps, ...
    'recordedAcceptedSteps',run.acceptedSteps, ...
    'elapsedSeconds',run.elapsedSeconds, ...
    'secondsPerStep',run.secondsPerStep, ...
    'canonicalTime',result.state.canonicalTime, ...
    'physicalTime',result.state.physicalTime, ...
    'stopReason',result.state.stopReason, ...
    'historyRecords',numel(common.c_l), ...
    'maximumRealizedCfl',finite_max(common,'realizedCfl'), ...
    'cflLimitedRecords',count_limiter(common,'cfl'));
if ~isfinite(statistics.secondsPerStep) && ...
        isfinite(statistics.elapsedSeconds) && statistics.acceptedSteps > 0
    statistics.secondsPerStep = ...
        statistics.elapsedSeconds/statistics.acceptedSteps;
end
end

function comparison = compare_physical_fields(first,second,window,limits)
comparison = empty_field_comparison();
try
    forward = ipm.output.compare(first,second,window);
    reverse = ipm.output.compare(second,first,window);
    firstRhoX = first.history.common.physicalRhoXInf(end);
    secondRhoX = second.history.common.physicalRhoXInf(end);
    forward.physicalRhoXRelativeDifference = ...
        directional_relative_difference(firstRhoX,secondRhoX);
    reverse.physicalRhoXRelativeDifference = ...
        directional_relative_difference(secondRhoX,firstRhoX);
    forward.physicalTimeDifference = ...
        second.state.physicalTime-first.state.physicalTime;
    reverse.physicalTimeDifference = ...
        first.state.physicalTime-second.state.physicalTime;
    firstWallWidth = common_wall_half_maximum_width(first);
    secondWallWidth = common_wall_half_maximum_width(second);
    forward.commonWallWidthRelativeDifference = ...
        directional_relative_difference(firstWallWidth,secondWallWidth);
    reverse.commonWallWidthRelativeDifference = ...
        directional_relative_difference(secondWallWidth,firstWallWidth);
    names = physical_metric_names();
    symmetric = struct();
    for index = 1:numel(names)
        metric = names{index};
        symmetric.(metric) = max(abs([ ...
            forward.(metric),reverse.(metric)]));
    end
    comparison.available = true;
    comparison.forward = forward;
    comparison.reverse = reverse;
    comparison.symmetricWorst = symmetric;
    comparison.limitsAvailable = ~isempty(fieldnames(limits));
    if comparison.limitsAvailable
        [comparison.withinTournamentLimits, ...
            comparison.maximumNormalizedLimitUsage] = ...
            covariance_limit_check(symmetric,limits);
    end
catch exception
    comparison.errorIdentifier = exception.identifier;
    comparison.errorMessage = exception.message;
end
end

function limits = common_covariance_limits(first,second)
firstLimits = protocol_value( ...
    first.protocol,'physicalCovarianceLimits',struct());
secondLimits = protocol_value( ...
    second.protocol,'physicalCovarianceLimits',struct());
if ~isstruct(firstLimits) || ~isscalar(firstLimits)
    firstLimits = struct();
end
if ~isstruct(secondLimits) || ~isscalar(secondLimits)
    secondLimits = struct();
end
if isempty(fieldnames(firstLimits))
    limits = secondLimits;
elseif isempty(fieldnames(secondLimits))
    limits = firstLimits;
elseif isequaln(firstLimits,secondLimits)
    limits = firstLimits;
else
    limits = struct();
end
end

function [passed,maximumUsage] = covariance_limit_check(values,limits)
mapping = { ...
    'rhoRelativeL2','rhoRelativeL2'; ...
    'omegaRelativeL2','omegaRelativeL2'; ...
    'rhoAbsoluteInf','rhoAbsoluteInf'; ...
    'omegaAbsoluteInf','omegaAbsoluteInf'; ...
    'labPeakShift','maximumAbsoluteLabPeakShift'; ...
    'physicalTimeDifference','maximumAbsolutePhysicalTimeDifference'; ...
    'physicalRhoXRelativeDifference','physicalRhoXRelativeDifference'; ...
    'wallPeakRelativeDifference','wallPeakRelativeDifference'; ...
    'commonWallWidthRelativeDifference','wallWidthRelativeDifference'};
usage = NaN(size(mapping,1),1);
for index = 1:size(mapping,1)
    if ~isfield(values,mapping{index,1}) || ...
            ~isfield(limits,mapping{index,2})
        passed = false;
        maximumUsage = Inf;
        return;
    end
    usage(index) = abs(values.(mapping{index,1})) / ...
        limits.(mapping{index,2});
end
passed = all(isfinite(usage)) && all(usage <= 1);
maximumUsage = max(usage);
end

function rates = compare_endpoint_rates(first,second)
names = {'c_l','c_omega'};
rates = struct();
for index = 1:numel(names)
    name = names{index};
    rates.(name) = compare_scalar( ...
        first.history.common.(name)(end), ...
        second.history.common.(name)(end));
end
firstCL = rates.c_l.first;
secondCL = rates.c_l.second;
firstCOmega = rates.c_omega.first;
secondCOmega = rates.c_omega.second;
rates.cOmegaOverCL = compare_scalar( ...
    guarded_ratio(firstCOmega,firstCL), ...
    guarded_ratio(secondCOmega,secondCL));
rates.cLMinusCOmega = compare_scalar( ...
    firstCL-firstCOmega,secondCL-secondCOmega);
rates.cLMinusCOmegaOverCL = compare_scalar( ...
    guarded_ratio(firstCL-firstCOmega,firstCL), ...
    guarded_ratio(secondCL-secondCOmega,secondCL));
rates.physicalRhoXInf = compare_scalar( ...
    first.history.common.physicalRhoXInf(end), ...
    second.history.common.physicalRhoXInf(end));
end

function pair = compare_scalar(first,second)
pair = struct('first',first,'second',second, ...
    'signedDifference',second-first, ...
    'absoluteDifference',abs(second-first), ...
    'signedRelativeDifference',relative_difference(first,second), ...
    'absoluteRelativeDifference',abs(relative_difference(first,second)));
end

function tails = compare_tail_rates(first,second)
firstDiagnostic = first.fit.gaugeRateConvergence;
secondDiagnostic = second.fit.gaugeRateConvergence;
sameWindowFractions = isequaln( ...
    firstDiagnostic.windowFractions,secondDiagnostic.windowFractions);
tails = struct( ...
    'firstValid',firstDiagnostic.valid, ...
    'secondValid',secondDiagnostic.valid, ...
    'sameWindowFractions',sameWindowFractions, ...
    'firstWindowFractions',firstDiagnostic.windowFractions, ...
    'secondWindowFractions',secondDiagnostic.windowFractions, ...
    'cL',compare_tail_series(firstDiagnostic,secondDiagnostic,'cL', ...
        sameWindowFractions), ...
    'cOmega',compare_tail_series( ...
        firstDiagnostic,secondDiagnostic,'cOmega',sameWindowFractions), ...
    'cOmegaOverCL',compare_tail_series( ...
        firstDiagnostic,secondDiagnostic,'cOmegaOverCL', ...
        sameWindowFractions), ...
    'cLMinusCOmegaOverCL',compare_tail_series( ...
        firstDiagnostic,secondDiagnostic,'cLMinusCOmegaOverCL', ...
        sameWindowFractions));
tails.firstWorstCLCOmegaTrend = NaN;
tails.secondWorstCLCOmegaTrend = NaN;
tails.signedWorstTrendDifference = NaN;
tails.absoluteWorstTrendDifference = NaN;
if tails.cL.valid && tails.cOmega.valid
    tails.firstWorstCLCOmegaTrend = max([ ...
        tails.cL.firstMaximumAbsoluteRelativeTrend, ...
        tails.cOmega.firstMaximumAbsoluteRelativeTrend]);
    tails.secondWorstCLCOmegaTrend = max([ ...
        tails.cL.secondMaximumAbsoluteRelativeTrend, ...
        tails.cOmega.secondMaximumAbsoluteRelativeTrend]);
    tails.signedWorstTrendDifference = ...
        tails.secondWorstCLCOmegaTrend-tails.firstWorstCLCOmegaTrend;
    tails.absoluteWorstTrendDifference = ...
        abs(tails.signedWorstTrendDifference);
end
end

function comparison = compare_tail_series(first,second,name,sameWindows)
comparison = empty_tail_series();
if ~isfield(first.seriesSummary,name) || ...
        ~isfield(second.seriesSummary,name)
    return;
end
firstSeries = first.seriesSummary.(name);
secondSeries = second.seriesSummary.(name);
required = {'maximumAbsoluteRelativeTrend','relativeWindowMeanSpread', ...
    'maximumRelativeDetrendedRms','windowRelativeTrends', ...
    'windowWeightedMeans','windowRelativeDetrendedRms','stable'};
if ~all(isfield(firstSeries,required)) || ...
        ~all(isfield(secondSeries,required))
    return;
end
sameArrayShapes = isequal(size(firstSeries.windowRelativeTrends), ...
        size(secondSeries.windowRelativeTrends)) && ...
    isequal(size(firstSeries.windowWeightedMeans), ...
        size(secondSeries.windowWeightedMeans)) && ...
    isequal(size(firstSeries.windowRelativeDetrendedRms), ...
        size(secondSeries.windowRelativeDetrendedRms));
comparison.valid = sameWindows && sameArrayShapes && ...
    all(isfinite([ ...
    firstSeries.maximumAbsoluteRelativeTrend, ...
    secondSeries.maximumAbsoluteRelativeTrend, ...
    firstSeries.relativeWindowMeanSpread, ...
    secondSeries.relativeWindowMeanSpread, ...
    firstSeries.maximumRelativeDetrendedRms, ...
    secondSeries.maximumRelativeDetrendedRms])) && ...
    all(isfinite(firstSeries.windowRelativeTrends(:))) && ...
    all(isfinite(secondSeries.windowRelativeTrends(:))) && ...
    all(isfinite(firstSeries.windowWeightedMeans(:))) && ...
    all(isfinite(secondSeries.windowWeightedMeans(:))) && ...
    all(isfinite(firstSeries.windowRelativeDetrendedRms(:))) && ...
    all(isfinite(secondSeries.windowRelativeDetrendedRms(:)));
comparison.firstStable = firstSeries.stable;
comparison.secondStable = secondSeries.stable;
comparison.firstMaximumAbsoluteRelativeTrend = ...
    firstSeries.maximumAbsoluteRelativeTrend;
comparison.secondMaximumAbsoluteRelativeTrend = ...
    secondSeries.maximumAbsoluteRelativeTrend;
comparison.firstRelativeWindowMeanSpread = ...
    firstSeries.relativeWindowMeanSpread;
comparison.secondRelativeWindowMeanSpread = ...
    secondSeries.relativeWindowMeanSpread;
comparison.firstMaximumRelativeDetrendedRms = ...
    firstSeries.maximumRelativeDetrendedRms;
comparison.secondMaximumRelativeDetrendedRms = ...
    secondSeries.maximumRelativeDetrendedRms;
comparison.firstWindowRelativeTrends = firstSeries.windowRelativeTrends;
comparison.secondWindowRelativeTrends = secondSeries.windowRelativeTrends;
comparison.firstWindowWeightedMeans = firstSeries.windowWeightedMeans;
comparison.secondWindowWeightedMeans = secondSeries.windowWeightedMeans;
comparison.firstWindowRelativeDetrendedRms = ...
    firstSeries.windowRelativeDetrendedRms;
comparison.secondWindowRelativeDetrendedRms = ...
    secondSeries.windowRelativeDetrendedRms;
if ~comparison.valid
    return;
end
comparison.signedMaximumTrendDifference = ...
    secondSeries.maximumAbsoluteRelativeTrend - ...
    firstSeries.maximumAbsoluteRelativeTrend;
comparison.absoluteMaximumTrendDifference = ...
    abs(comparison.signedMaximumTrendDifference);
comparison.signedWindowMeanSpreadDifference = ...
    secondSeries.relativeWindowMeanSpread - ...
    firstSeries.relativeWindowMeanSpread;
comparison.signedMaximumDetrendedRmsDifference = ...
    secondSeries.maximumRelativeDetrendedRms - ...
    firstSeries.maximumRelativeDetrendedRms;
comparison.windowRelativeTrendDifferences = ...
    secondSeries.windowRelativeTrends-firstSeries.windowRelativeTrends;
comparison.windowWeightedMeanDifferences = ...
    secondSeries.windowWeightedMeans-firstSeries.windowWeightedMeans;
end

function audit = contract_audit(result,run,specification)
common = result.history.common;
gauge = result.history.gauge;
scaling = result.config.scaling;
retired = retired_fields();
count = numel(common.c_l);
audit = empty_contract_audit();
audit.recordedAuditPassed = run.recordedExactContractPassed;
audit.recordedAuditEvidenceFields = run.recordedExactEvidenceFields;
audit.configSchemaVersion = result.config.schemaVersion;
[audit.gaugeContractFields,audit.lengthContractFields, ...
    audit.amplitudeContractFields,audit.feedbackContractFields] = ...
    metadata_contract_field_sets(result.metadata);
audit.retiredFieldsAbsent = ...
    isempty(intersect(fieldnames(scaling),retired));
audit.configCorePassed = result.config.schemaVersion == 4 && ...
    strcmp(scaling.scalingContract,'exact_gauge_no_feedback_v1') && ...
    strcmp(scaling.lengthGauge,specification.lengthGauge) && ...
    strcmp(scaling.cOmegaGauge,'gradient_energy') && ...
    scaling.lengthScaleGain == 1 && scaling.widthGaugeGain == 0 && ...
    scaling.omegaGaugeGain == 0 && scaling.travelingWaveGain == 0 && ...
    audit.retiredFieldsAbsent;
requiredCommon = {'timeSpeed','c_l','canonicalCL','c_omega', ...
    'canonicalCOmega'};
requiredGauge = {'c_lNominal','canonicalCLNominal', ...
    'lengthScaleGain','widthControlMode','widthCorrection', ...
    'canonicalWidthCorrection','lengthGaugeStrain', ...
    'lengthGaugeResidual','widthRateScale','omegaGaugeResidual'};
audit.coreHistoryComplete = has_finite_equal_length_fields( ...
    common,requiredCommon,count) && ...
    has_finite_equal_length_fields(gauge,requiredGauge,count);
audit.directClockPassed = audit.coreHistoryComplete && ...
    all(common.timeSpeed == 1);
audit.directRateIdentitiesPassed = audit.coreHistoryComplete && ...
    isequal(common.c_l,common.canonicalCL) && ...
    isequal(common.c_omega,common.canonicalCOmega) && ...
    isequal(common.c_l,gauge.c_lNominal) && ...
    isequal(common.canonicalCL,gauge.canonicalCLNominal);
audit.noFeedbackHistoryPassed = audit.coreHistoryComplete && ...
    all(gauge.lengthScaleGain == 1) && ...
    all(gauge.widthControlMode == 0) && ...
    all(gauge.widthCorrection == 0) && ...
    all(gauge.canonicalWidthCorrection == 0);
audit.fixedMeshPassed = isfield(result,'grid') && ...
    isstruct(result.grid) && isscalar(result.grid) && ...
    isfield(result.grid,'remeshCount') && result.grid.remeshCount == 0 && ...
    isfield(result.history,'mesh') && ...
    isfield(result.history.mesh,'remeshCount') && ...
    all(result.history.mesh.remeshCount == 0);

[audit.metadataCorePassed,audit.metadataStrengthenedPassed, ...
    audit.gaugeContractSchemaVersion,audit.missingStrengthenedFields, ...
    audit.mismatchedStrengthenedFields] = ...
    metadata_contract_audit(result.metadata,specification);
[audit.candidateDiagnosticsAvailable, ...
    audit.missingCandidateDiagnosticFields] = ...
    candidate_diagnostic_audit(gauge,specification.lengthGauge, ...
        count);
[audit.residualFieldsPassed, ...
    audit.maximumNormalizedLengthGaugeResidual, ...
    audit.maximumOmegaGaugeResidual] = ...
    residual_field_audit(gauge,count);
audit.currentStrengthenedFieldContractPassed = ...
    audit.configCorePassed && audit.metadataCorePassed && ...
    audit.metadataStrengthenedPassed && audit.directClockPassed && ...
    audit.directRateIdentitiesPassed && audit.noFeedbackHistoryPassed && ...
    audit.fixedMeshPassed && audit.candidateDiagnosticsAvailable && ...
    audit.residualFieldsPassed;
if audit.currentStrengthenedFieldContractPassed
    audit.evidenceClass = 'strengthened_current';
elseif audit.configCorePassed && audit.metadataCorePassed && ...
        audit.directClockPassed && audit.directRateIdentitiesPassed && ...
        audit.noFeedbackHistoryPassed && audit.fixedMeshPassed && ...
        audit.residualFieldsPassed
    audit.evidenceClass = 'legacy_core_only';
else
    audit.evidenceClass = 'invalid_or_incomplete_core';
end
audit.recordedAuditComparableToCurrent = ...
    islogical(audit.recordedAuditPassed) && ...
    audit.metadataStrengthenedPassed;
audit.recordedAuditAgreesWithCurrent = ...
    audit.recordedAuditComparableToCurrent && ...
    audit.recordedAuditPassed == ...
        audit.currentStrengthenedFieldContractPassed;
end

function [corePassed,strengthenedPassed,schemaVersion,missing,mismatch] = ...
        metadata_contract_audit(metadata,specification)
corePassed = false;
strengthenedPassed = false;
schemaVersion = NaN;
missing = {};
mismatch = {};
if ~isstruct(metadata) || ~isscalar(metadata) || ...
        ~isfield(metadata,'gaugeContract') || ...
        ~isstruct(metadata.gaugeContract) || ...
        ~isscalar(metadata.gaugeContract)
    missing{end+1} = 'metadata.gaugeContract';
    return;
end
contract = metadata.gaugeContract;
if isfield(contract,'schemaVersion') && isnumeric(contract.schemaVersion) && ...
        isscalar(contract.schemaVersion)
    schemaVersion = contract.schemaVersion;
end
requiredCore = {'clock','timeSpeed','feedback','length','amplitude'};
for index = 1:numel(requiredCore)
    if ~isfield(contract,requiredCore{index})
        missing{end+1} = ['gaugeContract.',requiredCore{index}]; %#ok<AGROW>
    end
end
if ~isempty(missing)
    return;
end
lengthContract = contract.length;
amplitudeContract = contract.amplitude;
feedback = contract.feedback;
if ~isstruct(lengthContract) || ~isscalar(lengthContract) || ...
        ~isstruct(amplitudeContract) || ~isscalar(amplitudeContract) || ...
        ~isstruct(feedback) || ~isscalar(feedback)
    mismatch{end+1} = 'gaugeContract.core_substructure_type';
    return;
end
coreNamesPresent = all(isfield(lengthContract,{'name','formula'})) && ...
    isfield(amplitudeContract,'name') && isfield(feedback,'rateLimiter');
if ~coreNamesPresent
    mismatch{end+1} = 'gaugeContract.core_substructure_fields';
    return;
end
corePassed = text_matches(contract.clock,'canonical_tau_direct') && ...
    isequal(contract.timeSpeed,1) && ...
    text_matches(lengthContract.name,specification.lengthGauge) && ...
    text_matches(lengthContract.formula,specification.formula) && ...
    text_matches(amplitudeContract.name,'gradient_energy') && ...
    text_matches(feedback.rateLimiter,'absent');

strengthenedNames = {'observable','evaluation', ...
    'registeredParameters','phaseInterpretation'};
for index = 1:numel(strengthenedNames)
    name = strengthenedNames{index};
    if ~isfield(lengthContract,name)
        missing{end+1} = ['gaugeContract.length.',name]; %#ok<AGROW>
    end
end
amplitudeStrengthenedNames = {'formula','observable','evaluation'};
for index = 1:numel(amplitudeStrengthenedNames)
    name = amplitudeStrengthenedNames{index};
    if ~isfield(amplitudeContract,name)
        missing{end+1} = ['gaugeContract.amplitude.',name]; %#ok<AGROW>
    end
end
if ~isfinite(schemaVersion) || schemaVersion ~= 2
    mismatch{end+1} = 'gaugeContract.schemaVersion~=2';
end
if isfield(lengthContract,'observable') && ...
        ~text_matches(lengthContract.observable,specification.observable)
    mismatch{end+1} = 'gaugeContract.length.observable';
end
if isfield(lengthContract,'evaluation') && ...
        ~text_matches(lengthContract.evaluation,specification.evaluation)
    mismatch{end+1} = 'gaugeContract.length.evaluation';
end
if isfield(lengthContract,'registeredParameters')
    parametersMatch = isstruct(lengthContract.registeredParameters) && ...
        isscalar(lengthContract.registeredParameters) && ...
        isequaln(orderfields(lengthContract.registeredParameters), ...
            orderfields(specification.registeredParameters));
    if ~parametersMatch
        mismatch{end+1} = ...
            'gaugeContract.length.registeredParameters';
    end
end
if isfield(lengthContract,'phaseInterpretation') && ...
        ~text_matches(lengthContract.phaseInterpretation, ...
            expected_phase_interpretation(specification.lengthGauge))
    mismatch{end+1} = 'gaugeContract.length.phaseInterpretation';
end
expectedAmplitudeFormula = [ ...
    'c_omega=-sum(w*(R_X*B_X+R_Y*B_Y))/' ...
    'sum(w*(R_X^2+R_Y^2))'];
if isfield(amplitudeContract,'formula') && ...
        ~text_matches(amplitudeContract.formula,expectedAmplitudeFormula)
    mismatch{end+1} = 'gaugeContract.amplitude.formula';
end
if isfield(amplitudeContract,'observable') && ...
        ~text_matches(amplitudeContract.observable, ...
            'global_discrete_gradient_energy')
    mismatch{end+1} = 'gaugeContract.amplitude.observable';
end
if isfield(amplitudeContract,'evaluation') && ...
        ~text_matches(amplitudeContract.evaluation,'fixed_grid_quadrature')
    mismatch{end+1} = 'gaugeContract.amplitude.evaluation';
end
strengthenedPassed = corePassed && isempty(missing) && isempty(mismatch);
end

