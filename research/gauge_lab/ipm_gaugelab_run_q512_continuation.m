        gradientAlgebra = audit_gradient_gauge_algebra(common,gauge);
        selectedAlgebra = gradientAlgebra;
    else
        quadraticAlgebra = audit_quadratic_gauge_algebra(common,gauge);
        selectedAlgebra = quadraticAlgebra;
    end
end
passed = complete && finite && selectedAlgebra.passed;
audit = struct( ...
    'gaugeName',gaugeName, ...
    'sharedRequiredFields',{sharedRequired}, ...
    'gaugeSpecificRequiredFields',{specificRequired}, ...
    'complete',complete,'finite',finite, ...
    'selectedGaugeAlgebra',selectedAlgebra, ...
    'gradientGaugeAlgebra',gradientAlgebra, ...
    'quadraticGaugeAlgebra',quadraticAlgebra, ...
    'noFeedbackHistory',noFeedback, ...
    'maximumOmegaGaugeResidual',maximumOmega, ...
    'maximumNormalizedLengthGaugeResidual',maximumLength, ...
    'maximumNormalizedTransportAnchorDefect',maximumTransport, ...
    'maximumNormalizedCanonicalTransportAnchorDefect', ...
        maximumCanonicalTransport);
end

function [complete,finite] = finite_history_fields(group,names,count)
