function width = common_wall_half_maximum_width(result)
x = result.grid.physicalX(:)';
wall = result.physical.omega(1,:);
[peak,peakIndex] = max(wall);
if ~isfinite(peak) || peak <= 0
    error('ipm:GaugeLabCLCflWallWidth', ...
        'The terminal physical wall omega has no positive finite peak.');
end
threshold = 0.5*peak;
left = peakIndex;
while left > 1 && wall(left-1) >= threshold
    left = left-1;
end
right = peakIndex;
while right < numel(wall) && wall(right+1) >= threshold
    right = right+1;
end
if left == 1 || right == numel(wall)
    error('ipm:GaugeLabCLCflWallWidth', ...
        ['The terminal physical wall-omega half-maximum component is ' ...
        'not interior.']);
end
leftCrossing = linear_crossing( ...
    x(left-1:left),wall(left-1:left),threshold);
rightCrossing = linear_crossing( ...
    x(right:right+1),wall(right:right+1),threshold);
width = rightCrossing-leftCrossing;
if ~isfinite(width) || width <= 0
    error('ipm:GaugeLabCLCflWallWidth', ...
        'The common terminal wall-omega half-maximum width is invalid.');
end
end

function crossing = linear_crossing(x,values,threshold)
difference = values(2)-values(1);
if difference == 0
    error('ipm:GaugeLabCLCflWallWidth', ...
        'A terminal wall-omega half-maximum crossing has zero slope.');
end
fraction = (threshold-values(1))/difference;
crossing = x(1)+fraction*(x(2)-x(1));
end

