noFeedback = false;
gradientAlgebra = empty_gradient_gauge_audit();
quadraticAlgebra = empty_quadratic_gauge_audit();
selectedAlgebra = empty_selected_gauge_audit(gaugeName);
if finite
    maximumOmega = max(abs(gauge.omegaGaugeResidual));
    maximumLength = max(normalized_anchor_residual( ...
        gauge.lengthGaugeResidual,gauge.c_lNominal, ...
        gauge.transportAnchorX));
    maximumTransport = max(normalized_anchor_residual( ...
        gauge.transportAnchorVelocity,gauge.c_lNominal, ...
