function audit = requested_endpoint_audit(result,settings,config)
state = result.state;
roundoffPhysical = endpoint_roundoff(settings.physicalFinalTime);
roundoffCanonical = endpoint_roundoff(settings.canonicalFinalTime);
physicalClockSpeed = result.scale.Comega/result.scale.Cx;
physicalStopTolerance = max(roundoffPhysical, ...
    config.time.minDt*physicalClockSpeed*(1+100*eps));
canonicalStopTolerance = max(roundoffCanonical,config.time.minDt);
physicalRemainder = settings.physicalFinalTime-state.physicalTime;
canonicalRemainder = settings.canonicalFinalTime-state.canonicalTime;
physicalReached = strcmp(state.stopReason,'physical_final_time') && ...
    physicalRemainder >= -roundoffPhysical && ...
    physicalRemainder <= physicalStopTolerance && ...
    canonicalRemainder >= -roundoffCanonical;
canonicalReached = strcmp(state.stopReason,'final_time') && ...
    canonicalRemainder >= -roundoffCanonical && ...
    canonicalRemainder <= canonicalStopTolerance && ...
    physicalRemainder >= -roundoffPhysical;
audit = struct( ...
    'passed',physicalReached || canonicalReached, ...
    'acceptedPhysicalEndpoint',physicalReached, ...
    'acceptedCanonicalEndpoint',canonicalReached, ...
    'physicalRemainder',physicalRemainder, ...
    'canonicalRemainder',canonicalRemainder, ...
    'physicalStopTolerance',physicalStopTolerance, ...
    'canonicalStopTolerance',canonicalStopTolerance, ...
    'terminalPhysicalClockSpeed',physicalClockSpeed, ...
    'minimumCanonicalStep',config.time.minDt);
end

function tolerance = endpoint_roundoff(value)
tolerance = 100*eps(max(1,abs(value)));
end

