function gate = assess_screening_gate(screen,limits,gauges)
gate = empty_screening_gate();
gate.status = 'assessing';
target = target_comparison(screen.successiveComparisons, ...
    'gradient_energy',1e5,1e6);
quadraticTarget = target_comparison(screen.successiveComparisons, ...
    'wall_omega_quadratic_peak',1e5,1e6);
noneTarget = target_comparison(screen.successiveComparisons, ...
    'none',1e5,1e6);
gate.targetComparison = struct( ...
    'referenceHalfWidth',1e5,'candidateHalfWidth',1e6);
gate.gradientEnergy = assess_gradient_candidate(target,limits);
gate.wallOmegaQuadraticPeak = assess_quadratic_candidate( ...
    quadraticTarget,screen.boxes,limits);
gate.none = assess_none_candidate(noneTarget,screen.boxes,limits);
checks = struct();
checks.allPreflightsPassed = screen.preflightPassed;
checks.allInitialRhsCompleted = all(arrayfun(@(box)all(cellfun( ...
    @(gauge)strcmp(box.gaugeRuns.(gauge).status,'completed'), ...
    gauges)),screen.boxes));
checks.gradientNegativeControlRejected = ...
    gate.gradientEnergy.rejectedForExtensiveNormalization;
checks.quadraticCandidateAdmissible = ...
    gate.wallOmegaQuadraticPeak.eligible;
checks.noneExploratoryControlValid = gate.none.initialScreenPassed && ...
    gate.none.promotionBlocked;
gate.checks = checks;
gate.failures = failed_checks(checks);
gate.passed = isempty(gate.failures);
if gate.passed
    gate.status = 'passed';
    gate.decision = ...
        'quadratic_candidate_admissible_for_time_evolution_screen';
else
    gate.status = 'gate_failed';
    gate.decision = 'no_candidate_promotion_from_initial_box_screen';
end
end

function assessment = assess_none_candidate(comparison,boxes,limits)
