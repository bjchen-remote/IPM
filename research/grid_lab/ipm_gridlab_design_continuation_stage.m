function [candidates,summary] = build_current_axis_x_fallbacks( ...
        dataset,externalReferenceX,profiles,limits,stageOptions,summary)
candidates = repmat(candidate_template(),0,1);
equalization = stageOptions.equalizationOptions;
if equalization.currentIncrementalReferenceDepth >= ...
        equalization.maximumIncrementalReferenceDepth
    summary.status = 'maximum_incremental_reference_depth_reached';
    return
end

summary.attempted = true;
currentReferenceX = dataset.snapshots(1).x;
audit = audit_current_x_reference( ...
    currentReferenceX,externalReferenceX,limits);
summary.referenceAudit = audit;
if ~audit.passed
    summary.status = 'current_axis_reference_audit_failed';
    return
end
currentReferenceX = double(currentReferenceX(:)');
summary.usedAsReference = true;
summary.status = 'candidates_built';
summary.incrementalGeneration = ...
    equalization.currentIncrementalReferenceDepth+1;
summary.parentAxisSignature = axis_signature(currentReferenceX);

% Every sigma is evaluated against this immutable entry-axis copy.  A
% candidate produced earlier in this loop can therefore never become the
% reference for another candidate in the same design round.
for index = 1:numel(equalization.currentAxisXSigmas)
    sigma = equalization.currentAxisXSigmas(index);
    overrides = struct('sigma',sigma, ...
        'power',equalization.currentAxisXPower);
    record = build_equalized_x_candidate( ...
        currentReferenceX,profiles,limits,stageOptions,overrides);
    record.family = ...
        'anchored_incremental_global_logwidth_equalization';
    if isfield(record.model,'amplitude')
        record.name = sprintf( ...
            'x_incremental_anchored_sigma_%.12g_A_%.12g', ...
            sigma,record.model.amplitude);
    else
        record.name = sprintf( ...
            'x_incremental_anchored_sigma_%.12g_failed',sigma);
    end
    record.model.kind = record.family;
    record.model.gridlabFamily = record.family;
    record.model.referenceProvenance = ...
        'trusted_terminal_axis_single_hop';
    record.model.parentAxisSignature = ...
        summary.parentAxisSignature;
    record.model.incrementalGeneration = ...
        summary.incrementalGeneration;
    record.model.referenceSnapshotIndex = 1;
    record.model.referenceAuditPassed = true;
    record.model.sameRoundRecursiveReference = false;
    if ~isfield(record.model,'anchorEnabled') || ...
            ~record.model.anchorEnabled
        record.status = 'incremental_anchor_required';
        record.admissible = false;
        record.meetsCoreTarget = false;
        record.meetsFrontTarget = false;
        record.meetsTargets = false;
        record.errorIdentifier = ...
            'ipm:gridlab:StageDesignIncrementalAnchor';
        record.errorMessage = [ ...
            'Current-axis incremental fallback requires a strict ' ...
            'common core/front anchor.'];
    end
    candidates(end+1,1) = record; %#ok<AGROW>
end
end

function audit = audit_current_x_reference(axis,externalReference,limits)
reasons = {};
quality = struct();
quadratureWeightsStrictlyPositive = false;
if ~(isnumeric(axis) && isvector(axis) && isreal(axis) && ...
        all(isfinite(axis(:))))
    reasons{end+1} = 'axis_not_finite_real_numeric_vector';
else
    axis = double(axis(:)');
    if numel(axis) ~= numel(externalReference)
        reasons{end+1} = 'node_count_mismatch';
    end
    if mod(numel(axis),2) ~= 1
        reasons{end+1} = 'node_count_not_odd';
    end
    if numel(axis) < 2 || any(diff(axis) <= 0)
        reasons{end+1} = 'axis_not_strictly_increasing';
    end
    if numel(axis) >= 2 && ...
            ~matching_endpoints(axis,externalReference)
        reasons{end+1} = 'domain_endpoint_mismatch';
    end
    tolerance = 1e3*eps(max(1,max(abs(axis))));
    if mod(numel(axis),2) == 1 && ...
            max(abs(axis+fliplr(axis))) > tolerance
        reasons{end+1} = 'axis_not_symmetric';
    end
end
if isempty(reasons)
    try
        weights = ipm.mesh.quadrature(axis);
        quality = ipm.mesh.quality(axis,7,weights);
        quadratureWeightsStrictlyPositive = all(weights > 0);
        if quality.maximumAdjacentCellRatio > ...
                limits.maxAdjacentCellRatio
            reasons{end+1} = 'adjacent_cell_ratio';
        end
        if quality.maximumLogSpacingCurvature > ...
                limits.maxLogSpacingCurvature
            reasons{end+1} = 'log_spacing_curvature';
        end
        if quality.minimumStencilRcond < limits.minStencilRcond
            reasons{end+1} = 'stencil_conditioning';
        end
        if quality.minimumQuadratureWeightRatio < ...
                limits.minQuadratureWeightRatio || ...
                ~quadratureWeightsStrictlyPositive
            reasons{end+1} = 'quadrature_margin';
        end
    catch exception
        reasons{end+1} = ...
            ['diagnostic_error:' exception.identifier];
    end
end
audit = struct('passed',isempty(reasons), ...
    'rejectionReasons',{reasons},'meshLimits',limits, ...
    'quality',quality, ...
    'quadratureWeightsStrictlyPositive', ...
        quadratureWeightsStrictlyPositive, ...
    'axisSignature',struct());
if audit.passed
    audit.axisSignature = axis_signature(axis);
end
end

function record = build_equalized_x_candidate( ...
        referenceX,profiles,limits,stageOptions,equalizeOverrides)
if nargin < 5
    equalizeOverrides = struct();
end
records = profiles.records;
positiveLimit = referenceX(end);
coreIntervals = zeros(numel(records),2);
frontIntervals = zeros(numel(records),2);
for index = 1:numel(records)
    coreIntervals(index,:) = [ ...
        max(0,records(index).safetyCoreCenter- ...
            records(index).safetyCoreWidthLeft), ...
        min(positiveLimit,records(index).safetyCoreCenter+ ...
            records(index).safetyCoreWidthRight)];
    frontIntervals(index,:) = [ ...
        max(0,records(index).leftFrontCenter- ...
            records(index).leftFrontHalfWidth), ...
        min(positiveLimit,records(index).leftFrontCenter+ ...
            records(index).leftFrontHalfWidth)];
end
intervals = [coreIntervals;frontIntervals];
targets = [repmat(stageOptions.targetXCoreCells,numel(records),1); ...
    repmat(stageOptions.minimumXFrontCells,numel(records),1)];
focusCenters = [[records.safetyCoreCenter], ...
    [records.leftFrontCenter]];
equalizeOptions = direct_equalize_options( ...
    stageOptions.equalizationOptions,limits,'symmetric', ...
    focusCenters,'x');
if isfield(equalizeOverrides,'sigma')
    equalizeOptions.sigma = equalizeOverrides.sigma;
end
if isfield(equalizeOverrides,'kernelKind')
    equalizeOptions.kernelKind = equalizeOverrides.kernelKind;
end
if isfield(equalizeOverrides,'corridorShoulderCells')
    equalizeOptions.corridorShoulderCells = ...
        equalizeOverrides.corridorShoulderCells;
end
if isfield(equalizeOverrides,'corridorExpansionShoulders')
    equalizeOptions.corridorExpansionShoulders = ...
        equalizeOverrides.corridorExpansionShoulders;
end
[anchorPosition,anchorProvenance] = combined_x_anchor( ...
    records,coreIntervals,frontIntervals,positiveLimit);
equalizeOptions.anchorPhysicalPosition = anchorPosition;
if anchorProvenance.enabled
    % One smooth focus avoids the derivative switch introduced by taking
    % the minimum distance to separate core and front focus centres.
    equalizeOptions.focusCenters = anchorPosition;
    if isfield(equalizeOverrides,'power')
        equalizeOptions.power = equalizeOverrides.power;
    else
        equalizeOptions.power = 2;
    end
end
anchorProvenance.requestedFocusCenters = focusCenters;
anchorProvenance.effectiveFocusCenters = equalizeOptions.focusCenters;
anchorProvenance.requestedKernelPower = ...
    stageOptions.equalizationOptions.xPower;
anchorProvenance.effectiveKernelPower = equalizeOptions.power;
anchorProvenance.kernelSigma = equalizeOptions.sigma;
try
    [axis,info] = ipm_gridlab_equalize_axis( ...
        referenceX,intervals,targets,equalizeOptions);
catch exception
    record = candidate_template();
    if anchorProvenance.enabled
        record.name = 'x_anchored_global_logwidth_equalization_failed';
        record.family = 'anchored_global_logwidth_equalization';
        formula = [ ...
            'log(h)=log(h_ref)-A*exp(-(d(r(u),r(F))/sigma)^p)' ...
            '+beta*(psi(u_cell)-psi(u_anchor))'];
        kernelCoordinateBasis = ...
            'r(u)=u*tanh(u/delta)/tanh(u_anchor/delta)';
    else
        record.name = 'x_global_logwidth_equalization_failed';
        record.family = 'direct_global_logwidth_equalization';
        formula = 'log(h)=log(h_ref)-A*exp(-(d(u,F)/sigma)^p)';
        kernelCoordinateBasis = 'reference_coordinate_u';
    end
    record.status = 'failed';
    record.model = struct( ...
        'kind',record.family, ...
        'gridlabFamily',record.family, ...
        'formula',formula, ...
        'sigma',equalizeOptions.sigma, ...
        'power',equalizeOptions.power, ...
        'focusCenters',equalizeOptions.focusCenters, ...
        'kernelCoordinateBasis',kernelCoordinateBasis, ...
        'anchorEnabled',anchorProvenance.enabled, ...
        'anchorPhysicalPosition',anchorPosition, ...
        'anchorProvenance',anchorProvenance);
    record.errorIdentifier = exception.identifier;
    record.errorMessage = exception.message;
    return
end
info.anchorProvenance = anchorProvenance;
[coreCounts,frontCounts] = x_resolution(axis,records);
record = candidate_template();
if info.anchorEnabled
    record.name = sprintf( ...
        'x_anchored_global_logwidth_equalized_A_%.12g',info.amplitude);
    record.family = 'anchored_global_logwidth_equalization';
else
    record.name = sprintf('x_global_logwidth_equalized_A_%.12g', ...
        info.amplitude);
    record.family = 'direct_global_logwidth_equalization';
end
record.model = equalization_model(info);
record = fill_candidate(record,axis,info,coreCounts,frontCounts);
record.status = info.status;
record.meetsCoreTarget = ...
    record.minimumCoreCells >= stageOptions.targetXCoreCells;
record.meetsFrontTarget = ...
    record.minimumFrontCells >= stageOptions.minimumXFrontCells;
record.meetsTargets = record.admissible && ...
    record.meetsCoreTarget && record.meetsFrontTarget;
end

function [position,provenance] = combined_x_anchor( ...
        records,coreIntervals,frontIntervals,positiveLimit)
coreCenters = double([records.safetyCoreCenter]);
frontCenters = double([records.leftFrontCenter]);
allIntervals = [coreIntervals;frontIntervals];
intersection = [max(allIntervals(:,1)),min(allIntervals(:,2))];
tolerance = 1024*eps(max(1,positiveLimit));
candidatePosition = 0.5*sum(intersection);
if all(isfinite(intersection)) && ...
        intersection(2)-intersection(1) > tolerance && ...
        candidatePosition > 0 && candidatePosition < positiveLimit
    position = candidatePosition;
    enabled = true;
    reason = 'strict_common_interval_midpoint';
else
    position = [];
    enabled = false;
    reason = 'no_strictly_interior_common_interval';
end
provenance = struct( ...
    'enabled',enabled, ...
    'policy','all_record_core_front_common_intersection_midpoint', ...
    'reason',reason, ...
    'physicalPosition',position, ...
    'trustedRecordCount',numel(records), ...
    'positiveDomainLimit',positiveLimit, ...
    'commonIntersection',intersection, ...
    'coreIntervals',coreIntervals, ...
    'leftFrontIntervals',frontIntervals, ...
    'coreCenters',coreCenters, ...
    'leftFrontCenters',frontCenters, ...
    'focusPolicy','single_anchor_focus_when_enabled', ...
    'anchoredKernelPower',2);
end

