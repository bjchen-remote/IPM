function [stageError,aspectError,sourceError] = fixed_rate_ssprk_check()
userOpts = struct('nx',33,'ny',17,'xlim',[-4,4],'ymax',4, ...
    'gridMode','uniform','gridStretch',0, ...
    'farBoundaryMode','dirichlet_zero', ...
    'transportScheme','muscl_minmod','symmetryMode','half_plane', ...
    'rescalingMode','dynamic','dynamicScaleGeometry','anisotropic', ...
    'anisotropicGaugeMode','fixed','anisotropicFixedCX',0.35, ...
    'anisotropicFixedCY',-0.2,'anisotropicFixedCOmega',0.1, ...
    'anisotropicFixedCR',0.05, ...
    'initialCondition','degenerate','adaptiveRemesh',false, ...
    'saveResults',false,'makePlots',false,'livePlot',false, ...
    'writeVideo',false,'verbose',false);
config = ipm.config.resolve(userOpts);
ops = ipm.mesh.build(config);
rho = ipm.field.initialDensity(ops,config.physics);
ops = ipm.evolve.initializeScaling(rho,ops);
scale = struct('logC_l',0,'logC_x',0,'logC_y',0, ...
    'logC_omega',0,'physicalTime',0,'X_shift',0,'canonicalTime',0);
dt = 0.02;
[rhoActual,flowActual,scaleActual] = ...
    ipm.evolve.stepSsprk3(rho,dt,ops,scale);
[rhoOracle,~,scaleOracle] = anisotropic_step_oracle(rho,dt,ops,scale);
stageError = max(abs(rhoActual-rhoOracle),[],'all');
stageError = max([stageError,abs(scaleActual.logC_l-scaleOracle.logC_l), ...
    abs(scaleActual.logC_y-scaleOracle.logC_y), ...
    abs(scaleActual.logC_omega-scaleOracle.logC_omega), ...
    abs(scaleActual.physicalTime-scaleOracle.physicalTime), ...
    abs(scaleActual.X_shift-scaleOracle.X_shift), ...
    abs(scaleActual.canonicalTime-scaleOracle.canonicalTime)]);
expectedAspect = exp(scaleActual.logC_y-scaleActual.logC_l);
aspectError = max([abs(flowActual.aspect-expectedAspect), ...
    abs(flowActual.poissonSolveInfo.kappa-expectedAspect)]);
sourceError = abs(flowActual.canonicalConservativeSource-( ...
    config.scaling.anisotropicFixedCX+ ...
    config.scaling.anisotropicFixedCY+ ...
    config.scaling.anisotropicFixedCOmega));
end

function [rhoNew,flow,scaleNew] = ...
    anisotropic_step_oracle(rho,dt,ops,scale)
z = pack_scale(scale);
[k1,flow1] = ipm.evolve.rhs(rho,ops,unpack_scale(z));
q1 = rho+dt*k1;
z1 = z+dt*scale_rate(z,flow1);
[k2,flow2] = ipm.evolve.rhs(q1,ops,unpack_scale(z1));
q2 = 0.75*rho+0.25*(q1+dt*k2);
z2 = 0.75*z+0.25*(z1+dt*scale_rate(z1,flow2));
[k3,flow3] = ipm.evolve.rhs(q2,ops,unpack_scale(z2));
rhoNew = (rho+2*(q2+dt*k3))/3;
zNew = (z+2*(z2+dt*scale_rate(z2,flow3)))/3;
scaleNew = unpack_scale(zNew);
[~,flow] = ipm.evolve.rhs(rhoNew,ops,scaleNew);
end

function z = pack_scale(scale)
z = [scale.logC_l;scale.logC_y;scale.logC_omega;scale.physicalTime; ...
    scale.X_shift;scale.canonicalTime];
end

function scale = unpack_scale(z)
scale = struct('logC_l',z(1),'logC_x',z(1),'logC_y',z(2), ...
    'logC_omega',z(3),'physicalTime',z(4),'X_shift',z(5), ...
    'canonicalTime',z(6));
end

function dz = scale_rate(z,flow)
dz = [flow.c_x;flow.c_y;flow.c_omega; ...
    flow.timeSpeed*exp(z(3)-z(1)); ...
    flow.c_x*z(5)+flow.c_r;flow.timeSpeed];
end
