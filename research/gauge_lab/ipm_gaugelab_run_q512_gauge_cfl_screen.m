function counterfactual = counterfactual_from_quadratic_history( ...
        common,gauge,gaugeName)
required = {'omegaGaugeQuadraticPeakX', ...
    'omegaGaugeQuadraticPeakValue','omegaGaugeQuadraticForcing', ...
    'omegaGaugeQuadraticCurvature', ...
    'omegaGaugeQuadraticNormalizedStationarityResidual', ...
    'omegaGaugeQuadraticCurvatureCondition', ...
    'omegaGaugeQuadraticWeightCondition', ...
    'omegaGaugeQuadraticActiveNodeMargin', ...
    'omegaGaugeQuadraticActiveSelectionMargin', ...
    'omegaGaugeQuadraticStencilCenterX', ...
    'omegaGaugeQuadraticVertexInteriorFraction', ...
    'omegaGaugeQuadraticRelativeSubgridLift', ...
    'omegaGaugeQuadraticRateResidual', ...
    'omegaGaugeQuadraticRateScale'};
require_history(gauge,required,'history.gauge');
peak = gauge.omegaGaugeQuadraticPeakValue(:);
forcing = gauge.omegaGaugeQuadraticForcing(:);
implied = -forcing./peak;
if strcmp(gaugeName,'wall_omega_quadratic_peak')
    runtime = common.c_omega(:);
    evaluationMode = 'active_gauge_history_independent_F_over_P';
else
    % Under `none`, the maintained solver records F and P without using
    % -F/P as its selected rate.  The independently reconstructed value is
    % therefore the counterfactual runtime value for agreement purposes.
    runtime = implied;
    evaluationMode = ...
        'selected_none_history_counterfactual_independent_F_over_P';
end
counterfactual = struct( ...
    'peakX',gauge.omegaGaugeQuadraticPeakX(:), ...
    'peakValue',peak, ...
    'forcing',forcing, ...
    'impliedCOmega',implied, ...
    'counterfactualQuadraticCOmega',implied, ...
    'runtimeQuadraticCOmega',runtime, ...
    'runtimeCOmegaAgreement',runtime-implied, ...
    'gaugeRateResidual',forcing+implied.*peak, ...
    'gaugeRateScale',max([abs(forcing),abs(implied.*peak), ...
        realmin*ones(size(peak))],[],2), ...
    'selectedRateResidual',forcing+common.c_omega(:).*peak, ...
    'curvature',gauge.omegaGaugeQuadraticCurvature(:), ...
    'normalizedStationarityResidual', ...
        gauge.omegaGaugeQuadraticNormalizedStationarityResidual(:), ...
    'curvatureCondition', ...
        gauge.omegaGaugeQuadraticCurvatureCondition(:), ...
    'weightCondition',gauge.omegaGaugeQuadraticWeightCondition(:), ...
    'activeNodeMargin',gauge.omegaGaugeQuadraticActiveNodeMargin(:), ...
    'activeSelectionMargin', ...
        gauge.omegaGaugeQuadraticActiveSelectionMargin(:), ...
    'stencilCenterX',gauge.omegaGaugeQuadraticStencilCenterX(:), ...
    'vertexInteriorFraction', ...
        gauge.omegaGaugeQuadraticVertexInteriorFraction(:), ...
    'relativeSubgridLift', ...
        gauge.omegaGaugeQuadraticRelativeSubgridLift(:), ...
    'recordedRateResidual',gauge.omegaGaugeQuadraticRateResidual(:), ...
    'recordedRateScale',gauge.omegaGaugeQuadraticRateScale(:), ...
    'stencilSwitchCount',count_stencil_switches( ...
        gauge.omegaGaugeQuadraticStencilCenterX(:)), ...
    'evaluationMode',evaluationMode);
end

