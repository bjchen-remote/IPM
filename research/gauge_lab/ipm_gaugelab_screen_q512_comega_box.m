function checks = runtime_checks(run,gauge,limits)
rates = run.rates;
quadratic = run.wallQuadraticPeak;
checks = struct();
checks.finiteRates = all(isfinite([rates.c_l,rates.c_omega, ...
    rates.c_r,rates.kappa]));
checks.directClock = rates.timeSpeed == 1;
checks.exactLengthGauge = abs(rates.lengthGaugeResidual) <= ...
    1e-12*max(abs(rates.c_l),1);
checks.anchorVelocityZero = abs(rates.transportAnchorVelocity) <= ...
    1e-12*max(abs(rates.c_l),1);
gradient = run.gradientEnergy;
checks.finiteGradientDiagnostics = all(isfinite([ ...
    gradient.energyX,gradient.energyY,gradient.energy, ...
    gradient.forcingX,gradient.forcingY,gradient.forcing, ...
    gradient.absoluteForcing,gradient.impliedCOmega, ...
    gradient.candidateCancellation, ...
    gradient.candidateNormalizedCancellation, ...
    gradient.energyYFraction,gradient.forcingYFraction, ...
    gradient.energyPerXWidth,gradient.forcingPerXWidth]));
far = run.farBoundary;
checks.finiteFarBoundaryDiagnostics = all(isfinite([ ...
    far.source,far.sourceRatio,far.velocity,far.velocityRatio, ...
    far.uInf,far.omegaInf,far.outerBandFraction]));
checks.finiteQuadraticDiagnostics = all(isfinite([ ...
    quadratic.peakIndex,quadratic.stencilIndices, ...
    quadratic.stencilWeights,quadratic.peakX,quadratic.peakValue, ...
    quadratic.forcing,quadratic.impliedCOmega, ...
    quadratic.candidateRateResidual, ...
    quadratic.candidateNormalizedRateResidual, ...
    quadratic.curvature, ...
    quadratic.normalizedStationarityResidual, ...
    quadratic.curvatureCondition,quadratic.weightCondition, ...
    quadratic.activeNodeMargin,quadratic.activeSelectionMargin, ...
    quadratic.stencilCenterX,quadratic.vertexInteriorFraction, ...
    quadratic.relativeSubgridLift]));
switch gauge
    case 'wall_omega_quadratic_peak'
        checks.quadraticRuntimeAgreement = isfinite( ...
            quadratic.runtimeAgreementMaximumRelativeError) && ...
            quadratic.runtimeAgreementMaximumRelativeError <= ...
            limits.maximumQuadraticRuntimeAgreementError;
        checks.quadraticGaugeResidual = abs( ...
            quadratic.candidateNormalizedRateResidual) <= 1e-12;
    case 'gradient_energy'
        checks.gradientGaugeResidual = abs( ...
            run.gradientEnergy.candidateNormalizedCancellation) <= 1e-12;
    case 'none'
        checks.noneGaugeExact = rates.c_omega == 0 && ...
            rates.canonicalCOmega == 0 && rates.omegaGaugeResidual == 0;
    otherwise
        checks.registeredGauge = false;
end
end

function comparisons = successive_comparisons(boxes,gauges)
comparisons = repmat(empty_comparison(), ...
    (numel(boxes)-1)*numel(gauges),1);
cursor = 0;
for gaugeIndex = 1:numel(gauges)
    gauge = gauges{gaugeIndex};
    for boxIndex = 1:numel(boxes)-1
        cursor = cursor+1;
        comparison = empty_comparison();
        comparison.gauge = gauge;
        comparison.referenceHalfWidth = boxes(boxIndex).boxHalfWidth;
        comparison.candidateHalfWidth = boxes(boxIndex+1).boxHalfWidth;
        reference = boxes(boxIndex).gaugeRuns.(gauge);
        candidate = boxes(boxIndex+1).gaugeRuns.(gauge);
        if strcmp(reference.status,'completed') && ...
                strcmp(candidate.status,'completed')
            comparison.available = true;
            comparison.status = 'compared';
            comparison.relativeDifferences = scalar_differences( ...
                reference,candidate);
            comparison.growthRatios = scalar_growth_ratios( ...
                reference,candidate,comparison.referenceHalfWidth, ...
                comparison.candidateHalfWidth);
        else
            comparison.status = 'rhs_unavailable';
        end
        comparisons(cursor) = comparison;
    end
end
end

