function validate_q512_config(config,nx,ny)
if nx ~= 1025 || ny ~= 513
    error('ipm:gridlab:CampaignResolution', ...
        ['This driver is restricted to 1025-by-513 stored nodes ' ...
        '(q512 quadrant cells); received %d-by-%d.'],nx,ny);
end
transport = config.transport;
scaling = config.scaling;
requiredTuple = strcmp(transport.spatialDiscretization,'high_order') && ...
    strcmp(transport.transportScheme,'weno5_fd') && ...
    strcmp(config.time.timeIntegrator,'ssprk54') && ...
    strcmp(config.remesh.remeshTransferScheme,'high_order');
if ~requiredTuple
    error('ipm:gridlab:CampaignNumericalTuple', ...
        'This driver requires high_order/weno5_fd/ssprk54/high_order.');
end
if ~strcmp(scaling.rescalingMode,'dynamic') || ...
        ~strcmp(scaling.dynamicScaleGeometry,'isotropic')
    error('ipm:gridlab:CampaignScaleGeometry', ...
        'This driver requires dynamic isotropic rescaling.');
end
if ~strcmp(config.physics.symmetryMode,'double_odd_omega')
    error('ipm:gridlab:CampaignSymmetry', ...
        'This driver requires double_odd_omega symmetry.');
end
levels = double(scaling.adaptiveLevels(:)');
requiredLevels = [0.1,0.5,0.9];
if numel(levels) ~= numel(requiredLevels) || ...
        max(abs(levels-requiredLevels)) > 64*eps
    error('ipm:gridlab:CampaignCoreLevels', ...
        ['This driver fixes adaptiveLevels=[0.1 0.5 0.9] so every ' ...
        'reported terminal core is the strict 0.9 connected component.']);
end
end

