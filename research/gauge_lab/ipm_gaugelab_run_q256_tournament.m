function [runs,display] = populate_baseline_display_comparisons( ...
        runs,baselineGauge,emptyComparison)
errorTemplate = struct('candidate','','identifier','','message','');
display = struct('usage','display_only_not_scored', ...
    'baselineGauge',baselineGauge,'available',false, ...
    'errors',repmat(errorTemplate,0,1));
baselineIndex = find(strcmp({runs.cOmegaGauge},baselineGauge) & ...
    cellfun(@isempty,{runs.errorIdentifier}) & ...
    ~cellfun(@isempty,{runs.resultFile}),1,'first');
if isempty(baselineIndex)
    return;
end
try
    baseline = ipm.output.validate(runs(baselineIndex).resultFile);
catch exception
    displayError = errorTemplate;
    displayError.candidate = baselineGauge;
    displayError.identifier = exception.identifier;
    displayError.message = exception.message;
    display.errors(end+1,1) = displayError;
    return;
end
display.available = true;
for index = 1:numel(runs)
    comparison = emptyComparison;
    comparable = ~isempty(runs(index).cOmegaGauge) && ...
        isempty(runs(index).errorIdentifier) && ...
        ~isempty(runs(index).resultFile);
    if comparable
        try
            if index == baselineIndex
                comparison = zero_comparison(emptyComparison);
            else
                candidate = ipm.output.validate(runs(index).resultFile);
                comparison = directional_physical_comparison( ...
                    baseline,candidate);
            end
        catch exception
            displayError = errorTemplate;
            displayError.candidate = runs(index).cOmegaGauge;
            displayError.identifier = exception.identifier;
            displayError.message = exception.message;
            display.errors(end+1,1) = displayError;
        end
    end
    runs(index).baselineDisplayComparison = comparison;
    % Historical alias retained for old plotting/reporting consumers only.
    runs(index).physicalComparison = comparison;
end
end

function comparison = zero_comparison(emptyComparison)
comparison = emptyComparison;
comparison.available = true;
names = comparison_metric_names();
for index = 1:numel(names)
    comparison.(names{index}) = 0;
end
end

function [runs,evidence] = evaluate_pairwise_covariance( ...
        runs,limits,emptyComparison,emptyPairwise,emptyPairRecord)
successful = false(size(runs));
for index = 1:numel(runs)
    successful(index) = ~isempty(runs(index).cOmegaGauge) && ...
        ~strcmp(runs(index).role,'negative_control') && ...
        isfield(runs(index).candidateSpecification, ...
        'productionCandidate') && ...
        runs(index).candidateSpecification.productionCandidate && ...
        isempty(runs(index).errorIdentifier) && ...
        ~isempty(runs(index).resultFile) && ...
        isfield(runs(index).audit,'hardPassed') && ...
        runs(index).audit.hardPassed;
    runs(index).pairwiseComparisons = repmat(emptyPairRecord,0,1);
    runs(index).pairwisePhysicalCovariance = emptyPairwise;
    runs(index).physicalCovariancePassed = false;
    runs(index).productionEligible = false;
    runs(index).artifactDisposition = 'failed_or_incomplete';
    runs(index).eligible = false;
end
competitors = find(successful);
competitorNames = {runs(competitors).cOmegaGauge};
for index = 1:numel(runs)
    summary = runs(index).pairwisePhysicalCovariance;
    summary.successfulCompetitorCount = numel(competitors);
    summary.requiredPeerCount = max(1,numel(competitors)-1);
    runs(index).pairwisePhysicalCovariance = summary;
end
errorTemplate = struct('candidateA','','candidateB','', ...
    'identifier','','message','');
evidence = struct();
evidence.method = 'symmetric_pairwise_bidirectional_worst';
evidence.successfulCompetitorDefinition = ...
    ['registered_production_candidate_with_hard_audit_passed_' ...
    'completed_without_error'];
evidence.minimumSuccessfulCompetitors = 2;
evidence.successfulCompetitorCount = numel(competitors);
evidence.successfulCompetitors = competitorNames;
evidence.requestedPairCount = ...
    numel(competitors)*(numel(competitors)-1)/2;
evidence.completedPairCount = 0;
evidence.errors = repmat(errorTemplate,0,1);

for firstPosition = 1:(numel(competitors)-1)
    firstIndex = competitors(firstPosition);
    for secondPosition = firstPosition+1:numel(competitors)
        secondIndex = competitors(secondPosition);
        firstRecord = emptyPairRecord;
        secondRecord = emptyPairRecord;
        firstRecord.peerGauge = runs(secondIndex).cOmegaGauge;
        secondRecord.peerGauge = runs(firstIndex).cOmegaGauge;
        try
            firstResult = ipm.output.validate(runs(firstIndex).resultFile);
            secondResult = ipm.output.validate(runs(secondIndex).resultFile);
            forward = directional_physical_comparison( ...
                firstResult,secondResult);
            reverse = directional_physical_comparison( ...
                secondResult,firstResult);
            symmetricWorst = symmetric_worst_comparison( ...
                forward,reverse,emptyComparison);
            pairPassed = covariance_passed(symmetricWorst,limits);
            firstRecord.available = true;
            firstRecord.forward = forward;
            firstRecord.reverse = reverse;
            firstRecord.symmetricWorst = symmetricWorst;
            firstRecord.passed = pairPassed;
            secondRecord.available = true;
            secondRecord.forward = reverse;
            secondRecord.reverse = forward;
            secondRecord.symmetricWorst = symmetricWorst;
            secondRecord.passed = pairPassed;
            evidence.completedPairCount = evidence.completedPairCount+1;
        catch exception
            firstRecord.errorIdentifier = exception.identifier;
            firstRecord.errorMessage = exception.message;
            secondRecord.errorIdentifier = exception.identifier;
            secondRecord.errorMessage = exception.message;
            pairError = errorTemplate;
            pairError.candidateA = runs(firstIndex).cOmegaGauge;
            pairError.candidateB = runs(secondIndex).cOmegaGauge;
            pairError.identifier = exception.identifier;
            pairError.message = exception.message;
            evidence.errors(end+1,1) = pairError;
        end
        runs(firstIndex).pairwiseComparisons(end+1,1) = firstRecord;
        runs(secondIndex).pairwiseComparisons(end+1,1) = secondRecord;
    end
end

for position = 1:numel(competitors)
    index = competitors(position);
    records = runs(index).pairwiseComparisons;
    summary = emptyPairwise;
    summary.successfulCompetitorCount = numel(competitors);
    summary.requiredPeerCount = max(1,numel(competitors)-1);
    summary.peerCount = nnz([records.available]);
    summary.peers = {records.peerGauge};
    summary.available = numel(competitors) >= 2 && ...
        numel(records) == numel(competitors)-1 && ...
        all([records.available]);
    if summary.available
        summary.worst = aggregate_pairwise_worst( ...
            records,emptyComparison);
        summary.passed = covariance_passed(summary.worst,limits);
    end
    runs(index).pairwisePhysicalCovariance = summary;
    runs(index).physicalCovariancePassed = summary.passed;
    if strcmp(runs(index).failureClass,'target_reached') && ...
            summary.available && ~summary.passed
        runs(index).failureClass = 'numerical_gate_failure';
    end
    runs(index).productionEligible = summary.passed && ...
        isfield(runs(index).audit,'productionEligible') && ...
        runs(index).audit.productionEligible;
    runs(index).eligible = runs(index).productionEligible;
    if runs(index).productionEligible
        runs(index).artifactDisposition = 'production_candidate';
    elseif isfield(runs(index).audit,'artifactDisposition') && ...
            strcmp(runs(index).audit.artifactDisposition, ...
            'read_only_history')
        runs(index).artifactDisposition = 'read_only_history';
    end
end
evidence.available = numel(competitors) >= 2 && ...
    isempty(evidence.errors) && ...
    evidence.completedPairCount == evidence.requestedPairCount;
end

function comparison = directional_physical_comparison(reference,candidate)
comparison = ipm.output.compare(reference,candidate,[-2,2,2]);
comparison.available = true;
comparison.physicalTimeDifference = ...
    candidate.state.physicalTime-reference.state.physicalTime;
comparison.physicalRhoXRelativeDifference = relative_difference( ...
    reference.history.common.physicalRhoXInf(end), ...
    candidate.history.common.physicalRhoXInf(end));
end

function worst = symmetric_worst_comparison( ...
        forward,reverse,emptyComparison)
worst = emptyComparison;
worst.available = forward.available && reverse.available;
names = comparison_metric_names();
for index = 1:numel(names)
    name = names{index};
    worst.(name) = max(abs([forward.(name),reverse.(name)]));
end
end

function worst = aggregate_pairwise_worst(records,emptyComparison)
worst = emptyComparison;
worst.available = ~isempty(records) && all([records.available]);
names = comparison_metric_names();
for nameIndex = 1:numel(names)
    name = names{nameIndex};
    values = NaN(numel(records),1);
    for recordIndex = 1:numel(records)
        values(recordIndex) = ...
            records(recordIndex).symmetricWorst.(name);
    end
    worst.(name) = max(values);
end
end

function names = comparison_metric_names()
names = {'rhoRelativeL2','omegaRelativeL2','rhoAbsoluteInf', ...
    'omegaAbsoluteInf','labPeakShift','physicalTimeDifference', ...
    'physicalRhoXRelativeDifference','wallPeakRelativeDifference', ...
    'wallWidthRelativeDifference'};
end

function passed = covariance_passed(comparison,limits)
passed = comparison.available && ...
    isfinite(comparison.physicalTimeDifference) && ...
    abs(comparison.physicalTimeDifference) <= ...
        limits.maximumAbsolutePhysicalTimeDifference && ...
    isfinite(comparison.labPeakShift) && ...
    abs(comparison.labPeakShift) <= limits.maximumAbsoluteLabPeakShift && ...
    isfinite(comparison.rhoAbsoluteInf) && ...
    comparison.rhoAbsoluteInf <= limits.rhoAbsoluteInf && ...
    isfinite(comparison.omegaAbsoluteInf) && ...
    comparison.omegaAbsoluteInf <= limits.omegaAbsoluteInf && ...
    isfinite(comparison.physicalRhoXRelativeDifference) && ...
    abs(comparison.physicalRhoXRelativeDifference) <= ...
        limits.physicalRhoXRelativeDifference && ...
    comparison.rhoRelativeL2 <= limits.rhoRelativeL2 && ...
    comparison.omegaRelativeL2 <= limits.omegaRelativeL2 && ...
    abs(comparison.wallPeakRelativeDifference) <= ...
        limits.wallPeakRelativeDifference && ...
    abs(comparison.wallWidthRelativeDifference) <= ...
        limits.wallWidthRelativeDifference;
end

function value = relative_difference(reference,candidate)
value = (candidate-reference)/max(abs(reference),eps);
end

function value = normalize_flag(value,name)
validLogical = islogical(value) && isscalar(value);
validNumeric = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && any(value == [0,1]);
if ~(validLogical || validNumeric)
    error('ipm:GaugeLabBoolean','%s must be logical or numeric 0/1.',name);
end
value = logical(value);
end

function classification = classify_exception(exception)
identifier = char(exception.identifier);
if is_gauge_design_identifier(identifier)
    classification = 'designed_gauge_failure';
elseif is_mesh_grid_identifier(identifier)
    classification = 'mesh_grid_gate_failure';
elseif is_numerical_identifier(identifier)
    classification = 'numerical_failure';
else
    classification = 'unexpected_error';
end
end

function classification = classify_stop_reason(stopReason)
stopReason = char(stopReason);
switch stopReason
    case 'physical_final_time'
        classification = 'target_reached';
    case {'gradient_threshold','maximum_principle_violation', ...
            'wall_profile_oscillation','final_time','maximum_steps'}
        classification = 'designed_safety_stop';
    case {'grid_smoothness_failure','grid_resolution_failure', ...
            'time_step_below_minimum','non_finite_solution'}
        classification = 'numerical_gate_failure';
    otherwise
        classification = 'unexpected_error';
end
end

function classification = classify_audit_failure(audit)
reasons = strsplit(char(audit.hardFailureReason),',');
reasons = reasons(~cellfun(@isempty,reasons));
gaugePrefixes = {'candidate_specification','dynamic_isotropic', ...
    'transport_anchor','fixed_localization','schema4_exact_no_feedback', ...
    'exact_no_feedback','retired_adaptive','direct_canonical_clock', ...
    'anchor_','window_','template_','bulk_','amplitude_gauge'};
isGauge = false(size(reasons));
for index = 1:numel(reasons)
    isGauge(index) = any(startsWith(strtrim(reasons{index}), ...
        gaugePrefixes));
end
if ~isempty(isGauge) && all(isGauge)
    classification = 'designed_gauge_failure';
elseif any(isGauge)
    classification = 'mixed_gauge_numerical_gate_failure';
else
    classification = 'numerical_gate_failure';
end
end

