finalQualityFieldsPresent = ...
    isfield(quality,'omegaGaugeQuadraticPeakValue') && ...
    isfield(quality,'omegaGaugeQuadraticCurvatureCondition') && ...
    isfield(quality,'omegaGaugeQuadraticWeightCondition') && ...
    isfield(quality,'omegaGaugeQuadraticActiveNodeMargin') && ...
    isfield(quality,'omegaGaugeQuadraticVertexInteriorFraction') && ...
    isfield(quality,'omegaGaugeQuadraticRateResidual');
contract = ipm.evolve.gaugeContract(options,ops);
contractRecorded = strcmp(contract.amplitude.name, ...
        'wall_omega_quadratic_peak') && ...
    strcmp(contract.amplitude.observable, ...
        'tracked_wall_omega_quadratic_peak') && ...
    strcmp(contract.amplitude.evaluation, ...
        'active_nonuniform_three_node_quadratic_vertex');
degenerateCasesRejected = ...
    quadratic_peak_rejected([1,0,0],[0,1,2],1) && ...
    quadratic_peak_rejected([0,0,0],[0,1,2],2) && ...
    quadratic_peak_rejected([1,0,1],[0,1,2],2);
syntheticX = [0,1,3];
syntheticValues = 2-(syntheticX-1.4).^2;
syntheticRate = [0.7,-0.2,1.1];
syntheticPeak = ipm.evolve.quadraticPeakFunctional( ...
    syntheticValues,syntheticX,2);
perturbation = 1e-5;
plusPeak = ipm.evolve.quadraticPeakFunctional( ...
    syntheticValues+perturbation*syntheticRate,syntheticX,2);
minusPeak = ipm.evolve.quadraticPeakFunctional( ...
    syntheticValues-perturbation*syntheticRate,syntheticX,2);
finiteDifferenceRate = (plusPeak.value-minusPeak.value)/(2*perturbation);
envelopeDerivativeError = abs(finiteDifferenceRate - ...
    sum(syntheticPeak.weights.*syntheticRate));

check = struct( ...
    'formulaError',formulaError, ...
    'rateResidual',abs(flow.omegaGaugeQuadraticRateResidual), ...
    'residualReconstructionError',abs(reconstructedResidual), ...
    'recordedResidualError',abs( ...
        recorded.history.gauge.omegaGaugeQuadraticRateResidual(end) - ...
        flowAfter.omegaGaugeQuadraticRateResidual), ...
    'amplitudeRateError',amplitudeRateError, ...
    'amplitudeRhsError',amplitudeRhsError, ...
    'shortStepRelativePeakDrift',abs( ...
        flowAfter.omegaGaugeQuadraticPeakValue-peak.value)/peak.value, ...
    'curvature',flow.omegaGaugeQuadraticCurvature, ...
    'curvatureCondition',flow.omegaGaugeQuadraticCurvatureCondition, ...
    'weightCondition',flow.omegaGaugeQuadraticWeightCondition, ...
    'activeNodeMargin',flow.omegaGaugeQuadraticActiveNodeMargin, ...
    'vertexInteriorFraction', ...
        flow.omegaGaugeQuadraticVertexInteriorFraction, ...
    'weightSumError',abs(sum(peak.weights)-1), ...
    'envelopeDerivativeError',envelopeDerivativeError, ...
    'historyFieldsPresent',historyFieldsPresent, ...
    'finalQualityFieldsPresent',finalQualityFieldsPresent, ...
    'contractRecorded',contractRecorded, ...
    'degenerateCasesRejected',degenerateCasesRejected, ...
    'shortStepFinite',all(isfinite(rhoAfter),'all') && ...
        all(cellfun(@(value)isnumeric(value) && isscalar(value) && ...
