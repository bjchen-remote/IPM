options = struct( ...
    'boxMode',settings.boxMode, ...
    'runMode','campaign', ...
    'confirmLongRun',true, ...
    'preflightOnly',~settings.execute, ...
    'outputRoot',outputRoot, ...
    'verbose',settings.verbose, ...
    'cfl',specification.cfl, ...
    'maxDt',settings.maxDt, ...
    'physicalFinalTime',settings.physicalFinalTime, ...
    'canonicalFinalTime',settings.canonicalFinalTime, ...
    'maxSteps',settings.maxSteps, ...
    'outputEvery',settings.outputEvery, ...
