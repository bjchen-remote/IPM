function audit = endpoint_audit(result,requested,config)
state = result.state;
roundoffPhysical = endpoint_roundoff(requested.physicalFinalTime);
roundoffCanonical = endpoint_roundoff(requested.finalTime);
physicalClockSpeed = result.scale.Comega/result.scale.Cx;
physicalTolerance = max(roundoffPhysical, ...
    config.time.minDt*physicalClockSpeed*(1+100*eps));
canonicalTolerance = max(roundoffCanonical,config.time.minDt);
physicalRemainder = requested.physicalFinalTime-state.physicalTime;
canonicalRemainder = requested.finalTime-state.canonicalTime;
physicalReached = strcmp(state.stopReason,'physical_final_time') && ...
    physicalRemainder >= -roundoffPhysical && ...
    physicalRemainder <= physicalTolerance && ...
    canonicalRemainder >= -roundoffCanonical;
canonicalReached = strcmp(state.stopReason,'final_time') && ...
    canonicalRemainder >= -roundoffCanonical && ...
    canonicalRemainder <= canonicalTolerance && ...
    physicalRemainder >= -roundoffPhysical;
audit = struct('passed',physicalReached || canonicalReached, ...
    'acceptedPhysicalEndpoint',physicalReached, ...
    'acceptedCanonicalEndpoint',canonicalReached, ...
    'physicalRemainder',physicalRemainder, ...
    'canonicalRemainder',canonicalRemainder, ...
    'physicalStopTolerance',physicalTolerance, ...
    'canonicalStopTolerance',canonicalTolerance);
end

function audit = maximum_steps_audit(result,requested,config,parentStep)
