function [directory,screenId] = create_output_directory(root)
if ~isfolder(root)
    mkdir(root);
end
stamp = char(datetime('now','TimeZone','UTC', ...
    'Format','yyyyMMdd''T''HHmmssSSS''Z'''));
[~,token] = fileparts(tempname);
screenId = sprintf('screen_%s_%s',stamp,token);
directory = fullfile(root,screenId);
if isfile(directory) || isfolder(directory)
    error('ipm:GaugeLabQ512COmegaBoxOutputCollision', ...
        'Output path already exists: %s',directory);
end
mkdir(directory);
end

