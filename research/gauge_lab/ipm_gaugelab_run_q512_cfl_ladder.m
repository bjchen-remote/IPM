function record = populate_from_root(record,rootRun,executed)
record.rootStatus = rootRun.status;
record.rootAccepted = any(strcmp(rootRun.status, ...
    {'preflight_only','completed'}));
record.boxMode = rootRun.boxMode;
record.runMode = rootRun.runMode;
record.preflightOnly = rootRun.preflightOnly;
record.freshStart = isequal(rootRun.freshStart,true);
record.restartInput = rootRun.restartInput;
record.rootSummaryFile = rootRun.summaryFile;
record.rootManifestFile = rootRun.manifestFile;
record.meshPassed = rootRun.meshPassed;
record.contractPassed = rootRun.contractPassed;
record.anchorNodeDistance = rootRun.meshAudit.anchorNodeDistance;
record.anchorIsGridNode = rootRun.meshAudit.anchorIsGridNode;
record.domain = rootRun.domain;
record.requested = rootRun.requested;
record.configSignature = config_signature(rootRun);
record.resultFile = rootRun.resultFile;
record.checkpointFile = rootRun.checkpointFile;
record.cost = struct( ...
    'steps',rootRun.steps, ...
    'wallSeconds',rootRun.wallSeconds, ...
    'wallSecondsPerStep',rootRun.wallSecondsPerStep);
record.stopReason = rootRun.stopReason;
record.status = rootRun.status;
if executed && ~isempty(rootRun.resultFile) && isfile(rootRun.resultFile)
    result = ipm.output.validate(rootRun.resultFile);
    record = summarize_result(record,result,rootRun);
    record.resultAvailable = true;
end
end

function record = summarize_result(record,result,rootRun)
common = result.history.common;
required = {'acceptedStep','canonicalTau','physicalTime','c_l', ...
    'c_omega','canonicalCL','canonicalCOmega','C_l','C_omega', ...
    'physicalRhoXInf','acceptedCanonicalDt','realizedCfl', ...
    'timestepActiveLimiter'};
require_history(common,required,'history.common');

terminal = numel(common.canonicalTau);
cL = common.canonicalCL(terminal);
cOmega = common.canonicalCOmega(terminal);
record.endpoint = struct( ...
    'canonicalTime',result.state.canonicalTime, ...
    'physicalTime',result.state.physicalTime, ...
    'physicalRhoXInf',common.physicalRhoXInf(terminal), ...
    'cL',cL, ...
    'cOmega',cOmega, ...
    'kappa',cL-cOmega, ...
    'cOmegaOverCL',safe_ratio(cOmega,cL), ...
    'cLMinusCOmegaOverCL',safe_ratio(cL-cOmega,cL), ...
    'C_l',common.C_l(terminal), ...
    'C_omega',common.C_omega(terminal), ...
    'physicalX',result.grid.physicalX([1,end]), ...
    'physicalY',result.grid.physicalY([1,end]), ...
    'comovingPhysicalX',result.grid.comovingPhysicalX([1,end]));
record.cost = struct( ...
    'steps',result.state.steps, ...
    'wallSeconds',rootRun.wallSeconds, ...
    'wallSecondsPerStep',rootRun.wallSecondsPerStep);
record.timestep = timestep_statistics( ...
    common,result.state.steps,record.cfl,result.config.time.maxDt, ...
    record.requested.outputEvery,result.config.time.minDt);
record.diagnostics = struct( ...
    'evidenceWindow','short_window_only', ...
    'lateTimeEvidence',false, ...
    'gaugeRateConvergence',result.fit.gaugeRateConvergence, ...
    'maximumGrowthRate',result.fit.maximumGrowthRate, ...
    'canonicalMaximumGrowth',result.fit.canonicalMaximumGrowth);
record.integrity = struct( ...
    'trustedTerminal',rootRun.postAudit.checks.continuousTrustedTerminal, ...
    'exactContract',rootRun.postAudit.checks.resultContract, ...
    'postAuditPassed',rootRun.postAudit.hardPassed, ...
    'postAuditFailures',{rootRun.postAudit.failures});
end

function statistics = timestep_statistics( ...
        common,steps,cfl,maxDt,outputEvery,minDt)
acceptedStep = common.acceptedStep(:);
acceptedDt = common.acceptedCanonicalDt(:);
realizedCfl = common.realizedCfl(:);
activeLimiter = string(common.timestepActiveLimiter(:));
accepted = isfinite(acceptedDt) & acceptedDt > 0;
recordedSteps = acceptedStep(accepted);
dtValues = acceptedDt(accepted);
cflValues = realizedCfl(accepted);
limiterValues = activeLimiter(accepted);

statistics = struct( ...
    'sampling','all_accepted_steps_requested', ...
    'outputEvery',outputEvery, ...
    'minimumAcceptedDt',minDt, ...
    'outputCadenceAtOrBelowMinimumDt',outputEvery <= minDt, ...
    'outputRecordCount',numel(acceptedStep), ...
    'acceptedStepSampleCount',nnz(accepted), ...
    'solverAcceptedSteps',steps, ...
    'completeAcceptedStepCoverage',false, ...
    'acceptedSteps',recordedSteps, ...
    'acceptedCanonicalDt',dtValues, ...
    'realizedCfl',cflValues, ...
    'activeLimiter',limiterValues, ...
    'acceptedCanonicalDtStatistics',distribution(dtValues), ...
    'realizedCflStatistics',distribution(cflValues), ...
    'activeLimiterCounts',limiter_counts(limiterValues), ...
    'requestedCfl',cfl, ...
    'requestedMaximumDt',maxDt, ...
    'maximumDtRespected',false, ...
    'maximumCflRespected',false);
if ~isempty(recordedSteps)
    uniqueSteps = unique(recordedSteps,'stable');
    statistics.completeAcceptedStepCoverage = ...
        numel(uniqueSteps) == steps && ...
        isequal(uniqueSteps(:),(1:steps)');
end
dtTolerance = 100*eps(max(1,maxDt));
cflTolerance = 100*eps(max(1,cfl));
statistics.maximumDtRespected = ~isempty(dtValues) && ...
    all(dtValues <= maxDt+dtTolerance);
statistics.maximumCflRespected = ~isempty(cflValues) && ...
    all(isfinite(cflValues)) && all(cflValues >= 0) && ...
    all(cflValues <= cfl+cflTolerance);
end

function values = distribution(samples)
values = struct('count',numel(samples),'minimum',NaN,'maximum',NaN, ...
    'mean',NaN,'median',NaN,'standardDeviation',NaN);
if isempty(samples) || any(~isfinite(samples))
    return
end
values.minimum = min(samples);
values.maximum = max(samples);
values.mean = mean(samples);
values.median = median(samples);
values.standardDeviation = std(samples,0);
end

function counts = limiter_counts(values)
known = ["max_dt","cfl","canonical_final_time", ...
    "physical_final_time"];
raw = zeros(size(known));
for index = 1:numel(known)
    raw(index) = nnz(values == known(index));
end
other = numel(values)-sum(raw);
denominator = max(numel(values),1);
counts = struct( ...
    'records',numel(values), ...
    'maxDt',raw(1), ...
    'cfl',raw(2), ...
    'canonicalFinalTime',raw(3), ...
    'physicalFinalTime',raw(4), ...
    'other',other, ...
    'maxDtFraction',raw(1)/denominator, ...
    'cflFraction',raw(2)/denominator, ...
    'canonicalFinalTimeFraction',raw(3)/denominator, ...
    'physicalFinalTimeFraction',raw(4)/denominator, ...
    'otherFraction',other/denominator);
end

function audit = shared_contract_audit(roots,settings,specifications)
checks = struct();
checks.twoRegisteredRoots = numel(roots) == 2;
checks.fixedCflCandidates = isequal([roots.cfl],[0.25,0.50]) && ...
    isequal([roots.cfl],[specifications.cfl]);
checks.campaignRootMode = all(strcmp({roots.runMode},'campaign'));
checks.expectedPreflightMode = ...
    all([roots.preflightOnly]) == ~settings.execute;
checks.freshStarts = all([roots.freshStart]);
checks.noRestartInputs = all(strcmp({roots.restartInput},'none'));
checks.sameDomain = isequaln(roots(1).domain,roots(2).domain);
checks.sameRequestedBoxMode = ...
    all(strcmp({roots.boxMode},settings.boxMode));
checks.requestedSameExceptCfl = requested_same_except_cfl(roots);
checks.configSameExceptCfl = signatures_same_except_cfl(roots);
checks.requestedBox = requested_box(roots,settings);
checks.meshContractsPassed = all([roots.meshPassed]) && ...
    all([roots.contractPassed]);
failures = failed_checks(checks);
audit = struct('checks',checks,'failures',{failures}, ...
    'passed',isempty(failures), ...
    'onlyAllowedDifference','time.cfl');
end

function passed = requested_same_except_cfl(roots)
passed = false;
if numel(roots) ~= 2 || isempty(fieldnames(roots(1).requested)) || ...
        isempty(fieldnames(roots(2).requested))
    return
end
left = roots(1).requested;
right = roots(2).requested;
if ~isfield(left,'cfl') || ~isfield(right,'cfl')
    return
end
left = rmfield(left,'cfl');
right = rmfield(right,'cfl');
passed = isequaln(orderfields(left),orderfields(right));
end

function passed = signatures_same_except_cfl(roots)
passed = false;
if numel(roots) ~= 2 || ...
        isempty(fieldnames(roots(1).configSignature)) || ...
        isempty(fieldnames(roots(2).configSignature))
    return
end
left = roots(1).configSignature;
right = roots(2).configSignature;
if ~isfield(left,'cfl') || ~isfield(right,'cfl')
    return
end
left = rmfield(left,'cfl');
right = rmfield(right,'cfl');
passed = isequaln(orderfields(left),orderfields(right));
end

function passed = requested_box(roots,settings)
passed = all(strcmp({roots.rootStatus},expected_root_status(settings))) && ...
    all(arrayfun(@(record) ...
        isequal(record.domain.initialPhysicalX, ...
        [-settings.boxHalfWidth,settings.boxHalfWidth]),roots));
if strcmp(settings.boxMode,'large_box')
    passed = passed && all(arrayfun(@(record) ...
        isequal(record.domain.initialPhysicalY,[0,settings.boxHalfWidth]), ...
        roots));
else
    passed = passed && all(arrayfun(@(record) ...
        isequal(record.domain.initialPhysicalY,[0,132]),roots));
end
end

