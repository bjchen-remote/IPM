function continuationRun = ipm_gaugelab_run_q512_continuation( ...
        inputCheckpoint,options)
%IPM_GAUGELAB_RUN_Q512_CONTINUATION Resume one registered schema-4 q512 run.
%   RUN = IPM_GAUGELAB_RUN_Q512_CONTINUATION(CHECKPOINT,OPTIONS) validates
%   one trusted schema-4 q512 checkpoint and registers a same-grid resume.
%   The default is preflight-only; set OPTIONS.execute=true to call the
%   sole numerical entry point IPM.SOLVE(OVERRIDES,CHECKPOINT).
%
%   The only solver horizons exposed here are finalTime,
%   physicalFinalTime, and maxSteps. They may be retained or extended but
%   never reduced, and all three must leave the stored accepted state open.
%   Grid, physics, diagnostics, gauges, CFL, maxDt, output cadence, RK, and
%   checkpoint cadence are inherited exactly. Result/checkpoint paths and
%   an explicit visualization whitelist may change.
%
%   OPTIONS.parentRootSummary is required and names (or contains) the
%   summary of the direct parent segment.  The first parent must be a
%   completed hard-passed fresh root; later parents may be completed,
%   hard-passed continuation segments.  In either case the summary must
%   reference CHECKPOINT by its complete validated signature.

if nargin < 1 || isempty(inputCheckpoint)
    error('ipm:GaugeLabQ512ContinuationCheckpoint', ...
        'A schema-version-4 q512 checkpoint is required.');
end
if nargin < 2 || isempty(options)
    options = struct();
end
settings = resolve_options(options);

% Read and verify before creating any registration artifact.
parentCheckpoint = ipm.output.readCheckpoint(inputCheckpoint);
[parentAudit,parentPassed] = audit_parent_checkpoint(parentCheckpoint);
if ~parentPassed
    error('ipm:GaugeLabQ512ContinuationContract', ...
        'The checkpoint is not a registered fixed-grid exact-gauge q512 state: %s.', ...
        strjoin(parentAudit.failures,', '));
end
parentSummaryAudit = audit_parent_root_summary( ...
    settings.parentRootSummary,parentCheckpoint);
if ~parentSummaryAudit.passed
    error('ipm:GaugeLabQ512ContinuationParentSummary', ...
        'The supplied parent root summary failed provenance checks: %s.', ...
        strjoin(parentSummaryAudit.failures,', '));
end

parentState = parentCheckpoint.payload.state;
requestedTime = requested_horizons(settings,parentState);
[horizonAudit,horizonsPassed] = audit_horizons( ...
    parentState,requestedTime);
if ~horizonsPassed
    error('ipm:GaugeLabQ512ContinuationHorizon', ...
        'Continuation horizons are not a nonreducing open extension: %s.', ...
        strjoin(horizonAudit.failures,', '));
end

[outputDirectory,runId] = create_output_directory(settings.outputRoot);
summaryFile = fullfile(outputDirectory,'continuation_summary.mat');
manifestFile = fullfile(outputDirectory,'continuation_manifest.jsonl');
resultFile = selected_path(settings.resultFile, ...
    fullfile(outputDirectory,'result.mat'));
checkpointFile = selected_path(settings.checkpointFile, ...
    fullfile(outputDirectory,'checkpoint.mat'));
videoFile = selected_path(settings.videoFile, ...
    fullfile(outputDirectory,'continuation.mp4'));

parentIdentity = checkpoint_identity(parentCheckpoint,inputCheckpoint);
[caseMetadata,restoreChain] = continuation_metadata( ...
    parentState,runId,parentIdentity,requestedTime,parentSummaryAudit);
overrides = registered_overrides(parentState.config,settings, ...
    requestedTime,resultFile,checkpointFile,videoFile,caseMetadata);
registeredConfig = resolve_resume_config(parentState.config,overrides);
[freezeAudit,freezePassed] = audit_frozen_config( ...
    parentState.config,registeredConfig);
if ~freezePassed
    error('ipm:GaugeLabQ512ContinuationFreeze', ...
        'A protected checkpoint configuration field changed: %s.', ...
        strjoin(freezeAudit.failures,', '));
end

registeredUtc = utc_stamp();
continuationRun = struct( ...
    'schemaVersion',4, ...
    'kind','q512_schema4_same_grid_continuation', ...
    'runId',runId, ...
    'status','registered', ...
    'registeredUtc',registeredUtc, ...
    'startedUtc','', ...
    'completedUtc','', ...
    'execute',settings.execute, ...
    'freshStart',false, ...
    'sameGridResume',true, ...
    'solverEntryPoint','ipm.solve(overrides,checkpoint)', ...
    'cOmegaGauge',registeredConfig.scaling.cOmegaGauge, ...
    'gaugeContract',parentState.runMetadata.gaugeContract, ...
    'parentCheckpointSource',parentIdentity.source, ...
    'parentCheckpointSignature',parentCheckpoint.signature, ...
    'parentCheckpointIdentity',parentIdentity, ...
    'parentRootSummary',parentSummaryAudit, ...
    'restoreChain',{restoreChain}, ...
    'parentAudit',parentAudit, ...
    'horizonAudit',horizonAudit, ...
    'freezeAudit',freezeAudit, ...
    'preflightPassed',parentPassed && horizonsPassed && freezePassed && ...
        parentSummaryAudit.passed, ...
    'requested',requested_record(requestedTime,registeredConfig, ...
        resultFile,checkpointFile,videoFile), ...
    'config',registeredConfig, ...
    'outputDirectory',outputDirectory, ...
    'summaryFile',summaryFile, ...
    'manifestFile',manifestFile, ...
    'requestedResultFile',resultFile, ...
    'requestedCheckpointFile',checkpointFile, ...
    'resultFile','', ...
    'checkpointFile','', ...
    'childCheckpointSignature',struct(), ...
    'wallSeconds',NaN, ...
    'segmentSteps',NaN, ...
    'totalSteps',NaN, ...
    'wallSecondsPerSegmentStep',NaN, ...
    'stopReason','', ...
    'segmentClassification','', ...
    'postAudit',struct(), ...
    'errorIdentifier','', ...
    'errorMessage','');
save_summary(summaryFile,continuationRun);
append_manifest(manifestFile,struct( ...
    'event','continuation_registered', ...
    'timestampUtc',registeredUtc, ...
    'runId',runId, ...
    'execute',settings.execute, ...
    'parentCheckpointSource',parentIdentity.source, ...
    'parentCheckpointToken',parentIdentity.signatureToken, ...
    'parentStep',parentIdentity.step, ...
    'parentCanonicalTime',parentIdentity.canonicalTime, ...
    'parentPhysicalTime',parentIdentity.physicalTime, ...
    'cOmegaGauge',parentIdentity.cOmegaGauge, ...
    'parentSummaryProvided',parentSummaryAudit.provided, ...
    'requested',continuationRun.requested, ...
    'frozenCfl',registeredConfig.time.cfl, ...
    'frozenMaxDt',registeredConfig.time.maxDt, ...
    'frozenCOmegaGauge',registeredConfig.scaling.cOmegaGauge, ...
    'preflightPassed',continuationRun.preflightPassed, ...
    'summaryFile',summaryFile));

if ~settings.execute
    continuationRun.status = 'preflight_only';
    continuationRun.completedUtc = utc_stamp();
    save_summary(summaryFile,continuationRun);
    append_manifest(manifestFile,struct( ...
        'event','continuation_preflight_complete', ...
        'timestampUtc',continuationRun.completedUtc, ...
        'runId',runId, ...
        'solveExecuted',false));
    fprintf(['Q512 CONTINUATION PREFLIGHT: parent step=%d, ' ...
        'tau=%.9g, t=%.9g, CFL=%.3g, summary=%s\n'], ...
        parentIdentity.step,parentIdentity.canonicalTime, ...
        parentIdentity.physicalTime,registeredConfig.time.cfl,summaryFile);
    return
end

continuationRun.status = 'running';
continuationRun.startedUtc = utc_stamp();
save_summary(summaryFile,continuationRun);
append_manifest(manifestFile,struct( ...
    'event','continuation_solve_started', ...
    'timestampUtc',continuationRun.startedUtc, ...
    'runId',runId, ...
    'parentCheckpointToken',parentIdentity.signatureToken, ...
    'cOmegaGauge',parentIdentity.cOmegaGauge));

wallClock = tic;
try
    % This is deliberately the only call that advances the PDE.
    result = ipm.solve(overrides,parentCheckpoint);
    continuationRun.wallSeconds = toc(wallClock);
catch exception
    continuationRun.wallSeconds = toc(wallClock);
    continuationRun.status = 'solver_failed';
    continuationRun.completedUtc = utc_stamp();
    continuationRun.errorIdentifier = exception.identifier;
    continuationRun.errorMessage = exception.message;
    save_summary(summaryFile,continuationRun);
    append_manifest(manifestFile,struct( ...
        'event','continuation_solve_failed', ...
        'timestampUtc',continuationRun.completedUtc, ...
        'runId',runId, ...
        'wallSeconds',continuationRun.wallSeconds, ...
        'errorIdentifier',exception.identifier, ...
        'errorMessage',exception.message));
    rethrow(exception)
end

try
    result = ipm.output.validate(result);
    [postAudit,childCheckpoint] = audit_result(result,parentCheckpoint, ...
        registeredConfig,requestedTime,checkpointFile, ...
        continuationRun.wallSeconds,parentIdentity);
catch exception
    continuationRun.status = 'postprocess_failed';
    continuationRun.completedUtc = utc_stamp();
    continuationRun.errorIdentifier = exception.identifier;
    continuationRun.errorMessage = exception.message;
    if exist('result','var') && isstruct(result) && ...
            isfield(result,'metadata') && ...
            isfield(result.metadata,'resultFile')
        continuationRun.resultFile = char(result.metadata.resultFile);
    end
    save_summary(summaryFile,continuationRun);
    append_manifest(manifestFile,struct( ...
        'event','continuation_postprocess_failed', ...
        'timestampUtc',continuationRun.completedUtc, ...
        'runId',runId, ...
        'wallSeconds',continuationRun.wallSeconds, ...
        'errorIdentifier',exception.identifier, ...
        'errorMessage',exception.message));
    rethrow(exception)
end

continuationRun.segmentSteps = postAudit.segmentSteps;
continuationRun.totalSteps = result.state.steps;
continuationRun.wallSecondsPerSegmentStep = ...
    postAudit.wallSecondsPerSegmentStep;
continuationRun.stopReason = result.state.stopReason;
continuationRun.segmentClassification = postAudit.segmentClassification;
continuationRun.resultFile = char(result.metadata.resultFile);
continuationRun.checkpointFile = postAudit.childCheckpointFile;
if isfield(childCheckpoint,'signature')
    continuationRun.childCheckpointSignature = childCheckpoint.signature;
else
    continuationRun.childCheckpointSignature = struct();
end
continuationRun.postAudit = postAudit;
continuationRun.completedUtc = utc_stamp();
if postAudit.hardPassed
    if strcmp(postAudit.segmentClassification,'maximum_steps_intermediate')
        continuationRun.status = 'completed_intermediate';
    else
        continuationRun.status = 'completed_endpoint';
    end
else
    continuationRun.status = 'postrun_rejected';
end
save_summary(summaryFile,continuationRun);
childIdentity = empty_checkpoint_identity();
if isfield(childCheckpoint,'signature')
    childIdentity = checkpoint_identity( ...
        childCheckpoint,continuationRun.checkpointFile);
end
append_manifest(manifestFile,struct( ...
    'event','continuation_solve_finished', ...
    'timestampUtc',continuationRun.completedUtc, ...
    'runId',runId, ...
    'status',continuationRun.status, ...
    'stopReason',continuationRun.stopReason, ...
    'segmentClassification',continuationRun.segmentClassification, ...
    'segmentSteps',continuationRun.segmentSteps, ...
    'totalSteps',continuationRun.totalSteps, ...
    'cOmegaGauge',continuationRun.cOmegaGauge, ...
    'wallSeconds',continuationRun.wallSeconds, ...
    'wallSecondsPerSegmentStep', ...
        continuationRun.wallSecondsPerSegmentStep, ...
    'postrunPassed',postAudit.hardPassed, ...
    'postrunFailures',{postAudit.failures}, ...
    'childCheckpointToken',childIdentity.signatureToken, ...
    'resultFile',continuationRun.resultFile, ...
    'checkpointFile',continuationRun.checkpointFile));

fprintf(['Q512 CONTINUATION RESULT: status=%s, stop=%s, ' ...
    'segment steps=%d, total steps=%d, wall=%.3f s\n'], ...
    continuationRun.status,continuationRun.stopReason, ...
    continuationRun.segmentSteps,continuationRun.totalSteps, ...
    continuationRun.wallSeconds);
if ~postAudit.hardPassed
    error('ipm:GaugeLabQ512ContinuationPostrunGate', ...
        'The continuation failed postrun gate(s): %s. See %s.', ...
        strjoin(postAudit.failures,', '),summaryFile);
end
end

function settings = resolve_options(options)
if ~isstruct(options) || ~isscalar(options)
    error('ipm:GaugeLabQ512ContinuationOptions', ...
        'options must be a scalar structure.');
end
allowed = {'execute','parentRootSummary','outputRoot','finalTime', ...
    'physicalFinalTime','maxSteps','resultFile','checkpointFile', ...
    'makePlots','livePlot','writeVideo','videoFile', ...
    'videoFrameRate','videoQuality','verbose'};
unknown = setdiff(fieldnames(options),allowed,'stable');
if ~isempty(unknown)
    error('ipm:GaugeLabQ512ContinuationOptions', ...
        ['Only horizons, artifact paths, and the visualization whitelist ' ...
        'may be set. Rejected option(s): %s.'],strjoin(unknown,', '));
end
if ~isfield(options,'parentRootSummary') || ...
        isempty(options.parentRootSummary)
    error('ipm:GaugeLabQ512ContinuationParentSummary', ...
        ['parentRootSummary is required and must identify the direct ' ...
        'completed, hard-passed parent segment.']);
end
settings = struct( ...
    'execute',optional_logical(options,'execute',false), ...
    'parentRootSummary',optional_value(options,'parentRootSummary',[]), ...
    'outputRoot',optional_path(options,'outputRoot',default_output_root()), ...
    'finalTime',optional_numeric(options,'finalTime',[]), ...
    'physicalFinalTime',optional_numeric(options,'physicalFinalTime',[]), ...
    'maxSteps',optional_numeric(options,'maxSteps',[]), ...
    'resultFile',optional_path(options,'resultFile',[]), ...
    'checkpointFile',optional_path(options,'checkpointFile',[]), ...
    'makePlots',optional_logical(options,'makePlots',[]), ...
    'livePlot',optional_logical(options,'livePlot',[]), ...
    'writeVideo',optional_logical(options,'writeVideo',[]), ...
    'videoFile',optional_path(options,'videoFile',[]), ...
    'videoFrameRate',optional_numeric(options,'videoFrameRate',[]), ...
    'videoQuality',optional_numeric(options,'videoQuality',[]), ...
    'verbose',optional_logical(options,'verbose',[]));
end

function [audit,passed] = audit_parent_checkpoint(checkpoint)
state = checkpoint.payload.state;
config = state.config;
scaling = config.scaling;
retired = retired_fields();
present = retired(isfield(scaling,retired));
present = unique([present,retired(isfield(state.rescaling,retired))], ...
    'stable');
rootLineage = root_lineage(config.output.caseMetadata);
metadataCaseMetadata = struct();
if isfield(state.runMetadata,'caseMetadata')
    metadataCaseMetadata = state.runMetadata.caseMetadata;
end
metadataLineage = root_lineage(metadataCaseMetadata);
chainAudit = existing_chain_audit( ...
    config.output.caseMetadata,state.runMetadata,state);
[rootIdentityAudit,rootIdentityPassed] = ...
    audit_registered_root_identity(state,rootLineage);
parentCommon = checkpoint.payload.log.history.common;
parentGauge = checkpoint.payload.log.history.gauge;
[gaugeAudit,gaugeHistoryPassed] = audit_gauge_history( ...
    parentCommon,parentGauge,scaling.cOmegaGauge);
[anchorDistance,anchorIndex] = min(abs(state.x-1));
anchorTolerance = 128*eps(max(1,max(abs(state.x))));
largeBoxAnchor = rootLineage.passed && ...
    strcmp(rootLineage.value.boxMode,'large_box');
checks = struct();
checks.checkpointSchema4 = checkpoint.schemaVersion == 4 && ...
    state.config.schemaVersion == 4 && state.config.frozen;
checks.q512NodeCounts = config.grid.nx == 1025 && ...
    config.grid.ny == 513 && numel(state.x) == 1025 && ...
    numel(state.y) == 513 && isequal(size(state.rho),[513,1025]);
checks.sameGridState = state.remeshCount == 0 && ...
    ~config.remesh.initialAnalyticRemesh && ~config.remesh.adaptiveRemesh;
checks.fixedGridCoordinates = isfield(config.grid,'customX') && ...
    isfield(config.grid,'customY') && ...
    isequal(state.x,config.grid.customX) && ...
    isequal(state.y,config.grid.customY) && ...
    isequal(state.baseX,config.grid.customX) && ...
    isequal(state.baseY,config.grid.customY) && ...
    isequal(state.x,state.baseX) && isequal(state.y,state.baseY);
checks.fixedGridHistory = isfield(checkpoint.payload.log.history.mesh, ...
    'remeshCount') && ...
    all(checkpoint.payload.log.history.mesh.remeshCount == 0);
checks.highOrderTuple = ...
    strcmp(config.transport.spatialDiscretization,'high_order') && ...
    strcmp(config.transport.transportScheme,'weno5_fd') && ...
    strcmp(config.time.timeIntegrator,'ssprk54') && ...
    strcmp(config.remesh.remeshTransferScheme,'high_order');
checks.dynamicIsotropic = ...
    strcmp(scaling.rescalingMode,'dynamic') && ...
    strcmp(scaling.dynamicScaleGeometry,'isotropic');
checks.exactGaugeRules = ...
    strcmp(scaling.scalingContract,'exact_gauge_no_feedback_v1') && ...
    strcmp(scaling.lengthGauge,'transport_anchor') && ...
    scaling.transportAnchorX == 1 && ...
    allowed_c_omega_gauge(scaling.cOmegaGauge) && ...
    rootLineage.passed && strcmp( ...
        scaling.cOmegaGauge,rootLineage.value.cOmegaGauge);
checks.noFeedback = scaling.lengthScaleGain == 1 && ...
    scaling.widthGaugeGain == 0 && scaling.omegaGaugeGain == 0 && ...
    scaling.travelingWaveGain == 0 && isempty(present);
checks.anchorEvaluationRegistered = state.x(1) < 1 && state.x(end) > 1 && ...
    (~largeBoxAnchor || anchorDistance <= anchorTolerance);
checks.frozenCflAndMaxDt = isfinite(config.time.cfl) && ...
    config.time.cfl > 0 && config.time.cfl <= 0.5 && ...
    isfinite(config.time.maxDt) && config.time.maxDt > 0;
checks.outputEvidencePolicy = config.output.saveResults && ...
    ~config.output.storeSnapshots && isfield(config.output,'checkpoint') && ...
    config.output.checkpoint.enabled && config.output.checkpoint.atExit;
checks.freshRootLineage = rootLineage.passed && ...
    metadataLineage.passed && isequaln(rootLineage.value, ...
    metadataLineage.value);
checks.registeredRootIdentity = rootIdentityPassed;
checks.caseMetadataIdentity = isfield(state.runMetadata,'caseMetadata') && ...
    isequaln(config.output.caseMetadata,state.runMetadata.caseMetadata);
checks.registeredContinuationChain = chainAudit.passed;
checks.gaugeContractMetadata = isfield(state.runMetadata,'gaugeContract') && ...
    gauge_contract_passed( ...
        state.runMetadata.gaugeContract,scaling.cOmegaGauge);
checks.directCanonicalHistory = direct_canonical_history_exact(parentCommon);
checks.gaugeHistoryCompleteFinite = gaugeHistoryPassed;
checks.selectedGaugeAlgebra = gaugeAudit.selectedGaugeAlgebra.passed;
checks.omegaGaugeResidual = ...
    gaugeAudit.maximumOmegaGaugeResidual <= 1e-10;
checks.transportAnchorResidual = max([ ...
    gaugeAudit.maximumNormalizedLengthGaugeResidual, ...
    gaugeAudit.maximumNormalizedTransportAnchorDefect, ...
    gaugeAudit.maximumNormalizedCanonicalTransportAnchorDefect]) <= 1e-10;
checks.noFeedbackHistory = gaugeAudit.noFeedbackHistory;
failures = failed_checks(checks);
passed = isempty(failures);
audit = struct('checks',checks,'failures',{failures}, ...
    'passed',passed,'retiredFieldsPresent',{present}, ...
    'rootLineage',rootLineage.value, ...
    'registeredRootIdentityAudit',rootIdentityAudit, ...
    'continuationChainAudit',chainAudit, ...
    'gaugeHistoryAudit',gaugeAudit, ...
    'anchorNode',state.x(anchorIndex), ...
    'anchorNodeDistance',anchorDistance, ...
    'anchorEvaluation',ternary_text(largeBoxAnchor, ...
        'large_box_anchor_aligned_node','matched_box_linear_interpolation'), ...
    'cfl',config.time.cfl,'maxDt',config.time.maxDt, ...
    'cOmegaGauge',scaling.cOmegaGauge, ...
    'grid',[config.grid.nx,config.grid.ny]);
end

function lineage = root_lineage(caseMetadata)
value = struct();
passed = isstruct(caseMetadata) && isscalar(caseMetadata) && ...
    isfield(caseMetadata,'q512GaugeRoot') && ...
    isstruct(caseMetadata.q512GaugeRoot) && ...
    isscalar(caseMetadata.q512GaugeRoot);
if passed
    value = caseMetadata.q512GaugeRoot;
    required = {'schemaVersion','runId','freshStart','restartInput', ...
        'boxMode','boxHalfWidth', ...
        'configurationContract','lengthGauge','transportAnchorX', ...
        'cOmegaGauge'};
    try
        passed = all(isfield(value,required)) && ...
            value.schemaVersion == 4 && isequal(value.freshStart,true) && ...
            strcmp(value.restartInput,'none') && ...
            any(strcmp(value.boxMode,{'matched','large_box'})) && ...
            is_finite_numeric_scalar(value.boxHalfWidth) && ...
            value.boxHalfWidth > 2 && ...
            strcmp(value.configurationContract, ...
                'exact_gauge_no_feedback_v1') && ...
            strcmp(value.lengthGauge,'transport_anchor') && ...
            value.transportAnchorX == 1 && ...
            allowed_c_omega_gauge(value.cOmegaGauge);
    catch
        passed = false;
    end
end
lineage = struct('passed',passed,'value',value);
end

function [audit,passed] = audit_registered_root_identity(state,lineage)
config = state.config;
metadata = config.output.caseMetadata;
checks = struct();
checks.lineageAvailable = lineage.passed;
checks.factoryCaseName = false;
checks.degeneratePrimitivePowerEight = false;
checks.boxGeometry = false;
checks.configuredAxesPresent = isfield(config.grid,'customX') && ...
    isfield(config.grid,'customY') && ~isempty(config.grid.customX) && ...
    ~isempty(config.grid.customY);
checks.stateConfigAxesExact = false;
checks.baseConfigAxesExact = false;
checks.fixedGridCoordinatesExact = false;
expectedCaseName = '';
expectedDomain = struct('x',[NaN,NaN],'y',[NaN,NaN]);
if lineage.passed
    root = lineage.value;
    if strcmp(root.boxMode,'matched')
        expectedCaseName = ...
            'coordinated_log_F80_R20_c114_quadrant_512';
        expectedDomain = struct('x',[-281,281],'y',[0,132]);
        checks.boxGeometry = root.boxHalfWidth == 281;
    else
        expectedCaseName = ...
            'coordinated_log_anchor_F80_R20_large_box_quadrant_512';
        halfWidth = root.boxHalfWidth;
        expectedDomain = struct('x',[-halfWidth,halfWidth], ...
            'y',[0,halfWidth]);
        checks.boxGeometry = isfinite(halfWidth) && halfWidth > 2;
    end
    checks.factoryCaseName = isfield(metadata,'caseName') && ...
        is_text(metadata.caseName) && ...
        strcmp(char(metadata.caseName),expectedCaseName);
    checks.degeneratePrimitivePowerEight = ...
        isfield(config.physics,'initialCondition') && ...
        is_text(config.physics.initialCondition) && ...
        strcmp(char(config.physics.initialCondition), ...
            'degenerate_primitive') && ...
        isfield(config.physics,'degeneratePower') && ...
        config.physics.degeneratePower == 8;
    if checks.configuredAxesPresent
        checks.stateConfigAxesExact = ...
            isequal(state.x,config.grid.customX) && ...
            isequal(state.y,config.grid.customY);
        checks.baseConfigAxesExact = ...
            isequal(state.baseX,config.grid.customX) && ...
            isequal(state.baseY,config.grid.customY);
        checks.fixedGridCoordinatesExact = ...
            isequal(state.x,state.baseX) && ...
            isequal(state.y,state.baseY);
        checks.boxGeometry = checks.boxGeometry && ...
            isequal(state.x([1,end]),expectedDomain.x) && ...
            isequal(state.y([1,end])',expectedDomain.y);
    else
        checks.boxGeometry = false;
    end
end
failures = failed_checks(checks);
passed = isempty(failures);
audit = struct('passed',passed,'checks',checks, ...
    'failures',{failures},'expectedCaseName',expectedCaseName, ...
    'expectedDomain',expectedDomain);
end

function audit = existing_chain_audit(caseMetadata,runMetadata,state)
hasChain = isstruct(caseMetadata) && isscalar(caseMetadata) && ...
    isfield(caseMetadata,'q512ContinuationChain');
hasCurrent = isstruct(caseMetadata) && isscalar(caseMetadata) && ...
    isfield(caseMetadata,'q512ContinuationCurrent');
chain = {};
checks = struct();
checks.chainAndCurrentPaired = hasChain == hasCurrent;
rootRunId = '';
rootGauge = '';
if isstruct(caseMetadata) && isscalar(caseMetadata) && ...
        isfield(caseMetadata,'q512GaugeRoot') && ...
        isstruct(caseMetadata.q512GaugeRoot) && ...
        isscalar(caseMetadata.q512GaugeRoot)
    rootTag = caseMetadata.q512GaugeRoot;
    if isfield(rootTag,'runId')
        rootRunId = char(rootTag.runId);
    end
    if isfield(rootTag,'cOmegaGauge')
        rootGauge = char(rootTag.cOmegaGauge);
    end
end
checks.rootGaugeAllowed = allowed_c_omega_gauge(rootGauge);
checks.currentGaugeMatchesRoot = ...
    isfield(state.config,'scaling') && ...
    isfield(state.config.scaling,'cOmegaGauge') && ...
    strcmp(state.config.scaling.cOmegaGauge,rootGauge);
if ~(hasChain || hasCurrent)
    resumeCount = 0;
    if isfield(runMetadata,'resumeCount')
        resumeCount = runMetadata.resumeCount;
    end
    checks.unresumedFreshRoot = isequal(resumeCount,0);
    failures = failed_checks(checks);
    audit = struct('passed',isempty(failures),'checks',checks, ...
        'failures',{failures},'count',0,'chain',{chain});
    return
end
if hasChain
    chain = caseMetadata.q512ContinuationChain;
    if isstruct(chain)
        chain = num2cell(chain);
    end
end
checks.cellChain = iscell(chain) && isvector(chain) && ~isempty(chain);
if checks.cellChain
    chain = reshape(chain,1,[]);
end
checks.validEvents = checks.cellChain;
checks.completeParentSignatures = checks.cellChain;
checks.parentSignatureStateIdentity = checks.cellChain;
checks.parentSignatureCommitsPriorChain = checks.cellChain;
checks.commonFreshRoot = checks.cellChain;
checks.commonAmplitudeGauge = checks.cellChain;
checks.directParentSummaryPerHop = checks.cellChain;
checks.uniqueRunIds = checks.cellChain;
checks.monotoneParentStates = checks.cellChain;
checks.nondecreasingRequestedHorizons = checks.cellChain;
if checks.cellChain
    runIds = cell(size(chain));
    parentSteps = NaN(size(chain));
    parentTau = NaN(size(chain));
    parentPhysical = NaN(size(chain));
    requestedFinal = NaN(size(chain));
    requestedPhysical = NaN(size(chain));
    requestedSteps = NaN(size(chain));
    for index = 1:numel(chain)
        [valid,values] = continuation_event_values(chain{index});
        checks.validEvents = checks.validEvents && valid;
        if valid
            runIds{index} = values.runId;
            parentSteps(index) = values.parentStep;
            parentTau(index) = values.parentCanonicalTime;
            parentPhysical(index) = values.parentPhysicalTime;
            requestedFinal(index) = values.requestedFinalTime;
            requestedPhysical(index) = values.requestedPhysicalFinalTime;
            requestedSteps(index) = values.requestedMaxSteps;
            signature = values.parentCheckpointSignature;
            checks.completeParentSignatures = ...
                checks.completeParentSignatures && ...
                complete_checkpoint_signature(signature);
            checks.parentSignatureStateIdentity = ...
                checks.parentSignatureStateIdentity && ...
                signature_state_matches_event(signature,values);
            checks.parentSignatureCommitsPriorChain = ...
                checks.parentSignatureCommitsPriorChain && ...
                signature_commits_chain_prefix( ...
                    signature,chain(1:index-1),rootRunId);
            checks.commonFreshRoot = checks.commonFreshRoot && ...
                strcmp(values.parentRootRunId,rootRunId);
            checks.commonAmplitudeGauge = ...
                checks.commonAmplitudeGauge && ...
                strcmp(values.cOmegaGauge,rootGauge) && ...
                checkpoint_signature_gauge_matches( ...
                    signature,rootGauge);
            if index == 1
                checks.directParentSummaryPerHop = ...
                    checks.directParentSummaryPerHop && ...
                    strcmp(values.parentSummaryKind, ...
                    'q512_fresh_exact_gauge_root') && ...
                    strcmp(values.parentSummaryRunId,rootRunId);
            else
                previousRunId = char(chain{index-1}.runId);
                checks.directParentSummaryPerHop = ...
                    checks.directParentSummaryPerHop && ...
                    strcmp(values.parentSummaryKind, ...
                    'q512_schema4_same_grid_continuation') && ...
                    strcmp(values.parentSummaryRunId,previousRunId);
            end
        end
    end
    if checks.validEvents
        checks.uniqueRunIds = numel(unique(runIds)) == numel(runIds);
        checks.monotoneParentStates = all(diff(parentSteps) > 0) && ...
            all(diff(parentTau) > 0) && all(diff(parentPhysical) > 0);
        for index = 2:numel(chain)
            checks.nondecreasingRequestedHorizons = ...
                checks.nondecreasingRequestedHorizons && ...
                horizon_not_reduced(requestedFinal(index), ...
                    requestedFinal(index-1),0) && ...
                horizon_not_reduced(requestedPhysical(index), ...
                    requestedPhysical(index-1),0) && ...
                requestedSteps(index) >= requestedSteps(index-1);
        end
    end
end
checks.currentIsLastEvent = hasCurrent && checks.cellChain && ...
    isstruct(caseMetadata.q512ContinuationCurrent) && ...
    isscalar(caseMetadata.q512ContinuationCurrent) && ...
    isequaln(caseMetadata.q512ContinuationCurrent,chain{end});
checks.resumeCountMatches = checks.cellChain && ...
    isfield(runMetadata,'resumeCount') && ...
    is_finite_numeric_scalar(runMetadata.resumeCount) && ...
    runMetadata.resumeCount == numel(chain);
checks.latestResumeMetadataMatches = false;
checks.currentConfigMatchesLatestRequest = false;
checks.currentStateDescendsFromLatestParent = false;
checks.currentCaseMetadataExact = false;
if checks.cellChain && checks.validEvents
    latest = chain{end};
    checks.latestResumeMetadataMatches = ...
        all(isfield(runMetadata,{'resumedFromStep', ...
        'resumedFromCanonicalTime','resumedFromPhysicalTime'})) && ...
        is_finite_numeric_scalar(runMetadata.resumedFromStep) && ...
        is_finite_numeric_scalar(runMetadata.resumedFromCanonicalTime) && ...
        is_finite_numeric_scalar(runMetadata.resumedFromPhysicalTime) && ...
        runMetadata.resumedFromStep == latest.parentStep && ...
        scalar_close(runMetadata.resumedFromCanonicalTime, ...
            latest.parentCanonicalTime) && ...
        scalar_close(runMetadata.resumedFromPhysicalTime, ...
            latest.parentPhysicalTime);
    checks.currentConfigMatchesLatestRequest = ...
        state.config.time.finalTime == latest.requestedFinalTime && ...
        state.config.time.physicalFinalTime == ...
            latest.requestedPhysicalFinalTime && ...
        state.config.time.maxSteps == latest.requestedMaxSteps;
    checks.currentStateDescendsFromLatestParent = ...
        state.step > latest.parentStep && ...
        state.scale.canonicalTime > latest.parentCanonicalTime && ...
        state.scale.physicalTime > latest.parentPhysicalTime;
    checks.currentCaseMetadataExact = ...
        isequaln(caseMetadata.q512ContinuationChain,chain) && ...
        isequaln(caseMetadata.q512ContinuationCurrent,latest) && ...
        isfield(runMetadata,'caseMetadata') && ...
        isequaln(runMetadata.caseMetadata,caseMetadata);
end
failures = failed_checks(checks);
audit = struct('passed',isempty(failures),'checks',checks, ...
    'failures',{failures},'count',numel(chain),'chain',{chain});
end

function [valid,values] = continuation_event_values(event)
required = {'schemaVersion','runId','registeredUtc', ...
    'parentCheckpointSource','parentCheckpointToken', ...
    'parentCheckpointSignature','parentStep', ...
    'parentCanonicalTime','parentPhysicalTime','requestedFinalTime', ...
    'requestedPhysicalFinalTime','requestedMaxSteps', ...
    'parentRootSummaryProvided','parentSummarySource','parentSummaryKind', ...
    'parentSummaryRunId','parentRootRunId'};
