end
values = string(common.timestepActiveLimiter);
count = nnz(values == string(name));
end

function value = guarded_ratio(numerator,denominator)
scale = max([1,abs(numerator),abs(denominator)]);
if ~all(isfinite([numerator,denominator])) || ...
        abs(denominator) <= 100*eps(scale)
    value = NaN;
else
    value = numerator/denominator;
end
end

function value = relative_difference(reference,candidate)
if ~all(isfinite([reference,candidate]))
    value = NaN;
    return;
end
scale = max(abs([reference,candidate]));
if scale == 0
    value = 0;
else
    value = (candidate-reference)/scale;
end
end

function value = directional_relative_difference(reference,candidate)
if ~all(isfinite([reference,candidate]))
    value = NaN;
else
    value = (candidate-reference)/max(abs(reference),eps);
end
end

function value = protocol_value(protocol,name,fallback)
if isstruct(protocol) && isscalar(protocol) && isfield(protocol,name)
    value = protocol.(name);
else
    value = fallback;
end
end

function value = optional_numeric_scalar(source,name,fallback)
value = fallback;
if isfield(source,name) && isnumeric(source.(name)) && ...
        isreal(source.(name)) && isscalar(source.(name))
    value = source.(name);
end
end

function value = optional_logical_scalar(source,name)
value = NaN;
if ~isfield(source,name)
    return;
end
candidate = source.(name);
if islogical(candidate) && isscalar(candidate)
    value = candidate;
elseif isnumeric(candidate) && isscalar(candidate) && ...
        isfinite(candidate) && any(candidate == [0,1])
    value = logical(candidate);
end
end

function value = scalar_text(value,name)
if isstring(value)
    if ~isscalar(value) || ismissing(value)
        error('ipm:GaugeLabCLCflText','%s must be scalar text.',name);
    end
    value = char(value);
end
if ~ischar(value) || ~isrow(value)
    error('ipm:GaugeLabCLCflText','%s must be scalar text.',name);
end
value = strtrim(value);
end

function matched = text_matches(value,expected)
matched = false;
if isstring(value)
    if ~isscalar(value) || ismissing(value)
        return;
    end
    value = char(value);
end
if ischar(value) && isrow(value)
    matched = strcmp(value,expected);
end
end

