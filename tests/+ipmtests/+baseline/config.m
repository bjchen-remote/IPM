weightedOperator = (weightedOperator+weightedOperator')/2;
oraclePoissonSolution = weightedOperator\poissonRightHandSide;
poissonDifference = norm( ...
    resolvedPoissonSolution-oraclePoissonSolution,inf);
poissonTolerance = 10*eps(max(1,norm(oraclePoissonSolution,inf)));
assert(poissonDifference <= poissonTolerance, ...
    'ipm:ResolvedPoissonOracle', ...
    'The cached pure-builder factorization differs from its matrix oracle.');

sourcePath = which('ipm.mesh.build');
pureBuilderSource = fileread(sourcePath);
assert(isempty(regexp(pureBuilderSource, ...
    'ipm\.config\.(schema|resolve)\s*\(','once')), ...
    'ipm:ResolvedBuilderPurity', ...
    'The pure operator builder performs option resolution.');
