function failures = ladder_failures(ladder,settings)
failures = cell(0,1);
expected = expected_root_status(settings);
for index = 1:numel(ladder.rungs)
    record = ladder.rungs(index);
    if ~strcmp(record.status,expected)
        failures{end+1,1} = sprintf('%s:root:%s', ...
            record.name,record.status); %#ok<AGROW>
    elseif settings.executeSmoke && ...
            ~record.comparisonToMatched.available
        failures{end+1,1} = sprintf('%s:comparison:%s', ...
            record.name,record.comparisonToMatched.status); %#ok<AGROW>
    end
end
if settings.executeSmoke
    for index = 1:numel(ladder.successiveLargeComparisons)
        record = ladder.successiveLargeComparisons(index);
        if ~record.comparison.available
            failures{end+1,1} = sprintf('%s_to_%s:comparison:%s', ...
                record.referenceRung,record.candidateRung, ...
                record.comparison.status); %#ok<AGROW>
        end
    end
    for index = 1:numel(ladder.campaignBoxGate.failures)
        failures{end+1,1} = sprintf('campaign_box_gate:%s', ...
            ladder.campaignBoxGate.failures{index}); %#ok<AGROW>
    end
end
end

