function [checkpoint,currentReference,restart] = ...
        resolve_terminal_input(input,campaignDirectory)
[kind,value,label] = classify_terminal_input(input);
restart = restart_template();
restart.sourceLabel = label;
switch kind
    case 'checkpoint_file'
        checkpoint = ipm.output.readCheckpoint(value);
        currentReference = label;
        restart.mode = 'native_checkpoint_file';
        restart.bitwiseRestartStateAvailable = true;
    case 'checkpoint_structure'
        checkpoint = ipm.output.readCheckpoint(value);
        requested = fullfile( ...
            campaignDirectory,'input_native_checkpoint.mat');
        [checkpoint,fileName] = ...
            ipm.output.writeCheckpoint(checkpoint,requested);
        currentReference = char(fileName);
        restart.mode = 'native_checkpoint_structure_copied';
        restart.bitwiseRestartStateAvailable = true;
    case {'result_file','result_structure'}
        result = ipm.output.validate(value);
        validate_q512_result(result);
        requested = fullfile( ...
            campaignDirectory,'input_result_bridge_checkpoint.mat');
        bridgeInput = result;
        if strcmp(kind,'result_file')
            bridgeInput = value;
        end
        [checkpoint,fileName] = ...
            ipm.output.checkpointFromResult(bridgeInput,requested);
        currentReference = char(fileName);
        restart.mode = 'terminal_result_bridge_machine_precision';
        restart.usedResultBridge = true;
        restart.bitwiseRestartStateAvailable = false;
        restart.bridgeWarning = [ ...
            'log(C) was reconstructed from exponentiated result scales; ' ...
            'this is not a bitwise native restart'];
        restart.bridgeCheckpointFile = currentReference;
    otherwise
        error('ipm:gridlab:CampaignTerminalKind', ...
            'Unsupported terminal input kind %s.',kind);
end
restart = annotate_bridge_ancestry(restart,checkpoint);
end

function restart = annotate_bridge_ancestry(restart,checkpoint)
metadata = checkpoint.payload.state.runMetadata;
hasBridge = false;
if isfield(metadata,'checkpointSource')
    source = string(metadata.checkpointSource);
    hasBridge = isscalar(source) && ~ismissing(source) && ...
        strcmp(source,"trusted_terminal_result_v2");
end
restart.hasResultBridgeAncestry = hasBridge;
restart.bitwiseToPreBridgeTrajectory = ~hasBridge;
if hasBridge && isempty(restart.bridgeWarning)
    restart.bridgeWarning = [ ...
        'this native accepted-state checkpoint descends from a terminal ' ...
        'result bridge; restart from the stored state is exact, but the ' ...
        'pre-bridge trajectory is only machine-precision equivalent'];
end
end

function [kind,value,label] = classify_terminal_input(input)
if ischar(input) || (isstring(input) && isscalar(input))
    fileName = absolute_path(char(input));
    if ~isfile(fileName)
        error('ipm:gridlab:CampaignTerminalMissing', ...
            'Terminal input does not exist: %s',fileName);
    end
    variables = whos('-file',fileName);
    names = {variables.name};
    hasCheckpoint = ismember('checkpoint',names);
    hasResult = ismember('result',names);
    if hasCheckpoint == hasResult
        error('ipm:gridlab:CampaignTerminalFile', ...
            ['Terminal MAT-file must contain exactly one recognized ' ...
            'variable: checkpoint or result.']);
    end
    if hasCheckpoint
        kind = 'checkpoint_file';
    else
        kind = 'result_file';
    end
    value = fileName;
    label = fileName;
elseif isstruct(input) && isscalar(input) && ...
        isfield(input,'kind') && ...
        strcmp(input.kind,'ipm_accepted_step_checkpoint')
    kind = 'checkpoint_structure';
    value = input;
    label = 'in_memory_checkpoint';
elseif isstruct(input) && isscalar(input)
    kind = 'result_structure';
    value = input;
    label = 'in_memory_result';
else
    error('ipm:gridlab:CampaignTerminalInput', ...
        'TERMINAL must be one scalar result/checkpoint or its MAT-file.');
end
end

