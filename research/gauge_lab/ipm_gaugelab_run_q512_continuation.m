    'omegaGaugeForcingX','omegaGaugeForcingY','omegaGaugeForcing', ...
    'omegaGaugeAbsoluteForcing','omegaGaugeForcingCancellationRatio'};
quadraticRequired = {'omegaPeakRateResidual','omegaGaugePeakX', ...
    'omegaGaugePeakCondition','omegaGaugeQuadraticPeakX', ...
    'omegaGaugeQuadraticPeakValue','omegaGaugeQuadraticForcing', ...
    'omegaGaugeQuadraticCurvature', ...
    'omegaGaugeQuadraticStationarityResidual', ...
    'omegaGaugeQuadraticNormalizedStationarityResidual', ...
    'omegaGaugeQuadraticCurvatureCondition', ...
    'omegaGaugeQuadraticWeightCondition', ...
    'omegaGaugeQuadraticActiveNodeMargin', ...
    'omegaGaugeQuadraticActiveSelectionMargin', ...
    'omegaGaugeQuadraticStencilCenterX', ...
    'omegaGaugeQuadraticVertexInteriorFraction', ...
    'omegaGaugeQuadraticRelativeSubgridLift', ...
    'omegaGaugeQuadraticRateResidual', ...
    'omegaGaugeQuadraticRateScale'};
recordCount = numel(common.t);
[sharedComplete,sharedFinite] = finite_history_fields( ...
    gauge,sharedRequired,recordCount);
specificRequired = {};
if strcmp(gaugeName,'gradient_energy')
    specificRequired = gradientRequired;
elseif strcmp(gaugeName,'wall_omega_quadratic_peak')
    specificRequired = quadraticRequired;
end
[specificComplete,specificFinite] = finite_history_fields( ...
    gauge,specificRequired,recordCount);
complete = allowed_c_omega_gauge(gaugeName) && ...
    sharedComplete && specificComplete;
finite = complete && sharedFinite && specificFinite;
maximumOmega = Inf;
