function verbose = resolve_verbose(options)
if ~isstruct(options) || ~isscalar(options)
    error('ipm:GaugeLabGroupV4Options', ...
        'Options must be a scalar structure.');
end
unknown = setdiff(fieldnames(options),{'verbose'});
if ~isempty(unknown)
    error('ipm:GaugeLabGroupV4OptionName', ...
        'Only the verbose display option may be changed.');
end
if isfield(options,'verbose')
    verbose = options.verbose;
else
    verbose = true;
end
validLogical = islogical(verbose) && isscalar(verbose);
validNumeric = isnumeric(verbose) && isreal(verbose) && ...
    isscalar(verbose) && isfinite(verbose) && any(verbose == [0,1]);
if ~(validLogical || validNumeric)
    error('ipm:GaugeLabGroupV4Verbose', ...
        'verbose must be logical or numeric 0/1.');
end
verbose = logical(verbose);
end

function status = classify_group_exception(exception)
identifier = char(exception.identifier);
if is_gauge_design_identifier(identifier)
    status = 'failed_gauge_design';
elseif is_mesh_grid_identifier(identifier)
    status = 'failed_grid_gate';
elseif is_numerical_identifier(identifier)
    status = 'failed_numerical_gate';
else
    status = 'failed_infrastructure';
end
end

function tf = is_gauge_design_identifier(identifier)
prefixes = {'ipm:Degenerate','ipm:OmegaGaugeWindow', ...
    'ipm:OmegaGaugeBulk','ipm:TemplateGauge', ...
    'ipm:AnchorWallGauge','ipm:TransportAnchor', ...
    'ipm:BadCOmegaGauge','ipm:BadLengthGauge', ...
    'ipm:BadScalingContract','ipm:SymmetryLengthGauge', ...
    'ipm:RetiredCOmegaGauge','ipm:OuterAnchorGeometry', ...
    'ipm:GaugeLabUnregisteredGauge','ipm:GaugeLabSupportKind'};
tf = any(startsWith(identifier,prefixes));
end

function tf = is_mesh_grid_identifier(identifier)
prefixes = {'ipm:GaugeLabMeshGate','ipm:GaugeLabResolution', ...
    'ipm:GaugeLabFixedMesh','ipm:AdaptiveAxis', ...
    'ipm:AdaptiveGrid','ipm:AdaptiveLevel', ...
    'ipm:AdaptiveMonitor','ipm:CustomGrid', ...
    'ipm:HighOrderGrid','ipm:HighOrderQuadrature', ...
    'ipm:HighOrderRemesh','ipm:SixthOrderGrid', ...
    'ipm:SixthOrderQuadrature','ipm:FiniteDifference', ...
    'ipm:MinimumLevelPoints','ipm:SymmetryGrid'};
tf = any(startsWith(identifier,prefixes));
end

function tf = is_numerical_identifier(identifier)
prefixes = {'ipm:NonFinite','ipm:HighOrderPoisson', ...
    'ipm:AnisotropicPoisson','ipm:Poisson','ipm:Weno', ...
    'ipm:TimeIntegrator','ipm:BadTimeStep', ...
    'ipm:ConservativeRemesh'};
tf = any(startsWith(identifier,prefixes));
end

function append_manifest(fileName,record)
fileId = fopen(fileName,'a');
if fileId < 0
    warning('ipm:GaugeLabGroupV4Manifest', ...
        'Could not append %s.',fileName);
    return;
end
cleanup = onCleanup(@()fclose(fileId));
fprintf(fileId,'%s\n',jsonencode(record));
end

function value = utc_stamp()
value = char(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
