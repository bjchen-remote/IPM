function check = quadratic_peak_gauge_check(options)
options.scaling.cOmegaGauge = 'wall_omega_quadratic_peak';
options.transport.spatialDiscretization = 'high_order';
options.transport.transportScheme = 'weno5_fd';
options.time.timeIntegrator = 'ssprk54';
options.remesh.remeshTransferScheme = 'high_order';
options.remesh.adaptiveRemesh = false;
ops = ipm.mesh.build(options);
rho = ipm.field.initialDensity(ops,options.physics);
ops = ipm.evolve.initializeScaling(rho,ops);
[rhs,flow] = ipm.evolve.rhs(rho,ops);

trackingMask = abs(ops.x-ops.rescaling.pinX) <= ...
    ops.rescaling.peakTrackingHalfWidth;
trackedWall = max(flow.source(1,:),0);
trackedWall(~trackingMask) = 0;
[~,peakIndex] = max(trackedWall);
peak = ipm.evolve.quadraticPeakFunctional( ...
    flow.source(1,:),ops.x,peakIndex);
baseRhs = rhs-flow.canonicalCOmega*rho;
baseRhsX = baseRhs*ops.Dx';
forcing = sum(peak.weights.*baseRhsX(1,peak.indices));
expected = -forcing/peak.value;
formulaError = abs(flow.canonicalCOmega-expected);
reconstructedResidual = forcing+flow.canonicalCOmega*peak.value;

amplitudeFactor = 3;
[scaledRhs,scaledFlow] = ipm.evolve.rhs(amplitudeFactor*rho,ops);
amplitudeRateError = max(abs([scaledFlow.canonicalCL, ...
    scaledFlow.canonicalCOmega,scaledFlow.canonicalCR] - ...
    amplitudeFactor*[flow.canonicalCL,flow.canonicalCOmega, ...
    flow.canonicalCR]));
amplitudeRhsError = weighted_l2( ...
    scaledRhs-amplitudeFactor^2*rhs,ops) / ...
    max(weighted_l2(amplitudeFactor^2*rhs,ops),eps);

scale = struct('logC_l',0,'logC_omega',0,'physicalTime',0, ...
    'X_shift',0,'canonicalTime',0);
stepSize = 1e-5;
[rhoAfter,flowAfter,scaleAfter] = ipm.evolve.stepSsprk54( ...
    rho,stepSize,ops,scale);
state = struct('rho',rhoAfter,'flow',flowAfter,'scale',scaleAfter, ...
    'ops',ops,'config',options,'mass0', ...
    sum(rho.*ops.integrationWeights,'all'),'rhoRange0', ...
    [min(rho,[],'all'),max(rho,[],'all')], ...
    'normalizedTime',stepSize,'step',1);
[recorded,~] = ipm.output.record(ipm.output.initializeLog(),state);
requiredHistory = {'omegaGaugeQuadraticPeakX', ...
    'omegaGaugeQuadraticPeakValue','omegaGaugeQuadraticCurvature', ...
    'omegaGaugeQuadraticCurvatureCondition', ...
    'omegaGaugeQuadraticWeightCondition', ...
    'omegaGaugeQuadraticActiveNodeMargin', ...
    'omegaGaugeQuadraticVertexInteriorFraction', ...
    'omegaGaugeQuadraticRelativeSubgridLift', ...
    'omegaGaugeQuadraticRateResidual','omegaGaugeQuadraticRateScale'};
