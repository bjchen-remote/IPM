function values = trusted_series(values,prefix,label)
if ~isnumeric(values) || ~isreal(values) || ~isvector(values) || ...
        numel(values) ~= numel(prefix)
    error('ipm:LatticeRefinementSeries', ...
        'The %s series is not aligned with the trusted mask.',label);
end
values = values(:);
values = values(prefix);
if any(~isfinite(values))
    error('ipm:LatticeRefinementSeries', ...
        'The trusted %s series contains nonfinite values.',label);
end
end

function require_strictly_increasing(values,label)
if any(diff(values) <= 0)
    error('ipm:LatticeRefinementCoordinate', ...
        'The trusted %s series must be strictly increasing.',label);
end
end

function require_positive(values,label)
if any(values <= 0)
    error('ipm:LatticeRefinementPositive', ...
        'The trusted %s series must be positive.',label);
end
end

function require_nonnegative(values,label)
if any(values < 0)
    error('ipm:LatticeRefinementNonnegative', ...
        'The trusted %s series must be nonnegative.',label);
end
end

function require_fields(value,names,context)
missing = names(~isfield(value,names));
if ~isempty(missing)
    error('ipm:LatticeRefinementField', ...
        'The %s is missing required field "%s".',context,missing{1});
end
end

function weights = trapezoid_weights(coordinate)
spacing = diff(coordinate);
weights = [spacing(1)/2; ...
    (spacing(1:end-1)+spacing(2:end))/2;spacing(end)/2];
end
